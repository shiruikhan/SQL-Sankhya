SELECT
  PRO.CODPROD,
  PRO.DESCRPROD,
  GRU.DESCRGRUPOPROD,
  PRO.USOPROD,
  :CODEMP AS CODEMP,
  :DATE   AS DTCONTAGEM,
  NVL(SUM(EST.QTDEST), 0) AS QTDEST,
  EST.CODPARC,
	EST.CODVOL,
	EST.CODLOCAL || ' - ' || LOC.DESCRLOCAL AS DESCRLOCAL,
  (SELECT MAX(CAB.DTENTSAI)
     FROM TGFITE ITE, TGFCAB CAB
     WHERE CAB.NUNOTA = ITE.NUNOTA
       AND ITE.ATUALESTOQUE = 1
       AND ITE.CODPROD = PRO.CODPROD
       AND CAB.DTENTSAI < :DATE) AS DT_ULT_ENT_ESTOQ,
  (SELECT NVL(CUSSEMICM, 0)
     FROM TGFCUS
     WHERE CODPROD = PRO.CODPROD
       AND CODEMP = :CODEMP
       AND ROWNUM = 1
       AND DTATUAL = (
           SELECT MAX(DTATUAL)
           FROM TGFCUS CN
           WHERE CODPROD = PRO.CODPROD
             AND DTATUAL <= :DATE
             AND CODEMP = :CODEMP
       )) AS CUSSEMICM,
  (SELECT NVL(CUSMEDICM, 0)
     FROM TGFCUS
     WHERE CODPROD = PRO.CODPROD
       AND CODEMP = :CODEMP
       AND ROWNUM = 1
       AND DTATUAL = (
           SELECT MAX(DTATUAL)
           FROM TGFCUS CN
           WHERE CODPROD = PRO.CODPROD
             AND DTATUAL <= :DATE
             AND CODEMP = :CODEMP
       )) AS CUSMEDICM,
  (SELECT NVL(CUSMED, 0)
     FROM TGFCUS
     WHERE CODPROD = PRO.CODPROD
       AND CODEMP = :CODEMP
       AND ROWNUM = 1
       AND DTATUAL = (
           SELECT MAX(DTATUAL)
           FROM TGFCUS CN
           WHERE CODPROD = PRO.CODPROD
             AND DTATUAL <= :DATE
             AND CODEMP = :CODEMP
       )) AS CUSMEDGERENCIAL,
  (SELECT NVL(SUM(EST2.ESTOQUE), 0)
     FROM TGFEST EST2
     WHERE EST2.CODPROD = PRO.CODPROD
       AND EST2.CODEMP = :CODEMP
       AND (EST2.CODPARC = 0 OR EST2.CODPARC IS NULL)
  ) AS EST_ATUAL
FROM TGFPRO PRO
  INNER JOIN TGFCTE EST ON PRO.CODPROD = EST.CODPROD
  INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
	INNER JOIN TGFLOC LOC ON EST.CODLOCAL = LOC.CODLOCAL
WHERE EST.DTCONTAGEM = :DATE
  AND PRO.USOPROD IN ('V','T','M','R','E','P','O')
  AND EST.QTDEST <> 0
  AND EST.CODEMP = :CODEMP
  AND (PRO.CODPROD = :CODPROD OR :CODPROD IS NULL)
  AND (PRO.USOPROD = :USOPROD OR :USOPROD IS NULL)
  AND (PRO.DESCRPROD LIKE :CONTENDO OR :CONTENDO IS NULL)
  AND (EST.CODLOCAL = :P_CODLOCAL OR :P_CODLOCAL IS NULL)
  AND EST.CODPARC = 0
GROUP BY PRO.CODPROD, PRO.DESCRPROD, GRU.DESCRGRUPOPROD, PRO.USOPROD, 
  EST.CODPARC,
	EST.CODVOL,
	EST.CODLOCAL,
	LOC.DESCRLOCAL
ORDER BY PRO.CODPROD