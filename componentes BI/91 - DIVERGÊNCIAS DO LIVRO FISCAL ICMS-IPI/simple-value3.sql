SELECT
	COUNT(1) QTDFIN
FROM TGFFIN FIN
INNER JOIN TGFTOP TPO ON(TPO.CODTIPOPER = FIN.CODTIPOPER AND TPO.DHALTER = FIN.DHTIPOPER)
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = FIN.CODEMP)
INNER JOIN TGFEMP GEMP ON(GEMP.CODEMP = FIN.CODEMP)
WHERE FIN.ORIGEM = 'F'
  AND TPO.ATUALLIVFIS NOT IN ('N','A')
  AND FIN.PROVISAO = 'N'
  AND GEMP.GERARLIVROS = 'S'
  AND (FIN.DTNEG BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN)
  AND (FIN.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
  AND (FIN.NUFIN = :P_NUNOTA OR :P_NUNOTA IS NULL)
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND FIN.NUNOTA IS NULL
  AND FIN.RECDESP <> 0
  AND NOT EXISTS (SELECT 1 FROM TGFLIV LIV WHERE LIV.NUNOTA = FIN.NUFIN AND FIN.CODEMP = LIV.CODEMP AND LIV.CODPARC = FIN.CODPARC)
  AND ((SELECT COALESCE(MAX('S'),'N') FROM TGFLIV_EXC E WHERE E.NUNOTA = FIN.NUFIN AND E.ORIGEM = 'F' AND FIN.CODEMP = E.CODEMP AND E.CODPARC = FIN.CODPARC) = :P_MOSTRAEXCLIV OR :P_MOSTRAEXCLIV = 'T')
  AND (/* TÍTULOS DE ORIGEM NO FINANCEIRO */
	/* BUSCA TÍTULO NÃO RENEGOCIADO OU TÍTULO ORIGEM DA RENEGOCIAÇÃO */
	((FIN.ORIGEM = 'F') AND (FIN.NURENEG IS NULL OR EXISTS(SELECT 1 FROM TGFREN REN WHERE REN.NUFIN = FIN.NUFIN AND REN.NURENEGORIG = 0 AND FIN.RECDESP = 0)))
	  OR
                /* TÍTULOS DE ORIGEM NO ESTOQUE (FINANCEIRO DE FRETE) */
	/* SE FRETERENEG LIGADO, BUSCA TÍTULO NÃO RENEGOCIADO OU TÍTULO DESTINO DA RENEGOCIAÇÃO */
	(((FIN.DESDOBDUPL = 'F') OR EXISTS(SELECT 1	FROM TGFFNF WHERE NUFIN = FIN.NUFIN) OR (TPO.CODMODDOC = 57	AND TPO.TIPMOV = 'I'))	AND (FIN.RECDESP <> 0) AND ((SELECT	LOGICO FROM	TSIPAR WHERE CHAVE = 'LIVFRETERENEG') = 'S'))	
	  OR
                /* TÍTULOS DE ORIGEM NO ESTOQUE (FINANCEIRO DE FRETE) */
	/* SE FRETERENEG DESLIGADO, BUSCA TÍTULO ORIGEM NA RENEGOCIAÇÃO OU TÍTULO NÃO RENEGOCIADO */
	(((FIN.DESDOBDUPL = 'F') OR 
	             EXISTS (SELECT 1 FROM TGFFNF WHERE NUFIN = FIN.NUFIN)) 
	             AND ((SELECT LOGICO FROM TSIPAR WHERE CHAVE = 'LIVFRETERENEG') = 'N') 
	             AND ((FIN.RECDESP = 0 AND FIN.NURENEG IS NOT NULL AND NOT EXISTS(SELECT 1 FROM TGFREN REN WHERE REN.NUFIN = FIN.NUFIN AND NURENEGORIG <> 0)) OR (FIN.RECDESP <> 0 AND FIN.NURENEG IS NULL))))
