SELECT COUNT(TB2.CODIGO) AS CINCO
FROM (SELECT TB.CODIGO,
            (CASE WHEN B.TIPOTEMPO = 'D' THEN DTPREV+B.TEMPO WHEN B.TIPOTEMPO = 'M' THEN ADD_MONTHS(DTPREV,B.TEMPO) WHEN B.TIPOTEMPO = 'A' THEN ADD_MONTHS(DTPREV,B.TEMPO*12) END) AS DATA
        FROM (SELECT BEM.CODBEM AS CODIGO, MAX(CTR.DTPREV) AS DTPREV FROM AD_ADCADBENS BEM INNER JOIN AD_PRVCTR CTR ON BEM.CODBEM = CTR.CODBEM GROUP BY BEM.CODBEM) TB
            INNER JOIN AD_ADCADBENS B ON TB.CODIGO = B.CODBEM) TB2
WHERE TB2.DATA - SYSDATE <= 5
	AND TB2.DATA - SYSDATE > 0
