SELECT DISTINCT PROC.IDIPROC, PROC.NROLOTE,LPA.CODPRODPA, PROPA.DESCRPROD AS DESCRPA, IPA.QTDPRODUZIR, 
 NVL(PROD.QTDPA,0) AS QTDPA, IPA.QTDPRODUZIR-NVL(PROD.QTDPA,0) AS SALDOPRODPA, PRC.DESCRABREV AS PROCESSOPROD,
PRC.CODPRC AS CODIGOPRC
FROM TPRIPROC PROC INNER JOIN TPRLPA LPA ON (PROC.IDPROC = LPA.IDPROC)
INNER JOIN TPRPRC PRC ON (PRC.IDPROC = PROC.IDPROC)
INNER JOIN TPREFX FX ON (FX.IDPROC = PROC.IDPROC)
INNER JOIN TPRIPA IPA ON (IPA.IDIPROC = PROC.IDIPROC AND IPA.CODPRODPA = LPA.CODPRODPA)
INNER JOIN TGFPRO PROPA ON (PROPA.CODPROD = LPA.CODPRODPA)
LEFT JOIN (SELECT NVL(SUM(I.QTDNEG),0) AS QTDPA, C.IDIPROC FROM TGFCAB C INNER JOIN TGFITE I ON (C.NUNOTA = I.NUNOTA)
WHERE C.TIPMOV='F' AND I.USOPROD='V' AND I.ATUALESTOQUE=1 AND C.DTNEG  BETWEEN :PER.INI AND :PER.FIN
GROUP BY C.IDIPROC) PROD ON (PROD.IDIPROC = PROC.IDIPROC)
WHERE TRUNC(PROC.DHINST) BETWEEN :PER.INI AND :PER.FIN
AND PRC.CODPRC IN :P_CODPRC
AND IPA.QTDPRODUZIR-NVL(PROD.QTDPA,0) > 0
AND (IPA.CODPRODPA = :P_CODPRODPA OR :P_CODPRODPA IS NULL)
ORDER BY PROC.IDIPROC
