SELECT ITE.NUNOTA,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL AS ITECODVOL,
	PRO.CODVOL AS PROCODVOL,
	PRO.CODVOLCOMPRA AS CODVOLCOMPRA,
	VOA.CODVOL AS VOLCODVOL
FROM TGFITE ITE
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	LEFT JOIN TGFVOA VOA ON PRO.CODPROD = VOA.CODPROD
WHERE PRO.CODVOL = :P_CODVOL
	OR PRO.CODVOLCOMPRA = :P_CODVOL
	OR ITE.CODVOL = :P_CODVOL
	OR VOA.CODVOL = :P_CODVOL
ORDER BY ITE.NUNOTA, PRO.CODPROD
