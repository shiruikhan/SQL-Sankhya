SELECT *
FROM(
SELECT NOMEUSU, PERC, SUM(VALOR_TOTAL) AS VALOR_TOTAL, SUM(VALOR_PERIODO) AS VALOR_PERIODO
FROM(
SELECT  USU.NOMEUSU,
(SUM(EAC.QTDPERIODO)/ 
 (
     SELECT SUM(EAC2.QTDPERIODO) FROM TRDEAC EAC2  
 )
) * 100 AS PERC,
(CASE WHEN :TIPO = 'T' THEN SUM(EAC.QTDGERAL) END) AS VALOR_TOTAL,
0 AS VALOR_PERIODO
FROM TRDPCO PCO 
INNER JOIN TRDEAC EAC ON(PCO.VALOR = EAC.RESOURCEID)
INNER JOIN TRDCON CON ON(CON.NUCONTROLE = PCO.NUCONTROLE)
INNER JOIN TSIUSU USU ON(USU.CODUSU = EAC.CODUSU) 
WHERE ((USU.CODUSU= :CODUSU) OR (:CODUSU IS NULL))
AND (UPPER(CON.DESCRCONTROLE) LIKE UPPER('%' || :TELA  ||   '%') OR (:TELA IS NULL))
AND :TIPO = 'T' 
GROUP BY USU.NOMEUSU

UNION ALL

SELECT  USU.NOMEUSU, 
(SUM(EAC.QTDPERIODO)/ 
 (
     SELECT SUM(EAC2.QTDPERIODO) FROM TRDEAC EAC2  
 )
) * 100 AS PERC,
0 AS VALOR_TOTAL,
(CASE WHEN :TIPO = 'P' THEN SUM(EAC.QTDPERIODO) END) AS VALOR_PERIODO
FROM TRDPCO PCO 
INNER JOIN TRDEAC EAC ON(PCO.VALOR = EAC.RESOURCEID)
INNER JOIN TRDCON CON ON(CON.NUCONTROLE = PCO.NUCONTROLE)
INNER JOIN TSIUSU USU ON(USU.CODUSU = EAC.CODUSU) 
WHERE ((USU.CODUSU= :CODUSU) OR (:CODUSU IS NULL))
AND (UPPER(CON.DESCRCONTROLE) LIKE UPPER('%' || :TELA  ||   '%') OR (:TELA IS NULL))
AND :TIPO = 'P'
GROUP BY USU.NOMEUSU
)
GROUP BY NOMEUSU, PERC
ORDER BY VALOR_TOTAL DESC, VALOR_PERIODO DESC
)
WHERE ROWNUM < 51
