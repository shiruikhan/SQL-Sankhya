SELECT 
DADOS2.DTREF,
DMT.CODDMT, 
DMT.DESCRDMT,
DADOS2.CTACTB, 
DADOS2.CODCTACTB,
REPLACE(REPLACE(REPLACE(INITCAP(DADOS2.DESCRCTA),' De ',' de '),' E ',' e '),'S/', 's/') AS DESCRCTA, 
:CRSELECAO AS CODCENCUS,
SUM(MES01) AS MES01, 
SUM(MES02) AS MES02,
SUM(MES03) AS MES03,
SUM(MES04) AS MES04,
SUM(MES05) AS MES05,
SUM(MES06) AS MES06,
SUM(MES07) AS MES07,
SUM(MES08) AS MES08,
SUM(MES09) AS MES09,
SUM(MES10) AS MES10,
SUM(MES11) AS MES11,
SUM(MES12) AS MES12,
SUM(DADOS2.TOTAL) AS TOTAL
FROM
TCBDMT DMT
LEFT JOIN
(SELECT DADOS.CTACTB, DADOS.CODCTACTB, DADOS.DESCRCTA, DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF,
SUM(DADOS.MES01) AS MES01, SUM(DADOS.MES02) AS MES02, SUM(DADOS.MES03) AS MES03, SUM(DADOS.MES04) AS MES04, SUM(DADOS.MES05) AS MES05, SUM(DADOS.MES06) AS MES06,
SUM(DADOS.MES07) AS MES07, SUM(DADOS.MES08) AS MES08, SUM(DADOS.MES09) AS MES09, SUM(DADOS.MES10) AS MES10, SUM(DADOS.MES11) AS MES11, SUM(DADOS.MES12) AS MES12, SUM(TOTAL) AS TOTAL
 FROM(
    SELECT LAN.CODEMP, TO_CHAR(LAN.DTMOV,'YYYY') AS DTREF, PLA.CTACTB, LAN.CODCTACTB, PLA.DESCRCTA, DMT.CODDMT, DMT.DESCRDMT, 
    CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 01 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES01,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 02 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES02,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 03 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES03,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 04 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES04,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 05 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES05,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 06 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES06,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 07 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES07,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 08 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES08,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 09 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES09,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 10 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES10,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 11 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES11,
	CASE WHEN TO_CHAR(LAN.REFERENCIA,'MM') = 12 THEN LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END ELSE 0 END AS MES12,
   (LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS TOTAL
    FROM
    TCBLAN LAN
    LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
    LEFT JOIN TCBPLA PLA2 ON PLA.CODCTACTBPAI = PLA2.CODCTACTB
    LEFT JOIN TCBLOT LOT ON LOT.NUMLOTE = LAN.NUMLOTE AND LOT.REFERENCIA = LAN.REFERENCIA AND LAN.CODEMP = LOT.CODEMP
    LEFT JOIN TCBCDM CDM ON (PLA2.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTB = CDM.CODCTACTB)
    LEFT JOIN TCBDMT DMT ON CDM.CODTDM = DMT.CODTDM AND CDM.CODDMT = DMT.CODDMT
    WHERE
        PLA.CTACTB>'3' 
	AND PLA.CTACTB <= '4'
    AND LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') 
    AND LAN.DTMOV <= LAST_DAY(:DAT1)
    AND LAN.NUMLOTE NOT IN (999,9999)
    AND LAN.CODEMP IN :CODEMP AND LAN.CODCENCUS = NVL(:CRSELECAO,LAN.CODCENCUS)
)DADOS
GROUP BY DADOS.CTACTB, DADOS.CODCTACTB, DADOS.DESCRCTA, DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF) DADOS2 ON 
((SUBSTR(DADOS2.CODDMT,1,1) = SUBSTR(DMT.CODDMT,1,1) AND DMT.GRAU=1) OR 
 (SUBSTR(DADOS2.CODDMT,1,3) = SUBSTR(DMT.CODDMT,1,3) AND DMT.GRAU=2) OR
 (SUBSTR(DADOS2.CODDMT,1,5) = SUBSTR(DMT.CODDMT,1,5) AND DMT.GRAU=3) OR
 (SUBSTR(DADOS2.CODDMT,1,7) = SUBSTR(DMT.CODDMT,1,7) AND DMT.GRAU=4) OR
 (SUBSTR(DADOS2.CODDMT,1,9) = SUBSTR(DMT.CODDMT,1,9) AND DMT.GRAU=5) OR
 (SUBSTR(DADOS2.CODDMT,1,11) = SUBSTR(DMT.CODDMT,1,11) AND DMT.GRAU=6) OR 
 (SUBSTR(DADOS2.CODDMT,1,14) = SUBSTR(DMT.CODDMT,1,14) AND DMT.GRAU=7))
WHERE 
    DMT.GRAU IN (1,2,3,4,5,6,7)
AND DMT.CODTDM= 2
AND DADOS2.TOTAL IS NOT NULL
AND (DMT.CODDMT = :CODDMT OR (DADOS2.CTACTB = :CODDMT AND DMT.ANALITICO='S'))
GROUP BY DADOS2.DTREF, DMT.CODDMT, DMT.DESCRDMT, DADOS2.CTACTB, DADOS2.CODCTACTB, DADOS2.DESCRCTA
ORDER BY DADOS2.CODCTACTB
