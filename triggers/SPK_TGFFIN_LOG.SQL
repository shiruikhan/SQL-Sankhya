create or replace TRIGGER SPK_TGFFIN_LOG
BEFORE INSERT OR UPDATE OR DELETE 
ON TGFFIN
FOR EACH ROW
DECLARE
  P_ACAO VARCHAR2(10);
  P_CHAVEPK VARCHAR2(400);
  P_CODUSU_SIS VARCHAR2(20);
BEGIN
  P_CODUSU_SIS := TO_CHAR(STP_GET_CODUSULOGADO);
  P_CHAVEPK := 'PK [' || 'NUNOTA' || '=' || :NEW.NUNOTA || ']';
  IF INSERTING THEN  
    IF :NEW.DTNEG IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTNEG',P_CODUSU_SIS,'INSERT',:NEW.DTNEG,' ');
    END IF;
	IF :NEW.DTENTSAI IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTENTSAI',P_CODUSU_SIS,'INSERT',:NEW.DTENTSAI,' ');
    END IF;
	IF :NEW.DTVENC IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTVENC',P_CODUSU_SIS,'INSERT',:NEW.DTVENC,' ');
    END IF;
	IF :NEW.HISTORICO IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'HISTORICO',P_CODUSU_SIS,'INSERT',:NEW.HISTORICO,' ');
    END IF;
	IF :NEW.VLRBAIXA IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'VLRBAIXA',P_CODUSU_SIS,'INSERT',:NEW.VLRBAIXA,' ');
    END IF;
	IF :NEW.VLRDESDOB IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'VLRDESDOB',P_CODUSU_SIS,'INSERT',:NEW.VLRDESDOB,' ');
    END IF;
	IF :NEW.DHBAIXA IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DHBAIXA',P_CODUSU_SIS,'INSERT',:NEW.DHBAIXA,' ');
    END IF;
    RETURN;
  ELSIF DELETING THEN 
    P_CHAVEPK := 'PK [' || 'NUNOTA' || '=' || :OLD.NUNOTA || ']';
    IF :OLD.DTNEG IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTNEG',P_CODUSU_SIS,'DELETE',' ',:OLD.DTNEG);
    END IF;
	IF :OLD.DTENTSAI IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTENTSAI',P_CODUSU_SIS,'DELETE',' ',:OLD.DTENTSAI);
    END IF;
	IF :OLD.DTVENC IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DTVENC',P_CODUSU_SIS,'DELETE',' ',:OLD.DTVENC);
    END IF;
	IF :OLD.HISTORICO IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'HISTORICO',P_CODUSU_SIS,'DELETE',' ',:OLD.HISTORICO);
    END IF;
	IF :OLD.VLRBAIXA IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'VLRBAIXA',P_CODUSU_SIS,'DELETE',' ',:OLD.VLRBAIXA);
    END IF;
	IF :OLD.VLRDESDOB IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'VLRDESDOB',P_CODUSU_SIS,'DELETE',' ',:OLD.VLRDESDOB);
    END IF;
	IF :OLD.DHBAIXA IS NOT NULL THEN   
      STP_GRAVATABLOG('TGFFIN', P_CHAVEPK,'DHBAIXA',P_CODUSU_SIS,'DELETE',' ',:OLD.DHBAIXA);
    END IF;
    RETURN;
  END IF;            
END;