  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_TGFFIN_ATL_IPTU" 
BEFORE UPDATE OF DHBAIXA ON TGFFIN
FOR EACH ROW
 WHEN (NEW.TIMORIGEM IN('AL','AV','FC')) DECLARE
  P_DTLIPTU NUMBER(10, 0);
  P_DTLRBIPTU NUMBER(10, 0);
BEGIN

   IF STP_GET_ATUALIZANDO THEN
    RETURN;
   END IF;

   IF NOT STP_GET_TIMUTILIZAIMOB
   THEN
      RETURN;
   END IF;

  IF(:NEW.DHBAIXA IS NOT NULL AND :OLD.DHBAIXA IS NULL) THEN
    P_DTLIPTU := GET_TSIPAR_INTEIRO('TIMDTLIPTU');
    P_DTLRBIPTU := GET_TSIPAR_INTEIRO('TIMDTLRBIPTU');
    FOR CUR IN (SELECT * FROM TIMDTL WHERE DTLPARCELA = :NEW.NUFIN AND DTLHISTORICO IN (P_DTLIPTU, P_DTLRBIPTU))
    LOOP
      UPDATE TIMPIP SET PIPVLRPAGO = CASE CUR.DTLHISTORICO
        WHEN P_DTLIPTU 
            THEN NVL(PIPVLRPAGO, 0) + CUR.DTLVALOR 
        WHEN P_DTLRBIPTU
            THEN NVL(PIPVLRPAGO, 0) - CUR.DTLVALOR
        ELSE 0 END
      WHERE PIPIPTU = CUR.DTLCODIPTU
        AND PIPIMOVEL = CUR.DTLIMOVEL
        AND PIPCODIGO = CUR.DTLPARCELAIPTU;
    END LOOP;
  ELSIF(:NEW.DHBAIXA IS NULL AND :OLD.DHBAIXA IS NOT NULL) THEN
    P_DTLIPTU := GET_TSIPAR_INTEIRO('TIMDTLIPTU');
    P_DTLRBIPTU := GET_TSIPAR_INTEIRO('TIMDTLRBIPTU');
    FOR CUR IN (SELECT * FROM TIMDTL WHERE DTLPARCELA = :NEW.NUFIN AND DTLHISTORICO IN (P_DTLIPTU, P_DTLRBIPTU))
    LOOP
      UPDATE TIMPIP SET PIPVLRPAGO = CASE CUR.DTLHISTORICO
        WHEN P_DTLIPTU 
            THEN NVL(PIPVLRPAGO, 0) - CUR.DTLVALOR 
        WHEN P_DTLRBIPTU
            THEN NVL(PIPVLRPAGO, 0) + CUR.DTLVALOR
        ELSE 0 END
      WHERE PIPIPTU = CUR.DTLCODIPTU
        AND PIPIMOVEL = CUR.DTLIMOVEL
        AND PIPCODIGO = CUR.DTLPARCELAIPTU;
    END LOOP;
  END IF;
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_TGFFIN_ATL_IPTU" ENABLE;
