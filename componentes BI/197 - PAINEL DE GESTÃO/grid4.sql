SELECT * FROM(
--TITULOS ORIGEM FINANCEIRO - TOP TIPO "V"
SELECT 
CASE WHEN T.TIPMOV = 'V' THEN 'Portal'
	 WHEN T.TIPMOV = 'D' THEN 'Devolução'
     ELSE 'Financeiro' END AS ORIGEM,
FIN.CODEMP, 
FIN.DTNEG,
FIN.DTENTSAI, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
FIN.NURENEG,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
CASE WHEN DHBAIXA IS NOT NULL THEN 1
	 WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 2
     ELSE 3 END AS CLASSIF,
FIN.HISTORICO,
PAR.CODCTACTB
FROM 
TGFFIN FIN 
LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
WHERE
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0) AND
FIN.CODEMP IN :CODEMP AND  
(CASE WHEN T.TIPMOV = 'V' THEN FIN.DTNEG ELSE FIN.DTENTSAI END) <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
((T.TIPMOV IN ('V') AND FIN.RECDESP = 1) OR
(T.TIPMOV IN ('D') AND FIN.RECDESP = -1)) AND
:OUTROS IN ('A','P')

UNION ALL

--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
SELECT 
CASE WHEN T.TIPMOV <> 'I' THEN 'Portal'
     ELSE 'Financeiro' END AS ORIGEM,
FIN.CODEMP, 
FIN.DTNEG, 
FIN.DTENTSAI,
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
FIN.NURENEG,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
CASE WHEN DHBAIXA IS NOT NULL THEN 1
	 WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 2
     ELSE 3 END AS CLASSIF,
FIN.HISTORICO,
159 AS CODCTACTB
FROM 
TGFFIN FIN 
LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
WHERE
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0) AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTNEG <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('I') AND 
FIN.RECDESP = 1 AND
NAT.AD_TIPOCTBZ = 'N' AND
:OUTROS IN ('A','F')
)
WHERE (CLASSIFICACAO = :CLASSIFICACAO OR :CLASSIFICACAO IS NULL)
ORDER BY CODPARC, DTVENC, DTNEG
