SELECT 
    CAB.NUNOTA,
    CAB.CODPARC,
    PAR.RAZAOSOCIAL,
    SUM(ITE.QTDNEG - ITE.QTDENTREGUE) AS QTDNEG,
    CAB.DTNEG,
    CAB.DTPREVENT,
    TPV.DESCRTIPVENDA
FROM TGFCAB CAB
INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
INNER JOIN TGFTPV TPV ON TPV.CODTIPVENDA = CAB.CODTIPVENDA AND TPV.DHALTER = CAB.DHTIPVENDA
WHERE CAB.PENDENTE = 'S'
  AND CAB.TIPMOV = 'P'
  AND ITE.PENDENTE = 'S'
  AND CAB.CODTIPOPER <> 900
  AND CAB.DTPREVENT <= :P_DATA
  AND ITE.CODPROD = :A_CODPROD
GROUP BY 
    CAB.NUNOTA,
    CAB.CODPARC,
    PAR.RAZAOSOCIAL,
    CAB.DTNEG,
    CAB.DTPREVENT,
    TPV.DESCRTIPVENDA
ORDER BY CAB.DTPREVENT, PAR.RAZAOSOCIAL
