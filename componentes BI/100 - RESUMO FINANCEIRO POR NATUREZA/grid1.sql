SELECT DISTINCT V.CODNAT,
	(SELECT DISTINCT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = V.CODNAT) AS DESCRNAT,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 01 THEN V.VLRBAIXA END) END)) AS JAN,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 02 THEN V.VLRBAIXA END) END)) AS FEV,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 03 THEN V.VLRBAIXA END) END)) AS MAR,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 04 THEN V.VLRBAIXA END) END)) AS ABR,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 05 THEN V.VLRBAIXA END) END)) AS MAI,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 06 THEN V.VLRBAIXA END) END)) AS JUN,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 07 THEN V.VLRBAIXA END) END)) AS JUL,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 08 THEN V.VLRBAIXA END) END)) AS AGO,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 09 THEN V.VLRBAIXA END) END)) AS SETE,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 10 THEN V.VLRBAIXA END) END)) AS OUTU,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 11 THEN V.VLRBAIXA END) END)) AS NOV,
	SUM((CASE WHEN V.ANO = :P_ANO THEN (CASE WHEN V.MES = 12 THEN V.VLRBAIXA END) END)) AS DEZ,
	SUM((CASE WHEN V.ANO = :P_ANO THEN V.VLRBAIXA END)) AS TOTAL
FROM (SELECT *
FROM (SELECT FIN.CODNAT,
        SUM(FIN.VLRBAIXA) AS VLRBAIXA,
        EXTRACT(MONTH FROM FIN.DHBAIXA) AS MES,
        EXTRACT(YEAR FROM FIN.DHBAIXA) AS ANO
    FROM TGFFIN FIN
    WHERE FIN.PROVISAO = 'N'
        AND FIN.RECDESP = -1
        AND FIN.DHBAIXA IS NOT NULL
        AND (:P_CODNAT IS NULL OR FIN.CODNAT = :P_CODNAT)
        AND (:P_ANO IS NULL OR EXTRACT(YEAR FROM FIN.DHBAIXA) = :P_ANO)
        AND NVL(FIN.NUFIN,0) NOT IN (SELECT R.NUFIN FROM TGFRAT R WHERE R.ORIGEM = 'F')
        AND NVL(FIN.NUNOTA,0) NOT IN (SELECT R.NUFIN FROM TGFRAT R WHERE R.ORIGEM = 'E')
    GROUP BY FIN.CODNAT, 
        EXTRACT(MONTH FROM FIN.DHBAIXA), 
        EXTRACT(YEAR FROM FIN.DHBAIXA)
    UNION ALL
    SELECT TB1.CODNAT,
        SUM(TB1.VLRBAIXA) AS VLRBAIXA,
        EXTRACT(MONTH FROM TB1.DHBAIXA) AS MES,
        EXTRACT(YEAR FROM TB1.DHBAIXA) AS ANO
    FROM (SELECT RAT.ORIGEM,
            RAT.NUFIN,
            RAT.CODNAT,
            ROUND(((RAT.PERCRATEIO/100) * FIN.VLRBAIXA),2) AS VLRBAIXA,
            FIN.DHBAIXA
        FROM TGFRAT RAT 
            INNER JOIN TGFFIN FIN ON (RAT.NUFIN = FIN.NUFIN AND RAT.ORIGEM = 'F')
        WHERE FIN.PROVISAO = 'N'
            AND FIN.RECDESP = -1
            AND FIN.DHBAIXA IS NOT NULL
            AND (:P_CODNAT IS NULL OR RAT.CODNAT = :P_CODNAT)
            AND (:P_ANO IS NULL OR EXTRACT(YEAR FROM FIN.DHBAIXA) = :P_ANO)
        UNION ALL
        SELECT RAT.ORIGEM,
            RAT.NUFIN,
            RAT.CODNAT,
            ROUND(((RAT.PERCRATEIO/100) * FIN.VLRBAIXA),2) AS VLRBAIXA  ,
            FIN.DHBAIXA  
        FROM TGFRAT RAT 
            INNER JOIN TGFFIN FIN ON (RAT.NUFIN = FIN.NUNOTA AND RAT.ORIGEM = 'E')
        WHERE FIN.PROVISAO = 'N'
            AND FIN.RECDESP = -1
            AND FIN.DHBAIXA IS NOT NULL
            AND (:P_CODNAT IS NULL OR RAT.CODNAT = :P_CODNAT)
            AND (:P_ANO IS NULL OR EXTRACT(YEAR FROM FIN.DHBAIXA) = :P_ANO)) TB1
    GROUP BY TB1.CODNAT, 
        EXTRACT(MONTH FROM TB1.DHBAIXA), 
        EXTRACT(YEAR FROM TB1.DHBAIXA))
ORDER BY CODNAT,
	MES,
    ANO) V
WHERE V.VLRBAIXA > 0
	AND (:P_CODNAT IS NULL OR V.CODNAT = :P_CODNAT) 
GROUP BY V.CODNAT
ORDER BY V.CODNAT
