SELECT 
    M.APELIDO AS GRUPO,
    NVL(V.VENDAS, 0) AS VENDAS,
    NVL(D.DEVOLUCOES, 0) AS DEVOLUCOES,
    M.VLRMET AS META,
    -- Saldo agora subtrai as devoluções antes de abater a meta
    (NVL(V.VENDAS, 0) - NVL(D.DEVOLUCOES, 0) - M.VLRMET) AS SALDO,
    CASE
        WHEN (NVL(V.VENDAS, 0) - NVL(D.DEVOLUCOES, 0) - M.VLRMET) >= 0 THEN '#b4f7b4ff'
        ELSE '#f38484'
    END AS BKCOLOR
FROM AD_TGSSGM M
LEFT JOIN (
    -- Subquery VENDAS (Exatamente como estava)
    SELECT 
        COMP.CODSGRU,
        SUM(I.QTDNEG) AS VENDAS
    FROM TGFCAB C
    INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
    INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
    INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
    INNER JOIN AD_TGSISGM COMP ON (
        (COMP.TIPO = 'G' AND G.CODGRUPOPROD = COMP.CODGRUPOPROD) OR
        (COMP.TIPO = 'P' AND G.CODGRUPAI = COMP.CODGRUPOPROD)
    )
    WHERE C.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
        AND C.TIPMOV = 'V'
        AND P.USOPROD = 'V'
        AND TRUNC(C.DTNEG, 'MM') = TRUNC(SYSDATE, 'MM')
        AND TRUNC(C.DTNEG, 'YYYY') = TRUNC(SYSDATE, 'YYYY')
        AND COMP.ANO = TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'))
        AND COMP.MES = TO_CHAR(SYSDATE, 'MM')
    GROUP BY 
        COMP.CODSGRU
) V ON M.CODSGRU = V.CODSGRU
LEFT JOIN (
    -- NOVA Subquery DEVOLUÇÕES
    SELECT 
        COMP.CODSGRU,
        SUM(I.QTDNEG) AS DEVOLUCOES
    FROM TGFCAB C
    INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
    INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
    INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
    INNER JOIN AD_TGSISGM COMP ON (
        (COMP.TIPO = 'G' AND G.CODGRUPOPROD = COMP.CODGRUPOPROD) OR
        (COMP.TIPO = 'P' AND G.CODGRUPAI = COMP.CODGRUPOPROD)
    )
    WHERE C.CODTIPOPER IN (1200,1201,1206,1216,1217,1272)
        AND C.TIPMOV = 'D'
        AND P.USOPROD = 'V'
        AND (C.CODEMP = 501 OR C.STATUSNFE <> 'D') -- Regra inserida aqui
        AND TRUNC(C.DTNEG, 'MM') = TRUNC(SYSDATE, 'MM')
        AND TRUNC(C.DTNEG, 'YYYY') = TRUNC(SYSDATE, 'YYYY')
        AND COMP.ANO = TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'))
        AND COMP.MES = TO_CHAR(SYSDATE, 'MM')
    GROUP BY 
        COMP.CODSGRU
) D ON M.CODSGRU = D.CODSGRU
-- Filtra a meta para o ano e mês corrente
WHERE M.ANO = TO_NUMBER(TO_CHAR(SYSDATE, 'YYYY'))
  AND M.MES = TO_CHAR(SYSDATE, 'MM')
ORDER BY M.APELIDO