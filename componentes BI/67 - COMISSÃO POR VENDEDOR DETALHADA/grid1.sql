SELECT 
CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)AS TOTALVENDA
,CAB.VLRNOTA+CAB.VLROUTROS-(CAB.VLRIPI+CAB.VLRSUBST + (CASE WHEN CAB.TIPFRETE = 'S' THEN CAB.VLRFRETE ELSE 0 END)) AS VLRBASE
,(SELECT SUM(C.VLRCOM) FROM TGFCOM C WHERE C.NUNOTAORIG = VCOM.NUNOTAORIG) AS VLRCOM
,(SELECT SUM(C.VLRCOM) FROM TGFCOM C WHERE C.NUNOTAORIG = VCOM.NUNOTAORIG AND C.NUFECHAMENTO=0) AS SALDOVLRCOM
,VCOM.COMLIQ
,NVL(CAB.AD_VLROUTROSFRETE,0) AS FRETE_OUTROS
,CAB.VLROUTROS as VLROUTROS
,VCOM.VLRDESDOB
,VCOM.VLRBAIXA
,/*(VCOM.VLRDESDOB/(CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)))*100 AS PERCPARCELA/*/
(VCOM.VLRDESDOB/(SELECT SUM(VLRDESDOB) FROM TGFFIN F WHERE F.NUNOTA =VCOM.NUNOTAORIG AND F.CODEMP = VCOM.CODEMP))*100 AS PERCPARCELA
,/*(VCOM.VLRBAIXA/(CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)))*100 AS PERCRECEBIDO */
(VCOM.VLRBAIXA/(SELECT SUM(VLRDESDOB) FROM TGFFIN F WHERE F.NUNOTA =VCOM.NUNOTAORIG AND F.CODEMP = VCOM.CODEMP))*100 AS PERCRECEBIDO 
,VCOM.NUNOTAORIG
,VCOM.FINNUFIN
,(SELECT VEN.APELIDO
  FROM TGFVEN VEN
  WHERE VEN.CODVEND = VCOM.CODVEND) AS REPRESENTANTE
,(SELECT RTRIM(LTRIM(CID.NOMECID))||'-'||RTRIM(LTRIM((UF.UF)))
  FROM TSIUFS UF,TSICID CID, TGFPAR PAR2
  WHERE UF.CODUF = CID.UF AND CID.CODCID = PAR2.CODCID AND PAR2.CODPARC = VCOM.CODPARC) AS ENDERECO
,FIN.CODEMP
,FIN.DESDOBRAMENTO
,VCOM.CODVEND
,VCOM.CODPARC
,VCOM.NOMEPARC
,VCOM.NUMNOTA
,VCOM.DTVENC
,VCOM.DHBAIXA
,VCOM.DTFATUR
,VCOM.PERCCOM AS PERCCOM
,VCOM.NUFECHAMENTO
,VCOM.NUNOTAORIG AS NUNOTA
, CASE WHEN VCOM.NUFECHAMENTO=0 AND VCOM.VLRBAIXA=0 THEN 'YELLOW' WHEN VCOM.NUFECHAMENTO=0 AND VCOM.VLRBAIXA>0 THEN '#98FB98' WHEN VCOM.NUFECHAMENTO>0 THEN '#00CED1' END BKCOLOR
FROM VGFCOM_FECH VCOM , TGFCAB CAB , TGFFIN FIN
WHERE CASE WHEN :P_TIPDATA = 'B' THEN VCOM.DHBAIXA ELSE VCOM.DTNEG END BETWEEN :P_PER.INI AND :P_PER.FIN
AND (VCOM.CODVEND = :P_CODVEND OR :P_CODVEND IS NULL )
AND VCOM.FINNUFIN = FIN.NUFIN
AND VCOM.NUNOTAORIG = CAB.NUNOTA
AND (VCOM.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
AND (VCOM.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
/*AND VCOM.POSICAO_QUERY IN
(3,4) --PELA BAIXA E RENEGOCIADA */

UNION
SELECT 
CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)AS TOTALVENDA
,CAB.VLRNOTA+CAB.VLROUTROS-(CAB.VLRIPI+CAB.VLRSUBST + CASE WHEN CAB.TIPFRETE = 'S' THEN CAB.VLRFRETE ELSE 0 END) AS VLRBASE
,(SELECT SUM(C.VLRCOM) FROM TGFCOM C WHERE C.NUNOTAORIG = VCOM.NUNOTAORIG) AS VLRCOM
,(SELECT SUM(C.VLRCOM) FROM TGFCOM C WHERE C.NUNOTAORIG = VCOM.NUNOTAORIG AND C.NUFECHAMENTO=0) AS SALDOVLRCOM
,VCOM.VLRCOM AS COMLIQ
,NVL(CAB.AD_VLROUTROSFRETE,0) AS FRETE_OUTROS
,CAB.VLROUTROS as VLROUTROS
,FIN.VLRDESDOB
,FIN.VLRBAIXA
/*,(FIN.VLRDESDOB/(CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)))*100 AS PERCPARCELA
,(FIN.VLRBAIXA/(CAB.VLRNOTA+CAB.VLROUTROS + NVL(CAB.AD_VLROUTROSFRETE,0)))*100 AS PERCRECEBIDO*/
,(FIN.VLRDESDOB/(SELECT SUM(VLRDESDOB) FROM TGFFIN F WHERE F.NUNOTA =FIN.NUNOTA AND F.CODEMP = FIN.CODEMP))*100 AS PERCPARCELA
,(FIN.VLRBAIXA/(SELECT SUM(VLRDESDOB) FROM TGFFIN F WHERE F.NUNOTA =FIN.NUNOTA AND F.CODEMP = FIN.CODEMP))*100 AS PERCRECEBIDO 
,VCOM.NUNOTAORIG
,FIN.NUFIN AS FINNUFIN
,(SELECT VEN.APELIDO
  FROM TGFVEN VEN
  WHERE VEN.CODVEND = VCOM.CODVEND) AS REPRESENTANTE
,(SELECT RTRIM(LTRIM(CID.NOMECID))||'-'||RTRIM(LTRIM((UF.UF)))
  FROM TSIUFS UF,TSICID CID, TGFPAR PAR2
  WHERE UF.CODUF = CID.UF AND CID.CODCID = PAR2.CODCID AND PAR2.CODPARC = FIN.CODPARC) AS ENDERECO
,FIN.CODEMP
,FIN.DESDOBRAMENTO
,VCOM.CODVEND
,FIN.CODPARC
,PAR.NOMEPARC
,FIN.NUMNOTA
,FIN.DTVENC
,FIN.DHBAIXA
,CAB.DTFATUR
,0 AS PERCCOM
,VCOM.NUFECHAMENTO
,VCOM.NUNOTAORIG AS NUNOTA
, CASE WHEN VCOM.NUFECHAMENTO=0 AND FIN.VLRBAIXA=0 THEN 'YELLOW' WHEN VCOM.NUFECHAMENTO=0 AND FIN.VLRBAIXA>0 THEN '98FB98' WHEN VCOM.NUFECHAMENTO>0 THEN '#00CED1' END BKCOLOR
FROM TGFCOM VCOM , TGFCAB CAB , TGFFIN FIN, TGFPAR PAR
WHERE CASE WHEN :P_TIPDATA = 'B' THEN FIN.DHBAIXA ELSE FIN.DTNEG END BETWEEN :P_PER.INI AND :P_PER.FIN
AND (VCOM.CODVEND = :P_CODVEND OR :P_CODVEND IS NULL )
AND VCOM.NUFINORIG = FIN.NUFIN
AND VCOM.NUNOTAORIG = CAB.NUNOTA
AND FIN.CODPARC = PAR.CODPARC
AND (FIN.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
/*AND VCOM.POSICAO_QUERY IN
(3,4) --PELA BAIXA E RENEGOCIADA */
ORDER BY 25 DESC, 15, 8 DESC
