SELECT TIPO, ENTSAI, CODEMP, NUNOTA, NUMNOTA, DTNEG, DTENTSAI, CODTIPOPER, 
	   CODPARC, NOMEPARC, IDENTINSCESTAD, CHAVENFE, SEQUENCIA, CODPROD, DESCRPROD, ORIGPROD,
	   QTDNEG, VLRUNIT, VLRTOT, CODCFO,  CODTRIB, CLASSIFICMS,
SUM(BASEICMS) AS BASEICMS, 
SUM(VLRICMS) AS VLRICMS, 
SUM(BASEICMS) AS BASEIPI, 
SUM(VLRICMS) AS VLRIPI,
SUM(BASERED_PIS) AS BASERED_PIS, 
SUM(BASERED_COFINS) AS BASERED_COFINS, 
SUM(VALOR_PIS) AS VALOR_PIS, 
SUM(VALOR_COFINS) AS VALOR_COFINS,
MAX(CST_PIS) AS CST_PIS,
MAX(CST_COFINS) AS CST_COFINS,
MAX(ALIQUOTA_PIS) AS ALIQUOTA_PIS,
MAX(ALIQUOTA_COFINS) AS ALIQUOTA_COFINS,
SUM(FRETE_ITEM) AS FRETE_ITEM
FROM
(
--A170 representação de itens de nota de serviço filtrada através do A100 que é a nota de serviço
SELECT
  'A170' AS TIPO
  ,LIS.ENTSAI, LIS.SEQUENCIA
  ,CAB.CODEMP, CAB.NUNOTA, CAB.NUMNOTA, CAB.DTNEG, CAB.DTENTSAI, CAB.CODTIPOPER, CAB.VLRNOTA, CAB.CHAVENFE
  ,PAR.CODPARC, PAR.NOMEPARC, PAR.IDENTINSCESTAD
  ,CASE WHEN PAR.CLASSIFICMS = 'R' THEN 'Revendedor' 
		WHEN PAR.CLASSIFICMS = 'C' THEN 'Consumidor Final'
		WHEN PAR.CLASSIFICMS = 'X' THEN 'Consumidor Contribuinte'
		ELSE '-----' END AS CLASSIFICMS
  ,ITE.CODPROD, PRO.DESCRPROD,PRO.ORIGPROD, ITE.QTDNEG, ITE.VLRUNIT, ITE.CODCFO,  ITE.CODTRIB
  ,(CASE WHEN DIN.CODINC=0 THEN ITE.VLRTOT ELSE 0 END) AS VLRTOT
  --ICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN DIN.BASE ELSE 0 END AS BASEICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRICMS
  --IPI
  ,CASE WHEN DIN.CODIMP = 3 THEN DIN.BASE ELSE 0 END AS BASEIPI
  ,CASE WHEN DIN.CODIMP = 3 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRIPI
  --PIS/COFINS  
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.BASERED ELSE 0 END AS BASERED_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.BASERED ELSE 0 END AS BASERED_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE  0 END AS VALOR_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VALOR_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.CST ELSE 0 END AS CST_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.CST ELSE 0 END AS CST_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_COFINS
  ,CASE WHEN DIN.CODIMP = 1 AND DIN.CODINC = 3 THEN DIN.VALOR ELSE 0 END AS FRETE_ITEM
  
FROM TGFLIS LIS
  ,TGFITE ITE
  ,TGFDIN DIN
  , TGFCAB CAB
  , TGFPAR PAR
  , TGFPRO PRO
WHERE EXISTS(
      (SELECT
        DISTINCT
        LIS1.NUNOTA
      FROM
        TGFLIS LIS1
      WHERE (LIS.DTMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
        AND (LIS1.DTMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)
        AND (LIS1.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
        AND LIS1.ORIGEM <> 'F'
        AND ((LIS1.ORIGEM = 'E' AND LIS1.ENTSAI = 'E' AND
               EXISTS (SELECT 1 FROM TGFDIN D1 WHERE D1.NUNOTA = LIS1.NUNOTA AND D1.CODIMP IN (6,7)
                       AND (((D1.VALOR <> 0 OR NVL(D1.VLRCRED,0) <> 0) AND
                             D1.CST IN (0,50,51,52,53,54,55,56,60,61,62,63,64,65,66))
                            /*CSTSEMCREDEFDCT OR D1.CST IN (70,71,72,73,74,75) CSTSEMCREDEFDCT*/))) OR
              (LIS1.ORIGEM = 'E' AND LIS1.ENTSAI = 'S' AND
               EXISTS (SELECT 1 FROM TGFDIN WHERE NUNOTA = LIS1.NUNOTA AND CODIMP IN (1,6,7)))
            )
        AND NOT EXISTS (SELECT LIV.NUNOTA FROM TGFLIV LIV WHERE LIV.NUNOTA = LIS1.NUNOTA AND LIV.ORIGEM = LIS1.ORIGEM)
        AND LIS1.NUNOTA = LIS.NUNOTA
      )
  )
  AND ITE.NUNOTA = LIS.NUNOTA
  AND (LIS.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
  AND ITE.SEQUENCIA = LIS.SEQUENCIA
  AND CAB.NUNOTA = ITE.NUNOTA
  AND ITE.CODPROD = PRO.CODPROD
  AND CAB.CODPARC = PAR.CODPARC
  AND LIS.ORIGEM = 'E'
  AND LIS.NUNOTA = DIN.NUNOTA
  AND LIS.SEQUENCIA = DIN.SEQUENCIA
  AND DIN.CODIMP IN (1,6,7)
   AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
   AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
   AND ITE.CODCFO >= :P_CODCFOPINI
   AND ITE.CODCFO <= :P_CODCFOPFIN
   AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
  
UNION

--C170 (itens) é encontrado através do C100 que é o resultado das notas
SELECT
  'C170' AS TIPO
  ,LIV.ENTSAI, LIV.SEQUENCIA
  ,CAB.CODEMP, CAB.NUNOTA, CAB.NUMNOTA, CAB.DTNEG, CAB.DTENTSAI, CAB.CODTIPOPER, CAB.VLRNOTA, CAB.CHAVENFE
  ,PAR.CODPARC, PAR.NOMEPARC, PAR.IDENTINSCESTAD
  ,CASE WHEN PAR.CLASSIFICMS = 'R' THEN 'Revendedor' 
		WHEN PAR.CLASSIFICMS = 'C' THEN 'Consumidor Final'
		WHEN PAR.CLASSIFICMS = 'X' THEN 'Consumidor Contribuinte'
		ELSE '-----' END AS CLASSIFICMS
  ,ITE.CODPROD, PRO.DESCRPROD,PRO.ORIGPROD, ITE.QTDNEG, ITE.VLRUNIT, ITE.CODCFO,  ITE.CODTRIB
  ,(CASE WHEN DIN.CODINC= 0 THEN CASE WHEN NVL(CAB.VLRLIQITEMNFE,'N')='N' THEN ITE.VLRTOT ELSE CASE WHEN NVL(ITE.CODMOTDESONERAICMS, 0) != 0 THEN ITE.VLRTOT - ITE.VLRDESC ELSE ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED END END ELSE 0 END) AS VLRTOT
  --ICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN DIN.BASE ELSE 0 END AS BASEICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRICMS
  --IPI
  ,CASE WHEN DIN.CODIMP = 3 THEN DIN.BASE ELSE 0 END AS BASEIPI
  ,CASE WHEN DIN.CODIMP = 3 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRIPI
  --PIS/COFINS  
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.BASERED ELSE 0 END AS BASERED_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.BASERED ELSE 0 END AS BASERED_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE  0 END AS VALOR_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VALOR_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.CST ELSE 0 END AS CST_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.CST ELSE 0 END AS CST_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_COFINS
  ,CASE WHEN DIN.CODIMP = 1 AND DIN.CODINC = 3 THEN DIN.BASE ELSE 0 END AS FRETE_ITEM
  
FROM TGFLIV LIV
  ,TGFITE ITE
  ,TGFDIN DIN
  ,TGFCAB CAB
  ,TGFPRO PRO
  ,TGFPAR PAR
WHERE EXISTS(
    SELECT 1
FROM(
  SELECT
    DISTINCT
    LIV.ENTSAI
  , LIV.NUNOTA
  , LIV.ORIGEM
  , LIV.CODEMP
  , CAB1.CODTIPOPER
  , NVL(CASE WHEN LIV.ORIGEM IN ('E', 'A') THEN CAB1.STATUSNFE
                   ELSE(SELECT CAB2.STATUSNFE
                      FROM TGFCAB CAB2
                        WHERE CAB2.NUNOTA = ABS(LIV.NUNOTA)
                        AND CAB2.STATUSNFE = 'D')
               END, 'N') AS STATUSNFE
  FROM TGFLIV LIV
       LEFT JOIN TGFCAB CAB1 ON LIV.ORIGEM IN ('E','A') AND LIV.NUNOTA = CAB1.NUNOTA
       LEFT JOIN TGFTPV TPV ON CAB1.CODTIPVENDA = TPV.CODTIPVENDA AND CAB1.DHTIPVENDA = TPV.DHALTER
       LEFT JOIN TGFTOP TPO ON CAB1.CODTIPOPER = TPO.CODTIPOPER AND CAB1.DHTIPOPER = TPO.DHALTER
     , TGFRGM RGM
  WHERE (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
    AND (RGM.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
    AND ('01/01/2021' BETWEEN RGM.DTINIREGIME AND NVL(RGM.DTFIMREGIME,SYSDATE))
    AND (LIV.DHMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
    AND (LIV.DHMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)    
    AND LIV.CODMODDOC IN (1, 4, 55, 65, 901)
    AND /* PREOCUPAR COM C100,C190 */
        (LIV.ORIGEM = 'E'
         AND LIV.ENTSAI = 'E'
         AND CAB1.TIPMOV <> 'D'
         AND EXISTS(SELECT 1
                    FROM TGFDIN D1
                    WHERE D1.NUNOTA = LIV.NUNOTA
                    AND D1.SEQUENCIA = LIV.SEQUENCIA
                    AND D1.CODIMP IN (6,7)
                    AND (((D1.VALOR <> 0 OR NVL(D1.VLRCRED,0) <> 0)
                      AND D1.CST IN (0,50,51,52,53,54,55,56,60,61,62,63,64,65,66))
                      OR ((SELECT T.LOGICO AS LOGICO
                             FROM TSIPAR T
                             WHERE T.CHAVE = 'CSTSEMCREDEFDCT') = 'S'
                            AND D1.CST IN (70,71,72,73,74,75)))
        ) OR
        (LIV.ORIGEM = 'E'
         AND LIV.ENTSAI = 'E'
         AND CAB1.TIPMOV = 'D'
         AND LIV.CODCFO IN (1201,1202,1203,1204,1410,1411,1660,1661,1662,2201,2202,2203,2204,2410,2411,2660,2661,2662,3201,3202,3211,3503,3553)
         AND EXISTS(SELECT 1
                    FROM TGFDIN D1
                    WHERE D1.NUNOTA = LIV.NUNOTA
                    AND D1.SEQUENCIA = LIV.SEQUENCIA
                    AND D1.CODIMP IN (1,6,7)
                    AND (((D1.VALOR <> 0 OR NVL(D1.VLRCRED,0) <> 0)
                       AND ((RGM.CODINCTRIB IN (1,3) AND D1.CST IN (0,50,51,52,53,54,55,56,60,61,62,63,64,65,66)) OR
                            (RGM.CODINCTRIB IN (2,3) AND D1.CST IN (98,99))))
                           OR ((SELECT T.LOGICO AS LOGICO
                             FROM TSIPAR T
                             WHERE T.CHAVE = 'CSTSEMCREDEFDCT') = 'S'
                            AND RGM.CODINCTRIB IN (1,3) AND D1.CST IN (70,71,72,73,74,75))))
         ) OR /* PREOCUPAR COM C100,C180,C190 */
		(LIV.ORIGEM = 'E'
		 AND LIV.ENTSAI = 'S'
		 AND CAB1.TIPMOV <> 'E'
		 AND EXISTS(SELECT 1
					FROM TGFDIN D2
					WHERE D2.NUNOTA = LIV.NUNOTA
					AND D2.SEQUENCIA = LIV.SEQUENCIA
					AND D2.CODIMP IN (6,7)
					AND (D2.CST <> 49 OR LIV.CODCFO = 5927))
		 ) OR
		 (LIV.ORIGEM = 'E'
		  AND LIV.ENTSAI = 'S'
		  AND CAB1.TIPMOV = 'E'
		  AND LIV.CODCFO IN (5201,5202,5205,5206,5207,5210,5410,5411,5660,5661,5662,6201,6202,6205,6206,6207,6210,6410,6411,6660,6661,6662,7201,7202,7205,7206,7207,7210,7211)
		  AND EXISTS(SELECT 1
					 FROM TGFDIN D2
					 WHERE D2.NUNOTA = LIV.NUNOTA
					 AND D2.SEQUENCIA = LIV.SEQUENCIA
					 AND D2.CODIMP IN (6,7)
					 AND D2.CST = 49)
		  ) OR
         (LIV.ORIGEM = 'A'
          AND EXISTS(SELECT 1
                     FROM TGFDIN D3
                     WHERE D3.NUNOTA = LIV.NUNOTA
                     AND D3.SEQUENCIA = LIV.SEQUENCIA
                     AND D3.CODIMP IN (1,6,7)
                     AND D3.CST <> 49
                     AND (LIV.ENTSAI = 'S' OR D3.VALOR <> 0 OR NVL(D3.VLRCRED,0) <> 0))
          ) OR
         (LIV.ORIGEM = 'C')
    )) C100
WHERE
(C100.STATUSNFE <> 'D' OR
C100.ORIGEM <> 'C' OR
C100.CODTIPOPER <> NVL(NVL((SELECT EMP.CODTIPOPERACOMP
                         FROM TGFEMP EMP
                         WHERE EMP.CODEMP = C100.CODEMP),
                         (SELECT INTEIRO
                         FROM TSIPAR
                         WHERE CHAVE = 'TOPIMPFISCAL')
                        )
                ,-1)
 ) AND C100.NUNOTA = LIV.NUNOTA)
AND ITE.NUNOTA = LIV.NUNOTA
AND ITE.NUNOTA = DIN.NUNOTA
AND ITE.SEQUENCIA = DIN.SEQUENCIA
AND ITE.CODPROD = PRO.CODPROD
AND CAB.CODPARC = PAR.CODPARC
AND DIN.CODIMP IN (1,6,7)
AND (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
AND ITE.SEQUENCIA = LIV.SEQUENCIA
AND LIV.ORIGEM IN ('E','A')
AND ITE.CODPROD = PRO.CODPROD
AND (LIV.DHMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
AND (LIV.DHMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)
AND CAB.NUNOTA = ITE.NUNOTA
AND CAB.NUNOTA = LIV.NUNOTA
AND CAB.NUNOTA = DIN.NUNOTA
   AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
   AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
   AND ITE.CODCFO >= :P_CODCFOPINI
   AND ITE.CODCFO <= :P_CODCFOPFIN
   AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL) 
   
  
--NOTAS FISCAIS FRETES 
UNION 

SELECT 'D100' AS TIPO
	    ,LIV.ENTSAI, LIV.SEQUENCIA
	    ,CAB.CODEMP, CAB.NUNOTA, CAB.NUMNOTA, CAB.DTNEG, CAB.DTENTSAI, CAB.CODTIPOPER, CAB.VLRNOTA, CAB.CHAVENFE
        ,PAR.CODPARC, PAR.NOMEPARC, PAR.IDENTINSCESTAD
		,CASE WHEN PAR.CLASSIFICMS = 'R' THEN 'Revendedor' 
			  WHEN PAR.CLASSIFICMS = 'C' THEN 'Consumidor Final'
			  WHEN PAR.CLASSIFICMS = 'X' THEN 'Consumidor Contribuinte'
			  ELSE '-----' END AS CLASSIFICMS
        ,ITE.CODPROD, PRO.DESCRPROD,PRO.ORIGPROD, ITE.QTDNEG, ITE.VLRUNIT, ITE.CODCFO, ITE.CODTRIB    
  ,(CASE WHEN DIN.CODINC= 0 THEN ITE.VLRTOT ELSE 0 END) AS VLRTOT
  --ICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN DIN.BASE ELSE 0 END AS BASEICMS
  ,CASE WHEN DIN.CODIMP = 1 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRICMS
  --IPI
  ,CASE WHEN DIN.CODIMP = 3 THEN DIN.BASE ELSE 0 END AS BASEIPI
  ,CASE WHEN DIN.CODIMP = 3 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VLRIPI
  --PIS/COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.BASERED ELSE 0 END AS BASERED_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.BASERED ELSE 0 END AS BASERED_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE  0 END AS VALOR_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN CASE WHEN DIN.VLRCRED IS NOT NULL AND DIN.VLRCRED <> 0 THEN DIN.VLRCRED ELSE DIN.VALOR END ELSE 0 END AS VALOR_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.CST ELSE 0 END AS CST_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.CST ELSE 0 END AS CST_COFINS
  ,CASE WHEN DIN.CODIMP = 6 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_PIS
  ,CASE WHEN DIN.CODIMP = 7 THEN DIN.ALIQUOTA ELSE 0 END AS ALIQUOTA_COFINS
  ,CASE WHEN DIN.CODIMP = 1 AND DIN.CODINC = 3 THEN DIN.BASE ELSE 0 END AS FRETE_ITEM   
	    
  FROM TGFLIV LIV
		INNER JOIN TGFCAB CAB    ON LIV.NUNOTA = CAB.NUNOTA AND LIV.ORIGEM IN ('E','A')
        INNER JOIN TGFTOP TPOCAB ON LIV.ORIGEM IN ('E','A') AND CAB.CODTIPOPER = TPOCAB.CODTIPOPER AND CAB.DHTIPOPER = TPOCAB.DHALTER
        INNER JOIN TGFITE ITE    ON LIV.NUNOTA = ITE.NUNOTA AND LIV.SEQUENCIA = ITE.SEQUENCIA,
        TSIEMP EMP, TGFDIN DIN, TGFPAR PAR, TGFPRO PRO
		
	WHERE ITE.NUNOTA = DIN.NUNOTA
	  AND ITE.SEQUENCIA = DIN.SEQUENCIA
      AND CAB.CODPARC = PAR.CODPARC
      AND ITE.CODPROD = PRO.CODPROD
	  AND DIN.CODIMP IN (1, 6, 7)
	  AND LIV.CODEMP = EMP.CODEMP
	  AND (LIV.DHMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
	  AND (LIV.DHMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)
	  AND (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
	  AND LIV.ENTSAI = 'E'
	  AND LIV.CODMODDOC IN (7, 8, 9, 10, 11, 26, 27, 57, 902)
	  AND LIV.ORIGEM <> 'D'
	  AND ((LIV.ORIGEM IN ('E','A') AND LIV.ENTSAI = 'E' AND CAB.TIPMOV <> 'D'
	         AND EXISTS (SELECT 1
	                     FROM TGFDIN D1
                         WHERE D1.NUNOTA = LIV.NUNOTA
	                     AND D1.SEQUENCIA = LIV.SEQUENCIA
	                     AND D1.CODIMP IN (1,6,7)
	                     AND (D1.VALOR <> 0 OR NVL(D1.VLRCRED,0) <> 0)
	                     AND D1.CST IN (0,50,51,52,53,54,55,56,60,61,62,63,64,65,66)
                         )
            ) 
            OR (LIV.ORIGEM = 'C')
	       )
	  AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
	  AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
	  AND ITE.CODCFO >= :P_CODCFOPINI
	  AND ITE.CODCFO <= :P_CODCFOPFIN
	  AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)

   
) V 

GROUP BY TIPO, ENTSAI, CODEMP, NUNOTA, NUMNOTA, DTNEG, DTENTSAI, CODTIPOPER, 
         CODPARC, NOMEPARC, IDENTINSCESTAD, CHAVENFE, SEQUENCIA, CODPROD, DESCRPROD, ORIGPROD, 
         QTDNEG, VLRUNIT, VLRTOT, CODCFO,  CODTRIB, CLASSIFICMS

ORDER BY TIPO, CODEMP, DTENTSAI, DTNEG, NUMNOTA, SEQUENCIA, ALIQUOTA_PIS, ALIQUOTA_COFINS
