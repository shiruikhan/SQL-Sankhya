WITH BASE AS (
  SELECT CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.TIPMOV,
	CAB.CODEMP,
	CAB.DTNEG,
	PAR.CODPARC,
	PAR.NOMEPARC,
	PAR.RAZAOSOCIAL,
	PAR.CGC_CPF,
	UFS.UF,
	UFS.DESCRICAO,
	(SELECT MAX(ITE.CODCFO) FROM TGFITE ITE WHERE ITE.NUNOTA = CAB.NUNOTA) AS COFCFO,
	CAB.VLRNOTA,
	CAB.VLRICMSDIFALDEST,
	CAB.VLRICMSDIFALREM,
	CAB.VLRICMSFCP,
	CAB.VLRICMS,
	AEM.GRUPOICMS,
	MAX((SELECT IE.INSCRICAO
	  FROM TSIIUF IE
	WHERE IE.CODUF = UFS.CODUF
	  AND IE.CODEMP = CAB.CODEMP)) AS INSCRICAO,
	(SELECT SUM(FIN.VLRDESDOB)
	  FROM TGFFIN FIN
	WHERE FIN.NUNOTA = CAB.NUNOTA
	  AND FIN.CODTIPTIT = 35) AS VLRDESDOBIMPOSTO
  FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
	INNER JOIN TSICID CID ON CID.CODCID = PAR.CODCID
	INNER JOIN TSIUFS UFS ON UFS.CODUF = CID.UF
	LEFT JOIN TGFPAEM AEM ON AEM.CODPARC = PAR.CODPARC AND AEM.CODEMP = CAB.CODEMP
  WHERE CAB.STATUSNOTA = 'L'
    AND CAB.STATUSNFE = 'A'
    AND (trunc(CAB.DTFATUR) >= :PERIODO.INI AND TRUNC(CAB.DTFATUR) <= :PERIODO.FIN)
    AND ((CAB.CODEMP = :EMPRESA) OR (:EMPRESA IS NULL))
    AND (CAB.TIPMOV = :TIPMOV)
    AND ((CID.CODCID = :CIDADE) OR (:CIDADE IS NULL))
    AND ((UFS.CODUF = :UF) OR (:UF IS NULL))
    AND ((CAB.NUMNOTA = :NOTA) OR (:NOTA IS NULL))
	AND (CASE WHEN :P_TIPOIMPOSTO = 'D' THEN CAB.VLRICMSDIFALDEST WHEN :P_TIPOIMPOSTO = 'R' THEN CAB.VLRICMSDIFALREM END) > 0
  GROUP BY CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.TIPMOV,
	CAB.CODEMP,
	CAB.DTNEG,
	PAR.CODPARC,
	PAR.NOMEPARC,
	PAR.RAZAOSOCIAL,
	PAR.CGC_CPF,
	UFS.UF,
	UFS.DESCRICAO,
	CAB.VLRNOTA,
	CAB.VLRICMSDIFALDEST,
	CAB.VLRICMSDIFALREM,
	CAB.VLRICMSFCP,
	CAB.VLRICMS,
	AEM.GRUPOICMS
)
SELECT BASE.*,
	CASE
	  WHEN INSCRICAO IS NULL THEN
	    CASE WHEN ROUND(NVL(VLRDESDOBIMPOSTO,0), 2) = ROUND(NVL(VLRICMSDIFALDEST,0) + NVL(VLRICMSFCP,0), 2)
	         THEN '#E8F5E9' ELSE '#FFEBEE' END
	  ELSE
	    CASE WHEN NVL(VLRDESDOBIMPOSTO,0) = 0
	         THEN '#E8F5E9' ELSE '#FFEBEE' END
	END AS BKCOLOR
FROM BASE
ORDER BY NUMNOTA