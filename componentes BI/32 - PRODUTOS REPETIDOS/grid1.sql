SELECT AD_CODANTERIOR, CODPROD, DESCRPROD, G.CODGRUPOPROD, DECODE(USOPROD,'M','Matéria Prima','C','Consumo','S','Serviço','V','Venda Fabricação',USOPROD) AS USADOCOMO, G.DESCRGRUPOPROD, P.ATIVO,
(SELECT COUNT(DISTINCT CODPRODPA) FROM TPRLMP MP WHERE MP.CODPRODMP = P.CODPROD) AS TOT
FROM TGFPRO P INNER JOIN TGFGRU G ON (P.CODGRUPOPROD = G.CODGRUPOPROD) WHERE AD_CODANTERIOR IN (
SELECT AD_CODANTERIOR FROM (
SELECT AD_CODANTERIOR, COUNT(*) FROM TGFPRO WHERE USOPROD <> 'S'
GROUP BY AD_CODANTERIOR
HAVING COUNT(*) > 1) D
)
ORDER BY 1,2
