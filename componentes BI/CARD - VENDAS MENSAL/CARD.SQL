SELECT
    CASE
        WHEN G.CODGRUPOPROD IN (3250001, 3250002, 3250003, 3161001, 31161002, 3180001) THEN G.DESCRGRUPOPROD
        WHEN G.CODGRUPAI IN (3160000, 3170000) THEN 'CARREGADOR'
        WHEN G.CODGRUPAI = 3490000 THEN PAI.DESCRGRUPOPROD
        ELSE G.DESCRGRUPOPROD
    END AS GRUPO,
    SUM(I.QTDNEG) AS VENDAS,
    CASE
        WHEN G.CODGRUPOPROD IN (3250001, 3250002, 3250003, 3161001, 31161002, 3180001) THEN
            CASE G.CODGRUPOPROD
                WHEN 3250001 THEN 7500
                WHEN 3250002 THEN 400
                WHEN 3250003 THEN 100
                WHEN 3161001 THEN 280
                WHEN 31161002 THEN 300
                WHEN 3180001 THEN 200
            END
        WHEN G.CODGRUPAI = 3490000 THEN 50
        WHEN G.CODGRUPAI  IN (3160000, 3170000) THEN 200
        ELSE 0
    END AS META
FROM TGFCAB C
    INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
    INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
    INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
    LEFT JOIN TGFGRU PAI ON G.CODGRUPAI = PAI.CODGRUPOPROD
WHERE C.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
    AND C.TIPMOV = 'V'
    AND TRUNC(C.DTNEG, 'MM') = TRUNC(SYSDATE, 'MM')
    AND TRUNC(C.DTNEG, 'YYYY') = TRUNC(SYSDATE, 'YYYY')
    AND P.USOPROD = 'V'
    AND (
        G.CODGRUPOPROD IN (3250001, 3250002, 3250003, 3161001, 31161002, 3180001)
        OR
        G.CODGRUPAI IN (3490000, 3160000, 3170000)
    )
GROUP BY
    CASE
        WHEN G.CODGRUPOPROD IN (3250001, 3250002, 3250003, 3161001, 31161002, 3180001) THEN G.DESCRGRUPOPROD
        WHEN G.CODGRUPAI IN (3160000, 3170000) THEN 'CARREGADOR'
        WHEN G.CODGRUPAI = 3490000 THEN PAI.DESCRGRUPOPROD
        ELSE G.DESCRGRUPOPROD
    END,
    CASE
        WHEN G.CODGRUPOPROD IN (3250001, 3250002, 3250003, 3161001, 31161002, 3180001) THEN
            CASE G.CODGRUPOPROD
                WHEN 3250001 THEN 7500
                WHEN 3250002 THEN 400
                WHEN 3250003 THEN 100
                WHEN 3161001 THEN 280
                WHEN 31161002 THEN 300
                WHEN 3180001 THEN 200
            END
        WHEN G.CODGRUPAI = 3490000 THEN 50
        WHEN G.CODGRUPAI IN (3160000, 3170000) THEN 200
        ELSE 0
    END
ORDER BY
    GRUPO