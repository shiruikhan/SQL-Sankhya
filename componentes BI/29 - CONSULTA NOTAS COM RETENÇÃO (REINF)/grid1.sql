SELECT EMPRESA, 
NUNOTA,
NUMNOTA,
DTNEG, 
DTENTSAI, 
CODPARC,
RAZAOSOCIAL,
SERVICO, 
DESCRPROD,
CODCFO, 
VLRNOTA,
SUM (VLR_TOT_SERV) AS VLR_TOT_SERV, 
SUM (BASE_INSS) AS BASE_INSS,
SUM (VALOR_INSS) AS VALOR_INSS,
ALIQ_INSS, 
EMP_ATIVA,
NF_TEM_SERV,
CLASS_CESSAO_MB_SERV,
TIPMOV_CPA,
ATUAL_LIV_ENT,
NF_CONFIRMADA,
CNPJ_VALIDO,
INSS_CALC_OUT_IMP
FROM 
(
SELECT CAB.CODEMP AS "EMPRESA", 
CAB.NUNOTA AS "NUNOTA",
CAB.NUMNOTA AS "NUMNOTA",
CAB.DTNEG, 
CAB.DTENTSAI, 
CAB.CODPARC,
PAR.RAZAOSOCIAL,
ITE.CODPROD AS "SERVICO", 
PRO.DESCRPROD, 
ITE.CODCFO, 
CAB.VLRNOTA,
ITE.VLRTOT AS VLR_TOT_SERV,
IMN.BASE AS BASE_INSS,
IMN.VALOR AS VALOR_INSS,
IMN.ALIQUOTA AS ALIQ_INSS, 

(SELECT EMP.ATIVO FROM TGFEMP EMP WHERE EMP.CODEMP=ITE.CODEMP) AS "EMP_ATIVA"
, CASE WHEN ITE.USOPROD='S' THEN 'S' ELSE 'N' END AS "NF_TEM_SERV"
, CASE WHEN (SELECT PRO.CLASSIFCESSAOOBRA FROM TGFPRO PRO WHERE PRO.CODPROD=ITE.CODPROD) IS NULL THEN 'N' ELSE 'S' END AS "CLASS_CESSAO_MB_SERV"
, CASE WHEN (SELECT TPO.TIPMOV FROM TGFTOP TPO, TGFCAB CAB WHERE TPO.CODTIPOPER=CAB.CODTIPOPER AND TPO.DHALTER=CAB.DHTIPOPER AND CAB.NUNOTA=ITE.NUNOTA) = 'C' THEN 'S' ELSE 'N' END AS "TIPMOV_CPA"
, CASE WHEN (SELECT TPO.ATUALLIVISS FROM TGFTOP TPO, TGFCAB CAB WHERE TPO.CODTIPOPER=CAB.CODTIPOPER AND TPO.DHALTER=CAB.DHTIPOPER AND CAB.NUNOTA=ITE.NUNOTA) = 'E' THEN 'S' ELSE 'N' END AS "ATUAL_LIV_ENT" 
, CASE WHEN (SELECT CAB.STATUSNOTA FROM TGFCAB CAB WHERE CAB.NUNOTA=ITE.NUNOTA) = 'L' THEN 'S' ELSE 'N' END AS "NF_CONFIRMADA"
, CASE WHEN (SELECT LENGTH(PAR.CGC_CPF) FROM TGFPAR PAR WHERE PAR.CODPARC=CAB.CODPARC) = 14 THEN 'S' ELSE 'N' END AS "CNPJ_VALIDO"

, CASE WHEN 
(SELECT NVL(1,0) FROM TGFIMN IMN  
WHERE IMN.NUNOTA = ITE.NUNOTA
AND IMN.SEQUENCIA = ITE.SEQUENCIA
AND IMN.TIPOIMPOSTO = 5 
AND (IMN.TIPIMP = -1 OR (IMN.TIPIMP = 0 AND EXISTS(SELECT 1 FROM TSIPAR WHERE CHAVE = 'GERIMPINCREINF' AND LOGICO = 'S'))) 
AND ((ROUND(NVL(IMN.ALIQUOTA, 0), 2) - ROUND(NVL(IMN.PERCINSSESPECIAL, 0), 2)) IN (3.5, 11))) = 1 THEN 'S' ELSE 'N' END AS "INSS_CALC_OUT_IMP"

FROM TGFCAB CAB, TGFITE ITE, TGFIMN IMN, TGFPAR PAR, TGFPRO PRO
WHERE CAB.NUNOTA=ITE.NUNOTA
AND ITE.NUNOTA = IMN.NUNOTA 
AND ITE.SEQUENCIA = IMN.SEQUENCIA
AND CAB.CODPARC = PAR.CODPARC
AND ITE.CODPROD = PRO.CODPROD
AND IMN.CODIMP IN (7,8)
AND ITE.CODCFO IN (1933,2933)
AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
AND (CAB.CODPARC = :P_CODPARC OR :P_CODPARC IS NULL)
AND (CAB.DTENTSAI >= :P_DTENTSAI.INI or :P_DTENTSAI.INI is null)
AND (CAB.DTENTSAI <= :P_DTENTSAI.FIN or :P_DTENTSAI.FIN is null)
AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)

) V

GROUP BY EMPRESA, NUNOTA, NUMNOTA, DTNEG, DTENTSAI, CODPARC, RAZAOSOCIAL, SERVICO, DESCRPROD, 
		CODCFO, VLRNOTA, ALIQ_INSS, EMP_ATIVA,NF_TEM_SERV, CLASS_CESSAO_MB_SERV, TIPMOV_CPA, 
		ATUAL_LIV_ENT, NF_CONFIRMADA, CNPJ_VALIDO, INSS_CALC_OUT_IMP
ORDER BY EMPRESA, DTNEG, DTENTSAI, NUMNOTA, CODPARC, SERVICO, CODCFO
