SELECT CAB.NUMNOTA,
	CAB.NUNOTA,
	CAB.DTNEG,
	CAB.CODPARC || ' - ' || PAR.RAZAOSOCIAL AS PARCEIRO,
	CAB.VLRNOTA + NVL(CAB.VLROUTROS,0) + NVL(AD_VLROUTROSFRETE,0) AS VALORTOTAL,
	(CASE WHEN CAB.CODEMP = 1 THEN '#B2FFFF' ELSE '#DFD2C4' END) AS BKCOLOR
FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
WHERE CAB.DTNEG >= :P_PERIODO.INI
	AND CAB.DTNEG <= :P_PERIODO.FIN
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
	AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124)
	AND (:P_CODVEND IS NULL OR CAB.CODVEND = :P_CODVEND)
ORDER BY CAB.NUMNOTA
