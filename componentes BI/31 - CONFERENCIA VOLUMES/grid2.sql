SELECT I.SEQUENCIA, I.CODPROD, PRO.DESCRPROD, I.QTDNEG, I.PESO, 
I.QTDNEG * I.PESO AS PESOTOT, 
I.QTDNEG * I.VOLUME AS VOLUME
FROM AD_VOLPED CAB, AD_VOLPEDITE I , TGFPRO PRO
WHERE CAB.NUNOTA = I.NUNOTA
 AND I.CODPROD = PRO.CODPROD
 AND CAB.NUNOTA = :P_NUNOTA
 AND I.SEQ = CAB.SEQ
 AND CAB.CODPROD = :A_CODPROD
 AND CAB.FRACIONADO = :A_FRACIONADO
