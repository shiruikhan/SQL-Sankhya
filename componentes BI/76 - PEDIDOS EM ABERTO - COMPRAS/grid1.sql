SELECT ITE.NUNOTA,
	CAB.NUMNOTA AS NUMPEDIDO,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	CAB.DTNEG AS EMISSAO,
	CAB.DTPREVENT AS PREVISAO,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	(CASE WHEN ITE.CODVOL = PRO.CODVOL THEN ITE.QTDNEG ELSE (CASE WHEN VOA.DIVIDEMULTIPLICA = 'M' THEN ITE.QTDNEG / VOA.QUANTIDADE ELSE ITE.QTDNEG * VOA.QUANTIDADE END) END) AS QTDNEG,
	(CASE WHEN ITE.CODVOL = PRO.CODVOL THEN ITE.QTDENTREGUE ELSE (CASE WHEN VOA.DIVIDEMULTIPLICA = 'M' THEN ITE.QTDENTREGUE / VOA.QUANTIDADE ELSE ITE.QTDENTREGUE * VOA.QUANTIDADE END) END) AS ENTREGUE,
	(CASE WHEN ITE.CODVOL = PRO.CODVOL THEN ITE.QTDNEG ELSE (CASE WHEN VOA.DIVIDEMULTIPLICA = 'M' THEN ITE.QTDNEG / VOA.QUANTIDADE ELSE ITE.QTDNEG * VOA.QUANTIDADE END) END) - (CASE WHEN ITE.CODVOL = PRO.CODVOL THEN ITE.QTDENTREGUE ELSE (CASE WHEN VOA.DIVIDEMULTIPLICA = 'M' THEN ITE.QTDENTREGUE / VOA.QUANTIDADE ELSE ITE.QTDENTREGUE * VOA.QUANTIDADE END) END) AS PENDENTE,
	CAB.OBSERVACAO
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON (ITE.NUNOTA = CAB.NUNOTA AND CAB.STATUSNOTA = 'L' AND CAB.TIPMOV = 'O' AND CAB.PENDENTE = 'S')
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
	LEFT JOIN TGFVOA VOA ON (ITE.CODPROD = VOA.CODPROD AND ITE.CODVOL = VOA.CODVOL)
WHERE (CAB.DTNEG >= :P_PERIODO.INI AND CAB.DTNEG <= :P_PERIODO.FIN)
	AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND (CAB.CODPARC = :P_CODPARC OR :P_CODPARC IS NULL)
	AND ITE.QTDNEG - ITE.QTDENTREGUE <> 0
	AND ITE.PENDENTE = 'S'
	AND (CAB.CODVEND = :P_CODVEND OR :P_CODVEND IS NULL)
	AND (CAB.DTPREVENT <= :P_DTCORTE OR :P_DTCORTE IS NULL)
ORDER BY CAB.DTNEG, CAB.NUNOTA, CAB.CODPARC
