create or replace PROCEDURE "SPK_TGFNCO_INC" (P_CODUSU NUMBER, P_IDSESSAO VARCHAR2, P_QTDLINHAS NUMBER, P_MENSAGEM OUT VARCHAR2) AS
	PARAM_DESCNCO NUMBER;
	PARAM_CODPROD NUMBER;
	--PARAM_QTDREC NUMBER;
	PARAM_QTDNC NUMBER;
	FIELD_NUNOTA NUMBER;
	
	P_COUNT NUMBER;
	P_FIM NUMBER;
	P_CODPARC NUMBER;
	P_CODPARCT NUMBER;
	P_DTRECEB DATE;
	P_NUMNOTA NUMBER;
	P_DTNCO DATE;
	
	BEGIN
		PARAM_DESCNCO := ACT_INT_PARAM(P_IDSESSAO, 'DESCNCO');
		PARAM_CODPROD := ACT_INT_PARAM(P_IDSESSAO, 'CODPROD');
		--PARAM_QTDREC := ACT_INT_PARAM(P_IDSESSAO, 'QTDREC');
		PARAM_QTDNC := ACT_INT_PARAM(P_IDSESSAO, 'QTDNC');
        
        P_COUNT := 1;
		
		SELECT MAX(NUNCO)+1 INTO P_COUNT FROM AD_TGFNCO;
		
		FOR I IN 1..P_QTDLINHAS
			LOOP
				FIELD_NUNOTA := ACT_INT_FIELD(P_IDSESSAO, I, 'NUNOTA');
				
				SELECT C.CODPARC INTO P_CODPARC FROM TGFCAB C WHERE C.NUNOTA = FIELD_NUNOTA;
				SELECT C.CODPARCTRANSP INTO P_CODPARCT FROM TGFCAB C WHERE C.NUNOTA = FIELD_NUNOTA;
				SELECT C.NUMNOTA INTO P_NUMNOTA FROM TGFCAB C WHERE C.NUNOTA = FIELD_NUNOTA;
				SELECT C.DTENTSAI INTO P_DTRECEB FROM TGFCAB C WHERE C.NUNOTA = FIELD_NUNOTA;
				SELECT SYSDATE INTO P_DTNCO FROM DUAL;
				
				INSERT INTO AD_TGFNCO (NUNCO,NUNOTA,CODUSU,NUMNOTA,DTRECEB,CODPARC,CODPROD,/*QTDREC,*/QTDNC,DTNCO,NCOAPO,TRANSP) 
					VALUES (P_COUNT,FIELD_NUNOTA,P_CODUSU,P_NUMNOTA,P_DTRECEB,P_CODPARC,PARAM_CODPROD/*,PARAM_QTDREC*/,PARAM_QTDNC,P_DTNCO,PARAM_DESCNCO,P_CODPARCT);
				
			END LOOP;
			
			SELECT MAX(NUNCO) INTO P_FIM FROM AD_TGFNCO;
			
			IF P_FIM = P_COUNT THEN 
				P_MENSAGEM := 'Apontamento de Não Conformidade realizado com sucesso e pode ser visualizado na tela de Não Conformidades sobre o Nº ' || P_COUNT;
			ELSE 
				P_MENSAGEM := 'Apontamento não pôde ser incluído, favor tentar novamente e se o erro persistir informar o setor de TI';
			END IF;
	END;