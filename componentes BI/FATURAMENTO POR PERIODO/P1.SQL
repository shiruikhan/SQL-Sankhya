WITH TOTALGERAL AS (
	SELECT SUM(ITE.QTDNEG) AS TOTAL
	FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
	INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
	WHERE TRUNC(CAB.DTNEG) BETWEEN :P_PER.INI AND :P_PER.FIN
		AND CAB.TIPMOV = 'V'
		AND PRO.USOPROD = 'V'
		AND (:P_GRUPO IS NULL OR GRU.CODGRUPOPROD = :P_GRUPO)
		AND (:P_CODEMP IS NULL OR CAB.CODEMP = :P_CODEMP)
		AND (:P_CODVEND IS NULL OR VEN.CODVEND = :P_CODVEND)
		AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
		AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
)
SELECT 
	ITE.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	SUM(ITE.QTDNEG) AS TOTAL,
	PRO.CODGRUPOPROD,
	GRU.DESCRGRUPOPROD,
	(SUM(ITE.QTDNEG) / TG.TOTAL) * 100 AS PARTE,
    (CASE WHEN PRO.AD_LINHA = 1 THEN 'Linha 1' WHEN PRO.AD_LINHA = 2 THEN 'Linha 2' ELSE 'Linha N/E' END) AS LINHA
FROM TGFITE ITE
    INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
    INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
    INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
    INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
    CROSS JOIN TOTALGERAL TG
WHERE TRUNC(CAB.DTNEG) BETWEEN :P_PER.INI AND :P_PER.FIN
	AND CAB.TIPMOV = 'V'
	AND PRO.USOPROD = 'V'
	AND (:P_GRUPO IS NULL OR GRU.CODGRUPOPROD = :P_GRUPO)
	AND (:P_CODEMP IS NULL OR CAB.CODEMP = :P_CODEMP)
	AND (:P_CODVEND IS NULL OR VEN.CODVEND = :P_CODVEND)
	AND (:P_CODPROD IS NULL OR ITE.CODPROD = :P_CODPROD)
	AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
	AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
GROUP BY 
	ITE.CODPROD, 
	PRO.DESCRPROD, 
	PRO.CODVOL, 
	PRO.CODGRUPOPROD, 
	GRU.DESCRGRUPOPROD, 
	TG.TOTAL,
    PRO.AD_LINHA
