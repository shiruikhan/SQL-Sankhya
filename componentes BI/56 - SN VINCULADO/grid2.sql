SELECT ITE.NUNOTA,
ITE.CODPROD AS CODPRODUTO,
PRO.COMPLDESC AS NOMEPRODUTO,
SER.SERIE AS SERIAL,
CAB.CODPARC AS CODPARCEIRO,
PAR.RAZAOSOCIAL AS NOMEPARCEIRO,
CAB.DTFATUR AS DATAFATURAMENTO,
CAB.NUMNOTA AS NUMERONOTA
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
INNER JOIN TGFSER SER ON (ITE.NUNOTA = SER.NUNOTA AND ITE.CODPROD = SER.CODPROD)
WHERE ITE.NUNOTA = :P_NUNOTA
