SELECT 
     FIN.CODPARC 
    ,PAR.NOMEPARC
    ,(SELECT NVL(SUM(VLRNOTA),0)
        FROM TGFCAB CAB 
      WHERE CAB.CODPARC = FIN.CODPARC
        AND CAB.TIPMOV = 'C' 
        AND CAB.STATUSNOTA = 'L'
        AND TRUNC(CAB.DTENTSAI) >= :P_DTCORTE.INI
		 AND TRUNC(CAB.DTENTSAI) <= :P_DTCORTE.FIN
        AND CAB.CODEMP IN :P_CODEMP
      ) AS VLR_COMRPAS
     
    ,(SELECT NVL(SUM(VLRDESDOB),0)
        FROM TGFFIN F 
      WHERE F.CODPARC = FIN.CODPARC
        AND TRUNC(F.DHBAIXA)  >= :P_DTCORTE.INI
		AND TRUNC(F.DHBAIXA) <= :P_DTCORTE.FIN
        AND F.RECDESP = -1
		AND F.PROVISAO = 'N'
        AND F.CODEMP  IN :P_CODEMP
      ) AS VLR_FINANCEIRO_BAIXA
      
    ,SUM(VG.VLRLIQUIDO) AS VLR_FINANCEIRO
    
FROM TGFFIN FIN
INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = FIN.CODPARC
INNER JOIN TSICID CID 
    ON CID.CODCID = PAR.CODCID
INNER JOIN TSIBAI BAI 
    ON BAI.CODBAI = PAR.CODBAI
INNER JOIN TSIEND EDN
    ON EDN.CODEND = PAR.CODEND
INNER JOIN TSIUFS UFS 
    ON UFS.CODUF = CID.UF
    
INNER JOIN TGFNAT NAT 
    ON NAT.CODNAT = FIN.CODNAT

INNER JOIN TGFTOP TOP   
    ON TOP.CODTIPOPER = FIN.CODTIPOPER
        AND TOP.DHALTER = FIN.DHTIPOPER
    
INNER JOIN VGFFIN VG
    ON VG.NUFIN = FIN.NUFIN
    
WHERE ((FIN.DHBAIXA IS NULL OR TRUNC(FIN.DHBAIXA) > :P_DTCORTE.FIN)
       AND NVL(FIN.DTENTSAI, FIN.DTNEG) <= :P_DTCORTE.FIN)

    AND FIN.CODEMP IN :P_CODEMP
    AND FIN.PROVISAO = 'N'
    AND FIN.RECDESP = -1
    AND FIN.CODNAT NOT IN (801003,101004,402001,801001,601001,601005)
    AND FIN.CODTIPOPER NOT IN (1306,1200,1201)
    AND FIN.CODPARC NOT IN (754,702,687,495,686,755,289,753,6501,899) -- LANÇAMENTOS MAL DIFERENCIADO PELA TOP
GROUP BY 
    FIN.CODPARC 
    ,PAR.NOMEPARC
