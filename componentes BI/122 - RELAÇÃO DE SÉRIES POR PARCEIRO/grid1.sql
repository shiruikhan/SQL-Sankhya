SELECT SER.CODPROD,
	PRO.DESCRPROD,
	SER.SERIE,
	SER.NUNOTA,
	SER.DTALTER,
    CAB.NUMNOTA
FROM TGFSER SER
	INNER JOIN TGFCAB CAB ON (SER.NUNOTA = CAB.NUNOTA AND CAB.CODPARC = :P_CODPARC AND CAB.TIPMOV = 'V')
	INNER JOIN TGFPRO PRO ON SER.CODPROD = PRO.CODPROD
WHERE SER.ATUALESTOQUE = -1
	AND (:P_CODPROD IS NULL OR SER.CODPROD = :P_CODPROD)
ORDER BY SER.DTALTER, SER.NUNOTA, SER.CODPROD
