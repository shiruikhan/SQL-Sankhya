SELECT SUM(RECEITA) AS RECEITA, DESCRNAT,CODNAT
FROM(
SELECT

        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) AS RECEITA, NAT.DESCRNAT, NAT.CODNAT

FROM TGFFIN FIN
INNER JOIN TGFNAT NATp ON ROUND((fin.CODNAT / 100),0) * 100 = NATP.CODNAT
INNER JOIN TGFNAT NAT ON fin.CODNAT = NAT.CODNAT
INNER JOIN TSICUS CUS ON CUS.CODCENCUS = FIN.CODCENCUS
WHERE FIN.DHBAIXA >= :PERIODO.INI 
AND FIN.DHBAIXA <= :PERIODO.FIN 
AND NATP.CODNAT= :CODNAT
AND FIN.DHBAIXA IS NOT NULL
AND FIN.PROVISAO='N'
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND FIN.RECDESP =  1

AND FIN.RECDESP <> 0
AND (FIN.CODEMP IN :EMPRESA)
GROUP BY
 NAT.DESCRNAT,NAT.CODNAT

UNION ALL

SELECT SUM(CASE WHEN MBC.RECDESP =  1 THEN MBC.VLRLANC ELSE 0 END) AS RECEITA, NAT.DESCRNAT, NAT.CODNAT
FROM TGFMBC MBC
INNER JOIN TSICTA CTA ON MBC.CODCTABCOINT = CTA.CODCTABCOINT
INNER JOIN TGFFIN FIN ON MBC.NUBCO = FIN.NUBCO
INNER JOIN TGFNAT NATp ON ROUND((fin.CODNAT / 100),0) * 100 = NATP.CODNAT
INNER JOIN TGFNAT NAT ON fin.CODNAT = NAT.CODNAT
WHERE  MBC.DTLANC     >=  :PERIODO.INI 
AND MBC.DTLANC     < :PERIODO.FIN 
AND NATP.CODNAT= :CODNAT
AND FIN.DHBAIXA IS NOT NULL
AND FIN.PROVISAO='N'
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND FIN.RECDESP =  1
AND CTA.CLASSE = 'D'
AND (FIN.CODEMP IN :EMPRESA) 
AND :ADIANTAMENTO = 'S'
GROUP BY
 NAT.DESCRNAT,NAT.CODNAT)
GROUP BY DESCRNAT, CODNAT

order by 1 desc
