create or replace TRIGGER TRG_INC_UPD_TPRIMRP_SPARK
BEFORE INSERT OR UPDATE ON TPRIMRP FOR EACH ROW
/*==============================================================================
  Nome do Script : TRG_INC_UPD_TPRIMRP_SPARK
  Tipo           : Trigger
  Descrição      : Calcula saldo de necessidade MRP com ajustes adicionais para análise de giro
  Tabela         : TPRIMRP
  Evento         : BEFORE INSERT OR UPDATE
  Escopo         : FOR EACH ROW / STATEMENT

  Autor          : Silvio Vieira
  Cargo          : Analista de Sistemas Sênior
  Empresa        : Spark Eletrônica
  Data de Criação: [A DEFINIR]
  Última Revisão : Abril/2026 — Padronização de cabeçalho e comentários
==============================================================================*/
DECLARE
BEGIN
  /*
  Autor: Dione Santos
  Data: 01/03/2022
  Motivo: Campo adicional para informar a Qte a ser somada para gerar necessidade de compra do MRP para Análise de Giro
  */

   -- SOMA A QTDE ADICIONAL AO SALDO JÁ EXISTENTE CALCULADO PELO MRP, VALOR É NEGATIVO PARA PODER GERAR NA ANALISE DE GIRO
   
   /* REGRA PARA NECESSIDADE COMPRA (QTDSALDO): QTDE MRP + QTDE MRP SALDO ANTERIOR + QTDE ADICIONAL - PEDIDO COMPRA - ESTOQUE */
   
   /* RETIRADO O TRECHO OBTER_TOTAIS_MRP QUE BUSCAVA O SALDO DA MP ANTERIOR POIS FOI IDENTIFICADO QUE NÃO ESTAVA GERANDO A DEMANDA DOS MPS DOS PIS,
   DESTA FORMA ALINHADO COM RENAN SILVA EM 25/03/22 PARA JOGAR N DEMANDA BRUTA DO PA A QTDE SALDO ANTERIOR, DESTA FORMA O SISTEMA JÁ IRIA PROPORCIONALIZAR
   PARA TODOS OS MPS QUE GERAM OP COMO SUB-ORDEM. FOI REFORÇADO QUE AS MPS QUE SÃO DE OP POR ESTOQUE OU SEJA NÃO GERA SUB-ORDEM NÃO SERÁ GERADO NA SUGESTÃO DE COMPRAS */
  :NEW.QTDSALDO := :NEW.QTDPEDCOMPRA + :NEW.QTDESTOQUE - :NEW.QTDMRP; -- + OBTEM_TOTAIS_MRP(:NEW.NUMPS,0,:NEW.CODPRODMP,'NA'));
  
  
 
  
  
  IF UPDATING AND NVL(:NEW.AD_QTDADICIONAL,0) <> NVL(:OLD.AD_QTDADICIONAL,0) AND :NEW.QTDSALDO <=0 THEN
    :NEW.QTDSALDO :=   :OLD.QTDSALDO + ((NVL(:NEW.AD_QTDADICIONAL,0)-NVL(:OLD.AD_QTDADICIONAL,0))*-1);  
  END IF;  
  
   
  IF UPDATING AND NVL(:NEW.AD_QTDADICIONAL,0) <> NVL(:OLD.AD_QTDADICIONAL,0) AND :NEW.QTDSALDO >0 THEN
    :NEW.QTDSALDO :=  NVL(:NEW.AD_QTDADICIONAL,0)*-1;  
  END IF; 
  
  
  IF UPDATING('AD_QTDADICIONAL') AND NVL(:NEW.AD_QTDADICIONAL,0) = 0 THEN
  :NEW.QTDSALDO := :NEW.QTDPEDCOMPRA + :NEW.QTDESTOQUE - :NEW.QTDMRP ;--+ OBTEM_TOTAIS_MRP(:NEW.NUMPS,0,:NEW.CODPRODMP,'NA'));
  END IF;
  
  
END TRG_INC_UPD_TPRIMRP_SPARK; 