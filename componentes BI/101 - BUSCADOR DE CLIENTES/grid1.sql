SELECT PAR.CODPARC,
	UPPER(PAR.RAZAOSOCIAL) AS RAZAOSOCIAL,
	PAR.TELEFONE,
	PAR.CGC_CPF,
	PAR.CODCID,
	UPPER(CID.NOMECID) AS NOMECID,
	PAR.CEP,
	PAR.CODEND,
	UPPER(concatStr((concatStr(trim(EDR.TIPO) , ' ')), trim(EDR.NOMEEND))) AS NOMEEND,
	UPPER(UFS.DESCRICAO) AS DESCRICAO,
	(SELECT VEN.APELIDO FROM TGFVEN VEN WHERE PAR.CODVEND = VEN.CODVEND) AS CODVEND,
	(SELECT MAX(TRUNC(C.DTNEG)) FROM TGFCAB C WHERE C.CODPARC = PAR.CODPARC) AS ULTIMACOMPRA
FROM TGFPAR PAR
	INNER JOIN TSICID CID ON PAR.CODCID = CID.CODCID
	--INNER JOIN TSICEP CEP ON PAR.CEP = CEP.CEP
	INNER JOIN TSIEND EDR ON PAR.CODEND = EDR.CODEND
	INNER JOIN TSIUFS UFS ON CID.UF = UFS.CODUF
WHERE PAR.ATIVO = 'S'
	AND PAR.CODPARC IN (SELECT DISTINCT CAB.CODPARC FROM TGFCAB CAB INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD WHERE CAB.TIPMOV = 'V' AND (:P_CODPROD IS NULL OR ITE.CODPROD = :P_CODPROD) AND PRO.USOPROD = 'V' AND CAB.DTNEG >= (ADD_MONTHS(SYSDATE,-12)))
	AND (:P_CODUF IS NULL OR UFS.CODUF = :P_CODUF)
	AND (:P_CODCID IS NULL OR PAR.CODCID = :P_CODCID)
	AND PAR.TIPPESSOA = 'J' 	
	AND PAR.CODPARC NOT IN (3,492)
ORDER BY PAR.CODPARC
