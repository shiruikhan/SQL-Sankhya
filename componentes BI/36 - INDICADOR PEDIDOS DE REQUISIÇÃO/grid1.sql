SELECT CAB.NUNOTA,
	CAB.CODCENCUS,
	CUS.DESCRCENCUS,
	CAB.CODTIPOPER,
	(SELECT DISTINCT DESCROPER FROM TGFTOP WHERE CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	ITE.QTDENTREGUE,
	CAB.DTNEG,
	CAB.AD_MOTIVO_DE_OPERACAO
FROM TGFITE ITE 
	LEFT JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA 
	LEFT JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD 
	LEFT JOIN TSICUS CUS ON CAB.CODCENCUS = CUS.CODCENCUS
WHERE (TRUNC(CAB.DTNEG) >= :P_PERIODO.INI AND TRUNC(CAB.DTNEG) <= :P_PERIODO.FIN) 
	AND (CAB.TIPMOV = 'J') 
	AND (ITE.STATUSNOTA = 'L') 
	AND (CAB.AD_NUMPS IS NULL)
 AND CAB.CODTIPOPER NOT IN (409)
ORDER BY CAB.NUNOTA
