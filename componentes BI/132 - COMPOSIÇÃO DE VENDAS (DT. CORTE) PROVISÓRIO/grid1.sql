SELECT V.CODPROD,
	V.DESCRPROD,
	SUM(V.QTDNEG) AS QTDNEG,
	V.PARCEIRO
FROM (SELECT SUBSTR(ITE.CODPROD,1,1) || SUBSTR(ITE.CODPROD,3) AS CODPROD,
			PRO.DESCRPROD,
			SUM(ITE.QTDNEG) AS QTDNEG,
			CAB.CODPARC || ' - ' || PAR.NOMEPARC AS PARCEIRO
		FROM TGFITE ITE
			INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D') /*AND CAB.STATUSNOTA = 'L'*/ AND CAB.TIPMOV = 'P' AND CAB.PENDENTE = 'S'
			INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD AND SUBSTR(PRO.CODPROD,1,1) = '3'
			INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
		WHERE CAB.DTPREVENT <= :P_DTCORTE
		GROUP BY ITE.CODPROD,
			PRO.DESCRPROD,
			CAB.CODPARC || ' - ' || PAR.NOMEPARC
		ORDER BY ITE.CODPROD) V
GROUP BY V.CODPROD,
	V.DESCRPROD,
	V.PARCEIRO
ORDER BY V.CODPROD
