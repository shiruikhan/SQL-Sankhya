create or replace TRIGGER SPK_TRG_APOQLD_INS 
BEFORE INSERT OR UPDATE ON AD_APOQLD 
FOR EACH ROW
DECLARE
	P_CODPROD INTEGER;	
	P_FICPRO TPRIPROC.NROLOTE%TYPE;
    
BEGIN
    P_FICPRO := :NEW.FICPRO;
    
    SELECT DISTINCT (IPA.CODPRODPA) INTO P_CODPROD
    FROM TPRIPROC OP
        INNER JOIN TPRIPA IPA ON OP.IDIPROC = IPA.IDIPROC
    WHERE OP.NROLOTE = P_FICPRO
        AND SUBSTR(IPA.CODPRODPA,1,1) IN (3,2);
    
    :NEW.CODPROD := P_CODPROD;
END;