SELECT * FROM (

SELECT
 CTACTB
,CODCTACTB
,DESCRCTA
,CASE WHEN TO_CHAR(:DAT1, 'MM') >= '01' THEN SUM(MES01) ELSE NULL END AS MES1,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '02' THEN SUM(MES02) ELSE NULL END AS MES2,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '03' THEN SUM(MES03) ELSE NULL END AS MES3,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '04' THEN SUM(MES04) ELSE NULL END AS MES4,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '05' THEN SUM(MES05) ELSE NULL END AS MES5,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '06' THEN SUM(MES06) ELSE NULL END AS MES6,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '07' THEN SUM(MES07) ELSE NULL END AS MES7,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '08' THEN SUM(MES08) ELSE NULL END AS MES8,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '09' THEN SUM(MES09) ELSE NULL END AS MES9,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '10' THEN SUM(MES10) ELSE NULL END AS MES10,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '11' THEN SUM(MES11) ELSE NULL END AS MES11,
CASE WHEN TO_CHAR(:DAT1, 'MM') >= '12' THEN SUM(MES12) ELSE NULL END AS MES12
FROM(
SELECT
LAN.DTMOV,
PLA.CODCTACTB,
PLA.CTACTB,
PLA.DESCRCTA,
SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) As VALOR,
LAN.REFERENCIA,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/01' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES01,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/02' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES02,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/03' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES03,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/04' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES04,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/05' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES05,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/06' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES06,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/07' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES07,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/08' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES08,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/09' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES09,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/10' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES10,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/11' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES11,
CASE WHEN TO_CHAR(LAN.REFERENCIA, 'YYYY/MM') <= TO_CHAR(:DAT1, 'YYYY') || '/12' THEN SUM(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN 1 ELSE -1 END) ELSE 0 END AS MES12
FROM TCBLAN LAN, TCBPLA PLA, TCBEMP EMP, TSIEMP PAR
WHERE 
 ( LAN.DTMOV <= :DAT1)   AND
 ( PLA.CTACTB >= '1')  AND
 ( PLA.CTACTB < '3')  AND
 ( LAN.NUMLOTE <> 9999)  AND
 ( LAN.CODEMP IN :CODEMP)  AND
LAN.CODCTACTB = PLA.CODCTACTB
AND PAR.CODEMP = LAN.CODEMP
AND EMP.CODEMP = LAN.CODEMP
AND NVL(LAN.VLRLANC,0) > 0
AND EMP.CODEMPPLACTA = PLA.CODEMP
AND (SUBSTR(PLA.CTACTB,1,6) = :CTACTB OR SUBSTR(PLA.CTACTB,1,9) = :CTACTB OR PLA.CTACTB = :CTACTB)
Group by 
PLA.CTACTB, LAN.DTMOV, PLA.CTACTB, PLA.DESCRCTA, LAN.REFERENCIA, PLA.CODCTACTB
)CT5
GROUP BY 
CTACTB, CODCTACTB, DESCRCTA

union all

SELECT NULL AS CTACTB, NULL AS CODCTACTB, NULL AS DESCRCTA, NULL AS MES01, NULL AS MES02, NULL AS MES3, NULL AS MES4,
NULL AS MES5, NULL AS MES6, NULL AS MES7, NULL AS MES8, NULL AS MES9, NULL AS MES10, NULL AS MES11, NULL AS MES12
FROM DUAL

)
ORDER BY
NVL(CTACTB,0)
