SELECT T.*,
    -- Totais anuais
    T.JANEIRO+T.FEVEREIRO+T.MAR+T.ABRIL+T.MAIO+T.JUNHO+T.JULHO+T.AGOSTO+T.SETEMBRO+T.OUTUBRO+T.NOVEMBRO+T.DEZEMBRO AS TOTAL,
    T.QTD_JANEIRO+T.QTD_FEVEREIRO+T.QTD_MAR+T.QTD_ABRIL+T.QTD_MAIO+T.QTD_JUNHO+T.QTD_JULHO+T.QTD_AGOSTO+T.QTD_SETEMBRO+T.QTD_OUTUBRO+T.QTD_NOVEMBRO+T.QTD_DEZEMBRO AS TOTAL_QTD,
    T.ESTMIN_CONSOLIDADO,
    -- Percentuais de participação mensal baseados na quantidade
    CASE WHEN T.TOTAL_QTD_JANEIRO > 0 THEN ROUND((T.QTD_JANEIRO / T.TOTAL_QTD_JANEIRO) * 100, 2) ELSE 0 END AS PERC_JANEIRO,
    CASE WHEN T.TOTAL_QTD_FEVEREIRO > 0 THEN ROUND((T.QTD_FEVEREIRO / T.TOTAL_QTD_FEVEREIRO) * 100, 2) ELSE 0 END AS PERC_FEVEREIRO,
    CASE WHEN T.TOTAL_QTD_MAR > 0 THEN ROUND((T.QTD_MAR / T.TOTAL_QTD_MAR) * 100, 2) ELSE 0 END AS PERC_MAR,
    CASE WHEN T.TOTAL_QTD_ABRIL > 0 THEN ROUND((T.QTD_ABRIL / T.TOTAL_QTD_ABRIL) * 100, 2) ELSE 0 END AS PERC_ABRIL,
    CASE WHEN T.TOTAL_QTD_MAIO > 0 THEN ROUND((T.QTD_MAIO / T.TOTAL_QTD_MAIO) * 100, 2) ELSE 0 END AS PERC_MAIO,
    CASE WHEN T.TOTAL_QTD_JUNHO > 0 THEN ROUND((T.QTD_JUNHO / T.TOTAL_QTD_JUNHO) * 100, 2) ELSE 0 END AS PERC_JUNHO,
    CASE WHEN T.TOTAL_QTD_JULHO > 0 THEN ROUND((T.QTD_JULHO / T.TOTAL_QTD_JULHO) * 100, 2) ELSE 0 END AS PERC_JULHO,
    CASE WHEN T.TOTAL_QTD_AGOSTO > 0 THEN ROUND((T.QTD_AGOSTO / T.TOTAL_QTD_AGOSTO) * 100, 2) ELSE 0 END AS PERC_AGOSTO,
    CASE WHEN T.TOTAL_QTD_SETEMBRO > 0 THEN ROUND((T.QTD_SETEMBRO / T.TOTAL_QTD_SETEMBRO) * 100, 2) ELSE 0 END AS PERC_SETEMBRO,
    CASE WHEN T.TOTAL_QTD_OUTUBRO > 0 THEN ROUND((T.QTD_OUTUBRO / T.TOTAL_QTD_OUTUBRO) * 100, 2) ELSE 0 END AS PERC_OUTUBRO,
    CASE WHEN T.TOTAL_QTD_NOVEMBRO > 0 THEN ROUND((T.QTD_NOVEMBRO / T.TOTAL_QTD_NOVEMBRO) * 100, 2) ELSE 0 END AS PERC_NOVEMBRO,
    CASE WHEN T.TOTAL_QTD_DEZEMBRO > 0 THEN ROUND((T.QTD_DEZEMBRO / T.TOTAL_QTD_DEZEMBRO) * 100, 2) ELSE 0 END AS PERC_DEZEMBRO
FROM (SELECT V.CODPROD,
            V.DESCRPROD,
            SUM(CASE WHEN V.MES = 1 THEN V.VLRNOTA ELSE 0 END) AS JANEIRO,
            SUM(CASE WHEN V.MES = 2 THEN V.VLRNOTA ELSE 0 END) AS FEVEREIRO,
            SUM(CASE WHEN V.MES = 3 THEN V.VLRNOTA ELSE 0 END) AS MAR,
            SUM(CASE WHEN V.MES = 4 THEN V.VLRNOTA ELSE 0 END) AS ABRIL,
            SUM(CASE WHEN V.MES = 5 THEN V.VLRNOTA ELSE 0 END) AS MAIO,
            SUM(CASE WHEN V.MES = 6 THEN V.VLRNOTA ELSE 0 END) AS JUNHO,
            SUM(CASE WHEN V.MES = 7 THEN V.VLRNOTA ELSE 0 END) AS JULHO,
            SUM(CASE WHEN V.MES = 8 THEN V.VLRNOTA ELSE 0 END) AS AGOSTO,
            SUM(CASE WHEN V.MES = 9 THEN V.VLRNOTA ELSE 0 END) AS SETEMBRO,
            SUM(CASE WHEN V.MES = 10 THEN V.VLRNOTA ELSE 0 END) AS OUTUBRO,
            SUM(CASE WHEN V.MES = 11 THEN V.VLRNOTA ELSE 0 END) AS NOVEMBRO,
            SUM(CASE WHEN V.MES = 12 THEN V.VLRNOTA ELSE 0 END) AS DEZEMBRO,
            -- Colunas de quantidade por mês
            SUM(CASE WHEN V.MES = 1 THEN V.QTDNEG ELSE 0 END) AS QTD_JANEIRO,
            SUM(CASE WHEN V.MES = 2 THEN V.QTDNEG ELSE 0 END) AS QTD_FEVEREIRO,
            SUM(CASE WHEN V.MES = 3 THEN V.QTDNEG ELSE 0 END) AS QTD_MAR,
            SUM(CASE WHEN V.MES = 4 THEN V.QTDNEG ELSE 0 END) AS QTD_ABRIL,
            SUM(CASE WHEN V.MES = 5 THEN V.QTDNEG ELSE 0 END) AS QTD_MAIO,
            SUM(CASE WHEN V.MES = 6 THEN V.QTDNEG ELSE 0 END) AS QTD_JUNHO,
            SUM(CASE WHEN V.MES = 7 THEN V.QTDNEG ELSE 0 END) AS QTD_JULHO,
            SUM(CASE WHEN V.MES = 8 THEN V.QTDNEG ELSE 0 END) AS QTD_AGOSTO,
            SUM(CASE WHEN V.MES = 9 THEN V.QTDNEG ELSE 0 END) AS QTD_SETEMBRO,
            SUM(CASE WHEN V.MES = 10 THEN V.QTDNEG ELSE 0 END) AS QTD_OUTUBRO,
            SUM(CASE WHEN V.MES = 11 THEN V.QTDNEG ELSE 0 END) AS QTD_NOVEMBRO,
            SUM(CASE WHEN V.MES = 12 THEN V.QTDNEG ELSE 0 END) AS QTD_DEZEMBRO,
            -- Totais mensais para cálculo de percentual
            SUM(SUM(CASE WHEN V.MES = 1 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_JANEIRO,
            SUM(SUM(CASE WHEN V.MES = 2 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_FEVEREIRO,
            SUM(SUM(CASE WHEN V.MES = 3 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_MAR,
            SUM(SUM(CASE WHEN V.MES = 4 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_ABRIL,
            SUM(SUM(CASE WHEN V.MES = 5 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_MAIO,
            SUM(SUM(CASE WHEN V.MES = 6 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_JUNHO,
            SUM(SUM(CASE WHEN V.MES = 7 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_JULHO,
            SUM(SUM(CASE WHEN V.MES = 8 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_AGOSTO,
            SUM(SUM(CASE WHEN V.MES = 9 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_SETEMBRO,
            SUM(SUM(CASE WHEN V.MES = 10 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_OUTUBRO,
            SUM(SUM(CASE WHEN V.MES = 11 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_NOVEMBRO,
            SUM(SUM(CASE WHEN V.MES = 12 THEN V.QTDNEG ELSE 0 END)) OVER() AS TOTAL_QTD_DEZEMBRO,
            -- Estoque Mínimo/Meta Spark
            SUM(V.ESTMIN) AS ESTMIN_CONSOLIDADO
        FROM (SELECT CASE WHEN :P_AGRUPADO = 'S' THEN TO_CHAR(PRO.AD_AGRUPADOR) ELSE TO_CHAR(PRO.CODPROD) END AS CODPROD,
                    CASE WHEN :P_AGRUPADO = 'S' THEN 'GRUPO: ' || TO_CHAR(PRO.AD_AGRUPADOR) ELSE PRO.DESCRPROD END AS DESCRPROD,
                    EXTRACT(MONTH FROM CAB.DTNEG) AS MES,
                    EXTRACT(YEAR FROM CAB.DTNEG) AS ANO,
                    SUM( (ITE.VLRTOT - NVL(ITE.VLRDESC,0)) + NVL(ITE.AD_VLROUTROS,0) ) AS VLRNOTA,
                    SUM(ITE.QTDNEG) AS QTDNEG,
                    NVL(PRO.ESTMIN,0) AS ESTMIN
                FROM TGFPRO PRO
                    INNER JOIN TGFITE ITE ON PRO.CODPROD = ITE.CODPROD
                    INNER JOIN TGFCAB CAB ON (CAB.NUNOTA = ITE.NUNOTA AND CAB.TIPMOV = 'V' AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202) AND EXTRACT(YEAR FROM CAB.DTNEG) = :P_ANO)
                WHERE (:P_CODPROD IS NULL OR (CASE WHEN :P_AGRUPADO = 'S' THEN TO_CHAR(PRO.AD_AGRUPADOR) ELSE TO_CHAR(PRO.CODPROD) END) = TO_CHAR(:P_CODPROD))
                  AND (:P_PA IS NULL OR :P_PA <> 'S' OR (:P_PA = 'S' AND SUBSTR(TO_CHAR(PRO.CODPROD),1,1) = '3'))
                GROUP BY PRO.CODPROD, PRO.AD_AGRUPADOR, PRO.DESCRPROD, EXTRACT(MONTH FROM CAB.DTNEG), EXTRACT(YEAR FROM CAB.DTNEG), PRO.ESTMIN) V
        GROUP BY V.CODPROD, V.DESCRPROD) T
ORDER BY T.CODPROD
