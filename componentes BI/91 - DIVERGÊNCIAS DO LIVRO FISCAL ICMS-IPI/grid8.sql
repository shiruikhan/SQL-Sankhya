WITH VALOROPCTGFCAB (NUCAMPO,NOMECAMPO,VALOR,OPCAO) AS (	
	SELECT 
		CAM.NUCAMPO,
		CAM.NOMECAMPO,
		OPC.VALOR,
		OPC.OPCAO 
	FROM TDDCAM CAM
	INNER JOIN TDDOPC OPC ON(OPC.NUCAMPO = CAM.NUCAMPO)
	WHERE CAM.NOMETAB = 'TGFCAB'
	AND CAM.NUCAMPO IN (SELECT OPC.NUCAMPO FROM TDDOPC OPC WHERE OPC.NUCAMPO = CAM.NUCAMPO)
),
VALOROPCTGFTOP (NUCAMPO,NOMECAMPO,VALOR,OPCAO) AS (	
	SELECT 
		CAM.NUCAMPO,
		CAM.NOMECAMPO,
		OPC.VALOR,
		OPC.OPCAO 
	FROM TDDCAM CAM
	INNER JOIN TDDOPC OPC ON(OPC.NUCAMPO = CAM.NUCAMPO)
	WHERE CAM.NOMETAB = 'TGFTOP'
	AND CAM.NUCAMPO IN (SELECT OPC.NUCAMPO FROM TDDOPC OPC WHERE OPC.NUCAMPO = CAM.NUCAMPO)
)
SELECT 
	R.*
FROM
(SELECT
	(SELECT V.OPCAO FROM VALOROPCTGFCAB V WHERE V.NOMECAMPO = 'TIPMOV' AND V.VALOR = TPO.TIPMOV) TIPMOV,
	ITE.NUNOTA,
	ITE.SEQUENCIA,
	CAB.NUMNOTA,
	CAB.DTNEG,
	CAB.DTENTSAI,
	ITE.VLRTOT,
	ITE.CODPROD,
	(SELECT PRO.DESCRPROD FROM TGFPRO PRO WHERE PRO.CODPROD = ITE.CODPROD) DESCRPROD,
	ITE.CODCFO,
	(SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'ATUALLIVFIS' AND V.VALOR = TPO.ATUALLIVFIS) ATUALLIVFIS,
	CAB.CODTIPOPER,
	TPO.DESCROPER,
	CAB.CODEMP,
	(SELECT EMP.RAZAOSOCIAL FROM TSIEMP EMP WHERE EMP.CODEMP =  CAB.CODEMP) RAZAOSOCIAL,
	CAB.CODPARC,
    (SELECT OPCAO FROM TDDOPC WHERE NUCAMPO = (SELECT NUCAMPO FROM TDDCAM WHERE NOMETAB = 'TGFITE' AND NOMECAMPO = 'CODTRIB') AND VALOR = ITE.CODTRIB) CODTRIB,	
	ITE.BASEICMS,
	ITE.ALIQICMS,
	ITE.VLRICMS,
	ITE.BASEIPI,
    (SELECT OPCAO FROM TDDOPC WHERE NUCAMPO = (SELECT NUCAMPO FROM TDDCAM WHERE NOMETAB = 'TGFITE' AND NOMECAMPO = 'CSTIPI') AND VALOR = COALESCE(ITE.CSTIPI,-1)) CSTIPI,	
     ITE.VLRIPI,
	ITE.ALIQIPI, 
	(SELECT V.OPCAO FROM VALOROPCTGFCAB V WHERE V.NOMECAMPO = 'STATUSNFE' AND V.VALOR = COALESCE(CAB.STATUSNFE,'M')) STATUSNFE, 
	 COALESCE((SELECT V.OPCAO FROM VALOROPCTGFCAB V WHERE V.NOMECAMPO = 'STATUSNFSE' AND V.VALOR = CAB.STATUSNFSE),'Não é NFS-e') STATUSNFSE, 
	(SELECT V.OPCAO FROM VALOROPCTGFCAB V WHERE V.NOMECAMPO = 'STATUSCTE' AND V.VALOR = COALESCE(CAB.STATUSCTE,'M')) STATUSCTE,	
	(SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'NFE' AND V.VALOR = COALESCE(TPO.NFE,'M')) TPONFE,
	(SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'CTE' AND V.VALOR = COALESCE(TPO.CTE,'M')) TPOCTE,
	(SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'NFSE' AND V.VALOR = COALESCE(TPO.NFSE,'M')) TPONFSE,
	(SELECT 
		E.DTEXCLUSAO
     FROM TGFLIV_EXC E
     WHERE E.NUNOTA = CAB.NUNOTA
       AND E.SEQUENCIA = ITE.SEQUENCIA
       AND E.DTEXCLUSAO =
                       (SELECT MAX(EE.DTEXCLUSAO)
                          FROM TGFLIV_EXC EE
                         WHERE EE.NUNOTA = E.NUNOTA
                           AND EE.SEQUENCIA = E.SEQUENCIA
                           AND EE.ORIGEM = E.ORIGEM)) AS DTEXCLIV
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON(ITE.NUNOTA = CAB.NUNOTA)
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
INNER JOIN TGFTOP TPO ON(TPO.CODTIPOPER = CAB.CODTIPOPER AND TPO.DHALTER = CAB.DHTIPOPER)
WHERE TPO.ATUALLIVFIS = 'N'            
  AND COALESCE(CAB.STATUSNFE, 'X') <> 'D'
  AND ((COALESCE(TPO.NFE, 'M') NOT IN ('M', 'T') AND CAB.STATUSNFE = 'A')
	   OR
       (COALESCE(TPO.CTE, 'M') NOT IN ('M', 'T') AND CAB.STATUSCTE = 'A')
	   OR 
	   (COALESCE(TPO.NFE, 'M') IN ('M', 'T') AND CAB.STATUSNOTA = 'L')
	   OR 
	   (COALESCE(TPO.CTE, 'M') IN ('M', 'T') AND CAB.STATUSNOTA = 'L'))
  AND (CAB.DTNEG BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN)
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
  AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
  AND NOT EXISTS (SELECT 1 FROM TGFLIV LIV WHERE LIV.NUNOTA = ITE.NUNOTA AND LIV.ORIGEM IN ('E', 'A'))
  AND CAB.TIPMOV IN ('C','E','V','D','T','M')
  AND ITE.SEQUENCIA > 0
)R
WHERE ((CASE WHEN R.DTEXCLIV IS NULL THEN 'N' ELSE 'S' END) = :P_MOSTRAEXCLIV OR :P_MOSTRAEXCLIV = 'T')
ORDER BY 
	   R.CODCFO, 
	   R.TIPMOV
