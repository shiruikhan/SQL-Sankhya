SELECT SUM(CASE WHEN CURVA = 'A' THEN SUM(VALOR) END) SOMAA,
	SUM(CASE WHEN CURVA = 'B' THEN SUM(VALOR) END) SOMAB,
	SUM(CASE WHEN CURVA = 'C' THEN SUM(VALOR) END) SOMAC,
	SUM(CASE WHEN CURVA = 'A' THEN SUM(VALOR) END)/SUM(VALOR) AS PERCA,
	SUM(CASE WHEN CURVA = 'B' THEN SUM(VALOR) END)/SUM(VALOR) AS PERCB,
	SUM(CASE WHEN CURVA = 'C' THEN SUM(VALOR) END)/SUM(VALOR) AS PERCC,
	SUM(CASE WHEN CURVA = 'A' THEN COUNT(RANKING) END) QTDEA,
	SUM(CASE WHEN CURVA = 'B' THEN COUNT(RANKING) END) QTDEB,
	SUM(CASE WHEN CURVA = 'C' THEN COUNT(RANKING) END) QTDEC,
	SUM(CASE WHEN CURVA = 'A' THEN SUM(KG) END) QTDEITA,
	SUM(CASE WHEN CURVA = 'B' THEN SUM(KG) END) QTDEITB,
	SUM(CASE WHEN CURVA = 'C' THEN SUM(KG) END) QTDEITC,
	SUM(CASE WHEN CURVA = 'A' THEN SUM(KG) END)/SUM(KG) PERCQTDEITA,
	SUM(CASE WHEN CURVA = 'B' THEN SUM(KG) END)/SUM(KG) PERCQTDEITB,
	SUM(CASE WHEN CURVA = 'C' THEN SUM(KG) END)/SUM(KG) PERCQTDEITC,
	(100-(:A+:B)) AS VLRC,
	SUM(CASE WHEN CURVA = 'A' OR CURVA = 'B' OR CURVA = 'C' THEN SUM(VALOR) END) SOMAABC,
	SUM(CASE WHEN CURVA = 'A' OR CURVA = 'B' OR CURVA = 'C' THEN COUNT(RANKING) END) QTDEABC,
	SUM(CASE WHEN CURVA = 'A' OR CURVA = 'B' OR CURVA = 'C' THEN SUM(KG) END) QTDEITABC
FROM (
	select CODIGO, 
		/*DESCRICAO, */
		SUM(VALORANT) AS VALOR,
		SUM(SUM(VALORANT)) OVER  (ORDER BY 3 desc ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS ACUMULADO, 
		(sum(sum(VALORANT)) OVER ())*0.8 AS VALORTOT,
		(sum(sum(VALORANT)) OVER ()) AS TOTAL,
		(SUM(VALORANT) / (sum(sum(VALORANT)) OVER ()))*100 AS PERC,
		(SUM(SUM(VALORANT)) OVER  (ORDER BY 3 desc ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)/(sum(sum(VALORANT)) OVER ()))*100 AS PERCACUM,
		SUM(KGANT) AS KG,
		ROWNUM AS RANKING,
		CASE WHEN ROWNUM <= ROUND(((SUM(COUNT(ROWNUM)) OVER ()))*(:A/100)) THEN 'A' WHEN ROWNUM > ROUND(((SUM(COUNT(ROWNUM)) OVER ()))*(:A/100)) AND ROWNUM <= ROUND(((SUM(COUNT(ROWNUM)) OVER ()))*(:A/100))+ROUND(((SUM(COUNT(ROWNUM)) OVER ()))*(:B/100)) THEN 'B' ELSE 'C' END CURVA,
		SUM(VALORANT)/SUM(KGANT) AS VALORMEDIO, ((SUM(SUM(KGANT)) OVER ())) AS TOTA,
		((MAX(MAX(ROWNUM)) OVER ())) AS QTDPRODUTO
	FROM (SELECT CASE WHEN ':@ANALISE' = 'Produtos' THEN PRO.AD_AGRUPADOR ELSE PAR.CODPARC || '-' || PAR.NOMEPARC END AS CODIGO,
			/*CASE WHEN ':@ANALISE' = 'Produtos' THEN PRO.DESCRPROD ELSE PAR.NOMEPARC END AS DESCRICAO,*/
			SUM ((((ITE.VLRTOT + NVL(ITE.AD_VLROUTROS,0)) - (CASE WHEN :DESC = 'S' THEN ITE.VLRDESC ELSE 0 END) - (CASE WHEN :REP = 'S' THEN ITE.VLRREPRED ELSE 0 END) + (CASE WHEN :ST = 'S' THEN ITE.VLRSUBST ELSE 0 END) + (CASE WHEN :IPI = 'S' THEN ITE.VLRIPI ELSE 0 END)) * CASE WHEN CAB.TIPMOV = 'D' THEN -1 ELSE 1 END) * VCAB.INDITENS) AS VALORANT,
			sum(ITE.QTDNEG) AS KGANT
		FROM TGFCAB CAB,
			TGFPAR PAR,
			TGFITE ITE,
			TGFPRO PRO,
			TGFGRU GRU,
			TGFTOP TPO,
			VGFCAB VCAB,
			TGFVEN VEN
		WHERE (CAB.STATUSNOTA = 'L' OR :STATUSNOTA = 'N')
			AND ITE.USOPROD <> 'D'
			AND TPO.GOLSINAL= -1
			AND CAB.CODVEND= VEN.CODVEND
			AND VCAB.NUNOTA= CAB.NUNOTA
			AND PRO.CODGRUPOPROD= GRU.CODGRUPOPROD
			AND TPO.GRUPO IN :GRUPO
			AND CAB.DTNEG BETWEEN :PERIODO.INI AND :PERIODO.FIN
			AND CAB.CODEMP IN :CODEMP
			AND ((CAB.CODPARC= :CODPARC) OR (:CODPARC IS NULL))
			AND ((CAB.CODVEND= :CODVEND) OR (:CODVEND IS NULL))
			AND ((GRU.CODGRUPOPROD = :PGRUPO) OR (:PGRUPO IS NULL))
			AND CAB.CODPARC = PAR.CODPARC
			AND CAB.NUNOTA = ITE.NUNOTA
			AND ITE.CODPROD = PRO.CODPROD
			AND CAB.CODTIPOPER = TPO.CODTIPOPER
			AND CAB.DHTIPOPER = TPO.DHALTER
		GROUP BY CASE WHEN ':@ANALISE' = 'Produtos' THEN PRO.AD_AGRUPADOR ELSE PAR.CODPARC || '-' || PAR.NOMEPARC END/*,
			CASE WHEN ':@ANALISE' = 'Produtos' THEN PRO.DESCRPROD ELSE PAR.NOMEPARC END*/ 
		order by 2 desc)
	GROUP BY CODIGO,
		/*DESCRICAO,*/
		ROWNUM order by 2 desc)
GROUP BY CURVA,
	VALOR,
	KG
