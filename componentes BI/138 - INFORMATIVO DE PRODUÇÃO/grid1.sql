SELECT *
FROM (SELECT V.DESCRICAO,
			V.CODPROD,
			SUM(V.QTDPRODUZIR) - NVL(SUM(V.QTDAPO),0) AS SALDO,
			V.AD_AGRUPADOR,
			V.AD_REFINTERNA
		FROM(SELECT EFX.DESCRICAO,
					IPA.CODPRODPA AS CODPROD,    
					MAX(IPA.QTDPRODUZIR) AS QTDPRODUZIR,
					NVL(SUM(APA.QTDAPONTADA),0) AS QTDAPO,
					MAX(IPA.QTDPRODUZIR) - NVL(SUM(APA.QTDAPONTADA),0) AS SALDO,
					PRO.AD_AGRUPADOR,
					PRO.AD_REFINTERNA
				FROM TPRIPROC PROC 
					LEFT JOIN TPRPRC PRC ON PROC.IDPROC = PRC.IDPROC
					LEFT JOIN TPRIPA IPA ON IPA.IDIPROC = PROC.IDIPROC
					LEFT JOIN TPRIATV ATV ON ATV.IDIPROC = PROC.IDIPROC
					LEFT JOIN TPREFX EFX ON EFX.IDEFX = ATV.IDEFX AND EFX.IDPROC = PRC.IDPROC
					LEFT JOIN TPRAPO APO ON ATV.IDIATV = APO.IDIATV
					LEFT JOIN TPRAPA APA ON APO.NUAPO = APA.NUAPO
					INNER JOIN TGFPRO PRO ON IPA.CODPRODPA = PRO.CODPROD
				WHERE EFX.DESCRICAO IN ('INSERÇÃO','SOLDA','DISSIPADOR','TAMPA/GABINETE','TESTE','MONTAGEM FINAL','EXPEDIÇÃO/CONFERENCIA')
					AND ATV.DHFINAL IS NULL
				GROUP BY EFX.DESCRICAO,
					IPA.CODPRODPA,
					APO.SITUACAO,
					IPA.NROLOTE,
					PRO.AD_REFINTERNA,
					PRO.AD_AGRUPADOR) V
		GROUP BY V.DESCRICAO,
			V.CODPROD,
			V.AD_REFINTERNA,
			V.AD_AGRUPADOR
		ORDER BY V.DESCRICAO)
PIVOT (SUM(NVL(SALDO,0)) FOR DESCRICAO IN (
        'INSERÇÃO' AS INSERCAO,
        'SOLDA' AS SOLDA,
        'DISSIPADOR' AS DISSIPADOR,
        'TAMPA/GABINETE' AS TAMPAGABINETE,
        'TESTE' AS TESTE,
        'MONTAGEM FINAL' AS MONTAGEMFINAL,
        'EXPEDIÇÃO/CONFERENCIA' AS EXPEDICAO))
