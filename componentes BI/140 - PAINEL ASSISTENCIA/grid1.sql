SELECT 
	F.NOMEFUNC,
	SUM(CASE WHEN ASS.DISJUNTOR IS NOT NULL THEN 1 ELSE 0 END) AS DISJUNTOR,
	SUM(CASE WHEN ASS.DISPLAY IS NOT NULL THEN 1 ELSE 0 END) AS DISPLAY,
	SUM(CASE WHEN ASS.ADESIVO IS NOT NULL THEN 1 ELSE 0 END) AS ADESIVO,
	SUM(CASE WHEN ASS.CHICOTE IS NOT NULL THEN 1 ELSE 0 END) AS CHICOTE,
	SUM(CASE WHEN ASS.LED IS NOT NULL THEN 1 ELSE 0 END) AS LED,
	SUM(CASE WHEN ASS.MICA IS NOT NULL THEN 1 ELSE 0 END) AS MICA,
	SUM(CASE WHEN ASS.CORRENTEMIN IS NOT NULL THEN 1 ELSE 0 END) AS CORRENTEMIN,
	SUM(CASE WHEN ASS.CORRENTEMAX IS NOT NULL THEN 1 ELSE 0 END) AS CORRENTEMAX,
	SUM(CASE WHEN ASS.CURTO IS NOT NULL THEN 1 ELSE 0 END) AS CURTO,
	SUM(CASE WHEN ASS.SOLDA IS NOT NULL THEN 1 ELSE 0 END) AS SOLDA,
	SUM(CASE WHEN ASS.INDUTOR IS NOT NULL THEN 1 ELSE 0 END) AS INDUTOR,
	SUM(CASE WHEN ASS.TRANSFORMADOR IS NOT NULL THEN 1 ELSE 0 END) AS TRANSFORMADOR,
	SUM(CASE WHEN ASS.COMPINVERTIDO IS NOT NULL THEN 1 ELSE 0 END) AS COMPINVERTIDO
FROM 
	AD_TGFASS ASS
	INNER JOIN TFPFUN F ON ASS.FUNCSOLDA = F.CODFUNC
WHERE 
	ASS.DTRECEB <= :P_DTENTSAI.FIN AND ASS.DTRECEB >= :P_DTENTSAI.INI
	AND ASS.T_DTFABRICACAO <= :P_DTFAB.FIN AND ASS.T_DTFABRICACAO >= :P_DTFAB.INI
	AND ASS.DTCONCLUSAO IS NOT NULL
	AND ASS.FUNCSOLDA IS NOT NULL
	AND ASS.DEFEITO = 'FAB'
GROUP BY 
	F.NOMEFUNC
ORDER BY 
	F.NOMEFUNC
