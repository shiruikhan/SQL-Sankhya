SELECT 
1 AS ORDEM,
D.CODPARC,
D.RAZAOSOCIAL,
NULLIF(D.VLR,0) AS VLR,
NULLIF(D.VLRFIN,0) AS VLRFIN,
NULLIF(D.VLRDEVOL,0) AS VLRDEVOL,
D.VLRTOTAL,
(D.VLRTOTAL / SUM(VLRTOTAL) OVER () )*100 AS REP,
CODCTACTB,
CTACTB
FROM(

	SELECT 
	CODPARC,
	UPPER(RAZAOSOCIAL) AS RAZAOSOCIAL,
	CODCTACTB,
	CTACTB,
	SUM(VLR) AS VLR,
     SUM(VLRFIN) AS VLRFIN,
	SUM(VLRDEVOL) AS VLRDEVOL,
	SUM(VALOR) AS VLRTOTAL
	FROM(
	
		--ORIGEM PORTAL - TIPMOV= "V"
		SELECT 
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		T.TIPMOV,
		PAR.CODCTACTB,
           PLA.CTACTB,
		CASE WHEN T.TIPMOV <> 'D' THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE 0 END AS VLR,
           0 AS VLRFIN, 
		CASE WHEN T.TIPMOV = 'D' THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE 0 END AS VLRDEVOL,
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
		WHERE
		FIN.CODEMP IN :CODEMP AND  
		(CASE WHEN T.TIPMOV = 'V' THEN FIN.DTNEG ELSE FIN.DTENTSAI END) <= :DAT1 AND  
		(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
		((T.TIPMOV IN ('V') AND FIN.RECDESP = 1) OR
		 (T.TIPMOV IN ('D') AND FIN.RECDESP = -1)) AND
		:OUTROS IN ('A','P')
		
		UNION ALL
		
		--ORIGEM FINANCEIRO - TIPMOV= "I"
		SELECT 
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		T.TIPMOV,
		PAR.CODCTACTB,
		PLA.CTACTB,
           0 AS VLR,
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT AS VLRFIN,
		0 AS VLRDESC,
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
		WHERE
		FIN.CODEMP IN :CODEMP AND  
		FIN.DTENTSAI <= :DAT1 AND  
		(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
		T.TIPMOV IN ('I') AND 
		FIN.RECDESP = 1 AND
		NAT.AD_TIPOCTBZ = 'N' AND
		:OUTROS IN ('A','F')
		)
		GROUP BY CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB
	)D
	
UNION ALL

SELECT 0 AS ORDEM, 0 AS CODPARC, '. TODOS' AS RAZAOSOCIAL, NULL AS VLR,NULL AS VLRFIN, NULL AS VLRDEVOL, NULL AS VLRTOTAL,NULL AS REP, NULL AS CODCTACTB, NULL AS CTACTB FROM DUAL
ORDER BY ORDEM,VLRTOTAL DESC, RAZAOSOCIAL
