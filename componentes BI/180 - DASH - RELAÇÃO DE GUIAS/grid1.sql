SELECT 
     G.CODEMP AS CODEMP
    ,G.DTREF  AS DTREF
    ,OPTION_LABEL('TGFOIR','TIPAPURACAO',G.TIPAPURACAO) AS TIPO
    ,G.CODREC      AS CODREC
    ,UFS.DESCRICAO AS DESCRICAO
    ,G.DTVCTO AS DTVCTO
	,G.CODUF  AS CODUF
    ,G.VALOR  AS VALOR
	,(SELECT  GUI.DESCRGUIA
		FROM AD_TGSFINDET D
		
	    INNER JOIN AD_TGSFINGUI GUI
			ON GUI.ID = D.ID
			
	  WHERE D.CODREC = G.CODREC) AS DESCRICAO_GUIA
   
FROM TGFOIR G
INNER JOIN TSIUFS UFS 
    ON UFS.CODUF = G.CODUF



WHERE G.DTREF >= :P_PERIODO.INI
  AND G.DTREF <= :P_PERIODO.FIN
  AND G.CODEMP IN :P_CODEMP

UNION ALL 
SELECT 
     CAB.CODEMP AS CODEMP
     ,TRUNC(CAB.DTENTSAI, 'MM') AS DTREF
     ,'Retenção Federal' AS TIPO
     ,IMC.CODREC AS CODREC
     ,'MG' AS DESCRICAO
     ,ADD_MONTHS(TRUNC(CAB.DTENTSAI, 'MM'), 1) + 19 AS DTVCTO
     ,49 AS CODUF
     ,SUM(IMN.VALOR) AS VALOR
	,(SELECT  GUI.DESCRGUIA
		FROM AD_TGSFINDET D
		
	    INNER JOIN AD_TGSFINGUI GUI
			ON GUI.ID = D.ID
			
	  WHERE D.CODREC = IMC.CODREC) AS DESCRICAO_GUIA
	  
FROM TGFCAB CAB
INNER JOIN TGFIMN IMN 
    ON IMN.NUNOTA = CAB.NUNOTA
INNER JOIN TGFIMC IMC 
    ON IMC.CODIMP = IMN.CODIMP
WHERE CAB.DTENTSAI >= :P_PERIODO.INI
  AND CAB.DTENTSAI <= :P_PERIODO.FIN
  AND CAB.CODEMP IN :P_CODEMP
GROUP BY 
     CAB.CODEMP,
     TRUNC(CAB.DTENTSAI, 'MM'),
     IMC.CODREC

ORDER BY CODEMP,DTREF
