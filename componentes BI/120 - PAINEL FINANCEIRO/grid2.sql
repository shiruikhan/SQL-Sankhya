SELECT FIN.NUFIN,
	FIN.NUNOTA,
	FIN.NUMNOTA,
	FIN.DTNEG,
	FIN.DESDOBRAMENTO,
	FIN.CODTIPTIT,
	TIT.DESCRTIPTIT,
	FIN.DTVENC,
	FIN.DHBAIXA,
	FIN.CODPARC,
	PAR.RAZAOSOCIAL,
	FIN.VLRDESDOB,
	FIN.VLRJURO,
    (SELECT M.DHCONCILIACAO FROM TGFMBC M WHERE M.NUBCO = FIN.NUBCO) AS DHCONCIL,
	FIN.VLRDESC,
	V.DESPCART,
	V.CARTAODESC,
	V.VLRLIQUIDO,
	FIN.CODNAT,
	FIN.VLRMULTA,
	FIN.VLRVARCAMBIAL,
	(SELECT DISTINCT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = FIN.CODNAT) AS NATUREZA,
	FIN.VLRBAIXA
FROM TGFFIN FIN
	INNER JOIN TGFPAR PAR 
		ON FIN.CODPARC = PAR.CODPARC
	INNER JOIN VGFFIN V 
		ON FIN.NUFIN = V.NUFIN
	INNER JOIN TGFTIT TIT 
		ON FIN.CODTIPTIT = TIT.CODTIPTIT
		
WHERE FIN.RECDESP = :P_RECDESP
	AND FIN.PROVISAO = 'N'
	AND NVL(FIN.DTENTSAI, FIN.DTNEG) <= :P_DTCORTE
    AND (FIN.DHBAIXA IS NULL OR FIN.DHBAIXA > :P_DTCORTE) 
	AND (:P_CODEMP IS NULL 
			OR FIN.CODEMP = :P_CODEMP
		)
	AND FIN.CODNAT IN :P_CODNAT
ORDER BY FIN.DTVENC
