SELECT APO.FUNCOPERADOR || ' - ' || CAD.NOMEFUNC AS OPERADORTESTE,
	NVL(SUM(APO.MINSERIDO),0) AS MINSERIDO,
	NVL(SUM(APO.FALTANDO),0) AS FALTANDO,
	NVL(SUM(APO.INVERTIDO),0) AS INVERTIDO,
	NVL(SUM(APO.TROCADO),0) AS TROCADO,
	NVL(SUM(APO.QUEIMADO),0) AS QUEIMADO,
	NVL(SUM(APO.CURTO),0) AS CURTO,
	NVL(SUM(APO.SOLDAFRIA),0) AS SOLDAFRIA,
	NVL(SUM(APO.DEFEITOMP),0) AS DEFEITOMP,
	NVL(SUM(APO.CHICOTE),0) AS CHICOTE,
	NVL(SUM(APO.DISPLAY),0) AS DISPLAY,
	NVL(SUM(APO.AJUTENSAO),0) AS AJUTENSAO,
	NVL(SUM(APO.ACORRENTE),0) AS ACORRENTE,
	NVL(SUM(APO.LED),0) AS LED,
	NVL(SUM(APO.CONSUMO),0) AS CONSUMO,
	NVL(SUM(APO.CORRENTE),0) AS CORRENTE,
	NVL(SUM(APO.PROGRAMACAO),0) AS PROGRAMACAO,
	NVL(SUM(APO.OUTROSDEFEITOS),0) AS OUTROSDEFEITOS,
	NVL(SUM(APO.ADESIVOTROC),0) AS ADESIVOTROCADO,
	NVL(SUM(APO.ADESIVOTORT),0) AS ADESIVOTORTO,
	NVL(SUM(APO.GABARRANHADO),0) AS GABINETEARRANHADO,
	NVL(SUM(APO.GABAMASSADO),0) AS GABINETEAMASSADO,
	NVL(SUM(APO.TAMPATROCA),0) AS TAMPATROCADA,
	NVL(SUM(APO.TAMPAAMASS),0) AS TAMPAAMASSADA
FROM AD_APOQLD APO
	INNER JOIN TFPFUN CAD ON APO.FUNCOPERADOR = CAD.CODFUNC
WHERE APO.DTAPO >= :P_PERIODO.INI
	AND APO.DTAPO <= :P_PERIODO.FIN
	AND APO.SETOR IN :P_SETOR
GROUP BY APO.FUNCOPERADOR || ' - ' || CAD.NOMEFUNC
