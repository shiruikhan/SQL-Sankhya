SELECT PRO.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	SUM(EST.ESTOQUE) AS ESTOQUE,
	NVL(PRO.LOCALIZACAO,'SEM LOC') AS LOCALIZACAO,
	(CASE WHEN NVL(PRO.LOCALIZACAO,'SEM LOC') = 'SEM LOC' THEN '#fff2cc' ELSE '#cfe2f3' END) AS BKCOLOR
FROM TGFPRO PRO 
	LEFT JOIN  TGFEST EST ON PRO.CODPROD = EST.CODPROD AND EST.CODLOCAL = 101
WHERE (PRO.CODGRUPOPROD = :P_GRUPOPRODUTO OR :P_GRUPOPRODUTO IS NULL)
	AND (PRO.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND (EST.ESTOQUE IS NOT NULL AND PRO.ATIVO = 'S')
GROUP BY PRO.CODPROD, PRO.DESCRPROD, PRO.CODVOL, PRO.LOCALIZACAO
	--HAVING SUM(EST.ESTOQUE) > 0
ORDER BY PRO.CODPROD
