  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VGF_CALDIFAL_SPARK" ("NUNOTA", "SEQUENCIA", "VLRTOT", "VLRDESC", "VLRICMS", "VLRIPI", "BASE", "ICMS", "DIFAL", "BASEAJD", "ALIQUOTA") AS 
  SELECT 
     TAB.NUNOTA
	,TAB.SEQUENCIA
	,TAB.VLRTOT
	,TAB.VLRDESC
	,TAB.VLRICMS
	,TAB.VLRIPI
	,TAB.BASE
	,TAB.ICMS
	,CASE 
		WHEN TAB.CODCFO <> 2352
			AND TAB.CODCFO <> 2932
			THEN ROUND((((TAB.BASE - TAB.ICMS) / 0.82) * 0.18) - TAB.ICMS, 2)
		ELSE ROUND(TAB.BASE * 0.06, 2)
		END AS DIFAL
	,CASE 
		WHEN TAB.CODCFO <> 2352
			AND TAB.CODCFO <> 2932
			THEN ROUND(((TAB.BASE - TAB.ICMS) / 0.82), 2)
		ELSE TAB.BASE
		END AS BASEAJD
	,SNK_DIVIDIR(TAB.ICMS, CASE 
			WHEN TAB.CODCFO <> 2352
				AND TAB.CODCFO <> 2932
				THEN ROUND(((TAB.BASE - TAB.ICMS) / 0.82), 2)
			ELSE TAB.BASE
			END) * 100 AS ALIQUOTA
FROM (
	SELECT ITE.NUNOTA
		,ITE.SEQUENCIA
		,ITE.VLRTOT
		,ITE.VLRDESC
		,ITE.VLRICMS
		,ITE.VLRIPI
		,CASE 
			WHEN NVL(ITE.VLRICMS, 0) = 0
				THEN (ITE.VLRTOT - NVL(ITE.VLRDESC, 0) - NVL(ITE.VLRICMS, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS
				
			WHEN ITE.BASEICMS <> ROUND(((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS), 2)
				THEN ROUND(((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS), 2)
			
			WHEN ITE.BASEICMS = ROUND(((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS), 2)
             THEN ITE.BASEICMS
			
			ELSE ITE.BASEICMS * C.INDITENSSEMOUTROS
			END AS BASE
			
		,CASE 
			WHEN NVL(ITE.VLRICMS, 0) = 0
				OR ITE.ALIQICMS < 4
				AND PRO.ORIGPROD NOT IN (
					1
					,2
					,3
					,8
					)
				THEN ((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS) * 0.12
			WHEN NVL(ITE.VLRICMS, 0) = 0
				OR ITE.ALIQICMS < 4
				AND PRO.ORIGPROD IN (
					1
					,2
					,3
					,8
					)
				THEN ((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS) * 0.04
			WHEN ITE.BASEICMS <> ROUND(((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS), 2)
				THEN ROUND(((ITE.VLRTOT - NVL(ITE.VLRDESC, 0) + NVL(ITE.VLRIPI, 0)) * C.INDITENSSEMOUTROS), 2) * (ITE.ALIQICMS / 100)
			ELSE NVL(ITE.VLRICMS, 0)
			END AS ICMS
		,ITE.CODCFO
		,0 AS RN
	FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON CAB.NUNOTA = ITE.NUNOTA
	INNER JOIN VGFCAB C ON C.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
	WHERE (
			(
				ITE.CODCFO = 2556
				OR ITE.CODCFO = 2551
				)
			OR (
				ITE.CODCFO = 2949
				AND CAB.CODTIPOPER = 224
				)
			OR (
				ITE.CODCFO = 2910
				AND CAB.CODTIPOPER = 316
				)
			)
	
	UNION ALL
	
	SELECT *
	FROM (
		SELECT CAB.NUNOTA AS NUNOTA
			,ITE.SEQUENCIA AS SEQUENCIA
			,ITE.VLRTOT * FC_RATEIOFRETE_SAPARK(CAB.NUNOTA) AS VLRTOT
			,ITE.VLRDESC AS VLRDESC
			,ITE.VLRICMS AS VLRICMS
			,ITE.VLRIPI AS VLRIPI
			,ITE.VLRTOT * FC_RATEIOFRETE_SAPARK(CAB.NUNOTA) AS BASE
			,ITE.VLRICMS AS ICMS
			,ITE.CODCFO AS CODCFO
			,ROW_NUMBER() OVER (
				PARTITION BY CAB.NUNOTA
				,ITE.SEQUENCIA ORDER BY CAB.NUNOTA
				) AS RN
		FROM TGFCAB CAB
		INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
		INNER JOIN TGFNCT NCT ON NCT.NUNOTA = CAB.NUNOTA
		WHERE ITE.CODCFO IN (
				2352
				,2932
				)
			AND EXISTS (
				SELECT 1
				FROM TGFCAB C
				WHERE C.CHAVENFE = NCT.CHAVENFE
					AND C.CODTIPOPER IN (
						201
						,221
						,224
						,209
						,316
						)
				)
		)
	WHERE RN = 1
	) TAB;
