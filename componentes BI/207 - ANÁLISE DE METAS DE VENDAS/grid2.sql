SELECT 
    C.NUNOTA AS NRO_NOTA,
    C.DTNEG AS DATA_VENDA,
    PAR.RAZAOSOCIAL AS CLIENTE,
    P.CODPROD AS COD_PRODUTO,
    P.DESCRPROD AS PRODUTO,
    I.QTDNEG AS QUANTIDADE,
    I.VLRTOT AS VALOR_TOTAL
FROM TGFCAB C
INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
INNER JOIN TGFPAR PAR ON C.CODPARC = PAR.CODPARC
INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
-- Join com a tabela de Composição do Grupo
INNER JOIN AD_TGSISGM COMP ON (
    (COMP.TIPO = 'G' AND G.CODGRUPOPROD = COMP.CODGRUPOPROD) OR
    (COMP.TIPO = 'P' AND G.CODGRUPAI = COMP.CODGRUPOPROD)
)
-- Join com o Cabeçalho da Meta para conseguir filtrar pelo Nome do Grupo clicado
INNER JOIN AD_TGSSGM M ON COMP.CODSGRU = M.CODSGRU 
                       AND COMP.ANO = M.ANO 
                       AND COMP.MES = M.MES
WHERE C.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
    AND C.TIPMOV = 'V'
    AND P.USOPROD = 'V'
    
    -- Filtra a data da venda pelos parâmetros globais do painel
    AND TO_CHAR(C.DTNEG, 'YYYY') = TO_CHAR(:P_ANO)
    AND TO_CHAR(C.DTNEG, 'MM') = :P_MES
    
    -- Filtra a composição também pelos parâmetros
    AND COMP.ANO = :P_ANO
    AND COMP.MES = :P_MES
    
   
    AND M.APELIDO = :A_GRUPO
    
ORDER BY C.DTNEG DESC, I.QTDNEG DESC
