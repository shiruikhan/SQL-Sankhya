SELECT 
CODEMP,
RAZAOABREV,
TIPO,
CODCTABCO,
DESCRICAO,
CODCTABCOINT,
ATIVA,
(CASE WHEN TIPO = 'Outras' OR TIPO = 'Adiantamento' THEN NULL ELSE SALDOREAL END) AS SALDOREAL, 
(CASE WHEN TIPO = 'Outras' OR TIPO = 'Adiantamento' THEN NULL ELSE SALDOBCO END) AS SALDOBCO,
(CASE WHEN TIPO <> 'Adiantamento' THEN NULL ELSE SALDOREAL END) AS SALDOADTOS, 
(CASE WHEN TIPO <>'Outras' THEN NULL ELSE SALDOBCO END) AS SALDOOUTRAS,
CODCTACTB
FROM (
	SELECT 
	CTA.CODEMP, 
	(SELECT INITCAP(NOMEFANTASIA) FROM TSIEMP E WHERE E.CODEMP = CTA.CODEMP) AS RAZAOABREV,
	CASE WHEN CLASSE = 'A' THEN 'Aplicação' 
	     WHEN CLASSE = 'D' THEN 'Adiantamento'
	     WHEN CLASSE = 'C' THEN 'Corrente'
	     WHEN CLASSE = 'X' THEN 'Espécie' 
	     WHEN CLASSE = 'G' THEN 'Garantida'
	     WHEN CLASSE = 'E' THEN 'Empréstimo'
	     WHEN CLASSE = 'O' THEN 'Outras' 
	     ELSE 'Corrente' END AS TIPO,  
	CTA.CODCTABCO, 
	CTA.DESCRICAO, 
	CTA.CODCTABCOINT, 
	SBC.REFERENCIA,
	CTA.ATIVA,
	(NVL(SBC.SALDOREAL,0) + NVL((SELECT SUM(T7.VLRLANC * T7.RECDESP)
	FROM TGFMBC T7 
	WHERE T7.CODCTABCOINT = SBC.CODCTABCOINT AND	  
	T7.DTLANC  >= to_date( '01/'||to_char(:DAT1, 'mm/yyyy')   , 'dd/mm/yyyy') AND 
	T7.DTLANC  < to_char(:DAT1+1,'dd/mm/yyyy')),0)) AS SALDOREAL,
	(NVL(SBC.SALDOBCO,0) + NVL((SELECT SUM(T7.VLRLANC * T7.RECDESP)
	FROM TGFMBC T7 
	WHERE T7.CODCTABCOINT = SBC.CODCTABCOINT AND	  
	T7.DHCONCILIACAO  >= to_date( '01/'||to_char(:DAT1, 'mm/yyyy')   , 'dd/mm/yyyy') AND 
	T7.DHCONCILIACAO  < to_char(:DAT1+1,'dd/mm/yyyy')  AND
	T7.CONCILIADO = 'S'),0)) AS SALDOBCO,
	CTA.CODCTACTB
	FROM   TGFSBC SBC, TSICTA CTA
	WHERE  
	CTA.CODEMP IN :CODEMP AND CTA.ATIVA='S' AND CTA.CODCTABCOINT NOT IN (30) AND  
	SBC.REFERENCIA = (SELECT MAX(REFERENCIA) FROM   TGFSBC T2  WHERE T2.CODCTABCOINT = SBC.CODCTABCOINT AND T2.REFERENCIA < to_char(:DAT1+1,'dd/mm/yyyy')) AND 
	SBC.CODCTABCOINT = CTA.CODCTABCOINT  
	ORDER BY 2, 4)
WHERE
(ATIVA = 'S' OR (ATIVA='N' AND SALDOREAL<>0)) AND
(TIPO = :TIPO OR :TIPO = '.Todos')
ORDER BY TIPO, CODCTABCOINT
