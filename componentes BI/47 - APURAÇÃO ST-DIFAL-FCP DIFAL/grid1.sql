SELECT	CASE WHEN T.ENTSAI = 'E' THEN 'ENTRADAS' ELSE 'SAIDAS' END AS MOVIMENTO,
		T.UF,
		T.ENTSAI,
       	SUM(T.BASEST) AS BASEST,
		SUM(T.ICMSST) AS VLRICMSST,
		SUM(T.DIFALDEST) AS DIFALDEST,
		SUM(T.ICMSCFP) AS ICMSFCP,
		SUM(T.FCPDIFALDEST) AS FCPDIFALDEST,
		SUM(T.FCPST) AS FCPST,
		SUM(T.STGNRE) AS STGNRE,
		SUM(T.STGNREABERTO) AS STGNREABERTO,
		SUM(T.STGNREPAGO) AS STGNREPAGO,
		SUM(T.DIFALFCPGRNE) AS DIFALFCPGRNE,
		SUM(T.DIFALFCPGRNEABERTO) AS DIFALFCPGRNEABERTO,
		SUM(T.DIFALFCPGRNEPAGO) AS DIFALFCPGRNEPAGO

FROM

(SELECT	UFS.UF,
		LIV.ENTSAI,
		LIV.CODCFO,
		LIV.NUNOTA,
		LIV.NUMNOTA,
		SUM(LIV.BASERETENCAO) AS BASEST,
		SUM(LIV.ICMSRETENCAO) AS ICMSST,
		CASE WHEN LIV.ENTSAI = 'E' THEN SUM(LIV.VLRICMSDIFALREM) ELSE SUM(LIV.VLRICMSDIFALDEST) END AS DIFALDEST,
		SUM(LIV.VLRICMSFCPINT) AS ICMSCFP,
		SUM(LIV.VLRICMSFCP) AS FCPDIFALDEST,
		SUM(LIV.VLRSTFCPINT) AS FCPST,
		CASE PAR.CLASSIFICMS
		WHEN 'C' THEN 'Consumidor Final'
		WHEN 'I' THEN 'Isento de ICMS'
		WHEN 'P' THEN 'Produtor Rural'
		WHEN 'R' THEN 'Revendedor'
		WHEN 'X' THEN 'Consumidor Final Contribuinte'
		END AS CLASSIFICACAO,
		CAST(PAR.CODPARC AS VARCHAR) + ' - ' + PAR.RAZAOSOCIAL AS PARCEIRO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202) AS STGNRE,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202
		 AND   FIN.DHBAIXA IS NULL) AS STGNREABERTO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202
		 AND   FIN.DHBAIXA IS NOT NULL) AS STGNREPAGO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602) AS DIFALFCPGRNE,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602
		 AND   FIN.DHBAIXA IS NULL) AS DIFALFCPGRNEABERTO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602
		 AND   FIN.DHBAIXA IS NOT NULL) AS DIFALFCPGRNEPAGO
		

FROM	TGFLIV LIV
INNER JOIN TGFCAB CAB ON CAB.NUNOTA = LIV.NUNOTA
INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA AND ITE.NUNOTA = LIV.NUNOTA AND ITE.SEQUENCIA = LIV.SEQUENCIA
INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC AND PAR.CODPARC = LIV.CODPARC
INNER JOIN TSICID CID ON CID.CODCID = PAR.CODCID
INNER JOIN TSIUFS UFS ON UFS.CODUF = CID.UF
LEFT JOIN TGFPEM PEM ON PEM.CODEMP = LIV.CODEMP AND PEM.CODPROD = ITE.CODPROD
LEFT JOIN TGFDIN DINP ON DINP.NUNOTA = CAB.NUNOTA AND DINP.NUNOTA = ITE.NUNOTA AND DINP.SEQUENCIA = ITE.SEQUENCIA AND DINP.NUNOTA = LIV.NUNOTA AND DINP.SEQUENCIA = LIV.SEQUENCIA AND DINP.CODIMP = 6
LEFT JOIN TGFDIN DINC ON DINC.NUNOTA = CAB.NUNOTA AND DINC.NUNOTA = ITE.NUNOTA AND DINC.SEQUENCIA = ITE.SEQUENCIA AND DINC.NUNOTA = LIV.NUNOTA AND DINC.SEQUENCIA = LIV.SEQUENCIA AND DINC.CODIMP = 7
LEFT JOIN TGFDIN DINI ON DINI.NUNOTA = CAB.NUNOTA AND DINI.NUNOTA = ITE.NUNOTA AND DINI.SEQUENCIA = ITE.SEQUENCIA AND DINI.NUNOTA = LIV.NUNOTA AND DINI.SEQUENCIA = LIV.SEQUENCIA AND DINI.CODIMP = 1


WHERE	LIV.CODEMP = :CODEMP
AND		LIV.DHMOV BETWEEN :PERIODO.INI AND :PERIODO.FIN
AND		LIV.ENTSAI = 'E'
AND		CAB.TIPMOV = 'D'

GROUP BY 	UFS.UF,
			LIV.ENTSAI,
			LIV.CODCFO,
			LIV.NUNOTA,
			LIV.NUMNOTA,
			PAR.CLASSIFICMS,
			PAR.CODPARC,
			PAR.RAZAOSOCIAL
			
UNION ALL 

SELECT	UFS.UF,
		LIV.ENTSAI,
		LIV.CODCFO,
		LIV.NUNOTA,
		LIV.NUMNOTA,
		SUM(LIV.BASERETENCAO) AS BASEST,
		SUM(LIV.ICMSRETENCAO) AS ICMSST,
		CASE WHEN LIV.ENTSAI = 'E' THEN SUM(LIV.VLRICMSDIFALREM) ELSE SUM(LIV.VLRICMSDIFALDEST) END AS DIFALDEST,
		SUM(LIV.VLRICMSFCPINT) AS ICMSCFP,
		SUM(LIV.VLRICMSFCP) AS FCPDIFALDEST,
		SUM(LIV.VLRSTFCPINT) AS FCPST,
		CASE PAR.CLASSIFICMS
		WHEN 'C' THEN 'Consumidor Final'
		WHEN 'I' THEN 'Isento de ICMS'
		WHEN 'P' THEN 'Produtor Rural'
		WHEN 'R' THEN 'Revendedor'
		WHEN 'X' THEN 'Consumidor Final Contribuinte'
		END AS CLASSIFICACAO,
		CAST(PAR.CODPARC AS VARCHAR) + ' - ' + PAR.RAZAOSOCIAL AS PARCEIRO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202) AS STGNRE,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202
		 AND   FIN.DHBAIXA IS NULL) AS STGNREABERTO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010202
		 AND   FIN.DHBAIXA IS NOT NULL) AS STGNREPAGO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602) AS DIFALFCPGRNE,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602
		 AND   FIN.DHBAIXA IS NULL) AS DIFALFCPGRNEABERTO,
		(SELECT ISNULL(SUM(FIN.VLRDESDOB), 0)
		 FROM  TGFFIN FIN
		 WHERE FIN.NUNOTA = LIV.NUNOTA
		 AND   FIN.CODNAT = 1010602
		 AND   FIN.DHBAIXA IS NOT NULL) AS DIFALFCPGRNEPAGO
		

FROM	TGFLIV LIV
INNER JOIN TGFCAB CAB ON CAB.NUNOTA = LIV.NUNOTA
INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA AND ITE.NUNOTA = LIV.NUNOTA AND ITE.SEQUENCIA = LIV.SEQUENCIA
INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC AND PAR.CODPARC = LIV.CODPARC
INNER JOIN TSICID CID ON CID.CODCID = PAR.CODCID
INNER JOIN TSIUFS UFS ON UFS.CODUF = CID.UF
LEFT JOIN TGFPEM PEM ON PEM.CODEMP = LIV.CODEMP AND PEM.CODPROD = ITE.CODPROD
LEFT JOIN TGFDIN DINP ON DINP.NUNOTA = CAB.NUNOTA AND DINP.NUNOTA = ITE.NUNOTA AND DINP.SEQUENCIA = ITE.SEQUENCIA AND DINP.NUNOTA = LIV.NUNOTA AND DINP.SEQUENCIA = LIV.SEQUENCIA AND DINP.CODIMP = 6
LEFT JOIN TGFDIN DINC ON DINC.NUNOTA = CAB.NUNOTA AND DINC.NUNOTA = ITE.NUNOTA AND DINC.SEQUENCIA = ITE.SEQUENCIA AND DINC.NUNOTA = LIV.NUNOTA AND DINC.SEQUENCIA = LIV.SEQUENCIA AND DINC.CODIMP = 7
LEFT JOIN TGFDIN DINI ON DINI.NUNOTA = CAB.NUNOTA AND DINI.NUNOTA = ITE.NUNOTA AND DINI.SEQUENCIA = ITE.SEQUENCIA AND DINI.NUNOTA = LIV.NUNOTA AND DINI.SEQUENCIA = LIV.SEQUENCIA AND DINI.CODIMP = 1


WHERE	LIV.CODEMP = :CODEMP
AND		LIV.DHMOV BETWEEN :PERIODO.INI AND :PERIODO.FIN
AND		LIV.ENTSAI = 'S'

GROUP BY 	UFS.UF,
			LIV.ENTSAI,
			LIV.CODCFO,
			LIV.NUNOTA,
			LIV.NUMNOTA,
			PAR.CLASSIFICMS,
			PAR.CODPARC,
			PAR.RAZAOSOCIAL) T
			
GROUP BY  T.ENTSAI, T.UF, T.ENTSAI

ORDER BY 1, 2
