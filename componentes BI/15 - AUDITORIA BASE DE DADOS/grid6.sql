SELECT B.CODPARC CODPARCEIROS,
       B.NOMEPARC NOMEPARCEIRO,
       SUM( B.QTDEFINANCEIROS) OPERACOES,
       ( SUM( B.QTDEFINANCEIROS) * 100 ) / ( SELECT COUNT(*) 
                                            FROM TGFFIN INNER JOIN TGFPAR ON TGFFIN.CODPARC = TGFPAR.CODPARC
                                           WHERE TGFPAR.CLIENTE = 'S'
                                             AND TGFFIN.RECDESP <> 0 ) PERCENTUAL
  FROM ( SELECT A.CODPARC,
                A.NOMEPARC,
                A.QTDEFINANCEIROS,
                A.TOTAL
           FROM ( SELECT TGFPAR.CODPARC, TGFPAR.NOMEPARC,
                       ( SELECT COUNT(TGFPAR.CODPARC) FROM TGFPAR WHERE TGFPAR.CLIENTE = 'S' ) TOTAL,
                       ( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.CODPARC = TGFPAR.CODPARC AND TGFFIN.RECDESP <> 0 ) QtdeFinanceiros,
                       ( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.CODPARC = TGFPAR.CODPARC AND TGFCAB.TIPMOV <> 'Z') QtdeOperacoes
  FROM TGFPAR 
 WHERE TGFPAR.CLIENTE = 'S') A
WHERE A.QTDEFINANCEIROS <> 0 ) B
GROUP BY B.CODPARC, B.NOMEPARC
ORDER BY SUM(B.QTDEFINANCEIROS) DESC
