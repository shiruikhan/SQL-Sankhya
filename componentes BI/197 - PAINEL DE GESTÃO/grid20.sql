SELECT * FROM (
SELECT 
FIN.DTENTSAI, 
FIN.CODPARC ||' - '||PAR.RAZAOSOCIAL AS "PARCEIRO", 
FIN.NUFIN,
FIN.NUMNOTA, 
(FIN.VLRDESDOB*FIN.RECDESP) As "VLRDESDOB", 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.HISTORICO,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago' 
     WHEN MONTHS_BETWEEN(TRUNC(DTVENC),TO_CHAR(:DAT1,'DD/MM/YYYY')) < 0 THEN 'Vencido' 
     WHEN MONTHS_BETWEEN(TRUNC(DTVENC),TO_CHAR(:DAT1,'DD/MM/YYYY')) <= 12 THEN 'A vencer até 12 meses' 
     ELSE 'Vencimento maior que 12 meses' END As "Prazo_CP_ou_LP",
FIN.CODNAT||' - '||NAT.DESCRNAT AS "NATUREZA",
FIN.CODNAT,
NAT.CODCTACTB AS CTACTBCP,
NAT.CODCTACTB2 AS CTACTBLP
FROM TGFFIN FIN, TGFPAR PAR, TGFNAT NAT
WHERE PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.CODNAT = NAT.CODNAT AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
FIN.RECDESP = -1 AND 
FIN.PROVISAO = 'N' AND 
NAT.CODNATPAI= 040500 AND
(FIN.NUMNOTA = :PROCESSO OR :PROCESSO = 0)
)
WHERE
(CODNAT= :NATUREZA OR :NATUREZA = 0)
ORDER BY 
NATUREZA,
DTVENC,
DTENTSAI,
NUMNOTA,
NUFIN
