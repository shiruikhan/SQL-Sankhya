WITH EstBase AS (
    SELECT EST.CODPROD, SUM(EST.ESTOQUE) AS ESTOQUE
    FROM TGFEST EST
    WHERE EST.CODLOCAL = 109 AND EST.CODEMP = 1
    GROUP BY EST.CODPROD
),
PlanProcProd AS (
    SELECT PROC.IDIPROC, IPA.CODPRODPA AS CODPROD, SUM(IPA.QTDPRODUZIR) AS QTD_PROD
    FROM TPRIPROC PROC
    INNER JOIN TPRIPA IPA ON IPA.IDIPROC = PROC.IDIPROC
    WHERE PROC.STATUSPROC IN ('A', 'P2')
      AND COALESCE(PROC.DTPREVENT, TRUNC(PROC.DHINC) + 7) <= CAST(:P_DATA AS DATE)
    GROUP BY PROC.IDIPROC, IPA.CODPRODPA
),
EntregasProc AS (
    SELECT C.IDIPROC, I.CODPROD, SUM(I.QTDNEG) AS QTD_ENTREGUE
    FROM TGFCAB C
    INNER JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    WHERE C.TIPMOV = 'F'
      AND I.ATUALESTOQUE = 1
      AND C.CODTIPOPER <> 900
    GROUP BY C.IDIPROC, I.CODPROD
),
PlanejadoPorProd AS (
    SELECT P.CODPROD, SUM(P.QTD_PROD - COALESCE(E.QTD_ENTREGUE, 0)) AS PLANEJADO_ESTOQUE
    FROM PlanProcProd P
    LEFT JOIN EntregasProc E ON E.IDIPROC = P.IDIPROC AND E.CODPROD = P.CODPROD
    GROUP BY P.CODPROD
),
PedidosEstoquePorProd AS (
    SELECT M.CODPROD, SUM(M.QTDPREV) AS PEDIDO_ABERTO_ESTOQUE
    FROM TGMMET M
    -- Ajuste para garantir comparação com o primeiro dia do mês
    WHERE M.DTREF = TRUNC(ADD_MONTHS(CAST(:P_DATA AS DATE), -1), 'MM')
    GROUP BY M.CODPROD
),
PedidosVendaPorProd AS (
    SELECT ITE.CODPROD, SUM(ITE.QTDNEG - ITE.QTDENTREGUE) AS PEDIDO_ABERTO_VENDA
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
    WHERE ITE.PENDENTE = 'S'
      AND CAB.PENDENTE = 'S'
      AND CAB.TIPMOV = 'P'
      AND CAB.CODTIPOPER <> 900
      AND CAB.DTPREVENT <= CAST(:P_DATA AS DATE)
    GROUP BY ITE.CODPROD
),

-- NOVA CTE: Captura as vendas diluídas filtrando pelo ano do :P_DATA
VendasAnoPorProd AS (
    SELECT 
        PRO.CODPROD,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 1 THEN ITE.QTDNEG ELSE 0 END) AS QTD_JAN,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 2 THEN ITE.QTDNEG ELSE 0 END) AS QTD_FEV,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 3 THEN ITE.QTDNEG ELSE 0 END) AS QTD_MAR,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 4 THEN ITE.QTDNEG ELSE 0 END) AS QTD_ABR,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 5 THEN ITE.QTDNEG ELSE 0 END) AS QTD_MAI,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 6 THEN ITE.QTDNEG ELSE 0 END) AS QTD_JUN,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 7 THEN ITE.QTDNEG ELSE 0 END) AS QTD_JUL,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 8 THEN ITE.QTDNEG ELSE 0 END) AS QTD_AGO,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 9 THEN ITE.QTDNEG ELSE 0 END) AS QTD_SET,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 10 THEN ITE.QTDNEG ELSE 0 END) AS QTD_OUT,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 11 THEN ITE.QTDNEG ELSE 0 END) AS QTD_NOV,
        SUM(CASE WHEN EXTRACT(MONTH FROM CAB.DTNEG) = 12 THEN ITE.QTDNEG ELSE 0 END) AS QTD_DEZ,
        SUM(ITE.QTDNEG) AS TOTAL_QTD_ANO
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
    INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
    WHERE CAB.TIPMOV = 'V' 
      AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
      AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
      AND EXTRACT(YEAR FROM CAB.DTNEG) = EXTRACT(YEAR FROM CAST(:P_DATA AS DATE))
      AND SUBSTR(TO_CHAR(PRO.CODPROD),1,1) = '3'
    GROUP BY PRO.CODPROD
),
-- CTE OTIMIZACAO 1: Calcula o NUMPS uma única vez para o período
ParametrosMRP AS (
    SELECT MAX(M.NUMPS) AS NUMPS_ATUAL
    FROM TPRMPS M 
    WHERE TRUNC(M.DTINICMPS, 'MM') = TRUNC(CAST(:P_DATA AS DATE), 'MM')
),
-- CTE OTIMIZACAO 2: Calcula o saldo anterior em lote, evitando subquery linha a linha
SaldoMRPAnterior AS (
    SELECT CODPROD, SUM(SALDO) AS SALDO_ANTERIOR
    FROM VGFSALDOMRP
    WHERE DTREF < TRUNC(CAST(:P_DATA AS DATE), 'MM')
    GROUP BY CODPROD
),

EstoqueProduto AS (
    SELECT 
        PRO.AD_AGRUPADOR,
        PRO.CODGRUPOPROD,
        GRU.DESCRGRUPOPROD,
        COALESCE(PRO.ESTMIN, 0) AS ESTMIN,
        COALESCE(PRO.ESTMAX, 0) AS ESTMAX,
        COALESCE(EST.ESTOQUE, 0) AS ESTOQUE,
        COALESCE(PRO.AD_LINHA, 'Sem info') AS LINHA,
        COALESCE(PL.PLANEJADO_ESTOQUE, 0) AS PLANEJADO_ESTOQUE,
        COALESCE(PE.PEDIDO_ABERTO_ESTOQUE, 0) AS PEDIDO_ABERTO_ESTOQUE,
        COALESCE(PV.PEDIDO_ABERTO_VENDA, 0) AS PEDIDO_ABERTO_VENDA,
        -- Colunas de Vendas
        COALESCE(VEN.QTD_JAN, 0) AS QTD_JAN,
        COALESCE(VEN.QTD_FEV, 0) AS QTD_FEV,
        COALESCE(VEN.QTD_MAR, 0) AS QTD_MAR,
        COALESCE(VEN.QTD_ABR, 0) AS QTD_ABR,
        COALESCE(VEN.QTD_MAI, 0) AS QTD_MAI,
        COALESCE(VEN.QTD_JUN, 0) AS QTD_JUN,
        COALESCE(VEN.QTD_JUL, 0) AS QTD_JUL,
        COALESCE(VEN.QTD_AGO, 0) AS QTD_AGO,
        COALESCE(VEN.QTD_SET, 0) AS QTD_SET,
        COALESCE(VEN.QTD_OUT, 0) AS QTD_OUT,
        COALESCE(VEN.QTD_NOV, 0) AS QTD_NOV,
        COALESCE(VEN.QTD_DEZ, 0) AS QTD_DEZ,
        COALESCE(VEN.TOTAL_QTD_ANO, 0) AS TOTAL_QTD_ANO,
        -- Saldo MRP Otimizado
        (
            OBTEM_TOTAIS_MRP(P_MRP.NUMPS_ATUAL, PRO.CODPROD, 0, 'M') 
            - OBTEM_TOTAIS_MRP(P_MRP.NUMPS_ATUAL, PRO.CODPROD, 0, 'P') 
            + COALESCE(S_MRP.SALDO_ANTERIOR, 0)
        ) AS SALDO_MRP
    FROM TGFPRO PRO
    INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
    -- JOIN com a CTE de parametros (retorna 1 linha, cartesiano controlado)
    CROSS JOIN ParametrosMRP P_MRP
    LEFT JOIN EstBase EST ON EST.CODPROD = PRO.CODPROD
    LEFT JOIN PlanejadoPorProd PL ON PL.CODPROD = PRO.CODPROD
    LEFT JOIN PedidosEstoquePorProd PE ON PE.CODPROD = PRO.CODPROD
    LEFT JOIN PedidosVendaPorProd PV ON PV.CODPROD = PRO.CODPROD
    LEFT JOIN VendasAnoPorProd VEN ON VEN.CODPROD = PRO.CODPROD
    -- JOIN com a CTE de saldo anterior
    LEFT JOIN SaldoMRPAnterior S_MRP ON S_MRP.CODPROD = PRO.CODPROD
    WHERE PRO.USOPROD = 'V'
      AND PRO.ATIVO = 'S'
      AND (COALESCE(PRO.AD_OBSOLETO, 'N') = 'N'
           OR EXISTS (
               SELECT 1
               FROM TGFEST EST2
               WHERE EST2.CODPROD = PRO.CODPROD
                 AND EST2.ESTOQUE > 0
                 AND EST2.CODLOCAL = 109
           ))
)
-- SELECT FINAL AGRUPADO POR AD_AGRUPADOR
SELECT 
    AD_AGRUPADOR,
    MAX(CODGRUPOPROD) AS CODGRUPOPROD,
    MAX(DESCRGRUPOPROD) AS DESCRGRUPOPROD,
    SUM(ESTMIN) AS ESTMIN,
    SUM(ESTMAX) AS ESTMAX,
    SUM(ESTOQUE) AS ESTOQUE,
    (CASE WHEN LINHA = '1' THEN 'Linha 1' WHEN LINHA = '2' THEN 'Linha 2' ELSE 'Sem info' END) AS LINHA,
    SUM(PLANEJADO_ESTOQUE) AS PLANEJADO_ESTOQUE,
    SUM(PEDIDO_ABERTO_ESTOQUE) AS PEDIDO_ABERTO_ESTOQUE,
    SUM(PEDIDO_ABERTO_VENDA) AS PEDIDO_ABERTO_VENDA,
    SUM(SALDO_MRP) AS SALDO_MRP,
    -- Agrupamento das Vendas
    SUM(QTD_JAN) AS QTD_JANEIRO,
    SUM(QTD_FEV) AS QTD_FEVEREIRO,
    SUM(QTD_MAR) AS QTD_MARCO,
    SUM(QTD_ABR) AS QTD_ABRIL,
    SUM(QTD_MAI) AS QTD_MAIO,
    SUM(QTD_JUN) AS QTD_JUNHO,
    SUM(QTD_JUL) AS QTD_JULHO,
    SUM(QTD_AGO) AS QTD_AGOSTO,
    SUM(QTD_SET) AS QTD_SETEMBRO,
    SUM(QTD_OUT) AS QTD_OUTUBRO,
    SUM(QTD_NOV) AS QTD_NOVEMBRO,
    SUM(QTD_DEZ) AS QTD_DEZEMBRO,
    SUM(TOTAL_QTD_VENDAS) AS TOTAL_QTD_VENDAS
FROM EstoqueProduto
WHERE AD_AGRUPADOR IS NOT NULL
GROUP BY 
    AD_AGRUPADOR, LINHA
ORDER BY 
    AD_AGRUPADOR
