SELECT ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	ITE.QTDNEG - ITE.QTDENTREGUE AS QTDPENDENTE,
	ITE.QTDNEG,
	ITE.VLRUNIT,
	ITE.VLRTOT,
	ITE.SEQUENCIA,
	ITE.CODLOCALORIG,
	LOC.DESCRLOCAL,
	ITE.OBSERVACAO
FROM TGFITE ITE
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	INNER JOIN TGFLOC LOC ON ITE.CODLOCALORIG = LOC.CODLOCAL
WHERE ITE.NUNOTA = :A_NUNOTA
ORDER BY ITE.SEQUENCIA
