SELECT 
	'Cabeçalho da nota' AS TABELA, 
	CAB.BASEICMS, 
	CAB.VLRICMS , 
	CAB.BASESUBSTIT, 
	CAB.VLRSUBST, 
	CAB.BASEIPI, 
	CAB.VLRIPI
FROM TGFCAB CAB
WHERE CAB.NUNOTA = :A_NUNOTA

UNION ALL

SELECT 
	'Itens da Nota' AS TABELA, 
	COALESCE(SUM(ITE.BASEICMS),0) BASEICMS, 
	COALESCE(SUM(ITE.VLRICMS),0) VLRICMS, 
	COALESCE(SUM(ITE.BASESUBSTIT),0) BASESUBSTIT, 
	COALESCE(SUM(ITE.VLRSUBST),0) VLRSUBST, 
	COALESCE(SUM(ITE.BASEIPI),0) BASEIPI, 
	COALESCE(SUM(ITE.VLRIPI),0) VLRIPI
FROM TGFITE ITE
WHERE NUNOTA = :A_NUNOTA

UNION ALL

SELECT 
	'Impostos da Nota' AS TABELA, 
    COALESCE((SELECT SUM(DIN.BASERED) FROM TGFDIN DIN WHERE DIN.CODIMP = 1 AND DIN.NUNOTA = :A_NUNOTA),0) BASEICMS, 
    COALESCE((SELECT SUM(DIN.VALOR) FROM TGFDIN DIN WHERE DIN.CODIMP = 1 AND DIN.NUNOTA = :A_NUNOTA),0) VLRICMS,
    COALESCE((SELECT SUM(DIN.BASERED) FROM TGFDIN DIN WHERE DIN.CODIMP = 2 AND DIN.NUNOTA = :A_NUNOTA),0) BASESUBSTIT, 
    COALESCE((SELECT SUM(DIN.VALOR) FROM TGFDIN DIN WHERE DIN.CODIMP = 2 AND DIN.NUNOTA = :A_NUNOTA),0) VLRSUBST,
    COALESCE((SELECT SUM(DIN.BASERED) FROM TGFDIN DIN WHERE DIN.CODIMP = 3 AND DIN.NUNOTA = :A_NUNOTA),0) BASEIPI, 
    COALESCE((SELECT SUM(DIN.VALOR) FROM TGFDIN DIN WHERE DIN.CODIMP = 3 AND DIN.NUNOTA = :A_NUNOTA),0) VLRIPI
FROM DUAL

UNION ALL

SELECT 
	'Livro Fiscal' AS TABELA,
	 COALESCE(SUM(LIV.BASEICMS),0) BASEICMS, 
	 COALESCE(SUM(LIV.VLRICMS),0) VLRICMS,
	 COALESCE(SUM(LIV.BASERETENCAO),0) BASESUBSTIT,
	 COALESCE(SUM(LIV.ICMSRETENCAO),0) VLRSUBST,
	 COALESCE(SUM(LIV.BASEIPI),0) BASEIPI,
	 COALESCE(SUM(LIV.VLRIPI),0) VLRIPI
FROM TGFLIV LIV
WHERE LIV.NUNOTA = :A_NUNOTA
  AND LIV.SEQUENCIA <> 9999
