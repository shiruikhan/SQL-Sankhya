SELECT 
     CAB.NUNOTA 
    ,CAB.NUMNOTA
    ,CAB.DTNEG
    ,CAB.CODEMP
    ,CAB.CODTIPOPER 
    ,TOP.DESCROPER
    ,CAB.NUFOP
    ,FOP.DESCRICAO
    ,CAB.CODPARC
    ,PAR.NOMEPARC
    ,MAX(CAB.VLRNOTA)    AS VLR_NOTA
    ,MAX(DIN.CODCST)     AS CST
    ,MAX(DIN.CCLASSTRIB) AS CLASSIFICACAO
    ,SUM(CASE WHEN  DIN.CODIMP = 14 THEN DIN.VALOR ELSE 0 END) AS VLR_CBS
    ,SUM(CASE WHEN  DIN.CODIMP = 12 THEN DIN.VALOR ELSE 0 END) AS VLR_IBS
    

FROM TGFCAB CAB

INNER JOIN TGFITE ITE 
        ON ITE.NUNOTA = CAB.NUNOTA 

INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = CAB.CODPARC 

INNER JOIN TGFTOP TOP 
        ON TOP.CODTIPOPER = CAB.CODTIPOPER 
       AND TOP.DHALTER   = CAB.DHTIPOPER 


INNER JOIN TGFDIN DIN 
    ON DIN.NUNOTA = ITE.NUNOTA 
      AND DIN.SEQUENCIA = ITE.SEQUENCIA 

LEFT JOIN TGFFOP FOP 
    ON FOP.NUFOP = CAB.NUFOP

WHERE CAB.DTNEG  >=  :P_PERIODO.INI
  AND CAB.DTNEG  <=  :P_PERIODO.FIN
  AND (CAB.CODTIPOPER = :P_CODTIPOPER OR :P_CODTIPOPER IS NULL )
  AND CAB.CODEMP IN :P_CODEMP  
  AND CAB.STATUSNFE = 'A'
  AND 'DENTRO DA REFORMA' = :A_STATUS
  AND  EXISTS (SELECT 1
              FROM TGFDIN DIN 
            WHERE DIN.NUNOTA = ITE.NUNOTA 
             AND DIN.SEQUENCIA = ITE.SEQUENCIA
             AND DIN.CCLASSTRIB IS NOT NULL
             AND DIN.CODIMP IN (12,14)
              )

GROUP BY  CAB.NUNOTA 
         ,CAB.NUMNOTA
         ,CAB.DTNEG		 
         ,CAB.CODEMP
         ,CAB.CODPARC
         ,PAR.NOMEPARC
         ,CAB.CODTIPOPER 
         ,TOP.DESCROPER
         ,CAB.NUFOP
         ,FOP.DESCRICAO
UNION ALL 

SELECT 
     CAB.NUNOTA 
    ,CAB.NUMNOTA
    ,CAB.DTNEG
    ,CAB.CODEMP
    ,CAB.CODTIPOPER 
    ,TOP.DESCROPER
    ,CAB.NUFOP
    ,FOP.DESCRICAO
    ,CAB.CODPARC
    ,PAR.NOMEPARC
    ,MAX(CAB.VLRNOTA)    AS VLR_NOTA
    ,MAX(DIN.CODCST)     AS CST
    ,MAX(DIN.CCLASSTRIB) AS CLASSIFICACAO
    ,SUM(CASE WHEN  DIN.CODIMP = 14 THEN DIN.VALOR ELSE 0 END) AS VLR_CBS
    ,SUM(CASE WHEN  DIN.CODIMP = 12 THEN DIN.VALOR ELSE 0 END) AS VLR_IBS

FROM TGFCAB CAB

INNER JOIN TGFITE ITE 
        ON ITE.NUNOTA = CAB.NUNOTA 

INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = CAB.CODPARC 

INNER JOIN TGFTOP TOP 
        ON TOP.CODTIPOPER = CAB.CODTIPOPER 
       AND TOP.DHALTER   = CAB.DHTIPOPER 


LEFT JOIN TGFDIN DIN 
    ON DIN.NUNOTA = ITE.NUNOTA 
      AND DIN.SEQUENCIA = ITE.SEQUENCIA 

LEFT JOIN TGFFOP FOP 
    ON FOP.NUFOP = CAB.NUFOP

WHERE CAB.DTNEG  >=  :P_PERIODO.INI
  AND CAB.DTNEG  <=  :P_PERIODO.FIN
  AND (CAB.CODTIPOPER = :P_CODTIPOPER OR :P_CODTIPOPER IS NULL )
  AND CAB.CODEMP IN :P_CODEMP
  AND CAB.STATUSNFE = 'A'
  AND NOT EXISTS (SELECT 1
              FROM TGFDIN DIN 
            WHERE DIN.NUNOTA = ITE.NUNOTA 
             AND DIN.SEQUENCIA = ITE.SEQUENCIA
             AND DIN.CCLASSTRIB IS NOT NULL
             AND DIN.CODIMP IN(12, 14)
              )
  AND 'FORA DA REFORMA' = :A_STATUS

GROUP BY  CAB.NUNOTA 
         ,CAB.NUMNOTA
		 ,CAB.DTNEG	
         ,CAB.CODEMP
         ,CAB.CODPARC
         ,PAR.NOMEPARC
         ,CAB.CODTIPOPER 
         ,TOP.DESCROPER
         ,CAB.NUFOP
         ,FOP.DESCRICAO
