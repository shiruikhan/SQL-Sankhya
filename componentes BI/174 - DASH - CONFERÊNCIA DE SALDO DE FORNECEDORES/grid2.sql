SELECT 
	 CAB.NUNOTA
	,CAB.NUMNOTA
	,CAB.DTENTSAI
	,CAB.CODPARC
	,PAR.NOMEPARC
	,CAB.VLRNOTA AS VLR_NOTA
	
FROM TGFCAB CAB 

INNER JOIN TGFPAR PAR 
	ON PAR.CODPARC = CAB.CODPARC 
	
WHERE CAB.CODPARC = :A_CODPARC
	AND CAB.TIPMOV = 'C' 
	AND CAB.STATUSNOTA = 'L'
	AND CAB.DTENTSAI  >= :P_DTCORTE.INI
	AND CAB.DTENTSAI  <= :P_DTCORTE.FIN
	AND CAB.CODEMP IN (1,2)
ORDER BY CAB.DTENTSAI ASC
