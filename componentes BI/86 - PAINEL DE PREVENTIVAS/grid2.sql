SELECT CTR.NUPREV,
	CTR.DTPREV,
	CTR.CODBEM,
	CTR.OBSERVACAO,
	(CASE WHEN CTR.TIPOMANUTENCAO = 'CP' THEN 'CORRETIVA PROGRAMADA' WHEN CTR.TIPOMANUTENCAO = 'CE' THEN 'CORRETIVA EMERGENCIAL' WHEN CTR.TIPOMANUTENCAO = 'P' THEN 'PREVENTIVA' ELSE 'CONDICIONAL' END) AS TIPOMANUTENCAO,
	CTR.OPERADOR,
	CTR.CUSTO,
	(CASE WHEN CTR.NATMENUTENCAO = 'E' THEN 'ELÉTRICA' WHEN CTR.NATMENUTENCAO = 'P' THEN 'PREDIAL' WHEN CTR.NATMENUTENCAO = 'M' THEN 'MECÂNICA' END) AS NATMENUTENCAO
FROM AD_PRVCTR CTR
WHERE CODBEM = :A_CODBEM
	AND (:P_PERIODO IS NULL OR (:P_PERIODO.INI >= CTR.DTPREV AND :P_PERIODO.FIN <= CTR.DTPREV))
