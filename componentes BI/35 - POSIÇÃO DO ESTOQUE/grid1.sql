SELECT PRO.CODPROD,
	PRO.AD_CODANTERIOR,
	PRO.DESCRPROD,
	PRO.CODVOL,
	NVL(SUM(EST.ESTOQUE),0) AS ESTOQUE,
	NVL(SUM(EST.RESERVADO),0) AS RESERVADO,
	NVL(SUM(EST.ESTOQUE) - SUM(EST.RESERVADO),0) AS SALDO,
	NVL(PRO.ESTMIN,0) AS ESTMIN,
	NVL(PRO.ESTMAX,0) AS ESTMAX,
	PAR.CODPARC || '-' || PAR.RAZAOSOCIAL AS FORN,
	PRO.LOCALIZACAO,
	--OBTEMCUSTO_SPARK (PRO.CODPROD,'S',1,'N',0,'N',' ',TRUNC(SYSDATE),1) AS CUSTOUNITMPGERENCIAL,
	CASE WHEN EXISTS (SELECT LMP.CODPRODMP 
						FROM TPRLMP LMP 
							INNER JOIN TGFPRO PRO2 ON(PRO2.CODPROD = LMP.CODPRODMP) 
							INNER JOIN TPREFX EFX ON(EFX.IDEFX = LMP.IDEFX) 
							INNER JOIN TGFLOC LOC ON(LOC.CODLOCAL = LMP.CODLOCALORIG) 
						WHERE LMP.CODPRODMP = PRO.CODPROD 
							AND (NVL(LMP.CONTROLEPA, ' ') = ' ' OR LMP.CONTROLEPA = ' ') 
							AND (LMP.TIPOUSOMP IN ('N'))) 
		THEN 'SIM' ELSE 'NÃO' END AS FICHA,
	CASE WHEN EXISTS (SELECT LMP.CODPRODMP 
						FROM TPRLMP LMP 
							INNER JOIN TGFPRO PRO2 ON(PRO2.CODPROD = LMP.CODPRODMP) 
							INNER JOIN TPREFX EFX ON(EFX.IDEFX = LMP.IDEFX) 
							INNER JOIN TGFLOC LOC ON(LOC.CODLOCAL = LMP.CODLOCALORIG) 
						WHERE LMP.CODPRODMP = PRO.CODPROD 
							AND (NVL(LMP.CONTROLEPA, ' ') = ' ' OR LMP.CONTROLEPA = ' ') 
							AND (LMP.TIPOUSOMP IN ('N'))) 
		THEN '#cfe2f3' ELSE '#fff2cc' END AS BKCOLOR,
	(SELECT NVL(SUM(ITE2.QTDNEG - ITE2.QTDENTREGUE),0) AS PENDENTE 
		FROM TGFPRO PRO2 
			LEFT JOIN TGFITE ITE2 ON PRO2.CODPROD = ITE2.CODPROD 
			LEFT JOIN TGFCAB CAB2 ON ITE2.NUNOTA = CAB2.NUNOTA 
			LEFT JOIN TGFTOP TOP2 ON (CAB2.CODTIPOPER = TOP2.CODTIPOPER AND CAB2.DHTIPOPER = TOP2.DHALTER) 
			LEFT JOIN TSICUS CUS2 ON CAB2.CODCENCUS = CUS2.CODCENCUS 
		WHERE ITE2.PENDENTE = 'S' 
			AND ITE2.STATUSNOTA = 'L' 
			AND ITE2.CODPROD = PRO.CODPROD 
			AND CAB2.TIPMOV = 'O') AS COMPRA
FROM TGFPRO PRO 
	LEFT JOIN TGFEST EST ON PRO.CODPROD = EST.CODPROD
	LEFT JOIN TGFPAR PAR ON PRO.CODPARCFORN = PAR.CODPARC
WHERE (PRO.CODGRUPOPROD = :P_GRUPOPRODUTO OR :P_GRUPOPRODUTO IS NULL)
	AND (PRO.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND (/*EST.ESTOQUE IS NOT NULL AND */PRO.ATIVO = 'S')
	AND (EST.CODLOCAL = :P_LOCAL OR :P_LOCAL IS NULL)
	AND (:P_CODPARC IS NULL OR PRO.CODPARCFORN = :P_CODPARC)
	AND (:LOCALIZACAO IS NULL OR PRO.LOCALIZACAO LIKE TO_CHAR('%' || :LOCALIZACAO || '%'))
GROUP BY PRO.CODPROD, PRO.AD_CODANTERIOR, PRO.DESCRPROD, PRO.CODVOL, PRO.ESTMIN, PRO.ESTMAX, PAR.CODPARC || '-' || PAR.RAZAOSOCIAL, PRO.LOCALIZACAO
ORDER BY PRO.CODPROD
