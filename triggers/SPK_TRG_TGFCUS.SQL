create or replace TRIGGER SPK_TRG_TGFCUS
BEFORE INSERT OR UPDATE ON TGFCUS
FOR EACH ROW
DECLARE
    P_INICIAL NUMBER;
    P_VLRCUSTO NUMBER;
	P_MAXCODREG NUMBER;
	P_MAXSEQUENCIA NUMBER;
	P_CODPROD NUMBER;
	P_EXISTE NUMBER;
	P_REGISTRO NUMBER;
	P_REGDATA DATE;

BEGIN
    
    P_VLRCUSTO := :NEW.CUSMED;
	P_CODPROD := :NEW.CODPROD;
	P_EXISTE := 0;
	P_INICIAL := 0;
	P_REGDATA := SYSDATE;

	SELECT MAX(CODREG) INTO P_MAXCODREG		
	FROM AD_TGSCIT;
	
	SELECT MAX(CODREG) INTO P_REGISTRO
	FROM AD_TGSCUS;
	
	SELECT COUNT(CODPROD) INTO P_EXISTE 
	FROM AD_TGSCIT 
	WHERE CODREG = P_MAXCODREG 
		AND CODPROD = P_CODPROD;
	
	IF P_EXISTE > 0 THEN
		P_MAXCODREG := P_MAXCODREG+1;
		P_MAXSEQUENCIA := 1;
	ELSE 
		SELECT MAX(SEQUENCIA)+1 INTO P_MAXSEQUENCIA
		FROM AD_TGSCIT
		WHERE CODREG = P_MAXCODREG;
	END IF;
	
	IF P_REGISTRO < P_MAXCODREG THEN 
		INSERT INTO AD_TGSCUS (CODREG, DTREF,CODUSU,DATA) VALUES (P_MAXCODREG,'01/01/2022',0,P_REGDATA);
	END IF;
	
	IF SUBSTR(TO_CHAR(P_CODPROD), 1, 1) = '3' THEN
		INSERT INTO AD_TGSCIT (CODREG, SEQUENCIA, CODPROD, CUSTO) VALUES (P_MAXCODREG, P_MAXSEQUENCIA, P_CODPROD, P_VLRCUSTO);
	END IF;
END;