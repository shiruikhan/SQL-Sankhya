SELECT SUM(VRCP) AS VRCP, SUM(VRLP) AS VRLP, SUM(VRTOT) AS VRTOT FROM (
SELECT 
FIN.CODPARC,
PAR.RAZAOSOCIAL,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN (FIN.VLRDESDOB)*FIN.RECDESP ELSE 0 END As VRCP,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN 0 ELSE (FIN.VLRDESDOB)*FIN.RECDESP END As VRLP,
FIN.VLRDESDOB*FIN.RECDESP AS VRTOT, 
FIN.DTENTSAI, 
FIN.NUMNOTA,
FIN.NUFIN, 
FIN.DTVENC, 
(FIN.VLRDESDOB*FIN.RECDESP) As VALORDESDOB, 
FIN.CODTIPOPER, 
FIN.HISTORICO
FROM 
TGFFIN FIN, TGFPAR PAR, TGFNAT NAT
WHERE 
PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.CODNAT = NAT.CODNAT AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
FIN.RECDESP = -1 AND 
FIN.PROVISAO = 'N' AND 
(NAT.AD_TIPOCTBZ='E')
)
