SELECT REPLACE(RAZAOSOCIAL,'BANCO ','') AS RAZAOSOCIAL, CODNAT, NUMNOTA, :PARCEIRO AS PARCEIRO2, ABS(SUM(VRCP)) AS VRCP, ABS(SUM(VRLP)) AS VRLP, COUNT(NUFIN) AS QTDE FROM (
SELECT 
FIN.CODPARC,
CASE WHEN FIN.CODNAT = 0902010 THEN PAR.NOMEPARC ELSE PAR.NOMEPARC||' - '||NUMNOTA END AS RAZAOSOCIAL,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN (FIN.VLRDESDOB)*FIN.RECDESP ELSE 0 END As VRCP,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN 0 ELSE (FIN.VLRDESDOB)*FIN.RECDESP END As VRLP,
FIN.VLRDESDOB*FIN.RECDESP AS VRTOT,
FIN.DTENTSAI, 
FIN.CODNAT,
NAT.DESCRNAT AS NUMNOTA,
FIN.NUFIN, 
FIN.DTVENC, 
(FIN.VLRDESDOB*FIN.RECDESP) As VALORDESDOB, 
FIN.CODTIPOPER, 
FIN.HISTORICO
FROM 
TGFFIN FIN, TGFPAR PAR, TGFNAT NAT
WHERE 
PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.CODNAT = NAT.CODNAT AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
FIN.RECDESP = -1 AND 
FIN.PROVISAO = 'N' AND 
(NAT.AD_TIPOCTBZ = 'E') AND
(FIN.CODPARC = :PARCEIRO OR :PARCEIRO = 0)
)
GROUP BY RAZAOSOCIAL, NUMNOTA, CODNAT
ORDER BY RAZAOSOCIAL, NUMNOTA
