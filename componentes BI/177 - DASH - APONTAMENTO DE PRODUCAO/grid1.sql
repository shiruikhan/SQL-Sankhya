SELECT  
     CAB.NUNOTA
    ,CAB.NUMNOTA
    ,CAB.DTNEG
    ,ITE.CODPROD 
    ,PRO.DESCRPROD
    ,ITE.QTDNEG
    ,ITE.QTDENTREGUE
    ,ITE.QTDNEG - ITE.QTDENTREGUE AS DISPONIVEL
FROM TGFCAB CAB 
INNER JOIN TGFITE ITE 
    ON ITE.NUNOTA = CAB.NUNOTA 

INNER JOIN TGFPRO PRO 
    ON PRO.CODPROD = ITE.CODPROD

WHERE CAB.CODPARC = 7540
 AND (ITE.QTDNEG - ITE.QTDENTREGUE) > 0
 AND ITE.CODPROD = :P_CODPROD 
 AND CAB.TIPMOV = 'O'
ORDER BY CAB.DTNEG ASC
