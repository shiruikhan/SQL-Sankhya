/*==============================================================================
  Nome do Script : TIM_GERADESCRICAO
  Tipo           : Function Nativa Sankhya (referencia -- nao customizada)
  Descricao      : Gera a descricao comercial do imovel (tipo, bairro, quartos,
                  edificio, endereco).
  Assinatura     : TIM_GERADESCRICAO (IMOVEL NUMBER) RETURN VARCHAR2
  Observacoes    : - Objeto nativo do ERP -- atualizacoes do Sankhya podem
                    sobrescrever esta function. Revisar apos cada upgrade
                    (mesmo cuidado descrito em nativo/triggers/README.md).
                  - Capturado do banco em 08/10/2026, via:
                    SELECT DBMS_METADATA.GET_DDL('FUNCTION', 'TIM_GERADESCRICAO', 'SPARKPRD') FROM dual;
==============================================================================*/
CREATE OR REPLACE FUNCTION TIM_GERADESCRICAO (IMOVEL NUMBER)
RETURN VARCHAR2
IS
  P_TPIDESCRICAO VARCHAR2(200);
  P_IMVBAIRRO VARCHAR2(200);
  P_QTDEQUARTOS NUMBER(10, 0);
  P_EDIFICIO VARCHAR2(200);
  P_COMPLEMENTO VARCHAR2(200);
  P_IMVTIPOENDERECO VARCHAR2(200);
  P_IMVNOMEENDERECO VARCHAR2(200);
  P_IMVNUMERO VARCHAR2(100);
  P_DESCRICAO VARCHAR2(4000);
BEGIN
  P_DESCRICAO := '';
  SELECT TPI.TPITIPODEIMOVEL, BAI.NOMEBAI, IMV.IMVIFEDIVQUARTOS
        , EDG.EDGEDIFICIO, IMV.IMVCOMPLEMENTO, ENDER.TIPO, ENDER.NOMEEND, IMV.IMVNUMERO 
    INTO P_TPIDESCRICAO, P_IMVBAIRRO, P_QTDEQUARTOS, P_EDIFICIO, P_COMPLEMENTO, P_IMVTIPOENDERECO,
          P_IMVNOMEENDERECO, P_IMVNUMERO
  FROM TIMIMV IMV
    INNER JOIN TIMTPI TPI ON TPI.TPICODIGO = IMV.IMVTIPODOIMOVEL
    LEFT JOIN TSIBAI BAI ON BAI.CODBAI = IMV.IMVBAIRRO
    LEFT JOIN TIMEDG EDG ON EDG.EDGCODIGO = IMV.IMVEDIFICIO
    LEFT JOIN TSIEND ENDER ON ENDER.CODEND = IMV.IMVCODEND
  WHERE IMV.IMVCODIGO = IMOVEL;
  
  IF P_TPIDESCRICAO IS NOT NULL THEN 
    P_DESCRICAO := P_DESCRICAO||P_TPIDESCRICAO;
  END IF;
  
  IF P_QTDEQUARTOS IS NOT NULL THEN 
    P_DESCRICAO := P_DESCRICAO||' - '||P_QTDEQUARTOS||'/4';
  END IF;
  
  IF P_EDIFICIO IS NOT NULL THEN 
    P_DESCRICAO := P_DESCRICAO||' - '||P_EDIFICIO;
  ELSE
    IF P_IMVNOMEENDERECO IS NOT NULL THEN
      P_DESCRICAO := P_DESCRICAO||' - '||P_IMVTIPOENDERECO||' '||P_IMVNOMEENDERECO;
      IF P_IMVNUMERO IS NOT NULL THEN
        P_DESCRICAO := P_DESCRICAO||', '||P_IMVNUMERO;
      END IF;
      IF P_COMPLEMENTO IS NOT NULL THEN
        P_DESCRICAO := P_DESCRICAO||', '||P_COMPLEMENTO;
      END IF;
    END IF;
  END IF;
  
  IF P_IMVBAIRRO IS NOT NULL THEN 
    P_DESCRICAO := P_DESCRICAO||' - '||P_IMVBAIRRO;
  END IF;
  
  RETURN P_DESCRICAO;
END;
