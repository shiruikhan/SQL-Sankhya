SELECT CAB.NUNOTA, CAB.CODEMP, CAB.NUMNOTA, CAB.DTENTSAI, CAB.CODPARC, PAR.NOMEPARC, ITE.CODPROD, PRO.DESCRPROD, PRO.CODVOL, ITE.QTDNEG, ITE.VLRUNIT,(CASE WHEN ITE.AD_VLRCHEIO IS NULL THEN ITE.VLRUNIT ELSE ITE.AD_VLRCHEIO END) AS VLRCHEIO, USU.NOMEUSU AS INCLUSOR, NAT.DESCRNAT
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
INNER JOIN TSIUSU USU ON CAB.CODUSUINC = USU.CODUSU
INNER JOIN TGFNAT NAT ON CAB.CODNAT = NAT.CODNAT
WHERE (CAB.CODPARC = :P_CODPARC OR :P_CODPARC IS NULL) AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL) AND (CAB.DTENTSAI >= :P_PERIODO.INI AND CAB.DTENTSAI <= :P_PERIODO.FIN) AND (CAB.TIPMOV = 'V') AND CAB.STATUSNOTA = 'L'
ORDER BY CAB.DTENTSAI, CAB.NUNOTA
