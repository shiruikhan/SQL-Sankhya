SELECT CO2.NUNOTAORIG,
	CO2.NUCONF,
	CASE WHEN CO2.STATUS = 'F' THEN 'FINALIZADO' ELSE 'EM ABERTO' END AS STATUS,
	CO2.CODUSUCONF,
	(SELECT DISTINCT NOMEUSU FROM TSIUSU WHERE CODUSU = CO2.CODUSUCONF) AS NOMECONF,
	to_char(DHINICONF, 'DD/MM/yyyy hh24:mi:ss') AS INICONF,
	to_char(DHFINCONF, 'DD/MM/yyyy hh24:mi:ss') AS FIMCONF,
	COI.CODBARRA,
	COI.CODPROD,
	PRO.DESCRPROD
FROM TGFCON2 CO2
	INNER JOIN TGFCOI2 COI ON CO2.NUCONF = COI.NUCONF
	INNER JOIN TGFPRO PRO ON COI.CODPROD = PRO.CODPROD
WHERE CO2.NUNOTAORIG = :P_NUNOTA
