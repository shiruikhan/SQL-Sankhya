SELECT ITE.CODEMP AS CODEMP,
	ITE.CODLOCALORIG,
	SER.CODPROD,
	PRO.DESCRPROD,
	SER.SERIE AS SERIE,
	SUM(SER.ATUALESTOQUE) AS ATUALESTOQUE
FROM TGFSER SER
	INNER JOIN TGFITE ITE ON SER.NUNOTA = ITE.NUNOTA
		AND SER.SEQUENCIA = ITE.SEQUENCIA
		AND SER.CODPROD = ITE.CODPROD
	INNER JOIN TGFPRO PRO ON SER.CODPROD = PRO.CODPROD
WHERE (SER.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND (ITE.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
	AND (ITE.CODLOCALORIG = :P_CODLOCALORIG OR :P_CODLOCALORIG IS NULL)
	AND (SER.SERIE = :P_SERIE OR :P_SERIE IS NULL)
GROUP BY ITE.CODEMP, ITE.CODLOCALORIG, SER.CODPROD, PRO.DESCRPROD, SER.SERIE
HAVING SUM(SER.ATUALESTOQUE) >= 1