SELECT SUM(DESPESA) AS DESPESA, DESCRNAT
FROM(
SELECT

        SUM(CASE WHEN FIN.RECDESP =  -1 THEN FIN.VLRDESDOB ELSE 0 END) AS DESPESA, NAT.DESCRNAT

FROM TGFFIN FIN
INNER JOIN TGFNAT NAT ON ROUND((fin.CODNAT / 10000),0) * 10000 = NAT.CODNAT
INNER JOIN TSICUS CUS ON CUS.CODCENCUS = FIN.CODCENCUS
LEFT JOIN TGFMBC MBC ON MBC.NUBCO = FIN.NUBCO
LEFT JOIN TSICTA CTA ON CTA.CODCTABCOINT =  MBC.CODCTABCOINT
WHERE FIN.DHBAIXA >= :PERIODO.INI 
AND FIN.DHBAIXA <= :PERIODO.FIN 
AND FIN.DHBAIXA IS NOT NULL
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND FIN.PROVISAO='N'
AND FIN.RECDESP =  -1
AND FIN.RECDESP <> 0
AND ((CTA.CLASSE IS NULL OR CTA.CLASSE <> 'D'))
AND (FIN.CODEMP in :EMPRESA)
GROUP BY
 NAT.DESCRNAT

UNION ALL

SELECT SUM(CASE WHEN MBC.RECDESP =  -1 THEN MBC.VLRLANC ELSE 0 END) AS DESPESA, NAT.DESCRNAT
FROM TGFMBC MBC
INNER JOIN TSICTA CTA ON MBC.CODCTABCOINT = CTA.CODCTABCOINT
INNER JOIN TGFFIN FIN ON MBC.NUBCO = FIN.NUBCO
INNER JOIN TGFNAT NAT ON ROUND((fin.CODNAT / 10000),0) * 10000 = NAT.CODNAT
WHERE  MBC.DTLANC     >=  :PERIODO.INI 
AND MBC.DTLANC     < :PERIODO.FIN 
AND FIN.DHBAIXA IS NOT NULL
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND FIN.PROVISAO='N'
AND FIN.RECDESP =  -1
AND CTA.CLASSE = 'D'
AND (FIN.CODEMP IN :EMPRESA) 
AND :ADIANTAMENTO = 'S'
GROUP BY NAT.DESCRNAT)
GROUP BY DESCRNAT
ORDER BY 1 DESC
