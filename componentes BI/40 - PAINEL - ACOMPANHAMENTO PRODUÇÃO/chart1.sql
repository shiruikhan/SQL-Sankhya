SELECT * FROM (
SELECT COUNT(*) AS TOT,
PRC.DESCRABREV AS VALUE,
PRC.DESCRABREV
 FROM
TPRIPROC PROC INNER JOIN TPRPRC PRC ON (PROC.IDPROC = PRC.IDPROC)
INNER JOIN TPRIPA IPA ON (IPA.IDIPROC = PROC.IDIPROC)
WHERE 
PRC.CODPRC IN :P_CODPRC
AND PROC.STATUSPROC IN :P_STATUSPROC
AND (PROC.IDIPROC = :P_IDIPROC OR :P_IDIPROC IS NULL)
AND NVL(PROC.DHTERMINO,TO_DATE('01/01/2099')) = CASE WHEN :P_FINAL='S' THEN NVL(PROC.DHTERMINO,TO_DATE('01/01/2099')) ELSE TO_DATE('01/01/2099') END
AND :P_DETALHAR = 'P' --PROCESSO PRODUTIVO
GROUP BY PRC.DESCRABREV
order by 2 desc) PROCESSO
UNION
SELECT * FROM (
SELECT COUNT(ATV.IDIATV) AS TOT,
EFX.DESCRICAO AS VALUE,
EFX.DESCRICAO
 FROM
TPRIPROC PROC INNER JOIN TPRPRC PRC ON (PROC.IDPROC = PRC.IDPROC)
INNER JOIN TPRIPA IPA ON (IPA.IDIPROC = PROC.IDIPROC)
INNER JOIN TPRIATV ATV ON (ATV.IDIPROC = PROC.IDIPROC)
INNER JOIN TPREFX EFX ON (EFX.IDEFX = ATV.IDEFX AND EFX.IDPROC = PRC.IDPROC)
WHERE 
PRC.CODPRC IN :P_CODPRC
AND PROC.STATUSPROC IN :P_STATUSPROC
AND (PROC.IDIPROC = :P_IDIPROC OR :P_IDIPROC IS NULL)
AND NVL(ATV.DHFINAL,TO_DATE('01/01/2099')) = CASE WHEN :P_FINAL='S' THEN NVL(ATV.DHFINAL,TO_DATE('01/01/2099')) ELSE TO_DATE('01/01/2099') END
AND :P_DETALHAR = 'A' --ATIVIDADE OPERAÇÕES PRODUÇÃO
GROUP BY EFX.DESCRICAO
order by PRC.CODPRC, EFX.IDEFX)ATIVIDADE
