create or replace FUNCTION OBTEMCUSTO_SPARK(
  P_CODPROD IN NUMBER,
  P_POREMP IN CHAR,
  P_CODEMP IN NUMBER,
  P_PORLOCAL IN CHAR,
  P_CODLOCAL IN NUMBER,
  P_PORCONTROLE IN CHAR,
  P_CONTROLE IN VARCHAR2,
  P_DATA IN DATE,
  P_TIPO IN NUMBER)
RETURN FLOAT
IS  P_CUSREP          TGFCUS.CUSREP%TYPE;
    P_CUSGER          TGFCUS.CUSMED%TYPE;
    P_CUSVARIAVEL     TGFCUS.CUSVARIAVEL%TYPE;
    P_CUSSEMICM       TGFCUS.CUSSEMICM%TYPE;
    P_CUSMEDICM       TGFCUS.CUSMEDICM%TYPE;
    P_ENTRADASEMICMS  TGFCUS.ENTRADASEMICMS%TYPE;
    P_ENTRADACOMICMS  TGFCUS.ENTRADACOMICMS%TYPE;
BEGIN
  BEGIN  
    SELECT NVL(CUSREP,0), 
           NVL(CUSMED,0), 
           NVL(CUSVARIAVEL,0), 
           NVL(CUSSEMICM,0), 
           NVL(CUSMEDICM,0), 
           NVL(ENTRADASEMICMS,0), 
           NVL(ENTRADACOMICMS,0)
      INTO P_CUSREP, 
           P_CUSGER, 
           P_CUSVARIAVEL, 
           P_CUSSEMICM, 
           P_CUSMEDICM, 
           P_ENTRADASEMICMS, 
           P_ENTRADACOMICMS
      FROM TGFCUS
     WHERE CODPROD = P_CODPROD
       AND (P_PORCONTROLE  = 'N' OR CONTROLE = P_CONTROLE)
       AND (P_PORLOCAL = 'N' OR CODLOCAL = P_CODLOCAL)
       AND (P_POREMP = 'N' OR CODEMP = P_CODEMP)
       AND DTATUAL = (SELECT MAX(DTATUAL) FROM TGFCUS CN
                       WHERE CODPROD = P_CODPROD
                         AND DTATUAL <= P_DATA
                         AND (P_PORCONTROLE  = 'N' OR CONTROLE = P_CONTROLE)
                         AND (P_PORLOCAL = 'N' OR CODLOCAL = P_CODLOCAL)
                         AND (P_POREMP = 'N' OR CODEMP = P_CODEMP)
                     );
  EXCEPTION
  WHEN NO_DATA_FOUND THEN 
        P_CUSREP :=0; 
       P_CUSGER:=0; 
       P_CUSVARIAVEL:=0;
       P_CUSSEMICM :=0;
       P_CUSMEDICM :=0;
       P_ENTRADASEMICMS:=0; 
       P_ENTRADACOMICMS:=0;
  END;

  IF P_TIPO = 0 THEN
    RETURN(P_CUSREP);
  ELSIF P_TIPO = 1 THEN
    RETURN(P_CUSGER);
  ELSIF P_TIPO = 2 THEN
    RETURN(P_CUSVARIAVEL);
  ELSIF P_TIPO = 3 THEN
    RETURN(P_CUSSEMICM);
  ELSIF P_TIPO = 4 THEN
    RETURN(P_CUSMEDICM);
  ELSIF P_TIPO = 5 THEN
    RETURN(P_ENTRADASEMICMS);
  ELSIF P_TIPO = 6 THEN
    RETURN(P_ENTRADACOMICMS);
  ELSE
    RETURN (0);
  END IF;
EXCEPTION
   WHEN NO_DATA_FOUND THEN RETURN (0);
END;