SELECT FIN.NUFIN, 
	FIN.CODEMP,
 FIN.CODPARC,
(SELECT PAR.NOMEPARC FROM TGFPAR PAR WHERE PAR.CODPARC=FIN.CODPARC) AS PARCEIRO,
	FIN.NUMNOTA, 
	FIN.DTNEG, 
	FIN.DHBAIXA, 
	FIN.CODTIPOPER, 
	FIN.VLRDESDOB, 
	FIN.VLRJURO, 
	FIN.VLRMULTA
FROM TGFFIN FIN
WHERE (FIN.DHBAIXA >= :P_PERIODO.INI AND FIN.DHBAIXA <=:P_PERIODO.FIN)
	AND FIN.CODTIPOPERBAIXA IN :P_CODTIPOPERBAIXA
	AND FIN.CODEMP IN (1,2)
	AND (FIN.VLRJURO > 0 OR FIN.VLRMULTA > 0)
