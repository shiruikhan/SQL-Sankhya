SELECT CODPARC, RAZAOSOCIAL, SUM(TOTAL) AS TOTAL, :NATUREZA AS NATUREZA2 FROM(
SELECT 
FIN.CODPARC, 
PAR.RAZAOSOCIAL,
((FIN.VLRDESDOB)* FIN.RECDESP) AS TOTAL,
FIN.DHBAIXA,
FIN.CODEMP,
FIN.DTENTSAI, 
FIN.DTNEG, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODTIPOPER
FROM TGFFIN FIN , TGFPAR PAR, TGFNAT NAT , TGFTOP T  
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODEMP IN :CODEMP  AND  
FIN.DTNEG <= :DAT1 AND 
(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
T.TIPMOV IN ('I')  AND
NAT.AD_TIPOCTBZ = 'A' AND
(FIN.CODNAT = :NATUREZA or :NATUREZA = 0)
)GROUP BY CODPARC, RAZAOSOCIAL
UNION ALL
SELECT 0 AS CODPARC, ' .TODOS' AS RAZAOSOCIAL, NULL AS TOTAL, :NATUREZA AS NATUREZA2 FROM DUAL
ORDER BY TOTAL DESC
