SELECT CAB.NUNOTA,
CAB.CHAVENFE,
	CAB.CODTIPOPER,
	(SELECT DISTINCT DESCROPER FROM TGFTOP T WHERE T.CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER,
	TRUNC(CAB.DTENTSAI) AS DTENTSAI,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	(SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE I WHERE I.NUNOTA = CAB.NUNOTA) AS QTDSALDO,
	(SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE IT WHERE IT.NUNOTA IN (SELECT DISTINCT C.NUNOTA FROM TGFCAB C WHERE C.CODTIPOPER = 1202 AND C.CHAVENFEREF = CAB.CHAVENFE)) AS DEBITO,
	(CASE WHEN (SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE I WHERE I.NUNOTA = CAB.NUNOTA) > (SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE IT WHERE IT.NUNOTA IN (SELECT DISTINCT C.NUNOTA FROM TGFCAB C WHERE C.CODTIPOPER = 1202 AND C.CHAVENFEREF = CAB.CHAVENFE)) THEN 'PENDENTE' 
		WHEN (SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE I WHERE I.NUNOTA = CAB.NUNOTA) = (SELECT (SUM(NVL(QTDNEG,0))) FROM TGFITE IT WHERE IT.NUNOTA IN (SELECT DISTINCT C.NUNOTA FROM TGFCAB C WHERE C.CODTIPOPER = 1202 AND C.CHAVENFEREF = CAB.CHAVENFE)) THEN 'COMPLETO' ELSE 'PENDENTE' END) TESTE	
FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
WHERE CAB.CODTIPOPER IN (1108,2208)
	AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
	AND (:P_PERIODO IS NULL OR (TRUNC(CAB.DTENTSAI) >= :P_PERIODO.INI AND TRUNC(CAB.DTENTSAI) <= :P_PERIODO.FIN))
ORDER BY CAB.DTENTSAI, CAB.NUNOTA
