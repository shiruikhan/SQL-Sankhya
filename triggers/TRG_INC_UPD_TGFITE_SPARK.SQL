create or replace TRIGGER TRG_INC_UPD_TGFITE_SPARK 
BEFORE UPDATE ON TGFITE 
FOR EACH ROW
DECLARE
	P_CODLOCAL NUMBER;
	P_TIPMOV TGFCAB.TIPMOV%TYPE;
	P_NUCONF TPRCONF.NUCONF%TYPE;

BEGIN
	BEGIN
		SELECT NVL(AD_CODLOCALDEST,0), TIPMOV INTO P_CODLOCAL, P_TIPMOV
		FROM TGFCAB 
		WHERE NUNOTA = :NEW.NUNOTA;
		EXCEPTION WHEN NO_DATA_FOUND THEN P_CODLOCAL:=0;
	END;

	IF P_TIPMOV = 'T' AND P_CODLOCAL > 0 AND :NEW.CODLOCALORIG <> P_CODLOCAL AND :NEW.SEQUENCIA < 0 THEN
		:NEW.CODLOCALORIG := P_CODLOCAL;
	END IF;

	IF P_TIPMOV = 'F' AND :NEW.ATUALESTOQUE =1 AND :NEW.RESERVA='N' THEN 
		BEGIN
			SELECT MAX(CON.NUCONF) INTO P_NUCONF 
			FROM TGFCAB CAB 
				INNER JOIN TPRIATV ATV ON (CAB.IDIPROC = ATV.IDIPROC)
				INNER JOIN TPRCONF CON ON (ATV.IDIATV = CON.IDIATV)
			WHERE CAB.NUNOTA = :NEW.NUNOTA;
			EXCEPTION WHEN NO_DATA_FOUND THEN P_NUCONF := 0;
		END;

		INSERT INTO TGFSER (NUNOTA,CODPROD,SEQUENCIA,SERIE,ATUALESTOQUE,CODUSU,DTALTER) 
			SELECT :NEW.NUNOTA,:NEW.CODPROD,:NEW.SEQUENCIA,CODBARRA,1,STP_GET_CODUSULOGADO(), SYSDATE FROM AD_TPRCOI WHERE NUCONF = P_NUCONF;
	END IF;
END; 