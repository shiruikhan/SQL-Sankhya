SELECT CAB.NUNOTA,
	TRUNC(CAB.DTNEG) AS DTNEG,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.QTDNEG,
	CAB.OBSERVACAO
FROM TGFITE ITE 
	LEFT JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA 
	LEFT JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD 
WHERE (CAB.TIPMOV <> 'J') 
	AND (ITE.STATUSNOTA = 'L') 
	AND (CAB.AD_NUMPS IS NULL)
	AND CAB.CODTIPOPER NOT IN (409)
    AND CAB.CODUSUINC = 81    
    AND TRUNC(CAB.DTNEG) = :A_DTNEG
	AND CAB.CODCENCUS = :A_CODCENCUS
	AND ITE.ATUALESTOQUE = -1
ORDER BY CAB.NUNOTA, ITE.CODPROD
