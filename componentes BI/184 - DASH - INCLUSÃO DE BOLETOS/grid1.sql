SELECT 
     FIN.CODEMP
    ,FIN.NUFIN
    ,FIN.NUMNOTA
    ,FIN.DESDOBRAMENTO
    ,FIN.CODPARC
    ,PAR.NOMEPARC
    ,F.VLRLIQUIDO
    ,FIN.DTVENC
    ,FIN.DTNEG
    ,TIT.DESCRTIPTIT
    ,CTA.DESCRICAO

FROM TGFFIN FIN 

 INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = FIN.CODPARC

 INNER JOIN VGFFIN F
    ON F.NUFIN = FIN.NUFIN

 INNER JOIN TGFTIT TIT 
    ON TIT.CODTIPTIT = FIN.CODTIPTIT

 INNER JOIN TSICTA CTA
    ON CTA.CODCTABCOINT = FIN.CODCTABCOINT

WHERE FIN.RECDESP = 1
  AND FIN.PROVISAO = 'N'
  AND FIN.NUCOMPENS IS NULL
  AND FIN.CODTIPTIT = 4
  AND FIN.CODCTABCOINT = :P_CONTA
  AND FIN.DTNEG = :P_DATA
