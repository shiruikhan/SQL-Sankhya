SELECT 
	COALESCE((SELECT 
				  COUNT(DISTINCT(LIV.NUNOTA))
			  FROM TGFLIV LIV 
			  INNER JOIN TGFCAB CAB ON(CAB.NUNOTA = LIV.NUNOTA)
			  INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
			   WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) 
			     AND LIV.NUNOTA = CAB.NUNOTA 
			     AND LIV.ESPDOC = 'NF' 
			     AND (LIV.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
			     AND (TRUNC(LIV.DHMOV) >= :P_DTNEG.INI AND TRUNC(LIV.DHMOV) <= :P_DTNEG.FIN)
			     AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
			     AND (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)),0) QTDNF,	
	COALESCE((SELECT 
				  COUNT(DISTINCT(LIV.NUNOTA))
			  FROM TGFLIV LIV 
			  INNER JOIN TGFCAB CAB ON(CAB.NUNOTA = LIV.NUNOTA)
			  INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
			  WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) 
			     AND LIV.NUNOTA = CAB.NUNOTA 
			     AND LIV.ESPDOC = 'CT' 
			     AND (LIV.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
			     AND (TRUNC(LIV.DHMOV) >= :P_DTNEG.INI AND TRUNC(LIV.DHMOV) <= :P_DTNEG.FIN)
			     AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
			     AND (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)),0) QTDCT,	
	COALESCE((SELECT 
				  COUNT(DISTINCT(LIV.NUNOTA))
			  FROM TGFLIV LIV 
			  INNER JOIN TGFFIN FIN ON(FIN.NUNOTA = LIV.NUNOTA)
			  INNER JOIN TGFTOP TPO ON(TPO.CODTIPOPER = FIN.CODTIPOPER AND TPO.DHALTER = FIN.DHTIPOPER)
			  INNER JOIN TSIEMP EMP ON(EMP.CODEMP = FIN.CODEMP)
			   WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) 
			     AND LIV.NUNOTA = FIN.NUFIN
			     AND LIV.ESPDOC = 'F' 
			     AND (LIV.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
			     AND (TRUNC(LIV.DHMOV) >= :P_DTNEG.INI AND TRUNC(LIV.DHMOV) <= :P_DTNEG.FIN)
			     AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
			     AND (LIV.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)),0) QTDFIN
FROM DUAL
