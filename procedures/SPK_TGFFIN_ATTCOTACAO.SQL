create or replace PROCEDURE "SPK_TGFFIN_ATTCOTACAO" (
	P_CODUSU NUMBER,
	P_IDSESSAO VARCHAR2,
	P_QTDLINHAS NUMBER,
	P_MENSAGEM OUT VARCHAR2
) AS
	PARAM_P_VLRMOEDA FLOAT;
	FIELD_NUFIN NUMBER;
BEGIN
	PARAM_P_VLRMOEDA := ACT_DEC_PARAM(P_IDSESSAO, 'P_VLRMOEDA');
	
	FOR I IN 1..P_QTDLINHAS
		LOOP
		
		FIELD_NUFIN := ACT_INT_FIELD(P_IDSESSAO, I, 'NUFIN');
		
		
		
		UPDATE TGFFIN F SET F.VLRMOEDA = PARAM_P_VLRMOEDA WHERE F.NUFIN = FIELD_NUFIN;
		
		
		
		END LOOP;
	P_MENSAGEM := 'Valor de Cotação atualizado com sucesso!';
END;