SELECT 
	LIB.CODPARC,
 LIB.NUNOTA,
 LIB.DHLIB,
 USU.NOMEUSU,
 LIB.VLRLIBERADO,
 LIB.VLRTOTPED,
 LIB.VLRLIMITE,
 LIB.VLRTOTFIN
FROM TGSLOGLIB LIB
 INNER JOIN TSIUSU USU ON LIB.CODUSULIB = USU.CODUSU
WHERE (LIB.CODPARC = :CODPARC OR LIB.CODPARCMATRIZ = :CODPARCMATRIZ)
 AND LIB.DHLIB >= ADD_MONTHS(SYSDATE, -12)
ORDER BY (LIB.VLRTOTFIN + LIB.VLRTOTPED - LIB.VLRLIMITE) DESC
FETCH FIRST 5 ROWS ONLY
