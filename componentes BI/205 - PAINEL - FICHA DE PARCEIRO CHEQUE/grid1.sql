SELECT CAB.NUNOTA
	,FIN.NUFIN
	,CAB.CODPARC
	,PAR.NOMEPARC
	,CAB.CODVEND
	,VEN.APELIDO
	,CAB.DTNEG
	,CAB.NUMNOTA
	,FIN.DESDOBRAMENTO
	,FIN.VLRDESDOB
	,(
		SELECT CHQ.NUMCHEQUE
		FROM TGFCHQ CHQ
		WHERE CHQ.NUFIN = FIN.NUFIN
		) AS NR_CHEQUE
	,'CHEQUE NÃO RECEBIDO' AS STATUS
	,NVL(FIN.AD_CHEQUECLI, 'N') AS CHEQUE_CLI
	,NVL(FIN.AD_CHEQUECOM, 'N') AS CHEQUE_COM
	,NVL(FIN.AD_CHEQUEFIN, 'N') AS CHEQUE_FIN
	,FIN.HISTORICO
FROM TGFCAB CAB
INNER JOIN TGFFIN FIN ON FIN.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
INNER JOIN TGFVEN VEN ON VEN.CODVEND = CAB.CODVEND
WHERE CAB.CODEMP = 501
	AND CAB.CODTIPVENDA = 139
	AND FIN.RECDESP = 1
	AND FIN.NUBCO IS NULL
	AND FIN.PROVISAO = 'N'
	AND :A_STATUS = 'CHEQUE NÃO RECEBIDO'
    AND (PAR.CODPARC = :CODPARC OR PAR.CODPARCMATRIZ = :CODPARCMATRIZ)
