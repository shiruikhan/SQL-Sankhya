SELECT CAB.NUNOTA,
	CAB.DTENTSAI,
	CAB.NUMNOTA,
	CAB.CODTIPOPER,
	(SELECT MAX(DESCROPER) FROM TGFTOP TOP WHERE TOP.CODTIPOPER=CAB.CODTIPOPER) AS TOP,
	ITE.CODPROD,
	(CASE WHEN ITE.CODLOCALORIG = 101 THEN CAB.AD_CODLOCALDEST ELSE ITE.CODLOCALORIG END) CODLOCAL,
	(SELECT LOC.DESCRLOCAL FROM TGFLOC LOC WHERE LOC.CODLOCAL= (CASE WHEN ITE.CODLOCALORIG = 101 THEN    	CAB.AD_CODLOCALDEST ELSE ITE.CODLOCALORIG END)) AS LOCAL,
	(SELECT DESCRPROD FROM TGFPRO PRO WHERE ITE.CODPROD=PRO.CODPROD) AS DESCRICAO,
	(SELECT P.RAZAOSOCIAL FROM TGFPAR P WHERE P.CODPARC = (SELECT CODPARCFORN FROM TGFPRO PRO WHERE ITE.CODPROD = PRO.CODPROD)) AS FORNECEDORPREF,
	ITE.QTDNEG
FROM TGFCAB CAB
	INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
WHERE TRUNC(CAB.DTENTSAI) >= :P_PERIODO.INI AND  TRUNC(CAB.DTENTSAI) <= :P_PERIODO.FIN
	AND CAB.CODTIPOPER = :P_CODTIPOPER
ORDER BY CAB.DTENTSAI, CAB.NUNOTA, ITE.CODPROD
