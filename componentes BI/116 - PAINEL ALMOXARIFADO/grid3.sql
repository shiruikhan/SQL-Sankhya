SELECT ITE.NUNOTA,
	CAB.DTENTSAI,
	ITE.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL, 
	(ITE.QTDNEG - ITE.QTDENTREGUE) AS PENDENTE, 
	TOP.DESCROPER
FROM TGFPRO PRO 
	LEFT JOIN TGFITE ITE ON PRO.CODPROD = ITE.CODPROD 
	LEFT JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA 
	LEFT JOIN TGFTOP TOP ON (CAB.CODTIPOPER = TOP.CODTIPOPER AND CAB.DHTIPOPER = TOP.DHALTER) 
	LEFT JOIN TSICUS CUS ON CAB.CODCENCUS = CUS.CODCENCUS
WHERE ITE.PENDENTE = 'S'
	AND ITE.STATUSNOTA = 'L' 
	AND ITE.CODPROD = :A_CODPROD 
	and CAB.TIPMOV = 'O' 
ORDER BY ITE.NUNOTA
