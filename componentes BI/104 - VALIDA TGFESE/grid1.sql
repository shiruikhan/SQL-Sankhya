SELECT CODPROD,
	SUM(CASE WHEN ATUALESTOQUE = 1 THEN QTDNEG ELSE 0 END) - SUM(CASE WHEN ATUALESTOQUE = -1 THEN QTDNEG ELSE 0 END) AS SALDO
FROM TGFESE
WHERE (CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND CODLOCALORIG = :P_CODLOCALORIG
	AND CODEMP = :P_CODEMP
	AND TRUNC(DTREFERENCIA) >= '01/01/2022'
	AND TRUNC(DTREFERENCIA) <= :P_DTREFERENCIA
GROUP BY CODPROD
	HAVING SUM(CASE WHEN ATUALESTOQUE = 1 THEN QTDNEG ELSE 0 END)- SUM(CASE WHEN ATUALESTOQUE = -1 THEN QTDNEG ELSE 0 END) > 0
ORDER BY CODPROD
