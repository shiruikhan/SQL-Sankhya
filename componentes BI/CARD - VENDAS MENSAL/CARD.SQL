  Nome do Script : CARD
  Tipo           : Componente BI — Card
  Dashboard      : CARD - VENDAS MENSAL
  Componente     : CARD
  Descrição      : Card com vendas mensais por grupo de produtos comparado com meta

  Parâmetros     : Sem parâmetros

  Tabelas        : TGFCAB, TGFITE, TGFPRO, TGFGRU

  Autor          : Silvio Vieira
  Cargo          : Analista de Sistemas Sênior
  Empresa        : Spark Eletrônica
  Data de Criação: [A DEFINIR]
  Última Revisão : Abril/2026 — Padronização de cabeçalho e comentários
==============================================================================*/

SELECT
    GRUPO,
    VENDAS,
    META,
    (VENDAS - META) AS SALDO,
    CASE
        WHEN (VENDAS - META) >= 0 THEN '#b4f7b4ff'
        ELSE '#f38484'
    END AS BKCOLOR
FROM (
    SELECT
        CASE
            WHEN G.CODGRUPOPROD IN (3170001,3250001,3250004,3250006) THEN '12V'
            WHEN G.CODGRUPOPROD IN (3170002,3250002,3250005) THEN '24V'
            WHEN G.CODGRUPOPROD IN (3250003) THEN '48V'
            WHEN G.CODGRUPOPROD IN (3160001) THEN 'Carregador'
            WHEN G.CODGRUPAI IN (3180000) THEN 'Central'
            WHEN G.CODGRUPOPROD IN (3161001,3161003) THEN 'Conversor'
            WHEN G.CODGRUPOPROD IN (3161002) THEN 'Conversor CH'
            WHEN G.CODGRUPAI IN (3340000) THEN 'Inversor'
            WHEN G.CODGRUPAI IN (3490000) THEN 'Nautico'
            WHEN (G.CODGRUPOPROD IN (3160002,3160003,3160004) OR G.CODGRUPAI IN (3370000)) THEN 'OEM'
            WHEN G.CODGRUPAI IN (3700000) THEN 'USB'
            ELSE G.DESCRGRUPOPROD
        END AS GRUPO,
        SUM(I.QTDNEG) AS VENDAS,
        CASE
            WHEN G.CODGRUPOPROD IN (3170001,3250001,3250004,3250006) THEN 7500
            WHEN G.CODGRUPOPROD IN (3170002,3250002,3250005) THEN 400
            WHEN G.CODGRUPOPROD IN (3250003) THEN 100
            WHEN G.CODGRUPOPROD IN (3160001) THEN 200
            WHEN G.CODGRUPAI IN (3180000) THEN 200
            WHEN G.CODGRUPOPROD IN (3161001,3161003) THEN 280
            WHEN G.CODGRUPOPROD IN (3161002) THEN 300
            WHEN G.CODGRUPAI IN (3340000) THEN 500
            WHEN G.CODGRUPAI IN (3490000) THEN 50
            WHEN (G.CODGRUPOPROD IN (3160002,3160003,3160004) OR G.CODGRUPAI IN (3370000)) THEN 150
            WHEN G.CODGRUPAI IN (3700000) THEN 0
            ELSE 0
        END AS META
    FROM TGFCAB C
        INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
        INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
        INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
        LEFT JOIN TGFGRU PAI ON G.CODGRUPAI = PAI.CODGRUPOPROD
    WHERE C.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
        AND C.TIPMOV = 'V'
        AND TRUNC(C.DTNEG, 'MM') = TRUNC(SYSDATE, 'MM')
        AND TRUNC(C.DTNEG, 'YYYY') = TRUNC(SYSDATE, 'YYYY')
        AND P.USOPROD = 'V'
        AND (
            G.CODGRUPOPROD IN (3170001, 3170002, 3250001, 3250002, 3250003, 3250004, 3250005, 3250006, 3160001, 3161001, 3161002, 3161003, 3160002, 3160003, 3160004)
            OR
            G.CODGRUPAI IN (3180000, 3340000, 3490000, 3370000, 3700000)
        )
    GROUP BY
        CASE
            WHEN G.CODGRUPOPROD IN (3170001,3250001,3250004,3250006) THEN '12V'
            WHEN G.CODGRUPOPROD IN (3170002,3250002,3250005) THEN '24V'
            WHEN G.CODGRUPOPROD IN (3250003) THEN '48V'
            WHEN G.CODGRUPOPROD IN (3160001) THEN 'Carregador'
            WHEN G.CODGRUPAI IN (3180000) THEN 'Central'
            WHEN G.CODGRUPOPROD IN (3161001,3161003) THEN 'Conversor'
            WHEN G.CODGRUPOPROD IN (3161002) THEN 'Conversor CH'
            WHEN G.CODGRUPAI IN (3340000) THEN 'Inversor'
            WHEN G.CODGRUPAI IN (3490000) THEN 'Nautico'
            WHEN (G.CODGRUPOPROD IN (3160002,3160003,3160004) OR G.CODGRUPAI IN (3370000)) THEN 'OEM'
            WHEN G.CODGRUPAI IN (3700000) THEN 'USB'
            ELSE G.DESCRGRUPOPROD
        END,
        CASE
            WHEN G.CODGRUPOPROD IN (3170001,3250001,3250004,3250006) THEN 7500
            WHEN G.CODGRUPOPROD IN (3170002,3250002,3250005) THEN 400
            WHEN G.CODGRUPOPROD IN (3250003) THEN 100
            WHEN G.CODGRUPOPROD IN (3160001) THEN 200
            WHEN G.CODGRUPAI IN (3180000) THEN 200
            WHEN G.CODGRUPOPROD IN (3161001,3161003) THEN 280
            WHEN G.CODGRUPOPROD IN (3161002) THEN 300
            WHEN G.CODGRUPAI IN (3340000) THEN 500
            WHEN G.CODGRUPAI IN (3490000) THEN 50
            WHEN (G.CODGRUPOPROD IN (3160002,3160003,3160004) OR G.CODGRUPAI IN (3370000)) THEN 150
            WHEN G.CODGRUPAI IN (3700000) THEN 0
            ELSE 0
        END
) SUB
ORDER BY GRUPO