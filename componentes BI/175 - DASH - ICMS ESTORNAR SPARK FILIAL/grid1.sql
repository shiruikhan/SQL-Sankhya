SELECT 
     TAB.NUNOTA
	,TAB.NUMNOTA
    ,TAB.CODPROD
    ,TAB.SEQUENCIA
    ,TAB.BASEICMS
    ,TAB.VLRICMS
    ,TAB.CODCFO
    ,TAB.NR_PEDIDO
    ,(SELECT C.AD_NUNOTASAI
            FROM TGFCAB C
           WHERE C.NUNOTA = TAB.NR_PEDIDO
          ) AS TRANSFERENCIA
    ,(SELECT SUM(I.VLRICMS)
        FROM TGFITE I 
        WHERE I.NUNOTA = (SELECT CASE WHEN TAB.NR_PEDIDO = 708606 AND CODPROD = 3125030 THEN 708992 ELSE C.AD_NUNOTASAI END
                             FROM TGFCAB C
                            WHERE C.NUNOTA = TAB.NR_PEDIDO
                          )
         AND I.CODPROD = TAB.CODPROD) AS ICMS_ORIGEM
    
FROM ( 
SELECT 
         CAB.NUNOTA
        ,CAB.NUMNOTA
        ,ITE.CODPROD
        ,ITE.SEQUENCIA
        ,ITE.BASEICMS
        ,ITE.VLRICMS
        ,ITE.CODCFO
        ,(SELECT MAX(VAR.NUNOTAORIG)
            FROM TGFVAR VAR
         WHERE VAR.NUNOTA =  CAB.NUNOTA
         ) AS NR_PEDIDO

FROM TGFCAB CAB
INNER JOIN TGFITE ITE 
    ON ITE.NUNOTA = CAB.NUNOTA 
WHERE CAB.DTNEG >= :P_PERIODO.INI
 AND  CAB.DTNEG <= :P_PERIODO.FIN
 AND  CAB.CODEMP = 2
 AND  CAB.STATUSNFE = 'A'
 AND  CAB.TIPMOV ='V'
)TAB
