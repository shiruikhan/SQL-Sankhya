SELECT
  F.NOME AS TECNICO,
  --COUNT(CASE WHEN ASS.DTCONCLUSAO IS NULL THEN 1 END) AS EM_ABERTO,
  COUNT(CASE WHEN ASS.DTCONCLUSAO IS NOT NULL THEN 1 END) AS FINALIZADA,
  COUNT(ASS.NUMOS) AS TOTAL_OS
FROM AD_TGFASS  ASS
  LEFT JOIN AD_CADFUNC F ON NVL(ASS.TECNICO,0) = F.IDFUNC
WHERE TRUNC(ASS.DTCONCLUSAO, 'MM')   = TRUNC(SYSDATE, 'MM')
  AND TRUNC(ASS.DTCONCLUSAO, 'YYYY') = TRUNC(SYSDATE, 'YYYY')
  --AND ASS.TECNICO IS NOT NULL
GROUP BY
  F.NOME
ORDER BY F.NOME
