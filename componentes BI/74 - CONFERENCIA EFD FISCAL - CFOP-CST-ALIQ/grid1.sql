SELECT  REFERENCIA,
SUM(VLRCTB) AS VLRTOT, 
CODCFO, 
ORIGEM,
CODTRIB, 
SUM(BASEICMS) AS BASEICMS, 
ALIQICMS,
SUM(VLRICMS) AS VLRICMS,
SUM(BASEST) AS BASEST, 
SUM(VLRST) AS VLRST, 
SUM(VLRIPI) AS VLRIPI

FROM
(
   SELECT CAB.NUNOTA, CAB.NUMNOTA, ITE.ORIGPROD AS ORIGEM,
		LIV.CODCFO, LIV.VLRCTB, LIV.CODTRIB, 
		LIV.BASEICMS, LIV.ALIQICMS, LIV.VLRICMS, 
		LIV.BASERETENCAO AS BASEST, LIV.ICMSRETENCAO AS VLRST, LIV.VLRIPI,  
		TRUNC(TO_DATE(LIV.DHMOV), 'MON') AS REFERENCIA

   FROM TGFCAB CAB, TGFITE ITE,
		TSICID CID, TSIUFS UF, 
		TGFLIV LIV

   WHERE LIV.NUNOTA = CAB.NUNOTA 
   AND LIV.NUNOTA = ITE.NUNOTA 
   AND LIV.SEQUENCIA = ITE.SEQUENCIA 
   AND CAB.NUNOTA = ITE.NUNOTA 
   AND CAB.CODCIDDESTINO = CID.CODCID
   AND CID.UF = UF.CODUF
   AND (LIV.DHMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
   AND (LIV.DHMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null) 
   AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
   AND LIV.CODCFO >= :P_CODCFOPINI
   AND LIV.CODCFO <= :P_CODCFOPFIN

   
) V 
GROUP BY REFERENCIA, CODCFO, ORIGEM, CODTRIB, ALIQICMS
ORDER BY REFERENCIA, CODCFO, ORIGEM, CODTRIB, ALIQICMS
