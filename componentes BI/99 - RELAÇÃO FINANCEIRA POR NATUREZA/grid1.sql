SELECT FIN.NUNOTA AS NUNICO,
	FIN.NUFIN AS NFINANCEIRO,
	FIN.NUMNOTA AS NRNOTA,
	FIN.CODPARC,
	PAR.RAZAOSOCIAL,
	FIN.CODNAT,
	(SELECT DISTINCT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = FIN.CODNAT) AS DESCRNAT,
	FIN.DTNEG,
	FIN.DTVENC,
	FIN.DHBAIXA,
	FIN.VLRBAIXA
FROM TGFFIN FIN
	INNER JOIN TGFPAR PAR ON FIN.CODPARC = PAR.CODPARC
WHERE (TRUNC(FIN.DHBAIXA) >= :P_BAIXA.INI AND TRUNC(FIN.DHBAIXA) <= :P_BAIXA.FIN)
	AND FIN.PROVISAO = 'N'
	AND FIN.RECDESP = -1
	AND FIN.DHBAIXA IS NOT NULL
	AND (:P_CODNAT IS NULL OR FIN.CODNAT = :P_CODNAT)
	AND NVL(FIN.NUFIN,0) NOT IN (SELECT R.NUFIN FROM TGFRAT R WHERE R.ORIGEM = 'F')
	AND NVL(FIN.NUNOTA,0) NOT IN (SELECT R.NUFIN FROM TGFRAT R WHERE R.ORIGEM = 'E')
UNION ALL
SELECT (SELECT DISTINCT FN.NUNOTA FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS NUNICO,
	F.NUFIN AS NFINANCEIRO,
	(SELECT DISTINCT FN.NUMNOTA FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS NRNOTA,
	(SELECT DISTINCT FN.CODPARC FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS CODPARC,
	(SELECT P.RAZAOSOCIAL FROM TGFPAR P WHERE P.CODPARC = (SELECT DISTINCT FN.CODPARC FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN)) AS RAZAOSOCIAL,
	F.CODNAT,
	(SELECT DISTINCT NA.DESCRNAT FROM TGFNAT NA WHERE NA.CODNAT = F.CODNAT) AS DESCRNAT,
	(SELECT DISTINCT FN.DTNEG FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS DTNEG,
	(SELECT DISTINCT FN.DTVENC FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS DTVENC,
	(SELECT DISTINCT FN.DHBAIXA FROM TGFFIN FN WHERE FN.NUFIN = F.NUFIN) AS DHBAIXA,
	F.VLRBAIXA
FROM (SELECT RAT.NUFIN,
			RAT.CODNAT,
			ROUND(((RAT.PERCRATEIO/100) * FIN.VLRBAIXA),2) AS VLRBAIXA
		FROM TGFRAT RAT 
			INNER JOIN TGFFIN FIN ON (RAT.NUFIN = FIN.NUFIN AND RAT.ORIGEM = 'F')
		WHERE FIN.PROVISAO = 'N'
		AND FIN.RECDESP = -1
		AND FIN.DHBAIXA IS NOT NULL
		AND (:P_CODNAT IS NULL OR RAT.CODNAT = :P_CODNAT)
		AND (TRUNC(FIN.DHBAIXA) >= :P_BAIXA.INI AND TRUNC(FIN.DHBAIXA) <= :P_BAIXA.FIN)) F
UNION ALL
SELECT C.NUFIN AS NUNICO,
	(SELECT DISTINCT FN.NUNOTA FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS NFINANCEIRO,
	(SELECT DISTINCT FN.NUMNOTA FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS NRNOTA,
	(SELECT DISTINCT FN.CODPARC FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS CODPARC,
	(SELECT P.RAZAOSOCIAL FROM TGFPAR P WHERE P.CODPARC = (SELECT DISTINCT FN.CODPARC FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN)) AS RAZAOSOCIAL,
	C.CODNAT,
	(SELECT DISTINCT NA.DESCRNAT FROM TGFNAT NA WHERE NA.CODNAT = C.CODNAT) AS DESCRNAT,
	(SELECT DISTINCT FN.DTNEG FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS DTNEG,
	(SELECT DISTINCT FN.DTVENC FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS DTVENC,
	(SELECT DISTINCT FN.DHBAIXA FROM TGFFIN FN WHERE FN.NUNOTA = C.NUFIN) AS DHBAIXA,
	C.VLRBAIXA
FROM (SELECT RAT.NUFIN,
			RAT.CODNAT,
			ROUND(((RAT.PERCRATEIO/100) * FIN.VLRBAIXA),2) AS VLRBAIXA
		FROM TGFRAT RAT 
			INNER JOIN TGFFIN FIN ON (RAT.NUFIN = FIN.NUNOTA AND RAT.ORIGEM = 'E')
		WHERE FIN.PROVISAO = 'N'
		AND FIN.RECDESP = -1
		AND FIN.DHBAIXA IS NOT NULL
		AND (:P_CODNAT IS NULL OR RAT.CODNAT = :P_CODNAT)
		AND (TRUNC(FIN.DHBAIXA) >= :P_BAIXA.INI AND TRUNC(FIN.DHBAIXA) <= :P_BAIXA.FIN)) C
