/*==============================================================================
  Nome do Script : SNK_BLOQUEIO_FECHAMENTO
  Tipo           : Function Nativa Sankhya (referencia -- nao customizada)
  Descricao      : Verifica se uma movimentacao (estoque/custo/financeiro/contabil/fiscal)
                  esta bloqueada por fechamento na data informada, considerando liberacoes
                  em TCBLBC.
  Assinatura     : SNK_BLOQUEIO_FECHAMENTO (P_CODEMP IN NUMBER, P_DATA IN DATE, P_TIPO_ACAO IN CHAR, P_TIPO_MOV IN CHAR, P_ROTINA_CTB IN CHAR, P_TIPO_ITEM IN CHAR, P_NUCHAVE IN NUMBER)
                   RETURN BOOLEAN
  Observacoes    : - Objeto nativo do ERP -- atualizacoes do Sankhya podem
                     sobrescrever esta function. Revisar apos cada upgrade
                     (mesmo cuidado descrito em trigger_nativa/README.md).
                   - Capturado do banco em 18/09/2026, via:
                     SELECT DBMS_METADATA.GET_DDL('FUNCTION', 'SNK_BLOQUEIO_FECHAMENTO', 'SPARKPRD') FROM dual;
==============================================================================*/
  create or replace FUNCTION SNK_BLOQUEIO_FECHAMENTO (P_CODEMP IN NUMBER, P_DATA IN DATE, P_TIPO_ACAO IN CHAR, P_TIPO_MOV IN CHAR, P_ROTINA_CTB IN CHAR,  P_TIPO_ITEM IN CHAR, P_NUCHAVE IN NUMBER)
RETURN BOOLEAN
IS
  P_BLOQUEIO BOOLEAN;
  P_TIPOFECHAMENTO CHAR(1);
  P_DTFECHAMENTO DATE;
  P_NUBLOQUEIO NUMBER;
  P_SEQUENCIA NUMBER;
  P_REFERENCIA DATE;
  P_DOC_REF_MENOR BOOLEAN;
  P_EXIST_LIB NUMBER;
  P_SYSDATE DATE;
  P_QTD_BLOQ_NA_REF NUMBER;
  P_REFFIXA VARCHAR(1);

  P_MOVIMENTACAO_ESTOQUE CHAR(2) := '01';
  P_MOVIMENTACAO_CUSTO_NOTA CHAR(2) := '02';
  P_MOVIMENTACAO_CUSTO_PROD CHAR(2) := '03';
  P_MOVIMENTACAO_FINANCEIRA CHAR(2) := '04';
  P_MOVIMENTACAO_BANCARIA CHAR(2) := '05';
  P_MOVIMENTACAO_CONTABIL CHAR(2) := '06';
  P_MOVIMENTACAO_FISCAL_ICMS_IPI CHAR(2) :='07';
  P_MOVIMENTACAO_FISCAL_ISS CHAR(2) := '08';
  P_MOVIMENTACAO_FISCAL_AJUSTE CHAR(2) := '09';
  P_MOVIMENTACAO_CUSTO_SERV CHAR(2) := '10';

  P_TIPO_ITEM_ESTOQUE_ENTRADA CHAR(1) := 'E';
  P_TIPO_ITEM_ESTOQUE_SAIDA CHAR(1) := 'S';
  P_TIPO_ITEM_FINANCEIRO_RECEITA CHAR(1) := 'R';
  P_TIPO_ITEM_FINANCEIRO_DESPESA CHAR(1) := 'D';

  P_TIPO_FECHAMENTO_48HORAS CHAR(1) := 'D';
  P_TIPO_FECHAMENTO_QUINZENAL CHAR(1) := 'Q';

  P_DIA_QUINZE NUMBER := 15;

  P_TIPO_ACAO_INCLUSAO CHAR(1) := 'I';
  P_TIPO_ACAO_ALTERACAO CHAR(1) := 'A';
  P_TIPO_ACAO_DELECAO CHAR(1) := 'D';
  P_ROTINA_DEFAULT CHAR(1) := '0';
  P_INCLUSAO_MOV_BANCARIO CHAR(1) := 'A';
  P_RECALCULO_CUSTO CHAR(1) := '9';

BEGIN

  P_SYSDATE := SYSDATE;

  IF (P_DATA IS NULL) OR P_CODEMP = 0 OR TRUNC(P_DATA) >= SYSDATE THEN  
    RETURN FALSE;
  END IF;

  P_DOC_REF_MENOR := SNK_TRUNC_DATE(P_DATA,'MM') < SNK_TRUNC_DATE(P_SYSDATE, 'MM');

  IF P_CODEMP IS NULL  AND P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_PROD THEN 
    SELECT COUNT(1) INTO P_QTD_BLOQ_NA_REF
    FROM TCBBFC BFC
    WHERE BFC.REFERENCIA =  TRUNC(P_DATA, 'MM');

    IF P_QTD_BLOQ_NA_REF > 0 THEN 
      RETURN TRUE;-- Usado para TRIGGER da TGFCUS quando o parÃ¿Æ¿Ã¿Â¢metro CUSTOPOREMP estiver desligado
    END IF;
  ELSE 
     BEGIN
        SELECT
          CASE 
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_ESTOQUE THEN
              CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_ESTOQUE_ENTRADA THEN
                BFC.DTFECHAMENTOENT
              ELSE 
                BFC.DTFECHAMENTOSAI
              END
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_NOTA OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_PROD OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_SERV THEN
              BFC.DTFECHAMENTOCUS
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_FINANCEIRA THEN
              CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_FINANCEIRO_DESPESA THEN
                BFC.DTFECHAMENTODESP
              ELSE 
                BFC.DTFECHAMENTOREC
              END
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_BANCARIA THEN
              BFC.DTFECHAMENTOBCO
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_CONTABIL THEN
              BFC.DTFECHAMENTOCTB
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ICMS_IPI OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ISS 
              OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_AJUSTE THEN
              BFC.DTFECHAMENTOFIS
          END AS DTFECHAMENTO,
          BFC.NUBLOQUEIO,
          BFC.SEQUENCIA,
          BFC.REFERENCIA,
          CASE 
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_ESTOQUE THEN
              CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_ESTOQUE_ENTRADA THEN
                BFC.TIPOFECHAESTENT
              ELSE 
                BFC.TIPOFECHAESTSAI
              END
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_NOTA OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_PROD THEN
              BFC.TIPOFECHACALCUST
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_FINANCEIRA THEN
              CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_FINANCEIRO_DESPESA THEN
                BFC.TIPOFECHAFINDESP
              ELSE 
                BFC.TIPOFECHAFINREC
              END
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_BANCARIA THEN
              BFC.TIPOFECHAMOVBCO
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_CONTABIL THEN
              BFC.TIPOFECHAMOVCTB
            WHEN P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ICMS_IPI OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ISS 
              OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_AJUSTE THEN
              BFC.TIPOFECHAMOVFIS
          END AS TIPOFECHAMENTO
          INTO P_DTFECHAMENTO, P_NUBLOQUEIO, P_SEQUENCIA, P_REFERENCIA, P_TIPOFECHAMENTO
        FROM TCBBFC BFC 
            WHERE BFC.CODEMP = P_CODEMP
            AND BFC.REFERENCIA =  TRUNC(P_DATA, 'MM');
      EXCEPTION WHEN NO_DATA_FOUND THEN
		BEGIN
			SELECT
			CASE 
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_ESTOQUE THEN
				CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_ESTOQUE_ENTRADA THEN
					BFC.DTFECHAMENTOENT
				ELSE 
					BFC.DTFECHAMENTOSAI
				END
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_NOTA OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_PROD OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_SERV THEN
				BFC.DTFECHAMENTOCUS
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_FINANCEIRA THEN
				CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_FINANCEIRO_DESPESA THEN
					BFC.DTFECHAMENTODESP
				ELSE 
					BFC.DTFECHAMENTOREC
				END
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_BANCARIA THEN
				BFC.DTFECHAMENTOBCO
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_CONTABIL THEN
				BFC.DTFECHAMENTOCTB
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ICMS_IPI OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ISS 
				OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_AJUSTE THEN
				BFC.DTFECHAMENTOFIS
			END AS DTFECHAMENTO,
			BFC.NUBLOQUEIO,
			BFC.SEQUENCIA,
			BFC.REFERENCIA,
			CASE 
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_ESTOQUE THEN
				CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_ESTOQUE_ENTRADA THEN
					BFC.TIPOFECHAESTENT
				ELSE 
					BFC.TIPOFECHAESTSAI
				END
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_NOTA OR P_TIPO_MOV = P_MOVIMENTACAO_CUSTO_PROD THEN
				BFC.TIPOFECHACALCUST
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_FINANCEIRA THEN
				CASE WHEN P_TIPO_ITEM = P_TIPO_ITEM_FINANCEIRO_DESPESA THEN
					BFC.TIPOFECHAFINDESP
				ELSE 
					BFC.TIPOFECHAFINREC
				END
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_BANCARIA THEN
				BFC.TIPOFECHAMOVBCO
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_CONTABIL THEN
				BFC.TIPOFECHAMOVCTB
				WHEN P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ICMS_IPI OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_ISS 
				OR P_TIPO_MOV = P_MOVIMENTACAO_FISCAL_AJUSTE THEN
				BFC.TIPOFECHAMOVFIS
			END AS TIPOFECHAMENTO,
			BFC.REFFIXA
			INTO P_DTFECHAMENTO, P_NUBLOQUEIO, P_SEQUENCIA, P_REFERENCIA, P_TIPOFECHAMENTO, P_REFFIXA
			FROM TCBBFC BFC 
				WHERE BFC.CODEMP = P_CODEMP
				AND BFC.REFERENCIA >=  TRUNC(P_DATA, 'MM') 
				AND BFC.REFFIXA = 'S'
                AND ROWNUM = 1
                ORDER BY BFC.REFERENCIA DESC;
		EXCEPTION WHEN NO_DATA_FOUND THEN
			P_REFERENCIA := NULL;
		END;
      END;
  END IF;

	IF P_REFERENCIA IS NOT NULL THEN
		IF (P_REFFIXA IS NOT NULL AND P_REFFIXA = 'S') THEN
			P_BLOQUEIO := TRUE;
		ELSE
			IF P_TIPOFECHAMENTO = P_TIPO_FECHAMENTO_48HORAS THEN
				P_BLOQUEIO := P_DATA < (P_SYSDATE - 2); 
			ELSE 
				IF P_TIPOFECHAMENTO = P_TIPO_FECHAMENTO_QUINZENAL THEN
					P_BLOQUEIO := P_DOC_REF_MENOR OR (TO_NUMBER(TO_CHAR(SYSDATE, 'DD')) > P_DIA_QUINZE AND TO_NUMBER(TO_CHAR(P_DATA, 'DD')) < P_DIA_QUINZE);
				ELSE 
					IF P_DTFECHAMENTO IS NOT NULL  AND SNK_TRUNC_DATE(P_SYSDATE, 'DD') >= P_DTFECHAMENTO THEN
						P_BLOQUEIO := TRUNC(P_DATA) <= P_DTFECHAMENTO; 
					END IF;
				END IF;
			END IF;
		END IF;
	END IF;
	

  IF P_BLOQUEIO THEN 
          SELECT COUNT(1) INTO P_EXIST_LIB 
          FROM TCBLBC L 
          WHERE L.NUBLOQUEIO = P_NUBLOQUEIO 
            AND L.SEQBLOQUEIO = P_SEQUENCIA 
            AND L.STATUSLIB = 'A' -- Aprovado 
              AND ((P_ROTINA_CTB = P_INCLUSAO_MOV_BANCARIO  AND L.TIPOACAO = P_TIPO_ACAO_INCLUSAO)
                   OR L.TIPOACAO = NVL(P_TIPO_ACAO, '')) 
              AND L.TIPOMOV = NVL(P_TIPO_MOV, 0) 
              AND P_SYSDATE BETWEEN DTINILIB AND DTFINLIB
              AND (P_ROTINA_CTB = P_INCLUSAO_MOV_BANCARIO
                  OR P_ROTINA_CTB = P_RECALCULO_CUSTO
                  OR L.ROTINACTB = P_ROTINA_CTB 
                  OR (NVL(L.ROTINACTB, P_ROTINA_DEFAULT) = P_ROTINA_DEFAULT  AND P_TIPO_ACAO = P_TIPO_ACAO_INCLUSAO)
                  OR EXISTS (SELECT 1 
                                  FROM TCBILB I 
                                  WHERE I.NULIBERACAO = L.NULIBERACAO 
                                    AND (P_TIPO_ITEM IS NULL OR I.TIPO = P_TIPO_ITEM)
                                    AND I.NUCHAVE = ABS(NVL(P_NUCHAVE, 0)))
              );

      IF P_EXIST_LIB > 0 THEN 
        P_BLOQUEIO := FALSE;
      END IF;
  END IF;

  RETURN P_BLOQUEIO;   
END;
