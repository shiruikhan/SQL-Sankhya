SELECT SUM(T.VLRICMS) AS VLRICMS,
	      SUM(T.VLRICMS) * :V_PERCPROP AS ESTORNO
	   
FROM (
/*** 1 - PEGO O ICMS DA ENTRADA DAS NOTAS FISCAIS NORMAL ***/

	SELECT SUM(LIV.VLRICMS) AS VLRICMS
	FROM TGFCAB CAB
	
	 INNER JOIN TGFITE ITE 
		ON CAB.NUNOTA = ITE.NUNOTA
		
	 INNER JOIN TGFLIV LIV
		ON LIV.NUNOTA = ITE.NUNOTA 
		 AND LIV.SEQUENCIA = ITE.SEQUENCIA 
	
	WHERE   CAB.STATUSNOTA = 'L'
		AND LIV.DHMOV >= :P_PERIODO.INI
		AND LIV.DHMOV <= :P_PERIODO.FIN
		AND CAB.CODEMP = 1
		AND LIV.ENTSAI = 'E'
		AND LIV.BASEICMS > 0
		AND CAB.CODTIPOPER NOT IN (1221,1204)
		
UNION ALL 

/*** 2 - PEGA O ICMS DO SIMPLES NACIONAL ***/

	SELECT SUM(AJD.VLRICMS) AS VLRICMS
	FROM TGFCAB CAB
	
	 INNER JOIN TGFITE ITE 
		ON CAB.NUNOTA = ITE.NUNOTA
		
	 INNER JOIN TGFLIV LIV
		ON LIV.NUNOTA = ITE.NUNOTA 
		 AND LIV.SEQUENCIA = ITE.SEQUENCIA 
		 
	 INNER JOIN TGFAJD AJD 
	    ON AJD.NUNOTA = ITE.NUNOTA 
		  AND AJD.SEQUENCIA = ITE.SEQUENCIA

	
	WHERE   CAB.STATUSNOTA = 'L'
		AND LIV.DHMOV >= :P_PERIODO.INI
		AND LIV.DHMOV <= :P_PERIODO.FIN
		AND CAB.CODEMP = 1
		AND LIV.ENTSAI = 'E'
		AND AJD.CODAJUSTE = 10990505
UNION ALL 

/*** 3 - PEGO A DEVOLUCAO DE VENDA EXCETO NCM FORA DO REGIME ***/

	SELECT SUM(LIV.VLRICMS)*-1 AS VLRICMS
	FROM TGFCAB CAB
	
	 INNER JOIN TGFITE ITE 
		ON CAB.NUNOTA = ITE.NUNOTA
		
	 INNER JOIN TGFLIV LIV
		ON LIV.NUNOTA = ITE.NUNOTA 
		 AND LIV.SEQUENCIA = ITE.SEQUENCIA
		 
	 INNER JOIN TGFPRO PRO 
		ON PRO.CODPROD = ITE.CODPROD
	
     INNER JOIN TGFTOP TOP	
        ON TOP.CODTIPOPER = CAB.CODTIPOPER  
          AND TOP.DHALTER = CAB.DHTIPOPER		
	
	WHERE   CAB.STATUSNOTA = 'L'
		AND LIV.DHMOV >= :P_PERIODO.INI
		AND LIV.DHMOV <= :P_PERIODO.FIN
		AND CAB.CODEMP = 1
		AND LIV.ENTSAI = 'E'
		AND (LIV.CODCFO IN (1201,2201,2410,1410,1208)OR TOP.CODTIPOPER = 1206)
		AND LIV.BASEICMS > 0
		AND PRO.NCM NOT IN (90303390, 85371090,85312000)
		
UNION ALL 
/*** 4 - PEGO A DEVOLUCAO DENTRO DO PERIODO ***/

	SELECT SUM(CASE WHEN LIV.VLRICMS > 0 THEN LIV.VLRICMS ELSE ITE.AD_VLRICMSSP END )*-1 AS VLRICMS
	FROM TGFCAB CAB
	
	 INNER JOIN TGFITE ITE 
		ON CAB.NUNOTA = ITE.NUNOTA
		
	 INNER JOIN TGFLIV LIV
		ON LIV.NUNOTA = ITE.NUNOTA 
		 AND LIV.SEQUENCIA = ITE.SEQUENCIA
		 
	 INNER JOIN TGFPRO PRO 
		ON PRO.CODPROD = ITE.CODPROD
		
	
	WHERE   CAB.STATUSNOTA = 'L'
		AND LIV.DHMOV >= :P_PERIODO.INI
		AND LIV.DHMOV <= :P_PERIODO.FIN
		AND CAB.CODEMP = 1
		AND LIV.ENTSAI = 'S'
		AND LIV.CODCFO IN (5201,6201,6410,6410)
		AND EXISTS (SELECT 1
		             FROM TGFCAB C 
					  INNER JOIN TGFVAR VAR 
						ON VAR.NUNOTA = CAB.NUNOTA
						AND VAR.SEQUENCIA = ITE.SEQUENCIA
					WHERE C.NUNOTA = VAR.NUNOTAORIG 
					  AND TRUNC(CAB.DTENTSAI,'MM') = TRUNC(C.DTENTSAI,'MM')
					)
UNION ALL 
/*** 5 - PEGA O ICMS NÃO  ***/

	SELECT SUM(AJD.VLRICMS)*-1 AS VLRICMS
	FROM TGFCAB CAB
	
	 INNER JOIN TGFITE ITE 
		ON CAB.NUNOTA = ITE.NUNOTA
		
	 INNER JOIN TGFLIV LIV
		ON LIV.NUNOTA = ITE.NUNOTA 
		 AND LIV.SEQUENCIA = ITE.SEQUENCIA 
		 
	 INNER JOIN TGFAJD AJD 
	    ON AJD.NUNOTA = ITE.NUNOTA 
		  AND AJD.SEQUENCIA = ITE.SEQUENCIA

	
	WHERE   CAB.STATUSNOTA = 'L'
		AND LIV.DHMOV >= :P_PERIODO.INI
		AND LIV.DHMOV <= :P_PERIODO.FIN
		AND CAB.CODEMP = 1
		AND LIV.ENTSAI = 'E'
		AND AJD.CODAJUSTE = 50000999
		AND AJD.CODOBSPADRAO = 123
)T
