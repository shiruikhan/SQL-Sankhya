SELECT COUNT(B.CODPARC) PARCEIROS,
      (( COUNT(B.CODPARC) * 100 ) / B.TOTAL ) AS PERCENTUAL
  FROM ( SELECT A.CODPARC,
                A.QTDEFINANCEIROS,
                A.TOTAL
           FROM ( SELECT TGFPAR.CODPARC,
                       ( SELECT COUNT(TGFPAR.CODPARC) FROM TGFPAR WHERE TGFPAR.FORNECEDOR = 'S' ) TOTAL,
                       ( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.CODPARC = TGFPAR.CODPARC AND TGFFIN.RECDESP <> 0 ) QtdeFinanceiros,
                       ( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.CODPARC = TGFPAR.CODPARC AND TGFCAB.TIPMOV <> 'Z') QtdeOperacoes
  FROM TGFPAR
 WHERE TGFPAR.FORNECEDOR = 'S' ) A
WHERE A.QTDEFINANCEIROS <> 0 ) B
GROUP BY B.TOTAL
