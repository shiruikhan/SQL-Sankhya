SELECT COUNT(NUMOS) AS CONTADOR, 'EM ANDAMENTO' AS STATUS
FROM AD_OSINTERNA
WHERE STATUS='A'
	AND SETOR = 'M'
GROUP BY STATUS
UNION ALL
SELECT COUNT(NUMOS) AS CONTADOR, 'PROGRAMADA' AS STATUS
FROM AD_OSINTERNA
WHERE STATUS='P'
	AND SETOR = 'M'
GROUP BY STATUS
UNION ALL
SELECT COUNT(NUMOS) AS CONTADOR, 'EM ANÁLISE' AS STATUS
FROM AD_OSINTERNA
WHERE STATUS='I'
	AND SETOR = 'M'
GROUP BY STATUS
