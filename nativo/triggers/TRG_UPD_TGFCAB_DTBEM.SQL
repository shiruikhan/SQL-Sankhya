/*==============================================================================
  Nome do Script : TRG_UPD_TGFCAB_DTBEM
  Tipo           : Trigger Nativa Sankhya (instalação do ERP, 12/2021 — referência, não customizada)
  Descrição      : Trigger AFTER EACH ROW UPDATE sobre TGFCAB.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 07/12/2021, última alteração em 03/07/2024.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026, via: SELECT DBMS_METADATA.GET_DDL('TRIGGER', 'TRG_UPD_TGFCAB_DTBEM', 'SPARKPRD') FROM dual;
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_UPD_TGFCAB_DTBEM" AFTER UPDATE ON TGFCAB 
FOR EACH ROW
      WHEN ( NVL(OLD.DTENTSAI, OLD.DTNEG) <> NVL(NEW.DTENTSAI, NEW.DTNEG) ) DECLARE
  P_COUNT           INT;
BEGIN

  -- VERIFICANDO SE O CLIENTE UTILIZA ESTA FUNCIONALIDADE
  SELECT COUNT(*) INTO P_COUNT
  FROM TSIVARBD
  WHERE UTILIZA_TCIBEM = 'N';
  IF P_COUNT > 0 THEN 
    RETURN;
  END IF;

  IF STP_GET_ATUALIZANDO THEN
    RETURN;
  END IF;

  SELECT COUNT(*) 
  INTO P_COUNT
  FROM TCIBEM
  WHERE NUNOTA = :NEW.NUNOTA
  AND ((DTCOMPRA IS NOT NULL AND DTCOMPRA = NVL(:OLD.DTENTSAI, :OLD.DTNEG)) OR 
       (DTINICIODEP IS NOT NULL AND DTINICIODEP = NVL(:OLD.DTENTSAI, :OLD.DTNEG)) OR
       (DTINIREFCIAP IS NOT NULL AND DTINIREFCIAP = NVL(:OLD.DTENTSAI, :OLD.DTNEG)) OR
       (DTINICIOAJ IS NOT NULL AND DTINICIOAJ = NVL(:OLD.DTENTSAI, :OLD.DTNEG)));
  IF P_COUNT > 0 THEN
    UPDATE TCIBEM SET
      DTCOMPRA = CASE WHEN DTCOMPRA IS NOT NULL AND DTCOMPRA = NVL(:OLD.DTENTSAI, :OLD.DTNEG) THEN NVL(:NEW.DTENTSAI, :NEW.DTNEG) ELSE DTCOMPRA END
    , DTINICIODEP = CASE WHEN DTINICIODEP IS NOT NULL AND DTINICIODEP = NVL(:OLD.DTENTSAI, :OLD.DTNEG) THEN NVL(:NEW.DTENTSAI, :NEW.DTNEG) ELSE DTINICIODEP END
    , DTINIREFCIAP = CASE WHEN DTINIREFCIAP IS NOT NULL AND DTINIREFCIAP = NVL(:OLD.DTENTSAI, :OLD.DTNEG) THEN NVL(:NEW.DTENTSAI, :NEW.DTNEG) ELSE DTINIREFCIAP END
    , DTINICIOAJ  = CASE WHEN DTINICIOAJ IS NOT NULL AND DTINICIOAJ = NVL(:OLD.DTENTSAI, :OLD.DTNEG) THEN NVL(:NEW.DTENTSAI, :NEW.DTNEG) ELSE DTINICIOAJ END
    WHERE NUNOTA = :NEW.NUNOTA;
  END IF;
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_UPD_TGFCAB_DTBEM" ENABLE;
