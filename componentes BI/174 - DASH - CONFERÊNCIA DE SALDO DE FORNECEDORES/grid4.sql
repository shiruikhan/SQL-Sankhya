SELECT 
         FIN.NUNOTA 
		,FIN.NUFIN
	    ,FIN.CODPARC 
		,PAR.NOMEPARC 
		,FIN.DTENTSAI
		,FIN.DHBAIXA
		,FIN.VLRDESDOB
		,FIN.VLRJURO
		,FIN.VLRDESC
		,FIN.VLRMULTA
		,FIN.VLRBAIXA	
FROM TGFFIN FIN
 INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = FIN.CODPARC 
WHERE (FIN.DHBAIXA IS NULL OR TRUNC(FIN.DHBAIXA) > :P_DTCORTE.FIN)
AND NVL(FIN.DTENTSAI, FIN.DTNEG) <= :P_DTCORTE.FIN
AND FIN.CODEMP IN (1,2)
AND FIN.CODPARC = :A_CODPARC
AND FIN.PROVISAO = 'N' 
AND FIN.RECDESP = -1
AND FIN.CODTIPOPER NOT IN (1306)
