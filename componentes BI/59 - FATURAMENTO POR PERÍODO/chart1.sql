SELECT 
    GRU.CODGRUPOPROD, 
    GRU.DESCRGRUPOPROD, 
    SUM(ITE.QTDNEG) AS TOTAL
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
	INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
WHERE 
    CAB.DTNEG BETWEEN :P_PER.INI AND :P_PER.FIN
    AND CAB.TIPMOV = 'V'
    AND PRO.USOPROD = 'V'
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
    AND (:P_GRUPO IS NULL OR GRU.CODGRUPOPROD = :P_GRUPO)
    AND (:P_CODEMP IS NULL OR CAB.CODEMP = :P_CODEMP)
    AND (:P_CODVEND IS NULL OR VEN.CODVEND = :P_CODVEND)
	AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
    AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
GROUP BY 
    GRU.CODGRUPOPROD, 
    GRU.DESCRGRUPOPROD
