SELECT 
FIN.CODPARC, 
NVL(PAR.NOMEPARC,PAR.RAZAOSOCIAL) AS RAZAOSOCIAL, 
FIN.DTENTSAI, 
FIN.NUMNOTA, 
FIN.NUFIN,
CASE WHEN NAT.AD_TIPOCTBZ= 'E' THEN FIN.VLRDESDOB*FIN.RECDESP ELSE NULL END As VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago'
     WHEN MONTHS_BETWEEN(TRUNC(DTVENC),TO_CHAR(:DAT1,'DD/MM/YYYY')) <= 12 THEN 'Vencidos ou a Vencer até 12 meses' 
     ELSE 'Vencimento maior que 12 meses' END As "Prazo_CP_ou_LP", 
FIN.CODTIPOPER, 
FIN.HISTORICO,
PAR.CODCTACTB3 AS CTBCP,
PAR.CODCTACTB4 AS CTBLP
FROM 
TGFFIN FIN, TGFPAR PAR, TGFNAT NAT
WHERE 
PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.CODNAT = NAT.CODNAT AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
FIN.RECDESP = -1 AND 
FIN.PROVISAO = 'N' AND 
(NAT.AD_TIPOCTBZ = 'E') AND
(FIN.CODPARC= :PARCEIRO OR :PARCEIRO = 0) AND
(FIN.CODNAT = :CODNAT OR :CODNAT IS NULL)
ORDER BY CODPARC, DTVENC, DTENTSAI, NUMNOTA, FIN.CODNAT DESC
