create or replace TRIGGER TRG_UPD_TGFCAB_TRANSP_SPARK
BEFORE INSERT OR UPDATE ON TGFCAB 
FOR EACH ROW
DECLARE
P_COUNT              INT;
P_VALIDA             VARCHAR2(10);
P_VLRFRETE           FLOAT;
P_VLROUTROS          FLOAT;
P_VLROUTROSCOMP      FLOAT;
--PRAGMA AUTONOMOUS_TRANSACTION;

BEGIN
  BEGIN
    SELECT NVL(AD_VERIFIPARCTRANSP,'N') INTO P_VALIDA
    FROM TGFTOP 
    WHERE CODTIPOPER = :NEW.CODTIPOPER
        AND DHALTER = :NEW.DHTIPOPER;

    EXCEPTION WHEN OTHERS THEN
      RAISE_APPLICATION_ERROR (-20101, 'Cód. Operacao: ' || :NEW.CODTIPOPER || ' Data operacao: ' || :NEW.DHTIPOPER); 
  END;      
    IF :NEW.CIF_FOB = 'S' AND :NEW.CODPARCTRANSP <> 0 AND P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L' THEN
		RAISE_APPLICATION_ERROR (-20101, 'CIF_FOB com marcação igual a "Sem Frete" não deve ter "Paceiro Transportadora" informada!');
    END IF;
    IF :NEW.CIF_FOB <> 'S' AND :NEW.CODPARCTRANSP = 0 AND  P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L'  THEN
		RAISE_APPLICATION_ERROR (-20101, 'Operação com frete, deverá informar "Parceiro Transportadora"!');
    END IF;     
	IF :NEW.TIPMOV = 'V' AND P_VALIDA = 'S' AND :NEW.VLRFRETE > 0 AND :NEW.TIPFRETE = 'N' AND :NEW.STATUSNOTA NOT IN ('L') THEN
	/* GRAVA O VALOR DO FRETE ORIUNDO DO PEDIDO EM TABELA ADICIONAL, PARA PODER ZERAR ATÉ CONFIRMAR A NOTA, 
	POIS SISTEMA ESTÁ ABRINDO TELA DE FINANCEIRO DE FRETE DEVIDO A INFORMAR TRANSPORTADORA,VALOR DE FRETE */
		IF INSERTING AND P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L' THEN
			:NEW.AD_NUNOTAENT := NULL;
			:NEW.AD_NUNOTASAI := NULL;
			INSERT INTO AD_FRETE  
			SELECT :NEW.NUNOTA, :NEW.VLRFRETE FROM DUAL;
		END IF;
		IF UPDATING('VLRFRETE') AND P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L' THEN
			UPDATE AD_FRETE SET VLRFRETE = :NEW.VLRFRETE WHERE NUNOTA = :NEW.NUNOTA;
		END IF;
		:NEW.VLRFRETE := 0; --ZERA O FRETE ATÉ CONFIRMAR
	END IF;
	BEGIN
		SELECT VLRFRETE INTO P_VLRFRETE FROM AD_FRETE WHERE NUNOTA = :NEW.NUNOTA;
		EXCEPTION WHEN NO_DATA_FOUND THEN
		P_VLRFRETE := 0;
	END;
	IF :NEW.TIPMOV = 'V' AND P_VALIDA = 'S' AND P_VLRFRETE > 0 AND :NEW.TIPFRETE = 'N' AND  :NEW.STATUSNOTA ='L' THEN
	 /* BUSCA O FRETE GRAVADO NA TABELA ADICONAL E APÓS CONFIRMAR INSERE NOVAMENTE. 
	  FOI VALIDADO NA EPOCA QUE O FRETE EXTRA NOTA CIF NÃO É IMPRESSO NO DANFE OU XML COM O LUCAS, 
	  POR ISSO FOI POSSÍVEL FAZER ESSE PROCEDIMENTO*/
		:NEW.VLRFRETE := P_VLRFRETE;
	END IF;
	BEGIN 
		SELECT NVL(SUM(AD_VLROUTROS),0), NVL(SUM(AD_VLROUTROSCOMP),0) INTO P_VLROUTROS, P_VLROUTROSCOMP
	FROM TGFITE 
	WHERE NUNOTA = :NEW.NUNOTA;
	EXCEPTION WHEN NO_DATA_FOUND THEN
		P_VLROUTROS := P_VLROUTROS;
	END;
	IF P_VLROUTROS > 0 AND P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L' THEN
		:NEW.VLROUTROS := P_VLROUTROS;
	END IF;
	IF   P_VLROUTROSCOMP > 0  AND P_VALIDA = 'S' AND :NEW.STATUSNOTA = 'L' THEN
		:NEW.VLROUTROS := P_VLROUTROSCOMP;
	END IF; 
END;				 