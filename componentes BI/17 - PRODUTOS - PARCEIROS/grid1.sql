SELECT PAR.CODPARC, PAR.RAZAOSOCIAL, PAR.NOMEPARC, ENDE.NOMEEND, PAR.NUMEND, BAI.NOMEBAI, CID.NOMECID,
       (SELECT OPCAO
          FROM TDDOPC OPC
         WHERE OPC.VALOR = PAR.CLASSIFICMS
           AND NUCAMPO = (SELECT NUCAMPO
                            FROM TDDCAM
                           WHERE NOMETAB = 'TGFPAR'
                             AND NOMECAMPO = 'CLASSIFICMS')) AS CLASSIFICMS,
       CASE WHEN PAR.CLASSIFICMS IS NULL THEN '/Sem Classificação Fiscal' END 
         || CASE WHEN PAR.CODEND = 0 THEN '/ Sem endereço' END
         || CASE WHEN PAR.NUMEND IS NULL THEN '/Endereço sem número' END
         || CASE WHEN PAR.NUMEND LIKE '0%' THEN '/Endereço sem número' END
         || CASE WHEN PAR.CODBAI = 0 THEN '/Sem bairro' END
         || CASE WHEN PAR.CODCID = 0 THEN '/Sem cidade' END
         || CASE WHEN CID.CODMUNFIS IS NULL OR CID.CODMUNFIS = 0 THEN '/Cidade sem Código de Município Fiscal (IBGE)' END
         || CASE WHEN PAR.CGC_CPF IS NULL THEN '/Sem CPF/CNPJ' END
         || CASE WHEN PAR.RAZAOSOCIAL IS NULL THEN '/Sem Razão Social' END
	    AS PROBLEMAS
  FROM TGFPAR PAR
       INNER JOIN TSIEND ENDE ON PAR.CODEND = ENDE.CODEND
       INNER JOIN TSIBAI BAI ON PAR.CODBAI = BAI.CODBAI
       INNER JOIN TSICID CID ON PAR.CODBAI = CID.CODCID
WHERE PAR.CODPARC <> 0
  AND ((CLIENTE = 'S' AND :A_TIPPARC = 'C')
       OR (FORNECEDOR = 'S' AND :A_TIPPARC = 'F')
       OR (TRANSPORTADORA = 'S' AND :A_TIPPARC = 'T')
       OR (MOTORISTA = 'S' AND :A_TIPPARC = 'M'))
  AND (PAR.CLASSIFICMS IS NULL
       OR PAR.CODEND = 0
       OR PAR.CODCID = 0
       OR CASE WHEN CID.CODMUNFIS IS NULL THEN 0 ELSE CID.CODMUNFIS END = 0
       OR PAR.CODBAI = 0
       OR (PAR.NUMEND IS NULL OR PAR.NUMEND = '0')
       OR PAR.CGC_CPF IS NULL
       OR PAR.RAZAOSOCIAL IS NULL
       )
