SELECT V.*,
    -- Bloco do Saldo Inicial mantido, mas com MAX(T1.SALDOBCO) para blindar contra duplicidade na TGFSBC
    ((SELECT SUM(ACUM) FROM (SELECT T4.VLRLANC * T4.RECDESP AS ACUM, ROW_NUMBER() OVER (ORDER BY T4.DHCONCILIACAO) AS numero_linha FROM TGFMBC T4 WHERE T4.CODCTABCOINT = :P_CODCTABCOINT AND T4.CONCILIADO = 'S' AND T4.DHCONCILIACAO >= :P_DHCONCILIACAO.INI AND T4.DHCONCILIACAO <= :P_DHCONCILIACAO.FIN ORDER BY T4.DHCONCILIACAO) subquery WHERE subquery.numero_linha <= to_number(V.LINHAMESTRE, '999999')) + 
    ((SELECT NVL(SUM(T3.VLRLANC * T3.RECDESP),0) FROM TGFMBC T3 WHERE T3.CODCTABCOINT = V.CODCTABCOINT AND T3.CONCILIADO = 'S' AND T3.DHCONCILIACAO >= TRUNC((V.DHCONCILIACAO-1),'MM') AND T3.DHCONCILIACAO < (:P_DHCONCILIACAO.INI)) +
    (SELECT MAX(T1.SALDOBCO) FROM TGFSBC T1 WHERE T1.CODCTABCOINT = :P_CODCTABCOINT AND T1.REFERENCIA = (SELECT MAX(REFERENCIA) FROM TGFSBC T2 WHERE T2.CODCTABCOINT = T1.CODCTABCOINT AND T2.REFERENCIA <= (V.DHCONCILIACAO-1))))) AS SALDOINICIAL,
    
    -- Colunas trazidas via LEFT JOIN
    FIN.CODPARC || ' - ' || PAR.NOMEPARC AS PARCEIRO,
    FIN.CODNAT || ' - ' || NAT.DESCRNAT AS NATUREZA

FROM (SELECT MBC.CODCTABCOINT,
            CTA.DESCRICAO,
            CTA.CODCTABCO,
            (CASE WHEN MBC.RECDESP = 1 THEN VLRLANC ELSE 0 END) as RECEITA,
            (CASE WHEN MBC.RECDESP = -1 THEN -VLRLANC ELSE 0 END) AS DESPESA,
            MBC.HISTORICO,
            MBC.NUMDOC,
            MBC.DHCONCILIACAO - 1 AS DTSALDOBCO,    
            MBC.DHCONCILIACAO,
            ROW_NUMBER() OVER (ORDER BY MBC.DHCONCILIACAO) AS LINHAMESTRE,
            MBC.NUBCO
        FROM TGFMBC MBC
            INNER JOIN TSICTA CTA ON MBC.CODCTABCOINT = CTA.CODCTABCOINT
        WHERE MBC.CODCTABCOINT = :P_CODCTABCOINT
            AND MBC.DHCONCILIACAO >= :P_DHCONCILIACAO.INI
            AND MBC.DHCONCILIACAO <= :P_DHCONCILIACAO.FIN
        ) V
-- Substituímos os Selects aninhados por LEFT JOINs limpos na consulta principal
LEFT JOIN TGFFIN FIN ON V.NUBCO = FIN.NUBCO AND V.NUBCO IS NOT NULL AND V.NUBCO > 0
LEFT JOIN TGFPAR PAR ON FIN.CODPARC = PAR.CODPARC
LEFT JOIN TGFNAT NAT ON FIN.CODNAT = NAT.CODNAT
ORDER BY V.DHCONCILIACAO
