SELECT LIV.CODEMP,
	CAB.NUNOTA,
	CAB.NUMNOTA,
	ITE.ORIGPROD AS ORIGEM,
	LIV.CODCFO,
	LIV.VLRCTB,
	LIV.CODTRIB,
	LIV.BASEICMS,
	LIV.ALIQICMS,
	LIV.VLRICMS, 
	LIV.BASERETENCAO AS BASEST,
	LIV.ICMSRETENCAO AS VLRST,
	LIV.VLRIPI,  
	LIV.DHMOV AS REFERENCIA
FROM TGFCAB CAB
	INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
	INNER JOIN TGFLIV LIV ON CAB.NUNOTA = LIV.NUNOTA
WHERE LIV.SEQUENCIA = ITE.SEQUENCIA 
	AND (LIV.DHMOV >= :P_PERIODO.INI or :P_PERIODO.INI is null)
	AND (LIV.DHMOV <= :P_PERIODO.FIN or :P_PERIODO.FIN is null) 
	AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
	AND LIV.CODCFO >= :P_CODCFOPINI
	AND LIV.CODCFO <= :P_CODCFOPFIN
	AND LIV.CODCFO = :A_CODCFOP
	AND LIV.CODTRIB = :A_CODTRIB
	AND LIV.ALIQICMS = :A_ALIQICMS
	AND ITE.ORIGPROD = :A_ORIGEM
