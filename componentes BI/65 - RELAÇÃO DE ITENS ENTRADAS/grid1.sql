SELECT CAB.NUNOTA, 
	CAB.CODEMP,
	CAB.NUMNOTA,	
	CAB.CODTIPOPER,
	(SELECT MAX(TOP2.DESCROPER) FROM TGFTOP TOP2 WHERE TOP2.CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER,
	CAB.DTENTSAI,
	CAB.CODPARC,
	PAR.NOMEPARC,
	ITE.CODPROD, 
	PRO.DESCRPROD, 
	ITE.CODVOL, 
	ITE.QTDNEG, 
	(ITE.QTDNEG - ITE.QTDENTREGUE) AS PENDENTE,
	(CASE WHEN CAB.CODEMP = 501 
		THEN 0 
		ELSE (CASE WHEN VOA.CODPROD IS NULL 
				THEN ITE.VLRUNIT
				WHEN VOA.DIVIDEMULTIPLICA = 'D' 
				THEN ITE.VLRUNIT / VOA.QUANTIDADE 
				ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
				END) END) AS VLRUNIT,
	(CASE WHEN CAB.CODEMP = 501 
		THEN (CASE WHEN VOA.CODPROD IS NULL 
				THEN ITE.VLRUNIT 
				WHEN VOA.DIVIDEMULTIPLICA = 'D' 
				THEN ITE.VLRUNIT / VOA.QUANTIDADE 
				ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
				END) 
		WHEN ITE.AD_VLRCHEIOCOM IS NULL 
		THEN (CASE WHEN VOA.CODPROD IS NULL 
				THEN ITE.VLRUNIT 
				WHEN VOA.DIVIDEMULTIPLICA = 'D' 
				THEN ITE.VLRUNIT / VOA.QUANTIDADE 
				ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
				END) 
		ELSE ITE.AD_VLRCHEIOCOM
		END) AS VLRCHEIO, 
	NVL(ITE.ALIQICMS,0) AS ALIQICMS,
	NVL(ITE.ALIQIPI,0) AS ALIQIPI,
	USU.NOMEUSU AS INCLUSOR,
	NAT.DESCRNAT,
	PRO.ESTMIN
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	LEFT JOIN TSIUSU USU ON CAB.CODUSUINC = USU.CODUSU
	INNER JOIN TGFNAT NAT ON CAB.CODNAT = NAT.CODNAT
	INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
	LEFT JOIN TGFVOA VOA ON (VOA.CODPROD = ITE.CODPROD AND VOA.CODVOL = ITE.CODVOL AND ((ITE.CONTROLE IS NULL AND VOA.CONTROLE = ' ') OR (ITE.CONTROLE IS NOT NULL AND ITE.CONTROLE = VOA.CONTROLE)))
WHERE (CAB.CODPARC = :P_CODPARC OR :P_CODPARC IS NULL) 
	AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL) 
	AND (CAB.DTENTSAI >= :P_PERIODO.INI AND CAB.DTENTSAI <= :P_PERIODO.FIN) 
	AND (CAB.TIPMOV IN ('C','D')) 
	AND CAB.STATUSNOTA = 'L' 
	/* ALTERAÇÃO DE CÓDIGO PARA TRATAR IMPORTAÇÕES*/
	AND CAB.CODTIPOPER <> 203
	/**/
	AND (CAB.CODNAT = :P_CODNAT OR :P_CODNAT IS NULL) 
	AND ((SUBSTR(PRO.CODGRUPOPROD,0,4) = SUBSTR(:P_CODGRUPOPROD,0,4)) OR :P_CODGRUPOPROD IS NULL) 
	AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
/* ALTERAÇÃO DE CÓDIGO PARA TRATAR IMPORTAÇÕES*/
UNION ALL
SELECT V.NUNOTA,
	V.CODEMP,
	V.NUMNOTA,
	V.CODTIPOPER,
	V.DESCROPER,
	V.DTENTSAI,
	V.CODPARC,
	V.NOMEPARC,
	V.CODPROD,
	V.DESCRPROD,
	V.CODVOL,
	V.QTDNEG,
	V.PENDENTE,
	((((V.VLRNOTA / (V.VLRUNIT * V.QTDNEG)) * V.VLRDESTAQUE) / V.QTDNEG) + V.VLRUNIT) AS VLRUNIT,
	(((((V.VLRNOTA + V.VLROUTROS) / (V.VLRCHEIO * V.QTDNEG)) * V.VLRDESTAQUE) / V.QTDNEG) + V.VLRCHEIO) AS VLRCHEIO,
	V.ALIQICMS,
	V.ALIQIPI,
	V.INCLUSOR,
	V.DESCRNAT,
	V.ESTMIN
FROM (
	SELECT CAB.NUNOTA, 
		CAB.CODEMP,
		CAB.NUMNOTA,	
		CAB.CODTIPOPER,
		(SELECT MAX(TOP2.DESCROPER) FROM TGFTOP TOP2 WHERE TOP2.CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER,
		CAB.DTENTSAI,
		CAB.CODPARC,
		PAR.NOMEPARC,
		ITE.CODPROD, 
		PRO.DESCRPROD, 
		ITE.CODVOL, 
		CAB.VLRDESTAQUE,
		CAB.VLRNOTA,
		CAB.VLROUTROS,
		ITE.QTDNEG, 
		(ITE.QTDNEG - ITE.QTDENTREGUE) AS PENDENTE,
		(CASE WHEN CAB.CODEMP = 501 
			THEN 0 
			ELSE (CASE WHEN VOA.CODPROD IS NULL 
					THEN ITE.VLRUNIT
					WHEN VOA.DIVIDEMULTIPLICA = 'D' 
					THEN ITE.VLRUNIT / VOA.QUANTIDADE 
					ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
					END) END) AS VLRUNIT,
		(CASE WHEN CAB.CODEMP = 501 
			THEN (CASE WHEN VOA.CODPROD IS NULL 
					THEN ITE.VLRUNIT 
					WHEN VOA.DIVIDEMULTIPLICA = 'D' 
					THEN ITE.VLRUNIT / VOA.QUANTIDADE 
					ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
					END) 
			WHEN ITE.AD_VLRCHEIOCOM IS NULL 
			THEN (CASE WHEN VOA.CODPROD IS NULL 
					THEN ITE.VLRUNIT 
					WHEN VOA.DIVIDEMULTIPLICA = 'D' 
					THEN ITE.VLRUNIT / VOA.QUANTIDADE 
					ELSE ITE.VLRUNIT * VOA.QUANTIDADE 
					END) 
			ELSE ITE.AD_VLRCHEIOCOM
			END) AS VLRCHEIO, 
		NVL(ITE.ALIQICMS,0) AS ALIQICMS,
		NVL(ITE.ALIQIPI,0) AS ALIQIPI,
		USU.NOMEUSU AS INCLUSOR,
		NAT.DESCRNAT,
		PRO.ESTMIN
	FROM TGFITE ITE
		INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
		INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
		INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
		LEFT JOIN TSIUSU USU ON CAB.CODUSUINC = USU.CODUSU
		INNER JOIN TGFNAT NAT ON CAB.CODNAT = NAT.CODNAT
		INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
		LEFT JOIN TGFVOA VOA ON (VOA.CODPROD = ITE.CODPROD AND VOA.CODVOL = ITE.CODVOL AND ((ITE.CONTROLE IS NULL AND VOA.CONTROLE = ' ') OR (ITE.CONTROLE IS NOT NULL AND ITE.CONTROLE = VOA.CONTROLE)))
	WHERE (CAB.CODPARC = :P_CODPARC OR :P_CODPARC IS NULL) 
		AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL) 
		AND (CAB.DTENTSAI >= :P_PERIODO.INI AND CAB.DTENTSAI <= :P_PERIODO.FIN) 
		AND (CAB.TIPMOV IN ('C','D')) 
		AND CAB.STATUSNOTA = 'L' AND CAB.CODTIPOPER = 203
		AND (CAB.CODNAT = :P_CODNAT OR :P_CODNAT IS NULL) 
		AND ((SUBSTR(PRO.CODGRUPOPROD,0,4) = SUBSTR(:P_CODGRUPOPROD,0,4)) OR :P_CODGRUPOPROD IS NULL) 
		AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
	ORDER BY CAB.DTENTSAI, 
		CAB.NUNOTA, 
		CAB.CODEMP, 
		CAB.CODPARC, 
		CAB.NUMNOTA) V
