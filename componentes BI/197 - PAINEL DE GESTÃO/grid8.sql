SELECT * FROM(
SELECT 
FIN.CODEMP, 
FIN.DTENTSAI,
FIN.DTNEG, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) AS VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Crédito Recebido/Compensado'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 30 THEN 'Crédito gerado até 30 dias'
	    WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 60 THEN 'Crédito gerado até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 90 THEN 'Crédito gerado até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 180 THEN 'Crédito gerado até 180 dias'
     ELSE 'Crédito gerado a mais de 180 dias' END AS CLASSIFICACAO,
FIN.HISTORICO,
198 AS CTACTB
FROM 
TGFFIN FIN , TGFPAR PAR , TGFNAT NAT , TGFTOP T  
WHERE 
FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1  AND  
(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null)  AND  
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não'  AND  
FIN.VLRDESDOB * FIN.RECDESP <> 0  
AND  T.TIPMOV IN ('E') AND
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0)
ORDER BY FIN.CODPARC, FIN.DTVENC
)
WHERE (CLASSIFICACAO = :CLASSIFICACAO OR :CLASSIFICACAO IS NULL)
