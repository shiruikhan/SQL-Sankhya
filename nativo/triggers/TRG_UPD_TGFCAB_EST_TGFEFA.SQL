/*==============================================================================
  Nome do Script : TRG_UPD_TGFCAB_EST_TGFEFA
  Tipo           : Trigger de origem Sankhya (lote de atualização do ERP de 01/07/2022 — referência)
  Descrição      : Trigger AFTER EACH ROW UPDATE sobre TGFCAB.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 01/07/2022, última alteração em 03/07/2024.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026, via: SELECT DBMS_METADATA.GET_DDL('TRIGGER', 'TRG_UPD_TGFCAB_EST_TGFEFA', 'SPARKPRD') FROM dual;
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_UPD_TGFCAB_EST_TGFEFA" AFTER UPDATE ON TGFCAB FOR EACH ROW 
 WHEN ((NEW.STATUSNOTA = 'L' AND OLD.STATUSNOTA = 'L') AND 
	 ((OLD.CODTIPOPER <> NEW.CODTIPOPER) OR	    
	   TRUNC (NVL (OLD.DTFATUR, OLD.DTNEG))  <> TRUNC (NVL (NEW.DTFATUR, NEW.DTNEG)))) DECLARE    
   OLD_DTFATUR      TGFCAB.DTFATUR%TYPE; 
   NEW_DTFATUR      TGFCAB.DTFATUR%TYPE;    
BEGIN 

   IF STP_GET_ATUALIZANDO THEN
    RETURN;
   END IF;

   OLD_DTFATUR  := TRUNC (NVL(:OLD.DTFATUR,  :OLD.DTNEG));    
   NEW_DTFATUR  := TRUNC (NVL(:NEW.DTFATUR,  :NEW.DTNEG));		 	
   IF (:OLD.CODTIPOPER <> :NEW.CODTIPOPER) OR (OLD_DTFATUR <> NEW_DTFATUR) THEN 
      MERGE INTO TGFEFA E 
      	USING (SELECT SUM(CASE WHEN I.ATUALESTOQUE = -1 THEN 0 ELSE I.QTDNEG END) AS QTDENTRADA 
                   , SUM(CASE WHEN I.ATUALESTOQUE = -1 THEN I.QTDNEG ELSE 0 END) AS QTDSAIDA 
                   , I.CONTROLE, I.CODPROD, I.CODLOCALORIG, I.CODEMP, I.ATUALESTOQUE, I.NUNOTA, I.RESERVA  
           	   FROM TGFITE I 
  		       WHERE I.NUNOTA = :NEW.NUNOTA 
			     AND I.RESERVA      = 'N' 
				 AND I.ATUALESTOQUE <> 0 
           	   GROUP BY I.CONTROLE, I.CODPROD, I.CODLOCALORIG, I.CODEMP, I.ATUALESTOQUE, I.NUNOTA, I.RESERVA) I 
	    ON (E.DTREFERENCIA = OLD_DTFATUR 
	  		AND E.CODTIPOPER   = :OLD.CODTIPOPER 
	  		AND E.CONTROLE     = I.CONTROLE 
	  		AND E.CODPROD      = I.CODPROD 
	  		AND E.CODLOCALORIG = I.CODLOCALORIG 
	  		AND E.CODEMP       = I.CODEMP) 
    	WHEN MATCHED THEN 
		  UPDATE SET E.QTDENTRADAS = E.QTDENTRADAS - I.QTDENTRADA, 
  	           E.QTDSAIDAS   = E.QTDSAIDAS   - I.QTDSAIDA			 
        WHEN NOT MATCHED THEN 
      		 INSERT (DTREFERENCIA, CODTIPOPER, TIPMOV, QTDENTRADAS, QTDSAIDAS, 
  	         		 CONTROLE, CODLOCALORIG, CODPROD, CODEMP) 
  			 VALUES (NEW_DTFATUR, :NEW.CODTIPOPER, :NEW.TIPMOV, 0, 0, 
              	     I.CONTROLE, I.CODLOCALORIG, I.CODPROD, I.CODEMP); 
      MERGE INTO TGFEFA E 
        USING (SELECT SUM(CASE WHEN I.ATUALESTOQUE = -1 THEN 0 ELSE I.QTDNEG END) AS QTDENTRADA 
                    , SUM(CASE WHEN I.ATUALESTOQUE = -1 THEN I.QTDNEG ELSE 0 END) AS QTDSAIDA 
                    , I.CONTROLE, I.CODPROD, I.CODLOCALORIG, I.CODEMP, I.ATUALESTOQUE, I.NUNOTA, I.RESERVA  
           	   FROM TGFITE I 
  		 	   WHERE I.NUNOTA = :NEW.NUNOTA 			   
		   		 AND I.RESERVA      = 'N'
		  	  	 AND I.ATUALESTOQUE <> 0 
           	   GROUP BY I.CONTROLE, I.CODPROD, I.CODLOCALORIG, I.CODEMP, I.ATUALESTOQUE, I.NUNOTA, I.RESERVA) I 
	    ON (E.DTREFERENCIA = NEW_DTFATUR 
	  		AND E.CODTIPOPER   = :NEW.CODTIPOPER 
	  		AND E.CONTROLE     = I.CONTROLE 
	  		AND E.CODPROD      = I.CODPROD 
	  		AND E.CODLOCALORIG = I.CODLOCALORIG 
	  		AND E.CODEMP       = I.CODEMP) 
        WHEN MATCHED THEN 
      		 UPDATE SET E.QTDENTRADAS = E.QTDENTRADAS + I.QTDENTRADA, 
  	         		    E.QTDSAIDAS   = E.QTDSAIDAS   + I.QTDSAIDA 
		WHEN NOT MATCHED THEN 
      		 INSERT (DTREFERENCIA, CODTIPOPER, TIPMOV, QTDENTRADAS, QTDSAIDAS, 
  	         		 CONTROLE, CODLOCALORIG, CODPROD, CODEMP) 
  			 VALUES (NEW_DTFATUR, :NEW.CODTIPOPER, :NEW.TIPMOV, I.QTDENTRADA, I.QTDSAIDA, 
              	     I.CONTROLE, I.CODLOCALORIG, I.CODPROD, I.CODEMP); 
   END IF; 
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_UPD_TGFCAB_EST_TGFEFA" ENABLE;
