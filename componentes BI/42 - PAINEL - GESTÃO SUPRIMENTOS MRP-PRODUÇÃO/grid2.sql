/*
OBTEM_TOTAIS_MRP(NRO MPS, CODPRODPA, CODPRODMP,TIPO)
P_TIPO:  
M-META PA ;
P - PRODUCAO PA;
S - SALDO PRODUZIR PA
N - NECESSIDADE MP NO MRP FILTRADO
NA - NECESSIDADE 
C - NECESSIDADE COMPRA MP NO MRP FILTRADO
E - ESTOQUE DISPONÍVEL MP
O - Ordem/Pedido de Compra
*/
SELECT LMP.CODPRODMP, 
SUM(LMP.QTDMISTURA*NVL(I.QTDPRODUZIRLIQ,0)) AS QTDMPS,
OBTEM_TOTAIS_MRP(I.NUMPS,NVL(:P_CODPRODPA,0),LMP.CODPRODMP,'O') AS TOTPEDCPA, 
OBTEM_TOTAIS_MRP(I.NUMPS,NVL(:P_CODPRODPA,0),LMP.CODPRODMP,'NA') AS SALDOMPSANT, 
OBTEM_TOTAIS_MRP(I.NUMPS,0,LMP.CODPRODMP,'E') AS ESTOQUEMP,
PRO.DESCRPROD AS DESCRMP,
PRO.CODVOL, 
NVL(PRO.AGRUPCOMPMINIMO,PRO.AGRUPMIN) AS AGRUPMIN,
PRO.CODPARCFORN
,PAR.NOMEPARC
                          FROM TPRIMPS I, TPRPRC PRC, TPRLPA LPA, TPRLMP LMP, TPRATV ATV , TPROEST EST, TGFPRO PRO
                          LEFT JOIN TGFPAR PAR ON (PAR.CODPARC = PRO.CODPARCFORN)
                          WHERE PRC.IDPROC = I.IDPROC
                              AND I.CODPROD = LPA.CODPRODPA
                              AND LPA.CODPRODPA = LMP.CODPRODPA
                              AND LMP.CODPRODMP = PRO.CODPROD
                              AND I.IDPROC = ATV.IDPROC
                              AND EST.IDEFX = ATV.IDEFX
                              AND LMP.IDEFX = ATV.IDEFX
                              AND LPA.IDPROC = I.IDPROC
                              AND EST.TIPOITENS='PA' --- APENAS ATIVIDADE APONTAMENTO
                              AND I.NUMPS = :A_NUMPS
                              AND (PRO.CODPARCFORN = :P_CODPARC OR :P_CODPARC IS NULL)
                              AND (LMP.CODPRODPA = :P_CODPRODPA OR :P_CODPRODPA IS NULL)
                              GROUP BY LMP.CODPRODMP, PRO.DESCRPROD, PRO.CODVOL, NVL(PRO.AGRUPCOMPMINIMO,PRO.AGRUPMIN), PRO.CODPARCFORN,PAR.NOMEPARC, I.NUMPS
                              HAVING SUM(LMP.QTDMISTURA*I.QTDPRODUZIRLIQ) > 0
                              ORDER BY PAR.NOMEPARC, 2 DESC,3
