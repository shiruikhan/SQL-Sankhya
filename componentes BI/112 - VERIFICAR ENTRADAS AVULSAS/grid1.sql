SELECT CAB.NUNOTA,
	CAB.DTNEG,
	CAB.CODTIPOPER,
	(SELECT DISTINCT DESCROPER FROM TGFTOP WHERE CODTIPOPER = CAB.CODTIPOPER) AS DESCRTOP,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	CASE WHEN EXISTS (SELECT I.CODPROD 
						FROM TGFITE I 
							INNER JOIN TGFCAB C ON I.NUNOTA = C.NUNOTA 
						WHERE I.CODPROD = ITE.CODPROD 
							AND I.CODEMP = 1
							AND C.CODTIPOPER IN (200,201,203,209,213,214,215,221,232,240,241)
							AND I.ATUALESTOQUE = 1
							AND C.DTNEG <= :P_DATACORTE)
		THEN '#65e10f' ELSE '#f26c63' END AS BKCOLOR,
	CASE WHEN EXISTS (SELECT IT.CODPROD 
						FROM TGFITE IT 
							INNER JOIN TGFCAB CA ON IT.NUNOTA = CA.NUNOTA 
						WHERE IT.CODPROD = ITE.CODPROD 
							AND IT.CODEMP = 1
							AND CA.CODTIPOPER IN (200,201,203,209,213,214,215,221,232,240,241)
							AND IT.ATUALESTOQUE = 1
							AND CA.DTNEG <= :P_DATACORTE)
		THEN 'OK' ELSE 'Verificar' END AS STATUS	
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
WHERE ITE.NUNOTA = :P_NUNOTA
