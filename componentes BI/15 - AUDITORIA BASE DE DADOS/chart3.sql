SELECT TGFCAB.CODUSU, 
        TSIUSU.NOMEUSU NOMEUSUARIO, 
        TSIGRU.NOMEGRUPO NOMEGRUPO,
        COUNT(TGFCAB.NUNOTA) QTDEOP,
        TO_CHAR(TGFCAB.DTALTER, 'YYYY/MM') MESANO
   FROM TGFTOP INNER JOIN TGFCAB ON TGFTOP.CODTIPOPER = TGFCAB.CODTIPOPER 
                                AND TGFTOP.DHALTER = TGFCAB.DHTIPOPER 
               LEFT JOIN TSIUSU ON TGFCAB.CODUSU = TSIUSU.CODUSU
               LEFT JOIN TSIGRU ON TSIGRU.CODGRUPO = TSIUSU.CODGRUPO
  WHERE TGFTOP.CODTIPOPER <> 0 
    AND TGFCAB.TIPMOV <> 'Z'
 /*   AND TGFCAB.DTALTER >= ADD_MONTHS( SYSDATE, -3 )  */
    AND TGFCAB.CODUSU = :A_CODUSU
 /*   AND ((:A_DESCRICAO = 'Compras' AND TGFTOP.TIPMOV IN ('C','O','E'))
               OR (:A_DESCRICAO = 'Vendas' AND TGFTOP.TIPMOV IN ('P','D','V'))
               OR (:A_DESCRICAO = 'Transferência' AND TGFTOP.TIPMOV IN ('T'))
               OR (:A_DESCRICAO = 'Requisição' AND TGFTOP.TIPMOV IN ('J','Q','L'))
               OR (:A_DESCRICAO = 'Produção' AND TGFTOP.TIPMOV IN ('F'))) */
GROUP BY TGFCAB.CODUSU, TSIUSU.NOMEUSU, TSIGRU.NOMEGRUPO, TO_CHAR(TGFCAB.DTALTER, 'YYYY/MM')
ORDER BY TO_CHAR(TGFCAB.DTALTER, 'YYYY/MM')
