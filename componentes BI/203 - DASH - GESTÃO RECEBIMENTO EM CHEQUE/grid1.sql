UNION ALL

SELECT CAB.NUNOTA
	,FIN.NUFIN
	,CAB.CODPARC
	,PAR.NOMEPARC
	,CAB.CODVEND
	,VEN.APELIDO
	,CAB.DTNEG
	,CAB.NUMNOTA
	,FIN.DESDOBRAMENTO
	,FIN.VLRDESDOB
	,(
		SELECT CHQ.NUMCHEQUE
		FROM TGFCHQ CHQ
		WHERE CHQ.NUFIN = FIN.NUFIN
		) AS NR_CHEQUE
	,'CHEQUE NÃO RECEBIDO' AS STATUS
	,CASE WHEN NVL(FIN.AD_CHEQUECLI, 'N') = 'N' THEN 'Não' ELSE 'Sim' END AS CHEQUE_CLI
	,CASE WHEN NVL(FIN.AD_CHEQUECOM, 'N') = 'N' THEN 'Não' ELSE 'Sim' END AS CHEQUE_COM
	,CASE WHEN NVL(FIN.AD_CHEQUEFIN, 'N') = 'N' THEN 'Não' ELSE 'Sim' END AS CHEQUE_FIN
	,FIN.HISTORICO
FROM TGFCAB CAB
INNER JOIN TGFFIN FIN ON FIN.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
INNER JOIN TGFVEN VEN ON VEN.CODVEND = CAB.CODVEND
WHERE CAB.CODEMP = 501
	AND CAB.CODTIPVENDA = 139
	AND FIN.RECDESP = 1
	AND FIN.CODTIPTIT = 5
	AND (FIN.NUBCO IS NULL AND FIN.NUCOMPENS IS NULL)
	AND FIN.PROVISAO = 'N'
	AND :P_STATUS = 3
