SELECT CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTENTSAI,
	PAR.CODPARC || ' - ' || PAR.RAZAOSOCIAL AS PARCEIRO,
	ITE.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	--ITE.QTDNEG * ITE.ATUALESTOQUE AS QTDNEG,
	(CASE WHEN CAB.CODTIPOPER IN (1202,1212,1213) THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) AS QTDNEG,
	(CASE WHEN CAB.CODTIPOPER IN (1202,1212,1213) THEN 'RETORNO' ELSE 'REMESSA' END) SITUACAO
FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
	INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
WHERE CAB.DTENTSAI >= :P_PERIODO.INI
	AND CAB.DTENTSAI <= :P_PERIODO.FIN
	AND ITE.CODPROD = :A_CODPROD
	--AND ITE.ATUALESTOQUE <> 0
	AND CAB.CODTIPOPER IN (1202,1108,2208,1123,1212,1213/*,2223*/)
	AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
	AND CAB.STATUSNOTA = 'L'
ORDER BY CAB.DTENTSAI