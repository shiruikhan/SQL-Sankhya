/*==============================================================================
  Nome do Script : TRG_UPT_TGFITE_AFTER
  Tipo           : Trigger — origem a confirmar (criada isoladamente em 27/10/2025)
  Descrição      : Trigger AFTER STATEMENT UPDATE sobre TGFITE.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 27/10/2025, última alteração em 21/09/2026.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026 (recaptura em pedaços — DDL completo, conferido pelo tamanho), via GET_DDL('TRIGGER', 'TRG_UPT_TGFITE_AFTER', 'SPARKPRD').
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_UPT_TGFITE_AFTER" 
AFTER UPDATE ON TGFITE
DECLARE
   CURSOR UPDITENS IS
     SELECT NUNOTA, SEQUENCIA, RESERVA, ATUALESTOQUE,
       CODEMP, CODPROD, CONTROLE, CODLOCAL,
       QTDNEG, QTDENTREGUE, QTDENTREGUE_D, QTDCONFERIDA,
       VLRUNIT, VLRCUS,
       BASEIPI, VLRIPI, BASEICMS,
       VLRDESC, BASESUBSTIT, VLRSUBST,
       CODVOL, CODTRIB, CODCFO, OBSERVACAO,
       VLRICMS, ALIQICMS, STATUSNOTA, NUTAB, ATUALTRANSF,
       PENDENTE, USOPROD, VLRTOT, 
     CSTIPI, PERCCOM, VLRCOM, ALTPRECO, QTDFIXADA,
     PERCCOMGER, VLRCOMGER, QTDWMS, BASICMMOD, BASICMSTMOD,
     QTDFAT, BASESTUFDEST, VLRICMSUFDEST, BASESTANT, GRUPOTRANSG, ATUALESTTERC, TERCEIROS, PERCPUREZA, PERCGERMIN, STATUSLOTE
     FROM TGFITE_UPD;

   CURSOR NOTAS IS SELECT DISTINCT NUNOTA FROM TGFITE_UPD
      WHERE (QTDENTREGUE_D <> QTDENTREGUE)
         OR (QTDNEG_D <> QTDNEG)
         OR (PENDENTE_D <> PENDENTE);

   P_NUNOTA                NUMBER(10);
   P_SEQUENCIA             NUMBER(5);
   P_CODEMPNEGOC           TGFITE.CODEMP%TYPE;
   P_RESERVA               CHAR;
   P_ATUALESTOQUE          NUMBER(5);
   P_CODEMP                TGFITE.CODEMP%TYPE;
   P_CODPROD               TGFITE.CODPROD%TYPE;
   P_CONTROLE              TGFITE.CONTROLE%TYPE;
   P_CODLOCAL              TGFITE.CODLOCALORIG%TYPE;
   P_QTDNEG                FLOAT;
   P_QTDENTREGUE           FLOAT;
   P_QTDENTREGUE_D         FLOAT;
   P_TIPMOV                CHAR;
   P_COUNT                 NUMBER(10);
   P_ACEITARPRODREP        CHAR;
   P_PENDENTE              CHAR;
   P_ATUALTRANSF           CHAR;
   P_QTDCONFERIDA          FLOAT;
   P_VLRUNIT               FLOAT;
   P_VLRCUS                FLOAT;
   P_BASEIPI               FLOAT;
   P_VLRIPI                FLOAT;
   P_BASEICMS              FLOAT;
   P_VLRDESC               FLOAT;
   P_BASESUBSTIT           FLOAT;
   P_VLRSUBST              FLOAT;
   P_CODVOL               TGFPRO.CODVOL%TYPE;
   P_CODTRIB               NUMBER(5);
   P_CODCFO                TGFTOP.CODCFO_ENTRADA%TYPE;
   P_OBSERVACAO            VARCHAR2(4000);
   P_VLRICMS               FLOAT;
   P_ALIQICMS              FLOAT;
   P_STATUSNOTA            CHAR;
   P_NUTAB                 TGFTAB.NUTAB%TYPE;
   P_PENDENTE_CAB          CHAR;
   P_USOPROD               CHAR;
   P_PENDENTE_TOP          CHAR;
   P_VLRTOT                TGFITE.VLRTOT%TYPE;
   /* INICIO - VARIAVEIS PARA MANTER COMPATIBILIDADE COM TGFITE, ALGUMAS PODEM N¿O SER UTILIZADAS DE IMEDIATO*/
  P_CSTIPI        TGFITE_UPD.CSTIPI%TYPE;
  P_PERCCOM      TGFITE_UPD.PERCCOM%TYPE;
  P_VLRCOM        TGFITE_UPD.VLRCOM%TYPE;
  P_ALTPRECO      TGFITE_UPD.ALTPRECO%TYPE;
  P_QTDFIXADA     TGFITE_UPD.QTDFIXADA%TYPE;
  P_PERCCOMGER     TGFITE_UPD.PERCCOMGER%TYPE;
  P_VLRCOMGER      TGFITE_UPD.VLRCOMGER%TYPE;
  P_QTDWMS        TGFITE_UPD.QTDWMS%TYPE;
  P_BASICMMOD      TGFITE_UPD.BASICMMOD%TYPE;
  P_BASICMSTMOD    TGFITE_UPD.BASICMSTMOD%TYPE;
  P_QTDFAT        TGFITE_UPD.QTDFAT%TYPE;
  P_BASESTUFDEST   TGFITE_UPD.BASESTUFDEST%TYPE;
  P_VLRICMSUFDEST  TGFITE_UPD.VLRICMSUFDEST%TYPE;
  P_BASESTANT      TGFITE_UPD.BASESTANT%TYPE;
  P_GRUPOTRANSG    TGFITE_UPD.GRUPOTRANSG%TYPE;
  P_ATUALESTTERC     TGFITE_UPD.ATUALESTTERC%TYPE;
  P_TERCEIROS      TGFITE_UPD.TERCEIROS%TYPE;
  P_PERCGERMIN    TGFITE_UPD.PERCGERMIN%TYPE;
  P_PERCPUREZA     TGFITE_UPD.PERCPUREZA%TYPE;
  P_STATUSLOTE    TGFITE_UPD.STATUSLOTE%TYPE;
   /* FIM */

 BEGIN

  IF STP_GET_ATUALIZANDO THEN
    RETURN;
  END IF;

   SELECT COUNT(1) INTO P_COUNT
   FROM TGFITE_UPD;
   IF P_COUNT > 0 THEN
     OPEN UPDITENS;
     OPEN NOTAS;
     DELETE FROM TGFITE_UPD;
     LOOP
       FETCH UPDITENS INTO P_NUNOTA, P_SEQUENCIA, P_RESERVA, P_ATUALESTOQUE,
           P_CODEMP, P_CODPROD, P_CONTROLE, P_CODLOCAL,
           P_QTDNEG, P_QTDENTREGUE, P_QTDENTREGUE_D, P_QTDCONFERIDA,
           P_VLRUNIT, P_VLRCUS, P_BASEIPI, P_VLRIPI, P_BASEICMS,
           P_VLRDESC, P_BASESUBSTIT, P_VLRSUBST,
           P_CODVOL, P_CODTRIB, P_CODCFO, P_OBSERVACAO,
           P_VLRICMS, P_ALIQICMS, P_STATUSNOTA, P_NUTAB, P_ATUALTRANSF,
           P_PENDENTE, P_USOPROD, P_VLRTOT,
        P_CSTIPI, P_PERCCOM, P_VLRCOM,P_ALTPRECO, P_QTDFIXADA,
        P_PERCCOMGER, P_VLRCOMGER, P_QTDWMS, P_BASICMMOD, P_BASICMSTMOD,
        P_QTDFAT, P_BASESTUFDEST, P_VLRICMSUFDEST, P_BASESTANT, P_GRUPOTRANSG, P_ATUALESTTERC, P_TERCEIROS, P_PERCPUREZA, P_PERCGERMIN, P_STATUSLOTE;
  
       EXIT WHEN UPDITENS%NOTFOUND;
       SELECT C.TIPMOV, C.CODEMPNEGOC, C.PENDENTE, T.PENDENTE INTO
              P_TIPMOV, P_CODEMPNEGOC, P_PENDENTE_CAB, P_PENDENTE_TOP
       FROM TGFCAB C, TGFTOP T
       WHERE C.NUNOTA = P_NUNOTA
       AND C.CODTIPOPER = T.CODTIPOPER
       AND C.DHTIPOPER = T.DHALTER;
  
       IF (P_TIPMOV = 'T') /* AND  (P_USOPROD <> 'D') */ AND (P_ATUALTRANSF = 'S') THEN
             /* aqui tem a atualizacao estoque do espelho no Sql Server, isto nao precisa aqui por
                causa da recursividade das triggers */
          UPDATE TGFITE
          SET
           CODEMP = P_CODEMPNEGOC,
           CODPROD = P_CODPROD,
           QTDNEG = P_QTDNEG,
           QTDCONFERIDA = P_QTDCONFERIDA,
           VLRUNIT = P_VLRUNIT,
           VLRCUS = P_VLRCUS,
           BASEIPI = P_BASEIPI,
           VLRIPI = P_VLRIPI,
            VLRTOT = P_VLRTOT,
           ALIQICMS = P_ALIQICMS,
           BASEICMS = P_BASEICMS,
           VLRICMS = P_VLRICMS,
           VLRDESC = P_VLRDESC,
           BASESUBSTIT = P_BASESUBSTIT,
           VLRSUBST = P_VLRSUBST,
           CODVOL = P_CODVOL,
           CODTRIB = P_CODTRIB,
           CODCFO = P_CODCFO,
           QTDENTREGUE = P_QTDENTREGUE,
           ATUALESTOQUE = P_ATUALESTOQUE * (-1),
           TERCEIROS  = P_TERCEIROS,
           RESERVA = P_RESERVA,
           STATUSNOTA = P_STATUSNOTA,
           NUTAB = P_NUTAB,
           PERCPUREZA = P_PERCPUREZA,
           PERCGERMIN = P_PERCGERMIN,
           STATUSLOTE = P_STATUSLOTE,
           ATUALESTTERC = P_ATUALESTTERC
          WHERE (NUNOTA = P_NUNOTA)
          AND (SEQUENCIA = (P_SEQUENCIA * (-1) ) );
       END IF;
    /* atualizacao do campo pendente do item e do cabecalho */
       IF (P_TIPMOV IN ('O','P','C', '8','N','1','2','J','V','Q') AND P_PENDENTE_TOP = 'S') THEN
         IF (P_PENDENTE_CAB = 'N' AND P_PENDENTE = 'S') AND NOT (P_TIPMOV = 'N' AND P_QTDENTREGUE_D = 0 AND P_QTDENTREGUE = 0) THEN
            UPDATE TGFCAB SET PENDENTE = 'S'
            WHERE NUNOTA = P_NUNOTA;
         END IF;
         IF (P_PENDENTE_CAB = 'S' AND P_PENDENTE = 'N' AND P_TIPMOV <> '8') THEN
            SELECT COUNT(1) INTO P_COUNT
            FROM TGFITE
            WHERE NUNOTA = P_NUNOTA
            AND PENDENTE = 'S';
            IF (P_COUNT = 0 ) THEN
               UPDATE TGFCAB SET PENDENTE = 'N'
               WHERE NUNOTA = P_NUNOTA
               AND PENDENTE = 'S';
            END IF;
         END IF;
       END IF;
    END LOOP;
    CLOSE UPDITENS;  
    /* atualizacao da provisao */
     LOOP
       FETCH NOTAS INTO P_NUNOTA;
       EXIT WHEN NOTAS%NOTFOUND;
        Provisao_Fin( P_NUNOTA );
     END LOOP;
     CLOSE NOTAS;
    /*acabou a at. da provisao */
  END IF;
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_UPT_TGFITE_AFTER" ENABLE;
