SELECT PRO.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	PRO.CODVOLCOMPRA,
	VOA.CODVOL AS ALTERNATIVA,
	VOA.QUANTIDADE,
	(CASE WHEN VOA.DIVIDEMULTIPLICA = 'M' THEN 'MULTIPLICA' ELSE 'DIVIDE' END) AS DIVIDEMULTIPLICA
FROM TGFPRO PRO
	LEFT JOIN TGFVOA VOA ON PRO.CODPROD = VOA.CODPROD
WHERE (:P_CODPROD IS NULL OR :P_CODPROD = PRO.CODPROD)
