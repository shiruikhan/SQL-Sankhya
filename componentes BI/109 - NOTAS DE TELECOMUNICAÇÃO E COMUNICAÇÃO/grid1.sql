SELECT 
    CAB.NUNOTA AS NRUNICO,
    CAB.NUMNOTA AS NRNOTA,
    CAB.DTENTSAI AS DATA,
    CAB.CODPARC,
    (SELECT NOMEPARC FROM TGFPAR PAR WHERE PAR.CODPARC=CAB.CODPARC) AS NOME,
    ITE.CODCFO AS CFOP,
    ITE.CODPROD AS CODPROD,
    (SELECT DESCRPROD FROM TGFPRO PRO WHERE PRO.CODPROD=ITE.CODPROD) AS DESCRICAOPRODUTO,
    CAB.VLRNOTA AS VLR
    
FROM TGFCAB CAB
JOIN TGFITE ITE ON (CAB.NUNOTA=ITE.NUNOTA)
WHERE CAB.DTENTSAI >= :P_PERIODO.INI
AND CAB.DTENTSAI <= :P_PERIODO.FIN
AND CAB.CODTIPOPER IN (208,223)
