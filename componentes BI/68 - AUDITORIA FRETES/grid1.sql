SELECT 
      CAB.NUNOTA,
      CAB.CODEMP,
      CAB.NUMNOTA,
      ITE.CODCFO AS CODCFO,
      CAB.CODPARC,
      PAR.NOMEPARC,
      CAB.CODTIPOPER,
      CAB.DTENTSAI,
      CAB.VLRNOTA,
	  CAB.CODNAT,
	  NAT.DESCRNAT,
	  CAB.CODCENCUS,
	  CUS.DESCRCENCUS,
	  NAT.CODCTACTB,
	  
	 NVL((
			SELECT PLA.DESCRCTA
			FROM TCBPLA PLA
			WHERE PLA.CODCTACTB = NVL(NAT.CODCTACTB, 0)
		  ),'SEM CONTA') AS DESC_CONTA,
	 (SELECT PLA.CTACTB FROM TCBPLA PLA WHERE PLA.CODCTACTB = NVL(NAT.CODCTACTB, 0)) AS EFD_CONTA,		  
      MAX(ITE.CODTRIB) AS CST_ICMS,
      SUM(CASE WHEN DIN.CODIMP = 1 THEN DIN.BASERED ELSE 0 END) AS BASEICMS,
      SUM(CASE WHEN DIN.CODIMP = 1 THEN DIN.VALOR ELSE 0 END) AS ICMS,
      MAX(CASE WHEN DIN.CODIMP = 6 THEN DIN.CST ELSE 0 END) AS CST_PIS,
      SUM(CASE WHEN DIN.CODIMP = 6 THEN DIN.BASERED ELSE 0 END) AS BASEPIS,
      SUM(CASE WHEN DIN.CODIMP = 6 THEN DIN.VALOR ELSE 0 END) AS PIS,
      MAX(CASE WHEN DIN.CODIMP = 7 THEN DIN.CST ELSE 0 END) AS CST_COFINS,
      SUM(CASE WHEN DIN.CODIMP = 7 THEN DIN.BASERED ELSE 0 END) AS BASECOFINS,
      SUM(CASE WHEN DIN.CODIMP = 7 THEN DIN.VALOR ELSE 0 END) AS COFINS,
      CAB2.NUNOTA AS NUNOTAVINCULADO,
      MAX_NCT.NUMERO AS NUMERO,
      CAB2.CHAVENFE,
      CAB2.CODTIPOPER AS TOPVINCULADA,
	  MAX((SELECT T.DESCROPER FROM TGFTOP T WHERE T.CODTIPOPER = CAB2.CODTIPOPER AND T.DHALTER = CAB2.DHTIPOPER)) AS TPO,
      CASE 
          WHEN (CAB.CODTIPOPER = 225 AND CAB2.CODTIPOPER IN (214,1125,305)) 
            OR (CAB.CODTIPOPER = 226 AND CAB2.CODTIPOPER IN (1100,1117,1126,1200,2200,2202))
            OR (CAB.CODTIPOPER = 234 AND CAB2.CODTIPOPER IN (201)) THEN 'SIM' 
          WHEN CAB.CODTIPOPER = 242 AND CAB2.CODTIPOPER IN (201,267,231,1266,1267,1327) THEN 'NÃO' 
          ELSE 'VERIFICAR' 
      END AS VALIDADOR,
      CASE 
          WHEN CAB2.VLRFRETE > 0 THEN CAB2.VLRFRETE 
          ELSE CAB2.AD_VLROUTROSFRETE 
      END AS VLRFRETEVINCULADO
FROM TGFCAB CAB

	INNER JOIN TGFTOP TPO 
		ON TPO.CODTIPOPER = CAB.CODTIPOPER
		  AND TPO.DHALTER = CAB.DHTIPOPER

	INNER JOIN TGFITE ITE 
		ON ITE.NUNOTA = CAB.NUNOTA
	
	INNER JOIN TGFDIN DIN 
		ON DIN.NUNOTA = ITE.NUNOTA 
	AND DIN.SEQUENCIA = ITE.SEQUENCIA
   
	INNER JOIN TGFNAT NAT 
		ON NAT.CODNAT = CAB.CODNAT
	
	INNER JOIN TGFPAR PAR 
		ON CAB.CODPARC = PAR.CODPARC
	
	INNER JOIN TSICUS CUS 
		ON CUS.CODCENCUS = CAB.CODCENCUS 
	
	INNER JOIN (
		SELECT 
			NUNOTA, 
			MAX(NUMERO) AS NUMERO,
			MAX(CHAVENFE) AS MAX_CAMPO 
		FROM TGFNCT
		GROUP BY NUNOTA
	) MAX_NCT 
		ON CAB.NUNOTA = MAX_NCT.NUNOTA
		
	LEFT JOIN TGFCAB CAB2 
		ON CAB2.CHAVENFE = MAX_NCT.MAX_CAMPO
		
	LEFT JOIN TGFPAR PAR2
		ON CAB2.CODPARC = PAR2.CODPARC
		
	LEFT JOIN TGFPAR PAR3 
		ON CAB2.CODPARCTRANSP = PAR3.CODPARC
		
WHERE CAB.CODTIPOPER IN (225,226,234,242) 

 AND TRUNC(CAB.DTENTSAI) BETWEEN :P_PRAZO.INI AND :P_PRAZO.FIN
 AND (:P_CODPARC1 IS NULL OR CAB.CODPARC = :P_CODPARC1)
 AND (:P_NUMNOTA IS NULL OR CAB.NUMNOTA = :P_NUMNOTA)
 AND (:P_NUMNOTAVINCULADA IS NULL OR CAB2.NUMNOTA = :P_NUMNOTAVINCULADA)
GROUP BY 
      CAB.NUNOTA,
      CAB.CODEMP,
      CAB.NUMNOTA,
      ITE.CODCFO,
      CAB.CODPARC,
      PAR.NOMEPARC,
      CAB.CODTIPOPER,
      CAB.DTENTSAI,
      CAB.VLRNOTA,
	  CAB.CODNAT,
	  NAT.DESCRNAT,
	  CAB.CODCENCUS,
	  CUS.DESCRCENCUS,
	  NAT.CODCTACTB,
      CAB2.NUNOTA,
      CAB2.CHAVENFE,
      CAB2.CODTIPOPER,
      CAB2.VLRFRETE,
      CAB2.AD_VLROUTROSFRETE,
      MAX_NCT.NUMERO
	 
UNION ALL 
