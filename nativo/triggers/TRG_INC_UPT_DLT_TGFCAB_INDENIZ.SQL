/*==============================================================================
  Nome do Script : TRG_INC_UPT_DLT_TGFCAB_INDENIZ
  Tipo           : Trigger Nativa Sankhya (instalação do ERP, 12/2021 — referência, não customizada)
  Descrição      : Trigger AFTER EACH ROW INSERT OR UPDATE OR DELETE sobre TGFCAB.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 07/12/2021, última alteração em 28/09/2026.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026 (recaptura em pedaços — DDL completo, conferido pelo tamanho), via GET_DDL('TRIGGER', 'TRG_INC_UPT_DLT_TGFCAB_INDENIZ', 'SPARKPRD').
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_INC_UPT_DLT_TGFCAB_INDENIZ" AFTER DELETE OR INSERT OR UPDATE ON TGFCAB
FOR EACH ROW
      WHEN (
NVL(NEW.VLRINDENIZ,0) <> 0 OR NVL(OLD.VLRINDENIZ,0) <> 0 OR 
     NEW.STATUSNOTA <> OLD.STATUSNOTA
      ) DECLARE 
  P_ATUALINDENIZ      TGFTOP.ATUALINDENIZ%TYPE;
  P_ATUALINDENIZ_D    TGFTOP.ATUALINDENIZ%TYPE;
  P_MAXINDENIZ        TGFPAR.MAXCREDINDENIZ%TYPE;
  P_VLRINDENIZ        TGFCAB.VLRINDENIZ%TYPE;
  ERRMSG              VARCHAR2(255);
  ERROR               EXCEPTION;
  P_VALIDAR           BOOLEAN;
  P_COUNT             NUMBER(05);
BEGIN
  
  -- VERIFICANDO SE O CLIENTE UTILIZA ESTA FUNCIONALIDADE
  SELECT COUNT(*) INTO P_COUNT
  FROM TSIVARBD
  WHERE UTILIZA_INDENIZ = 'N';
  IF P_COUNT > 0 THEN 
    RETURN;
  END IF;

  IF STP_GET_ATUALIZANDO THEN
    RETURN;
  END IF;

   /* 
   Sincronização de dados
   */
  P_VALIDAR := Fpodevalidar('TGFCAB');
  IF UPDATING('NUNOTA') THEN
    ERRMSG := 'A coluna NUNOTA não pode ser alterada.';
    RAISE ERROR;
  END IF;

  IF INSERTING OR UPDATING THEN
    BEGIN
      SELECT ATUALINDENIZ
      INTO P_ATUALINDENIZ
      FROM TGFTOP
      WHERE CODTIPOPER = :NEW.CODTIPOPER
      AND DHALTER = :NEW.DHTIPOPER;
    EXCEPTION WHEN NO_DATA_FOUND THEN
      ERRMSG := 'Não foi encontrada a TOP ' || TO_CHAR(:NEW.CODTIPOPER) || ' com data de alteração igual a ' || TO_CHAR(:NEW.DHTIPOPER) || ' .';
      RAISE ERROR;      
    END;      
  END IF;
  
  IF :NEW.TIPMOV <> 'D' AND (INSERTING OR UPDATING) THEN
    IF P_ATUALINDENIZ = 0 THEN
      IF :NEW.VLRINDENIZ <> 0 THEN
        ERRMSG := 'Valor de Indenização deve ser zero.';
        RAISE ERROR;
      END IF;
    ELSIF P_ATUALINDENIZ = 1 THEN
      SELECT MAXCREDINDENIZ
      INTO P_MAXINDENIZ
      FROM TGFPAR
      WHERE CODPARC = :NEW.CODPARC;
      IF P_MAXINDENIZ IS NULL THEN
        SELECT MAXCREDINDENIZ
        INTO P_MAXINDENIZ
        FROM TGFEMP
        WHERE CODEMP = :NEW.CODEMP;
      END IF;
      P_VLRINDENIZ := :NEW.VLRNOTA;
      IF :NEW.VLRINDENIZ <> ROUND(P_VLRINDENIZ * P_MAXINDENIZ / 100,2) THEN
        ERRMSG := 'Valor de Indenização deve ser ' || ROUND(P_VLRINDENIZ * P_MAXINDENIZ / 100,2);
        RAISE ERROR;
      END IF;
    ELSIF P_ATUALINDENIZ = -1 THEN
      SELECT MAXDEBINDENIZ
      INTO P_MAXINDENIZ
      FROM TGFPAR
      WHERE CODPARC = :NEW.CODPARC;
      IF P_MAXINDENIZ IS NULL THEN
        SELECT MAXDEBINDENIZ
        INTO P_MAXINDENIZ
        FROM TGFEMP
        WHERE CODEMP = :NEW.CODEMP;
      END IF;
      P_VLRINDENIZ := :NEW.VLRNOTA + :NEW.VLRINDENIZ;
      IF :NEW.VLRINDENIZ > ROUND(P_VLRINDENIZ * P_MAXINDENIZ / 100,2) THEN
        ERRMSG := 'Valor de Indenização maior que o permitido. % Máximo: ' || P_MAXINDENIZ ||'.';
        RAISE ERROR;
      END IF;
    END IF;
  END IF;
  
  IF P_ATUALINDENIZ = 1 AND :NEW.STATUSNOTA <> 'L' THEN -- ALTERACAO DE CREDITO NAO CONFIRMADO
    P_ATUALINDENIZ := 0;
  END IF;
  IF P_ATUALINDENIZ = 1 AND NVL(:OLD.STATUSNOTA,'X') <> 'L' AND :NEW.STATUSNOTA = 'L' THEN -- CONFIRMACAO DE CREDITO
    UPDATE TGFPAR SET SALDOINDENIZ = NVL(SALDOINDENIZ,0) + (:NEW.VLRINDENIZ * P_ATUALINDENIZ) 
    WHERE CODPARC = :NEW.CODPARC;
  ELSIF UPDATING AND (NVL(:OLD.VLRINDENIZ,0) <> :NEW.VLRINDENIZ) AND (:OLD.CODPARC = :NEW.CODPARC) THEN
    UPDATE TGFPAR SET SALDOINDENIZ = NVL(SALDOINDENIZ,0) + (:NEW.VLRINDENIZ * P_ATUALINDENIZ) - (NVL(:OLD.VLRINDENIZ,0) * P_ATUALINDENIZ)
    WHERE CODPARC = :NEW.CODPARC;
  ELSE
    IF NVL(:OLD.VLRINDENIZ,0) <> 0 AND (DELETING OR NVL(:OLD.VLRINDENIZ,0) <> :NEW.VLRINDENIZ) THEN
      BEGIN
        SELECT ATUALINDENIZ
        INTO P_ATUALINDENIZ_D
        FROM TGFTOP
        WHERE CODTIPOPER = :OLD.CODTIPOPER
        AND DHALTER = :OLD.DHTIPOPER;
      EXCEPTION WHEN NO_DATA_FOUND THEN
        ERRMSG := 'Não foi encontrada a TOP ' || TO_CHAR(:OLD.CODTIPOPER) || ' com data de alteração igual a ' || TO_CHAR(:OLD.DHTIPOPER) || ' .';
        RAISE ERROR;        
      END;      
      IF (P_ATUALINDENIZ_D=-1) OR (:OLD.STATUSNOTA = 'L') THEN 
        UPDATE TGFPAR SET SALDOINDENIZ = NVL(SALDOINDENIZ,0) - (NVL(:OLD.VLRINDENIZ,0) * P_ATUALINDENIZ_D)
        WHERE CODPARC = :OLD.CODPARC;
      END IF;
    END IF;
    IF :NEW.VLRINDENIZ <> 0 AND (INSERTING OR NVL(:OLD.VLRINDENIZ,0) <> :NEW.VLRINDENIZ) THEN
      UPDATE TGFPAR SET SALDOINDENIZ = NVL(SALDOINDENIZ,0) + (:NEW.VLRINDENIZ * P_ATUALINDENIZ)
      WHERE CODPARC = :NEW.CODPARC;
    END IF;
  END IF;
  RETURN;  
EXCEPTION
  WHEN ERROR THEN
  ERRMSG := ERRMSG || 'Nota de Nro Único: '|| TO_CHAR(:NEW.NUNOTA);  
  /* 
    Sincronização de dados não faz validações
    */
  IF (P_VALIDAR) THEN 
    RAISE_APPLICATION_ERROR(-20101, ERRMSG);
  END IF; 
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_INC_UPT_DLT_TGFCAB_INDENIZ" ENABLE;
