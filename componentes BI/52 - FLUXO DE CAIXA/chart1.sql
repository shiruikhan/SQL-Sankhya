SELECT SUM(RECEITA) AS RECEITA, SUM(DESPESA) AS DESPESA, PER,ORDEM,SUM(AZUL) AS AZUL, SUM(VERMELHO) AS VERMELHO
FROM(
SELECT
        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) AS RECEITA, 
        SUM(CASE WHEN FIN.RECDESP = -1 THEN FIN.VLRDESDOB ELSE 0 END) AS DESPESA,
TO_CHAR(FIN.DHBAIXA,'Mon/YYYY') AS PER,
TO_CHAR(FIN.DHBAIXA,'YYYYMM') AS ORDEM,
case when

        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) -
        SUM(CASE WHEN FIN.RECDESP = -1 THEN FIN.VLRDESDOB ELSE 0 END) >0
then 
        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) -
        SUM(CASE WHEN FIN.RECDESP = -1 THEN FIN.VLRDESDOB ELSE 0 END) end as AZUL,

case when

        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) -
        SUM(CASE WHEN FIN.RECDESP = -1 THEN FIN.VLRDESDOB ELSE 0 END) <=0
then 
        SUM(CASE WHEN FIN.RECDESP = -1 THEN FIN.VLRDESDOB ELSE 0 END) -
        SUM(CASE WHEN FIN.RECDESP =  1 THEN FIN.VLRDESDOB ELSE 0 END) end as VERMELHO
FROM TGFFIN FIN
INNER JOIN TGFNAT NAT ON FIN.CODNAT= NAT.CODNAT
LEFT JOIN TGFMBC MBC ON MBC.NUBCO = FIN.NUBCO
LEFT JOIN TSICTA CTA ON CTA.CODCTABCOINT =  MBC.CODCTABCOINT
WHERE FIN.DHBAIXA >= :PERIODO.INI 
AND FIN.DHBAIXA <= :PERIODO.FIN 
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND FIN.DHBAIXA IS NOT NULL
AND FIN.PROVISAO='N'
AND FIN.RECDESP <> 0
AND ((CTA.CLASSE IS NULL OR CTA.CLASSE <> 'D')) 
AND (FIN.CODEMP IN :EMPRESA) 
GROUP BY
TO_CHAR(FIN.DHBAIXA,'Mon/YYYY') ,
TO_CHAR(FIN.DHBAIXA,'YYYYMM')


UNION ALL

SELECT SUM(CASE WHEN MBC.RECDESP = 1 THEN MBC.VLRLANC ELSE 0 END) AS RECEITA,
SUM(CASE WHEN MBC.RECDESP = -1 THEN MBC.VLRLANC ELSE 0 END) AS DESPESA,
TO_CHAR(MBC.DTLANC,'Mon/YYYY') AS PER,
TO_CHAR(MBC.DTLANC,'YYYYMM') AS ORDEM,
case when

        SUM(CASE WHEN MBC.RECDESP =  1 THEN MBC.VLRLANC ELSE 0 END) -
        SUM(CASE WHEN MBC.RECDESP = -1 THEN MBC.VLRLANC ELSE 0 END) >0
then 
        SUM(CASE WHEN MBC.RECDESP =  1 THEN MBC.VLRLANC ELSE 0 END) -
        SUM(CASE WHEN MBC.RECDESP = -1 THEN MBC.VLRLANC ELSE 0 END) end as AZUL,

case when

        SUM(CASE WHEN MBC.RECDESP =  1 THEN MBC.VLRLANC ELSE 0 END) -
        SUM(CASE WHEN MBC.RECDESP = -1 THEN MBC.VLRLANC ELSE 0 END) <=0
then 
        SUM(CASE WHEN MBC.RECDESP = -1 THEN MBC.VLRLANC ELSE 0 END) -
        SUM(CASE WHEN MBC.RECDESP =  1 THEN MBC.VLRLANC ELSE 0 END) end as VERMELHO
FROM TGFMBC MBC
INNER JOIN TSICTA CTA ON MBC.CODCTABCOINT = CTA.CODCTABCOINT
INNER JOIN TGFFIN FIN ON MBC.NUBCO = FIN.NUBCO
INNER JOIN TGFNAT NAT ON FIN.CODNAT= NAT.CODNAT
WHERE  MBC.DTLANC     >=  :PERIODO.INI 
AND MBC.DTLANC     < :PERIODO.FIN 
AND (FIN.CODCENCUS = :CODCENCUS OR :CODCENCUS IS NULL)
AND CTA.CLASSE = 'D'
AND (FIN.CODEMP IN :EMPRESA) 
AND :ADIANTAMENTO = 'S'
GROUP BY
TO_CHAR(MBC.DTLANC,'Mon/YYYY'),
TO_CHAR(MBC.DTLANC,'YYYYMM'))
GROUP BY PER,ORDEM
ORDER BY 4
