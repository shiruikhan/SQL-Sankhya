SELECT
CTB.DTREF,
CTB.CODCENCUS,
CUS.DESCRCENCUS,
CUS.GRUPO,
SUM(RECBRU) AS RECBRU,
SUM(DEDREC) AS DEDREC,
SUM(RECLIQ) AS RECLIQ,
SUM(TOTCUS) AS TOTCUS,
SUM(RESBRU) AS RESBRU,
SUM(TOTCOM) AS TOTCOM,
SUM(TOTADM) AS TOTADM,
SUM(RESLIQ) AS RESLIQ,
SUM(TOTDEM) AS TOTDEM,
SUM(TOTFIN) AS TOTFIN,
SUM(RESANT) AS RESANT,
SUM(IRCSLL) AS IRCSLL,
SUM(RESEXE) AS RESEXE,
SUM(EBITDA) AS EBITDA
FROM

(
SELECT 
DTREF,
CODCENCUS,
CASE WHEN NUORDEM = 35 THEN TOTAL ELSE 0 END AS RECBRU,
CASE WHEN NUORDEM = 39 THEN TOTAL ELSE 0 END AS DEDREC,
CASE WHEN NUORDEM = 40 THEN TOTAL ELSE 0 END AS RECLIQ,
CASE WHEN NUORDEM = 50 THEN TOTAL ELSE 0 END AS TOTCUS,
CASE WHEN NUORDEM = 55 THEN TOTAL ELSE 0 END AS RESBRU,
CASE WHEN NUORDEM = 70 THEN TOTAL ELSE 0 END AS TOTCOM,
CASE WHEN NUORDEM = 80 THEN TOTAL ELSE 0 END AS TOTADM,
CASE WHEN NUORDEM = 85 THEN TOTAL ELSE 0 END AS RESLIQ,
CASE WHEN NUORDEM = 90 THEN TOTAL ELSE 0 END AS TOTDEM,
CASE WHEN NUORDEM = 93 THEN TOTAL ELSE 0 END AS TOTFIN,
CASE WHEN NUORDEM = 95 THEN TOTAL ELSE 0 END AS RESANT,
CASE WHEN NUORDEM = 98 THEN TOTAL ELSE 0 END AS IRCSLL,
CASE WHEN NUORDEM = 99 THEN TOTAL ELSE 0 END AS RESEXE,
CASE WHEN NUORDEM = 199 THEN TOTAL ELSE 0 END AS EBITDA
FROM(

	/* CONTAS SINTÉTICAS */
	SELECT 
	DADOS2.DTREF,
	DADOS2.CODCENCUS,
	DMT.GRAU,
	TO_NUMBER(DMT.NUORDEM) AS NUORDEM,
	DMT.CODDMT, 
	DMT.DESCRDMT, 
	SUM(DADOS2.TOTAL) AS TOTAL,
	CASE WHEN DMT.CODDMT IN ('3.1.1.1.1.1','3.1.1.1.1','3.1.1.1','3.1.1','3.1') THEN  '#66ccff'
	     WHEN DMT.CODDMT IN ('3.1.1.1.1.2','3.1.1.1.2','3.1.1.2','3.1.3','3.1.5') THEN '#b3e6ff'
	     WHEN DMT.CODDMT IN ('3.1.1.2.1','3.1.1.2.5') THEN '#e6f7ff'
	     WHEN DMT.CODDMT IN ('3') THEN '#33bbff'
	     WHEN :DRE = 'S' THEN '#cceeff'
	     ELSE '#ffffff' END AS BKCOLOR
	FROM
	TCBDMT DMT
	LEFT JOIN
	(SELECT DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF,DADOS.CODCENCUS, SUM(TOTAL) AS TOTAL
	 FROM(
	    SELECT LAN.CODEMP, TO_CHAR(LAN.DTMOV,'YYYY') AS DTREF, LAN.CODCTACTB, DMT.CODDMT, DMT.DESCRDMT, LAN.CODCENCUS,
	   (LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS TOTAL
	    FROM
	    TCBLAN LAN
	    LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
	    LEFT JOIN TCBPLA PLA2 ON PLA.CODCTACTBPAI = PLA2.CODCTACTB
	    LEFT JOIN TCBCDM CDM ON (PLA2.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTB = CDM.CODCTACTB)
	    LEFT JOIN TCBDMT DMT ON CDM.CODTDM = DMT.CODTDM AND CDM.CODDMT = DMT.CODDMT
	    WHERE
	    PLA.CTACTB>'3'
	    AND LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') 
	    AND LAN.DTMOV <= LAST_DAY(:DAT1)
	    AND LAN.CODEMP IN :CODEMP
	    AND LAN.NUMLOTE NOT IN (999,9999)	
	)DADOS
	GROUP BY DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF, DADOS.CODCENCUS) DADOS2 ON 
	((SUBSTR(DADOS2.CODDMT,1,1) = SUBSTR(DMT.CODDMT,1,1) AND DMT.GRAU=1) OR 
	 (SUBSTR(DADOS2.CODDMT,1,3) = SUBSTR(DMT.CODDMT,1,3) AND DMT.GRAU=2) OR
	 (SUBSTR(DADOS2.CODDMT,1,5) = SUBSTR(DMT.CODDMT,1,5) AND DMT.GRAU=3) OR
	 (SUBSTR(DADOS2.CODDMT,1,7) = SUBSTR(DMT.CODDMT,1,7) AND DMT.GRAU=4) OR
	 (SUBSTR(DADOS2.CODDMT,1,9) = SUBSTR(DMT.CODDMT,1,9) AND DMT.GRAU=5) OR
	 (SUBSTR(DADOS2.CODDMT,1,11) = SUBSTR(DMT.CODDMT,1,11) AND DMT.GRAU=6) OR
	 (SUBSTR(DADOS2.CODDMT,1,14) = SUBSTR(DMT.CODDMT,1,14) AND DMT.GRAU=7))
	WHERE 
	    DMT.GRAU IN (1,2,3,4,5,6,7)
	AND DMT.CODTDM= 2
	AND DADOS2.TOTAL IS NOT NULL
	GROUP BY DMT.GRAU, TO_NUMBER(DMT.NUORDEM), DMT.CODDMT,DMT.DESCRDMT, DADOS2.DTREF, DADOS2.CODCENCUS
	
	UNION ALL
	
	/* CONTA ANALÍTICAS */
	SELECT 
	DTREF,
	CODCENCUS,
	10 AS GRAU,
	TO_NUMBER(NUORDEM) AS NUORDEM,
	CTACTB, 
	REPLACE(REPLACE(INITCAP(DESCRCTA),' De ',' de '),' E ',' e ') AS DESCRCTA, 
	SUM(TOTAL) AS TOTAL,
	'#ffffff' AS BKCOLOR
	FROM
	(
	SELECT DADOS.DTREF, DADOS.CODEMP, DADOS.NUORDEM, DADOS.CTACTB, DADOS.DESCRCTA, DADOS.CODCENCUS, SUM(TOTAL) AS TOTAL
	 FROM(
	    SELECT LAN.CODEMP, TO_CHAR(LAN.DTMOV,'YYYY') AS DTREF, PLA.CTACTB, LAN.CODCTACTB, PLA.DESCRCTA, DMT.NUORDEM,LAN.CODCENCUS,
	   (LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS TOTAL
	    FROM
	    TCBLAN LAN
	    LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
	    LEFT JOIN TCBPLA PLA2 ON PLA.CODCTACTBPAI = PLA2.CODCTACTB
	    LEFT JOIN TCBCDM CDM ON (PLA2.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTB = CDM.CODCTACTB) AND CDM.CODTDM=2
	    JOIN TCBDMT DMT ON CDM.CODTDM = DMT.CODTDM AND CDM.CODDMT = DMT.CODDMT
	    WHERE
	    PLA.CTACTB>'3'
	    AND LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') 
	    AND LAN.DTMOV <= LAST_DAY(:DAT1)
	    AND LAN.CODEMP IN :CODEMP
	    AND LAN.NUMLOTE NOT IN (999,9999)	
		)DADOS
		GROUP BY DADOS.CTACTB, DADOS.DESCRCTA, DADOS.DTREF,DADOS.CODEMP, DADOS.NUORDEM, DADOS.CODCENCUS
	)DADOS2
	WHERE 
	DADOS2.TOTAL IS NOT NULL
	AND :DRE = 'S'
	GROUP BY DTREF, CTACTB, DESCRCTA, TO_NUMBER(NUORDEM), CODCENCUS

	UNION ALL
	
	/* RELACAO CONTAS PÓS RESULTADO DESPREZADAS PARA CALCULO EBITDA */
	SELECT 
	DADOS2.DTREF,
	DADOS2.CODCENCUS,
	DMT.GRAU,
	TO_NUMBER(DMT.NUORDEM)+100 AS NUORDEM,
	DMT.CODDMT, 
	CASE WHEN DMT.CODDMT IN ('3.1.1.1.2.9','3.1.1.2.1.9','3.1.1.2.5.9','3.1.5.2','3.2') THEN '( + ) '||DMT.DESCRDMT ELSE '( - ) '||DMT.DESCRDMT END AS DESCRDMT,
	SUM(DADOS2.TOTAL)*-1 AS TOTAL,
	'#d1d1e0' AS BKCOLOR
	FROM
	TCBDMT DMT
	LEFT JOIN
	(SELECT DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF, DADOS.CODCENCUS, SUM(TOTAL) AS TOTAL
	 FROM(
	    SELECT LAN.CODEMP, TO_CHAR(LAN.DTMOV,'YYYY') AS DTREF, LAN.CODCTACTB, DMT.CODDMT, DMT.DESCRDMT,LAN.CODCENCUS,
	   (LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS TOTAL
	    FROM
	    TCBLAN LAN
	    LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
	    LEFT JOIN TCBPLA PLA2 ON PLA.CODCTACTBPAI = PLA2.CODCTACTB
	    LEFT JOIN TCBCDM CDM ON (PLA2.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTB = CDM.CODCTACTB)
	    LEFT JOIN TCBDMT DMT ON CDM.CODTDM = DMT.CODTDM AND CDM.CODDMT = DMT.CODDMT
	    WHERE
	    PLA.CTACTB>'3'
	    AND LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') 
	    AND LAN.DTMOV <= LAST_DAY(:DAT1)
	    AND LAN.CODEMP IN :CODEMP
	    AND LAN.NUMLOTE NOT IN (999,9999)	
	)DADOS
	GROUP BY DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF, DADOS.CODCENCUS) DADOS2 ON 
	((SUBSTR(DADOS2.CODDMT,1,1) = SUBSTR(DMT.CODDMT,1,1) AND DMT.GRAU=1) OR 
	 (SUBSTR(DADOS2.CODDMT,1,3) = SUBSTR(DMT.CODDMT,1,3) AND DMT.GRAU=2) OR
	 (SUBSTR(DADOS2.CODDMT,1,5) = SUBSTR(DMT.CODDMT,1,5) AND DMT.GRAU=3) OR
	 (SUBSTR(DADOS2.CODDMT,1,7) = SUBSTR(DMT.CODDMT,1,7) AND DMT.GRAU=4) OR
	 (SUBSTR(DADOS2.CODDMT,1,9) = SUBSTR(DMT.CODDMT,1,9) AND DMT.GRAU=5) OR
	 (SUBSTR(DADOS2.CODDMT,1,11) = SUBSTR(DMT.CODDMT,1,11) AND DMT.GRAU=6) OR
	 (SUBSTR(DADOS2.CODDMT,1,14) = SUBSTR(DMT.CODDMT,1,14) AND DMT.GRAU=7))
	WHERE 
	    DMT.GRAU IN (1,2,3,4,5,6,7)
	AND DMT.CODTDM= 2
	AND DADOS2.TOTAL IS NOT NULL
	AND DMT.CODDMT IN ('3.1.1.1.2.9','3.1.1.2.1.9','3.1.1.2.5.9','3.1.5.1','3.1.5.2','3.2') /*GRUPOS DESPREZADOS NA ANÁLISE DO EBITDA*/
	GROUP BY DMT.GRAU, TO_NUMBER(DMT.NUORDEM), DMT.CODDMT,DMT.DESCRDMT, DADOS2.DTREF, DADOS2.CODCENCUS
	
	UNION ALL	

	/* RESULTADO EBITDA */
	SELECT 
	DADOS2.DTREF,
	DADOS2.CODCENCUS,
	DMT.GRAU,
	TO_NUMBER(DMT.NUORDEM)+100 AS NUORDEM,
	DMT.CODDMT, 
	'( = ) EBITDA' AS DESCRDMT, 
	SUM(DADOS2.TOTAL) AS TOTAL,
	'#4dffc3' AS BKCOLOR
	FROM
	TCBDMT DMT
	LEFT JOIN
	(SELECT DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF, DADOS.CODCENCUS, SUM(TOTAL) AS TOTAL
	 FROM(
	    SELECT LAN.CODEMP, TO_CHAR(LAN.DTMOV,'YYYY') AS DTREF, LAN.CODCTACTB, DMT.CODDMT, DMT.DESCRDMT, LAN.CODCENCUS,
	   (LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS TOTAL
	    FROM
	    TCBLAN LAN
	    LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
	    LEFT JOIN TCBPLA PLA2 ON PLA.CODCTACTBPAI = PLA2.CODCTACTB
	    LEFT JOIN TCBCDM CDM ON (PLA2.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTBPAI = CDM.CODCTACTB) OR (PLA.CODCTACTB = CDM.CODCTACTB)
	    LEFT JOIN TCBDMT DMT ON CDM.CODTDM = DMT.CODTDM AND CDM.CODDMT = DMT.CODDMT
	    WHERE
	    PLA.CTACTB>'3'
	    AND LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') 
	    AND LAN.DTMOV <= LAST_DAY(:DAT1)
	    AND LAN.CODEMP IN :CODEMP
	    AND LAN.NUMLOTE NOT IN (999,9999)	
	)DADOS
	GROUP BY DADOS.CODDMT, DADOS.DESCRDMT, DADOS.CODEMP, DADOS.DTREF, DADOS.CODCENCUS) DADOS2 ON 
	((SUBSTR(DADOS2.CODDMT,1,1) = SUBSTR(DMT.CODDMT,1,1) AND DMT.GRAU=1) OR 
	 (SUBSTR(DADOS2.CODDMT,1,3) = SUBSTR(DMT.CODDMT,1,3) AND DMT.GRAU=2) OR
	 (SUBSTR(DADOS2.CODDMT,1,5) = SUBSTR(DMT.CODDMT,1,5) AND DMT.GRAU=3) OR
	 (SUBSTR(DADOS2.CODDMT,1,7) = SUBSTR(DMT.CODDMT,1,7) AND DMT.GRAU=4) OR
	 (SUBSTR(DADOS2.CODDMT,1,9) = SUBSTR(DMT.CODDMT,1,9) AND DMT.GRAU=5) OR
	 (SUBSTR(DADOS2.CODDMT,1,11) = SUBSTR(DMT.CODDMT,1,11) AND DMT.GRAU=6) OR
	 (SUBSTR(DADOS2.CODDMT,1,14) = SUBSTR(DMT.CODDMT,1,14) AND DMT.GRAU=7))
	WHERE 
	    DMT.GRAU IN (1,2,3,4,5,6,7)
	AND DMT.CODTDM= 2
	AND DADOS2.TOTAL IS NOT NULL
	AND DADOS2.CODDMT NOT IN ('3.1.1.1.2.9','3.1.1.2.1.9','3.1.1.2.5.9','3.1.5.1','3.1.5.2','3.2')
	AND DMT.CODDMT IN ('3') 
	GROUP BY DMT.GRAU, TO_NUMBER(DMT.NUORDEM), DMT.CODDMT,DMT.DESCRDMT, DADOS2.DTREF, DADOS2.CODCENCUS
		
)
WHERE NUORDEM IN (35,39,40,50,55,70,80,85,90,93,95,98,99,199)
ORDER BY 
DTREF, CODCENCUS, NUORDEM, GRAU
)CTB,
(
	SELECT C.CODCENCUS, C.DESCRCENCUS, P.DESCRCENCUS AS GRUPO FROM TSICUS C LEFT JOIN TSICUS P ON P.CODCENCUS = C.CODCENCUSPAI
)CUS
WHERE
CTB.CODCENCUS = CUS.CODCENCUS
GROUP BY
CTB.DTREF, CTB.CODCENCUS, CUS.DESCRCENCUS, CUS.GRUPO
ORDER BY RECBRU DESC, REPLACE(GRUPO,'OPERACIONAL','AAA'), DESCRCENCUS
