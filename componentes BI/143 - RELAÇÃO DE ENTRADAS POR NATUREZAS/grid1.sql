SELECT CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTENTSAI,
	CAB.CODEMP,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	ITE.QTDNEG,
	CAB.CODTIPOPER,
	PRO.USOPROD,
	CAB.CODNAT,
	NVL(NAT.DESCRNAT,'SEM NATUREZA') AS DESCRNAT
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	LEFT JOIN TGFNAT NAT ON CAB.CODNAT = NAT.CODNAT
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
WHERE CAB.DTENTSAI >= :P_PERIODO.INI
	AND CAB.DTENTSAI <= :P_PERIODO.FIN
	AND CAB.TIPMOV = 'C'
	AND CAB.STATUSNOTA = 'L'
ORDER BY CAB.NUNOTA,
	ITE.CODPROD
