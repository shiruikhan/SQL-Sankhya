CREATE OR REPLACE PROCEDURE "STP_TFPFUN_ALTERADEP" (
    P_CODUSU   NUMBER,
    P_IDSESSAO VARCHAR2,
    P_QTDLINHAS NUMBER,
    P_MENSAGEM OUT VARCHAR2
) AS
    PARAM_NEWCODDEP VARCHAR2(4000);
    FIELD_CODEMP    NUMBER;
    FIELD_CODFUNC   NUMBER;
    V_TOTAL_ATUALIZADO NUMBER := 0;
BEGIN

    PARAM_NEWCODDEP := ACT_TXT_PARAM(P_IDSESSAO, 'NEWCODDEP');

    FOR I IN 1..P_QTDLINHAS LOOP
        FIELD_CODEMP  := ACT_INT_FIELD(P_IDSESSAO, I, 'CODEMP');
        FIELD_CODFUNC := ACT_INT_FIELD(P_IDSESSAO, I, 'CODFUNC');

        UPDATE TFPFUN
           SET CODDEP = PARAM_NEWCODDEP
         WHERE CODFUNC = FIELD_CODFUNC
           AND CODEMP  = FIELD_CODEMP;

        V_TOTAL_ATUALIZADO := V_TOTAL_ATUALIZADO + SQL%ROWCOUNT;
    END LOOP;

    P_MENSAGEM := 'Departamento atualizado com sucesso para ' || V_TOTAL_ATUALIZADO || ' funcionário(s).';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        P_MENSAGEM := 'Erro ao atualizar departamento: ' || SQLERRM;
END;
