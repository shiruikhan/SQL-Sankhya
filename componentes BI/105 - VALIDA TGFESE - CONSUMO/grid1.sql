SELECT ESE.CODPROD,
	SUM(CASE WHEN ESE.ATUALESTOQUE = 1 THEN ESE.QTDNEG ELSE 0 END) - SUM(CASE WHEN ESE.ATUALESTOQUE = -1 THEN ESE.QTDNEG ELSE 0 END) AS SALDO
FROM TGFESE ESE
	INNER JOIN TGFPRO PRO ON (ESE.CODPROD = PRO.CODPROD)
WHERE (ESE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND ESE.CODLOCALORIG = :P_CODLOCALORIG
	AND ESE.CODEMP = :P_CODEMP
	AND TRUNC(ESE.DTREFERENCIA) <= :P_DTREFERENCIA
	AND PRO.USOPROD IN('B','C','1','2','I')
GROUP BY ESE.CODPROD
HAVING SUM(CASE WHEN ESE.ATUALESTOQUE = 1 THEN ESE.QTDNEG ELSE 0 END)- SUM(CASE WHEN ESE.ATUALESTOQUE = -1 THEN ESE.QTDNEG ELSE 0 END) <> 0
ORDER BY ESE.CODPROD
