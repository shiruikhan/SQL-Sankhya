SELECT DADOS.*, 
	CASE WHEN MOD(ROWNUM,2) = 0  THEN '#DCDCDC' ELSE '#FFDAB9' END  AS BKCOLOR 
FROM (SELECT C.NUNOTA,
			C.NUMNOTA,
			C.VLRNOTA,
			C.CODPARC,
			CASE WHEN P.NOMEPARC = '<SEM PARCEIRO>' THEN 'PEDIDO' ELSE P.NOMEPARC END AS PARCEIRO,
			C.DTENTSAI ,
			C.DTALTER,
			trunc(sysdate) - C.DTENTSAI DIASSEMCONFIRMAR,
			CASE WHEN C.TIPMOV = 'O' THEN 'PEDIDO COMPRA' WHEN C.TIPMOV = 'P' THEN 'PEDIDO VENDA' WHEN C.TIPMOV = 'J' THEN 'PEDIDO' WHEN C.TIPMOV = 'Q' THEN 'BAIXA' WHEN C.TIPMOV = 'V' THEN 'VENDA' WHEN C.TIPMOV = 'C' THEN 'COMPRA' WHEN C.TIPMOV = 'T' THEN 'TRANSF.' WHEN C.TIPMOV = 'F' THEN 'PRODUÇÃO' ELSE 'OUTROS' END AS TIPMOV,
			U.NOMEUSU,
			TPO.CODTIPOPER || ' - ' || TPO.DESCROPER AS DESCROPER
		FROM TGFCAB C INNER JOIN TGFPAR P ON (C.CODPARC = P.CODPARC)	
			INNER JOIN TSIUSU U ON (C.CODUSUINC = U.CODUSU)
			INNER JOIN TGFTOP TPO ON (C.CODTIPOPER = TPO.CODTIPOPER AND C.DHTIPOPER = TPO.DHALTER)
		WHERE C.STATUSNOTA <> 'L'  
			AND C.TIPMOV <> 'Z'
		ORDER BY 10,11 ASC, C.DTNEG ASC) DADOS
