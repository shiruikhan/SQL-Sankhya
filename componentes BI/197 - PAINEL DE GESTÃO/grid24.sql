SELECT * FROM(

SELECT 
TIPO,
CODPARC,
RAZAOSOCIAL,
SUM(VLRTOTALFIN) AS VLRTOTALFIN,
SUM(VLRTOTALFIN) - SUM(VLRTOTALCTB) AS VLRDIVERGENCIA,
SUM(VLRTOTALCTB) AS VLRTOTALCTB,
CODCTACTB,
CTACTB,
DESCRCTA
FROM(

	-- CLIENTES - POSIÇÃO FINANCEIRA
	SELECT 
	TIPO,
	CODPARC,
	UPPER(RAZAOSOCIAL) AS RAZAOSOCIAL,
	SUM(VALOR) AS VLRTOTALFIN,
	CODCTACTB,
	CTACTB,
	DESCRCTA,
	0 AS VLRTOTALCTB
	FROM(
	
	/*CLIENTES EM ABERTO E DEVOLUÇÕES DE CLIENTES EM ABERTO - INICIO*/
		--TITULOS ORIGEM FINANCEIRO - TOP TIPO "V"
		SELECT 
		CASE WHEN T.TIPMOV = 'V' THEN 'CLIENTES'
			 WHEN T.TIPMOV = 'D' THEN 'DEVOL. VENDA'
		     ELSE 'CLIENTES' END AS TIPO,
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
		CASE WHEN T.TIPMOV = 'V' THEN PAR.CODCTACTB
			 WHEN T.TIPMOV = 'D' THEN 197
		     ELSE PAR.CODCTACTB END AS CODCTACTB,
		CASE WHEN T.TIPMOV = 'V' THEN PLA.CTACTB
			 WHEN T.TIPMOV = 'D' THEN '2.1.01.10.004'
		     ELSE PLA.CTACTB END AS CTACTB,
		CASE WHEN T.TIPMOV = 'V' THEN PLA.DESCRCTA
			 WHEN T.TIPMOV = 'D' THEN 'DEVOL. VENDAS A COMPENSAR'
		     ELSE PLA.CTACTB END AS DESCRCTA
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
		LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
		WHERE
		FIN.CODEMP IN :CODEMP AND  
		(CASE WHEN T.TIPMOV = 'V' THEN FIN.DTNEG ELSE FIN.DTENTSAI END) <= :DAT1 AND  
		(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
		 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
		((T.TIPMOV IN ('V') AND FIN.RECDESP = 1) OR
		(T.TIPMOV IN ('D') AND FIN.RECDESP = -1))
		
		UNION ALL
		
		--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
		SELECT 
		'CLIENTES' AS TIPO,
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
		PAR.CODCTACTB AS CODCTACTB,
		PLA.CTACTB,
		PLA.DESCRCTA
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
		LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
		WHERE
		FIN.CODEMP IN :CODEMP AND  
		FIN.DTNEG <= :DAT1 AND  
		(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
		 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
		T.TIPMOV IN ('I') AND 
		FIN.RECDESP = 1 AND
		NAT.AD_TIPOCTBZ = 'N'
		/*CLIENTES EM ABERTO E DEVOLUÇÕES DE CLIENTES EM ABERTO - FIM*/	
	) GROUP BY
	TIPO, CODPARC, UPPER(RAZAOSOCIAL),CODCTACTB, CTACTB, DESCRCTA
			
		UNION ALL
		
		--CLIENTES - POSIÇÃO CONTÁBIL
		SELECT
		CASE WHEN CODCTACTB = 197 THEN 'DEVOL. VENDA' ELSE 'CLIENTES' END AS TIPO,
		CODPARC,
		RAZAOSOCIAL,
		0 AS VLRTOTALFIN,
		CODCTACTB,
		CTACTB,
		DESCRCTA,
		SUM(VLRTOTAL) AS VLRTOTALCTB
		FROM(
			SELECT
			PAR.CODPARC,
			PAR.RAZAOSOCIAL,
			LAN.CODCTACTB,
			PLA.CTACTB,
			PLA.DESCRCTA,
			LAN.VLRLANC*DECODE(LAN.TIPLANC,'R',-1,1) AS VLRTOTAL
			FROM
			TCBLAN LAN
			LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
			LEFT JOIN TGFPAR PAR ON PAR.CODCTACTB = PLA.CODCTACTB
			WHERE
			LAN.DTMOV <= :DAT1 AND 
			LAN.CODEMP IN :CODEMP AND
			(PLA.CODCTACTBPAI = 169 OR LAN.CODCTACTB = 197)
		)
		GROUP BY CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB, DESCRCTA
		HAVING SUM(VLRTOTAL) <> 0
)
GROUP BY TIPO, CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB, DESCRCTA
HAVING SUM(VLRTOTALFIN) <> SUM(VLRTOTALCTB)

UNION ALL

SELECT 
TIPO,
CODPARC,
RAZAOSOCIAL,
SUM(VLRTOTALFIN) AS VLRTOTALFIN,
SUM(VLRTOTALFIN) - SUM(VLRTOTALCTB) AS VLRDIVERGENCIA,
SUM(VLRTOTALCTB) AS VLRTOTALCTB,
CODCTACTB,
CTACTB,
DESCRCTA
FROM(

	-- FORNECEDORES - POSIÇÃO FINANCEIRA
	SELECT 
	TIPO,
	CODPARC,
	UPPER(RAZAOSOCIAL) AS RAZAOSOCIAL,
	SUM(VALOR) AS VLRTOTALFIN,
	CODCTACTB AS CODCTACTB,
	CTACTB,
	DESCRCTA,
	0 AS VLRTOTALCTB
	FROM(	
		/*FORNECEDORES EM ABERTO E DEVOLUÇÕES DE FORNECEDORES EM ABERTO - INICIO*/
		--TITULOS ORIGEM PORTAL - TOP TIPO "C"/"E"
		SELECT
		CASE WHEN T.TIPMOV = 'C' THEN 'FORNECEDORES'
			 WHEN T.TIPMOV = 'E' THEN 'DEVOL. COMPRA'
		     ELSE 'FORNECEDORES' END AS TIPO,
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		NVL(((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) As VALOR, 
		CASE WHEN T.TIPMOV = 'C' THEN PAR.CODCTACTB2
			 WHEN T.TIPMOV = 'E' THEN 198
			 ELSE PAR.CODCTACTB2 END AS CODCTACTB,
		CASE WHEN T.TIPMOV = 'C' THEN PLA.CTACTB
			 WHEN T.TIPMOV = 'E' THEN '1.1.03.10.003'
			 ELSE PLA.CTACTB END AS CTACTB,
		CASE WHEN T.TIPMOV = 'C' THEN PLA.DESCRCTA
			 WHEN T.TIPMOV = 'E' THEN 'DEVOL. DE COMPRAS A COMPENSAR'
			 ELSE PLA.DESCRCTA END AS DESCRCTA
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
		LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
		LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
		WHERE
		FIN.CODEMP IN :CODEMP  AND  
		FIN.DTENTSAI <= :DAT1 AND 
		(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
		((T.TIPMOV IN ('C') AND FIN.RECDESP = -1) OR 
		 (T.TIPMOV IN ('E') AND FIN.RECDESP = 1))
		
		UNION ALL
		
		--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
		SELECT
		'FORNECEDORES' AS TIPO,
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		NVL(((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) As VALOR, 
		PAR.CODCTACTB2 AS CODCTACTB,
		PLA.CTACTB AS CTACTB,
		PLA.DESCRCTA
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
		LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
		LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
		WHERE
		FIN.CODEMP IN :CODEMP  AND  
		FIN.DTENTSAI <= :DAT1 AND 
		(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
		T.TIPMOV IN ('I') AND
		FIN.CODTIPOPER <> 0 AND  
		FIN.RECDESP = -1 AND
		NAT.AD_TIPOCTBZ = 'N' AND
        T.TIPMOV||'-'||NAT.CODNAT NOT IN ('I-301006')
		/*FORNECEDORES EM ABERTO E DEVOLUÇÕES DE FORNECEDORES EM ABERTO - FIM*/
	)	
	GROUP BY TIPO, CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB, DESCRCTA

	UNION ALL
	
	--FORNECEDORES - POSIÇÃO CONTÁBIL
	SELECT
	CASE WHEN CODCTACTB = 198 THEN 'DEVOL. COMPRA' ELSE 'FORNECEDORES' END AS TIPO,
	CODPARC,
	RAZAOSOCIAL,
	0 AS VLRTOTALFIN,
	CODCTACTB,
	CTACTB,
	DESCRCTA,
	SUM(VLRTOTAL) AS VLRTOTALCTB
	FROM(
		SELECT
		PAR.CODPARC,
		UPPER(PAR.RAZAOSOCIAL) AS RAZAOSOCIAL,
		LAN.CODCTACTB,
		PLA.CTACTB,
		PLA.DESCRCTA,
		LAN.VLRLANC*DECODE(LAN.TIPLANC,'R',-1,1) AS VLRTOTAL
		FROM
		TCBLAN LAN
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = LAN.CODCTACTB
		LEFT JOIN TGFPAR PAR ON PAR.CODCTACTB2 = PLA.CODCTACTB
		WHERE
		LAN.DTMOV <= :DAT1 AND 
		LAN.CODEMP IN :CODEMP AND
		(PLA.CODCTACTBPAI = 194 OR PLA.CODCTACTB = 198)
	)
	GROUP BY CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB, DESCRCTA
	HAVING SUM(VLRTOTAL) <> 0
)
GROUP BY TIPO, CODPARC, RAZAOSOCIAL, CODCTACTB, CTACTB, DESCRCTA
HAVING SUM(VLRTOTALFIN) <> SUM(VLRTOTALCTB)

)
ORDER BY 1,5
