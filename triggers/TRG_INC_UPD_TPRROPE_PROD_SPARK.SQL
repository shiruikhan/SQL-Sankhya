create or replace TRIGGER "SPARKPRD"."TRG_INC_UPD_TPRROPE_PROD_SPARK" 
  BEFORE INSERT OR UPDATE ON TPRROPE 
  FOR EACH ROW 
DECLARE 
P_COUNT  INT;
P_CODLOCALORIG TGFITE.CODLOCALORIG%TYPE;
P_LOCAL        TGFLOC.DESCRLOCAL%TYPE;
BEGIN

  BEGIN
    SELECT E.CODLOCALORIG INTO P_CODLOCALORIG 
       FROM TPROEST EST INNER JOIN TPROEST E ON (E.IDEFX = EST.IDEFXBASE)
          WHERE EST.IDEFX =  :NEW.IDEFX
          AND EST.SEQOPER = :NEW.SEQOPER 
           AND E.TIPOITENS='PA';
   EXCEPTION WHEN NO_DATA_FOUND THEN
   P_CODLOCALORIG :=0;
   END;

  /*INSERE O LOCAL DESTINO PARA FATURAR O PEDIDO REQUISIÇÃO, BASEADO NA ATIVIDADE QUE REALIZOU O APONTAMENTO */

  SELECT COUNT(*) INTO P_COUNT FROM TGFCAB WHERE NUNOTA = :NEW.NUNOTA AND TIPMOV='J';

   IF P_COUNT = 1 AND P_CODLOCALORIG > 0 THEN
      SELECT DESCRLOCAL INTO P_LOCAL FROM TGFLOC WHERE CODLOCAL = P_CODLOCALORIG;

      UPDATE TGFCAB SET AD_CODLOCALDEST = P_CODLOCALORIG,OBSERVACAO = 'Local Destino: ' || P_LOCAL 
         WHERE NUNOTA = :NEW.NUNOTA;
   END IF;

END; 
