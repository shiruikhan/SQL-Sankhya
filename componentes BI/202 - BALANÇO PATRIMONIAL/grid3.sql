SELECT  
TO_CHAR(LAN.DTMOV,'MM/YYYY') AS MES, 
LAN.DTMOV, 
PLA.CTACTB, 
LAN.CODCTACTB, 
REPLACE(REPLACE(REPLACE(INITCAP(PLA.DESCRCTA),' De ',' de '),' E ',' e '),'S/', 's/') AS DESCRCTA, 
LAN.NUMLOTE, 
LAN.NUMLANC, 
LAN.SEQUENCIA, 
REPLACE(REPLACE(REPLACE(INITCAP(LAN.COMPLHIST),' De ',' de '),' E ',' e '),'S/', 's/') AS COMPLHIST, 
(LAN.VLRLANC * CASE WHEN LAN.TIPLANC = 'D' THEN -1 ELSE 1 END) AS VALOR,
LAN.CODCENCUS||' - '||CUS.DESCRCENCUS AS CR,
LAN.CODPROJ||' - '||PRJ.IDENTIFICACAO AS PROJETO,
NVL(CAB.NUMNOTA, FIN.NUMNOTA) AS NUMNOTA,
NVL(CAB.CODNAT,FIN.CODNAT)||' - '||NAT.DESCRNAT AS NATUREZA,
NVL(CAB.CODPARC,FIN.CODPARC)||' - '||UPPER(PAR.RAZAOSOCIAL) AS PARCEIRO,
LAN.CODEMP,
CASE WHEN INT.ORIGEM = 'E' THEN 'PORTAL'
     WHEN INT.ORIGEM IN ('B','F') THEN 'FINANCEIRO'
     WHEN INT.ORIGEM = 'M' THEN 'BANCÁRIO'
     ELSE 'CONTABIL' END AS ORIG
FROM TCBPLA PLA, TSICUS CUS, TCSPRJ PRJ, TCBLAN LAN
LEFT JOIN TCBINT INT ON INT.REFERENCIA = LAN.REFERENCIA AND INT.NUMLANC = LAN.NUMLANC AND INT.SEQUENCIA = LAN.SEQUENCIA AND INT.NUMLOTE = LAN.NUMLOTE AND INT.CODEMP=LAN.CODEMP
LEFT JOIN TGFCAB CAB ON INT.NUNICO = CAB.NUNOTA AND INT.ORIGEM= 'E'
LEFT JOIN TGFFIN FIN ON INT.NUNICO = FIN.NUFIN AND INT.ORIGEM IN ('B','F')
LEFT JOIN TGFPAR PAR ON PAR.CODPARC = NVL(CAB.CODPARC,FIN.CODPARC)
LEFT JOIN TGFNAT NAT ON NAT.CODNAT = NVL(CAB.CODNAT,FIN.CODNAT)
LEFT JOIN TCBLOT LOT ON LOT.NUMLOTE = LAN.NUMLOTE AND LOT.REFERENCIA = LAN.REFERENCIA AND LAN.CODEMP = LOT.CODEMP
WHERE 
CUS.CODCENCUS = LAN.CODCENCUS AND
PRJ.CODPROJ = LAN.CODPROJ AND
LAN.DTMOV >= TO_CHAR(trunc(:DAT1,'YYYY'), 'DD/MM/YYYY') AND
LAN.DTMOV <= LAST_DAY(:DAT1) AND
LAN.CODCTACTB = PLA.CODCTACTB AND
LAN.NUMLOTE NOT IN (999,9999) AND
LAN.CODEMP IN :CODEMP AND
LOT.COMENTARIOS NOT LIKE 'Encerramento das Contas de Resultado%' AND
LAN.CODCTACTB = :CODCTACTB AND
TO_CHAR(LAN.DTMOV,'MM') = NVL(:MESTEXTO,TO_CHAR(LAN.DTMOV,'MM'))
ORDER BY 
DTMOV DESC, COMPLHIST
