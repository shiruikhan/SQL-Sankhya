SELECT PRC.NROLOTE AS FICHA,
    PRC.NUMPS AS PLANO,
    PRC.DHINST AS DTINICIO,
    PRC.DTPREVENT AS DTPREVENTREGA,
    PRC.DHTERMINO AS DTFINALIZA,
    PRC.IDPROC,
    PRC.IDIPROC,
    IPA.CODPRODPA AS CODPROD,
    IPA.QTDPRODUZIR AS QTDTOTAL,
    IPA.CONCLUIDO AS STATUSCONCLUSAO,
    PRO.AD_REFINTERNA AS MODELO,
    (CASE WHEN PRO.AD_LINHA = 1 THEN 'Linha 1' WHEN PRO.AD_LINHA = 2 THEN 'Linha 2' ELSE 'Sem info' END) AS LINHA,
    (
        SELECT MAX( LMP.CODPRODMP )
        FROM TPRLMP LMP
            INNER JOIN TGFPRO MP ON LMP.CODPRODMP = MP.CODPROD
            INNER JOIN TGFGRU GRU ON MP.CODGRUPOPROD = GRU.CODGRUPOPROD AND GRU.CODGRUPOPROD = 2550000
        WHERE LMP.CODPRODPA = IPA.CODPRODPA
            AND SUBSTR(TO_CHAR(LMP.CODPRODMP), 1, 1) = '2'
            AND LMP.IDEFX = EFX.IDEFX
    ) AS CODPRODPLACA,
    EFX.DESCRICAO AS SETOR,
    TRUNC(APO.DHAPO) AS DTAPONTAMENTO,
    SUM(NVL(APA.QTDAPONTADA, 0)) AS QTDAPONTADA,
    NVL(TRUNC(APO.DHAPO), PRC.DTPREVENT) AS DATA_EIXO
FROM TPRIPROC PRC
    INNER JOIN TPRIPA IPA ON PRC.IDIPROC = IPA.IDIPROC
    INNER JOIN TGFPRO PRO ON IPA.CODPRODPA = PRO.CODPROD
    INNER JOIN TPRLPA LPA ON IPA.CODPRODPA = LPA.CODPRODPA AND PRC.IDPROC = LPA.IDPROC
    INNER JOIN TPREFX EFX ON LPA.IDPROC = EFX.IDPROC/* AND EFX.DESCRICAO IN ('APONTAMENTO INSERSORA','APONTAMENTO REVISORA','INSERÇÃO','SOLDA','TESTE','DISSIPADOR','TAMPA/GABINETE','MONTAGEM FINAL','EXPEDIÇÃO/CONFERENCIA','DISPLAY','PRODUÇÃO KIT IBM')*/
    LEFT JOIN TPRIATV TV ON TV.IDIPROC = PRC.IDIPROC AND TV.IDEFX = EFX.IDEFX
    LEFT JOIN TPRAPO APO ON APO.IDIATV = TV.IDIATV AND APO.SITUACAO = 'C'
    LEFT JOIN TPRAPA APA ON APA.NUAPO = APO.NUAPO
WHERE (PRC.NROLOTE = :P_NROLOTE OR :P_NROLOTE IS NULL)
    AND EFX.DESCRICAO IN :P_DESCRICAO
    AND PRC.NROLOTE >= (TO_CHAR(SYSDATE, 'YY') || '00000') AND PRC.NROLOTE <= (TO_CHAR(SYSDATE, 'YY') || '99999')
    --AND SUBSTR(TO_CHAR(PRC.NROLOTE), 1, 2) = TO_CHAR(SYSDATE, 'YY')
    AND (PRC.NUMPS = :P_NUMPS OR :P_NUMPS IS NULL)
    AND (PRC.DTPREVENT >= :P_DTPREVENT.INI OR :P_DTPREVENT.INI IS NULL)
    AND (PRC.DTPREVENT <= :P_DTPREVENT.FIN OR :P_DTPREVENT.FIN IS NULL)
GROUP BY 
    PRC.NROLOTE, 
    PRC.NUMPS, 
    PRC.DHINST, 
    PRC.DTPREVENT, 
    PRC.DHTERMINO, 
    PRC.IDPROC, 
    PRC.IDIPROC, 
    IPA.CODPRODPA, 
    IPA.QTDPRODUZIR, 
    IPA.CONCLUIDO, 
    PRO.AD_REFINTERNA, 
    PRO.AD_LINHA, 
    EFX.IDEFX, 
    EFX.DESCRICAO, 
    TRUNC(APO.DHAPO)
ORDER BY PRC.NROLOTE, PRC.DTPREVENT, TRUNC(APO.DHAPO)