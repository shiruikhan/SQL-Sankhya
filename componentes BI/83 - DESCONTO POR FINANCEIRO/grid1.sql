SELECT FIN.NUFIN,
	FIN.NUMNOTA,
	FIN.CODPARC,
	PAR.NOMEPARC,
	FIN.DTVENC,
	FIN.DHBAIXA,
	FIN.VLRDESDOB,
	FIN.VLRDESC,
 FIN.HISTORICO
FROM TGFFIN FIN
	INNER JOIN TGFPAR PAR ON FIN.CODPARC = PAR.CODPARC
WHERE (FIN.DHBAIXA >= :P_PERIODO.INI AND FIN.DHBAIXA <= :P_PERIODO.FIN)
	AND FIN.CODEMP IN :P_CODEMP
	AND FIN.RECDESP IN :P_RECDESP
	AND FIN.VLRDESC > 0
