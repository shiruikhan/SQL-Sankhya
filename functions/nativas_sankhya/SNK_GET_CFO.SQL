/*==============================================================================
  Nome do Script : SNK_GET_CFO
  Tipo           : Function Nativa Sankhya (referencia -- nao customizada)
  Descricao      : Recalcula o CFO/CFOP de um item conforme substituicao tributaria, uso do
                  produto e diversas regras fiscais (tabela extensa de ajustes).
  Assinatura     : SNK_GET_CFO (P_TIPSUBST VARCHAR2 ,P_CLASSIFICMS VARCHAR2 ,P_USOPROD VARCHAR2 ,P_TIPMOV VARCHAR2 ,P_BASESUBSTIT FLOAT ,P_BASEICMS FLOAT ,P_CODTRIB NUMBER ,P_CODCFO NUMBER ,P_CODGRUPOICMS NUMBER ,P_CLASSUBTRIB NUMBER ,P_TEMISS VARCHAR2)
                   RETURN NUMBER
  Observacoes    : - Objeto nativo do ERP -- atualizacoes do Sankhya podem
                     sobrescrever esta function. Revisar apos cada upgrade
                     (mesmo cuidado descrito em trigger_nativa/README.md).
                   - Capturado do banco em 18/09/2026, via:
                     SELECT DBMS_METADATA.GET_DDL('FUNCTION', 'SNK_GET_CFO', 'SPARKPRD') FROM dual;
==============================================================================*/
  create or replace FUNCTION SNK_GET_CFO (P_TIPSUBST		VARCHAR2
									  ,P_CLASSIFICMS 	VARCHAR2
									  ,P_USOPROD		VARCHAR2
									  ,P_TIPMOV			VARCHAR2
									  ,P_BASESUBSTIT	FLOAT
									  ,P_BASEICMS		FLOAT
									  ,P_CODTRIB		NUMBER
									  ,P_CODCFO 		NUMBER
									  ,P_CODGRUPOICMS	NUMBER
									  ,P_CLASSUBTRIB	NUMBER
									  ,P_TEMISS			VARCHAR2)
RETURN NUMBER
AS
	P_RESULT				NUMBER(10);
	P_CODCFO_AUX			NUMBER(10);
	P_CONSUMIDOR			VARCHAR2(1);
	P_PRODUTOR_RURAL		VARCHAR2(1);
	P_FABRIC_PROPRIA		VARCHAR2(1);
	P_MATERIA_PRIMA			VARCHAR2(1);
	P_IMOBILIZADO			VARCHAR2(1);
	P_CONSUMO				VARCHAR2(1);
	P_GRUPODECR5510			NUMBER(10);
	P_TIPSUBST_AUX			VARCHAR(1);
	P_RESTO					NUMBER(10);
	P_INTEIRO				NUMBER(10);
	P_CFOPAQUSERVDEN 		NUMBER(10);
	P_CFOPAQUSERVFOR 		NUMBER(10);
	P_CFOPPRESERVDEN 		NUMBER(10);
	P_CFOPPRESERVFOR 		NUMBER(10);
BEGIN
	P_CODCFO_AUX := NVL(P_CODCFO, 0);
	P_RESULT := P_CODCFO_AUX;

	P_CONSUMIDOR := CASE WHEN NVL(P_CLASSIFICMS, '*') = 'C' THEN 'S' ELSE 'N' END;
	P_PRODUTOR_RURAL := CASE WHEN NVL(P_CLASSIFICMS, '*') = 'P' THEN 'S' ELSE 'N' END;
	P_FABRIC_PROPRIA := CASE WHEN NVL(P_USOPROD, '*') IN ('V', 'P', '2', '1') THEN 'S' ELSE 'N' END;
	P_MATERIA_PRIMA := CASE WHEN NVL(P_USOPROD, '*') IN ('M', 'E', 'O') THEN 'S' ELSE 'N' END;
	P_IMOBILIZADO := CASE WHEN NVL(P_USOPROD, '*') = 'I' THEN 'S' ELSE 'N' END;
	P_CONSUMO := CASE WHEN NVL(P_USOPROD, '*') = 'C' THEN 'S' ELSE 'N' END;

	P_GRUPODECR5510 := GET_TSIPAR_INTEIRO('GRUPODECR5510');

	IF (P_GRUPODECR5510 > 0 AND NVL(P_CODGRUPOICMS, 0) = P_GRUPODECR5510) OR
		(P_CODCFO_AUX < 5000 AND NVL(P_TIPSUBST, '*') = 'P' AND NVL(P_TIPMOV, '*') <> 'D') OR
		(NVL(P_TIPSUBST, '*') IN ('P', 'A') AND NVL(P_BASESUBSTIT, 0) = 0 AND NVL(P_BASEICMS, 0) <> 0 AND P_CONSUMIDOR = 'N') THEN
		P_TIPSUBST_AUX := 'N';
	ELSE
		P_TIPSUBST_AUX := NVL(P_TIPSUBST, '*');
	END IF;

	P_RESTO := MOD(P_CODCFO_AUX, 1000);
	P_INTEIRO := P_CODCFO_AUX - P_RESTO;

	IF NVL(P_USOPROD, '*') IN ('B', 'F') AND P_INTEIRO > 4 THEN
		P_RESULT := P_INTEIRO + 910;
	ELSE
		IF P_CODCFO_AUX < 1000 THEN
			P_RESULT := SNK_GET_CFO_ANT(P_TIPSUBST_AUX
									   ,P_USOPROD
									   ,P_CODCFO_AUX
									   ,P_CONSUMIDOR);

		ELSIF P_CODCFO_AUX = 1904 AND P_TIPSUBST_AUX <> 'N' THEN
			P_RESULT := 1415;

		ELSIF P_CODCFO_AUX IN (5904, 6904) AND P_TIPSUBST_AUX <> 'N' THEN
			IF P_FABRIC_PROPRIA = 'S' THEN
				P_RESULT := P_INTEIRO + 414;
			ELSE
				P_RESULT := P_INTEIRO + 415;
			END IF;
		ELSIF P_RESTO < 900 THEN
			IF P_IMOBILIZADO = 'S' AND (550 > P_RESTO OR P_RESTO > 557) THEN
				P_RESULT := P_INTEIRO + 551;

			ELSIF P_INTEIRO < 5000 THEN
				IF P_RESTO = 101 THEN
					IF P_MATERIA_PRIMA = 'N' THEN
						P_RESULT := P_INTEIRO + 102;
					END IF;
				ELSIF P_RESTO = 102 THEN
					IF P_MATERIA_PRIMA = 'S' THEN
						P_RESULT := P_INTEIRO + 101;
					END IF;
				ELSIF P_RESTO = 201 THEN
					IF P_FABRIC_PROPRIA = 'N' THEN
						P_RESULT := P_INTEIRO + 202;
					END IF;
				ELSIF P_RESTO = 202 THEN
					IF P_FABRIC_PROPRIA = 'S' THEN
						P_RESULT := P_INTEIRO + 201;
					END IF;
				ELSIF P_RESTO = 151 THEN
					IF P_MATERIA_PRIMA = 'N' THEN
						P_RESULT := P_INTEIRO + 152;
					END IF;
				ELSIF P_RESTO = 152 THEN
					IF P_MATERIA_PRIMA = 'S' THEN
						P_RESULT := P_INTEIRO + 151;
					END IF;
				ELSIF P_RESTO = 116 THEN
					IF P_MATERIA_PRIMA = 'N' THEN
						P_RESULT := P_INTEIRO + 117;
					END IF;
				ELSIF P_RESTO = 117 THEN
					IF P_MATERIA_PRIMA = 'S' THEN
						P_RESULT := P_INTEIRO + 116;
					END IF;
				END IF;
			ELSE
				IF P_RESTO = 101 THEN
					IF P_FABRIC_PROPRIA = 'N' THEN
						P_RESULT := P_INTEIRO + 102;
					END IF;
				ELSIF P_RESTO = 102 THEN
					IF P_FABRIC_PROPRIA = 'S' THEN
						P_RESULT := P_INTEIRO + 101;
					END IF;
				ELSIF P_RESTO = 201 THEN
					IF P_MATERIA_PRIMA = 'N' THEN
						P_RESULT := P_INTEIRO + 202;
					END IF;
				ELSIF P_RESTO = 202 THEN
					IF P_MATERIA_PRIMA = 'S' THEN
						P_RESULT := P_INTEIRO + 201;
					END IF;
				ELSIF P_RESTO = 151 THEN
					IF P_FABRIC_PROPRIA = 'N' THEN
						P_RESULT := P_INTEIRO + 152;
					END IF;
				ELSIF P_RESTO = 152 THEN
					IF P_FABRIC_PROPRIA = 'S' THEN
						P_RESULT := P_INTEIRO + 151;
					END IF;
				ELSIF P_RESTO = 116 THEN
					IF P_FABRIC_PROPRIA = 'N' THEN
						P_RESULT := P_INTEIRO + 117;
					END IF;
				ELSIF P_RESTO = 117 THEN
					IF P_FABRIC_PROPRIA = 'S' THEN
						P_RESULT := P_INTEIRO + 116;
					END IF;
				END IF;
			END IF;

			IF P_CODCFO_AUX = 6109 AND P_FABRIC_PROPRIA = 'N' THEN
				P_RESULT := 6110;
			END IF;

			IF P_CODCFO_AUX = 6110 AND P_FABRIC_PROPRIA = 'S' THEN
				P_RESULT := 6109;
			END IF;

			IF P_CONSUMO = 'S' AND NVL(P_CLASSUBTRIB, 0) = 6 AND P_RESTO <> 653 AND P_RESULT < 3000 THEN
				P_RESULT := P_INTEIRO + 653;
			END IF;

			IF P_CONSUMO = 'S' AND P_RESULT IN (1102, 2102, 5202, 6202) THEN
				P_RESULT := P_INTEIRO + 556;
			END IF;

			IF P_CONSUMO = 'S' AND P_RESULT IN (1152, 2152, 5252, 6252) THEN
				P_RESULT := P_INTEIRO + 557;
			END IF;

			IF P_CONSUMIDOR = 'S' THEN
				IF P_RESULT = 6101 THEN
					P_RESULT := 6107;

				ELSIF P_RESULT = 6102 THEN
					P_RESULT := 6108;
				END IF;
			END IF;

			IF P_TIPSUBST_AUX <> 'P' OR NVL(P_BASESUBSTIT, 0) <> 0 OR P_CONSUMIDOR = 'N' OR P_INTEIRO <> 5000 THEN
				IF P_TIPSUBST_AUX <> 'N' AND NVL(P_BASESUBSTIT, 0) = 0 THEN
					IF P_RESULT = 5102 THEN
						P_RESULT := 5405;

					ELSIF P_RESULT = 6102 THEN
						P_RESULT := 6404;
					END IF;
				END IF;

				IF P_TIPSUBST_AUX <> 'N' THEN
					IF P_RESULT IN (1101, 2101) THEN
						P_RESULT := P_INTEIRO + 401;

					ELSIF P_RESULT IN (5101, 6101) THEN
						IF NVL(P_BASESUBSTIT, 0) <> 0 THEN
							P_RESULT := P_INTEIRO + 401;
						END IF;
					ELSIF P_RESULT IN (1102, 2102, 5102, 6102) THEN
						P_RESULT := P_INTEIRO + 403;

					ELSIF P_RESULT = 5104 THEN
						P_RESULT := P_INTEIRO + 405;

					ELSIF P_RESULT IN (1551, 2551) THEN
						P_RESULT := P_INTEIRO + 406;

					ELSIF P_RESULT IN (1556, 2556) THEN
						P_RESULT := P_INTEIRO + 407;

					ELSIF P_RESULT IN (1151, 2151, 5151, 6151) THEN
						P_RESULT := P_INTEIRO + 408;

					ELSIF P_RESULT IN (1152, 2152, 5152, 6152) THEN
						P_RESULT := P_INTEIRO + 409;

					ELSIF P_RESULT IN (1201, 2201) THEN
						IF NVL(P_BASESUBSTIT, 0) <> 0 THEN
							P_RESULT := P_INTEIRO + 410;
						END IF;
					ELSIF P_RESULT IN (5201, 6201) THEN
						P_RESULT := P_INTEIRO + 410;

					ELSIF P_RESULT IN (1202, 2202, 5202, 6202) THEN
						P_RESULT := P_INTEIRO + 411;

					ELSIF P_RESULT IN (5553, 6553) THEN
						P_RESULT := P_INTEIRO + 412;

					ELSIF P_RESULT IN (5556, 6556) THEN
						P_RESULT := P_INTEIRO + 413;
					END IF;
				END IF;
			END IF;
		END IF;
	END IF;

	IF NVL(P_USOPROD, '*') = 'S' AND NVL(P_TEMISS, '*') = 'S' AND P_RESULT <> 0 AND NVL(P_TIPMOV, '*') NOT IN ('T', 'Q') THEN
		P_CFOPAQUSERVDEN := GET_TSIPAR_INTEIRO('CFOPAQUSERVDEN');
		P_CFOPAQUSERVFOR := GET_TSIPAR_INTEIRO('CFOPAQUSERVFOR');
		P_CFOPPRESERVDEN := GET_TSIPAR_INTEIRO('CFOPPRESERVDEN');
		P_CFOPPRESERVFOR := GET_TSIPAR_INTEIRO('CFOPPRESERVFOR');

		IF P_CFOPAQUSERVDEN <> 0 AND P_RESULT >= 1000 AND P_RESULT <= 1999 THEN
			P_RESULT := P_CFOPAQUSERVDEN;

		ELSIF P_CFOPAQUSERVFOR <> 0 AND P_RESULT >= 2000 AND P_RESULT <= 2999 THEN
			P_RESULT := P_CFOPAQUSERVFOR;

		ELSIF P_CFOPPRESERVDEN <> 0 AND P_RESULT >= 5000 AND P_RESULT <= 5999 THEN
			P_RESULT := P_CFOPPRESERVDEN;

		ELSIF P_CFOPPRESERVFOR <> 0 AND P_RESULT >= 6000 AND P_RESULT <= 6999 THEN
			P_RESULT := P_CFOPPRESERVFOR;
		END IF;
	END IF;

	RETURN P_RESULT;
END;
