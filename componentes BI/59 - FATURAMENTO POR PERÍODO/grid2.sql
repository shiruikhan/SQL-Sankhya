WITH TOTAIS_GERAIS AS (
	SELECT
		SUM(ITE2.QTDNEG) AS TOTAL_QTD,
		SUM((ITE2.VLRTOT - ITE2.VLRDESC) + NVL(ITE2.AD_VLROUTROS, 0)) AS TOTAL_VALOR
	FROM TGFITE ITE2
	INNER JOIN TGFCAB CAB2 ON ITE2.NUNOTA = CAB2.NUNOTA
	INNER JOIN TGFPRO PRO2 ON ITE2.CODPROD = PRO2.CODPROD
	INNER JOIN TGFGRU GRU2 ON PRO2.CODGRUPOPROD = GRU2.CODGRUPOPROD
	INNER JOIN TGFVEN VEN2 ON CAB2.CODVEND = VEN2.CODVEND
	WHERE TRUNC(CAB2.DTNEG) BETWEEN :P_PER.INI AND :P_PER.FIN
		AND CAB2.TIPMOV = 'D'
		AND PRO2.USOPROD = 'V'
        AND (CAB2.CODEMP = 501 OR CAB2.STATUSNFE <> 'D')
		AND (:P_GRUPO IS NULL OR GRU2.CODGRUPOPROD = :P_GRUPO)
		AND (:P_CODEMP IS NULL OR CAB2.CODEMP = :P_CODEMP)
		AND (:P_CODVEND IS NULL OR VEN2.CODVEND = :P_CODVEND)
		AND CAB2.CODTIPOPER IN (1200,1201,1206,1216,1217,1272,2202)
)
SELECT 
	PRO.AD_AGRUPADOR,
	PRO.CODVOL,
	SUM(ITE.QTDNEG) AS QTD,
	PRO.CODGRUPOPROD,
	GRU.DESCRGRUPOPROD,
	VEN.CODVEND,
	VEN.APELIDO,
	(SUM(ITE.QTDNEG) / NULLIF(TG.TOTAL_QTD, 0)) * 100 AS PARTE,
	SUM(ITE.VLRTOT - ITE.VLRDESC) AS TOTALLIQ,
	SUM(NVL(ITE.AD_VLROUTROS, 0)) AS TOTALOUTROS,
	SUM(ITE.VLRTOT - ITE.VLRDESC) + SUM(NVL(ITE.AD_VLROUTROS, 0)) AS TOTAL,
	((SUM(ITE.VLRTOT - ITE.VLRDESC) + SUM(NVL(ITE.AD_VLROUTROS, 0))) / NULLIF(TG.TOTAL_VALOR, 0)) * 100 AS PARTEFATURADO
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
INNER JOIN TSICID CID ON PAR.CODCID = CID.CODCID
CROSS JOIN TOTAIS_GERAIS TG
WHERE TRUNC(CAB.DTNEG) BETWEEN :P_PER.INI AND :P_PER.FIN
	AND CAB.TIPMOV = 'D'
	AND PRO.USOPROD = 'V'
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
	AND (:P_GRUPO IS NULL OR GRU.CODGRUPOPROD = :P_GRUPO)
	AND (:P_CODEMP IS NULL OR CAB.CODEMP = :P_CODEMP)
	AND (:P_CODVEND IS NULL OR VEN.CODVEND = :P_CODVEND)
	AND (:P_CODPROD IS NULL OR ITE.CODPROD = :P_CODPROD)
	AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
	AND (:P_CODUF IS NULL OR CID.UF = :P_CODUF)
	AND CAB.CODTIPOPER IN (1200,1201,1206,1216,1217,1272,2202)
GROUP BY 
	PRO.AD_AGRUPADOR, 
	PRO.CODVOL, 
	PRO.CODGRUPOPROD, 
	GRU.DESCRGRUPOPROD, 
	VEN.CODVEND, 
	VEN.APELIDO,
	TG.TOTAL_QTD,
	TG.TOTAL_VALOR
ORDER BY PRO.AD_AGRUPADOR
