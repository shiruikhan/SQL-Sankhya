SELECT CAB.NUNOTA,
	CAB.DTNEG,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.QTDNEG
FROM TGFCAB CAB
	INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
WHERE CAB.CODPARC = :A_CODPARC
	AND CAB.TIPMOV = 'V'
	AND CAB.DTNEG >= (ADD_MONTHS(SYSDATE,-12))
	AND PRO.USOPROD = 'V'
