  CREATE OR REPLACE EDITIONABLE PROCEDURE "SPARKPRD"."GET_IMPOSTOS_RAT_EST" (P_NUNOTA                INT,
                                                  P_SEQUENCIA             INT,
                                                  P_QTDSAI                FLOAT,
                                                  P_VLRICMS           OUT FLOAT,
                                                  P_BASESUBST         OUT FLOAT,
                                                  P_VLRSUBST          OUT FLOAT,
                                                  P_BASESTFCPINTANT   OUT FLOAT,
                                                  P_VLRSTFCPINTANT    OUT FLOAT,
                                                  P_PERCSTFCPINTANT   OUT FLOAT,
                                                  P_PERCSUBST         OUT FLOAT)
AS
    PRAGMA AUTONOMOUS_TRANSACTION;
    P_UTILBASEREDRAST         CHAR (1);
    P_COUNT                   NUMBER (10);
    P_VLRICMS_USADO           FLOAT := 0;
    P_BASESUBST_USADO         FLOAT := 0;
    P_VLRSUBST_USADO          FLOAT := 0;
    P_BASESTFCPINTANT_USADO   FLOAT := 0;
    P_VLRSTFCPINTANT_USADO    FLOAT := 0;
    P_TIPMOV				  CHAR(1) := '*';
BEGIN	
    SELECT COUNT (1)
    INTO P_COUNT
    FROM TGFITS ITS
    WHERE ITS.NUNOTA = P_NUNOTA
        AND ITS.SEQUENCIA = P_SEQUENCIA
        AND ITS.QTDSAI + P_QTDSAI = ITS.QTDENT
        AND ITS.QTDENT = NVL ((    SELECT SUM (QTDSAI)
                                FROM TGFVAS VAS
                                WHERE VAS.NUNOTAORIG = ITS.NUNOTA
                                    AND VAS.SEQUENCIAORIG = ITS.SEQUENCIA), 0) + P_QTDSAI;

    IF P_COUNT > 0 THEN
        SELECT SUM (NVL(VAS.VLRICMS, 0)) AS VLRICMS,
               SUM (NVL(VAS.BASESUBST, 0)) AS BASESUBST,
               SUM (NVL(VAS.VLRSUBST, 0)) AS VLRSUBST,
               SUM (NVL(VAS.BASESTFCPINT, 0)) AS BASESTFCPINT,
               SUM (NVL(VAS.VLRSTFCPINT, 0)) AS VLRSTFCPINT
        INTO P_VLRICMS_USADO,
             P_BASESUBST_USADO,
             P_VLRSUBST_USADO,
             P_BASESTFCPINTANT_USADO,
             P_VLRSTFCPINTANT_USADO
        FROM TGFVAS VAS
        WHERE NUNOTAORIG = P_NUNOTA 
        AND SEQUENCIAORIG = P_SEQUENCIA;
    END IF;
    IF P_VLRICMS_USADO IS NULL THEN
    	P_VLRICMS_USADO := 0;
    END IF;
   
    IF P_BASESUBST_USADO IS NULL THEN
    	P_BASESUBST_USADO := 0;
    END IF;
   
    IF P_VLRSUBST_USADO IS NULL THEN
    	P_VLRSUBST_USADO := 0;
    END IF;
   
    IF P_BASESTFCPINTANT_USADO IS NULL THEN
    	P_BASESTFCPINTANT_USADO := 0;
    END IF;
   
    IF P_VLRSTFCPINTANT_USADO IS NULL THEN
    	P_VLRSTFCPINTANT_USADO := 0;
    END IF;

    P_UTILBASEREDRAST := GET_TSIPAR_LOGICO ('UTILBASEREDRAST');
	
	SELECT NVL(MAX(TIPMOV), '*') INTO P_TIPMOV --UTILIZANDO O MAX PARA EVITAR ERRO SE O CABECALHO AINDA NAO TIVER SIDO COMMITADO 
    	FROM TGFCAB
    	WHERE NUNOTA = P_NUNOTA;

    SELECT COUNT (1)
    INTO P_COUNT
    FROM TGFIPRE IPRE
    WHERE IPRE.NUNOTA = P_NUNOTA
        AND IPRE.SEQUENCIA = P_SEQUENCIA
        AND IPRE.DIGITADO = 'S';

    IF P_COUNT > 0 THEN
        --NOTAS DE IMPOSTO DE RASTREAMENTO DE ESTOQUE DIGITADAS
        SELECT CASE WHEN (P_VLRICMS_USADO <= 0) OR ((P_VLRICMS_USADO > 0) AND ((SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRICMS, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE  SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO END,
				CASE WHEN (P_BASESUBST_USADO <= 0) OR ((P_BASESUBST_USADO > 0) AND ((SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.BASESUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO END,
				CASE WHEN (P_VLRSUBST_USADO <= 0) OR ((P_VLRSUBST_USADO > 0) AND ((SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRSUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO END,
				CASE WHEN (P_BASESTFCPINTANT_USADO <= 0) OR ((P_BASESTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.BASESTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO END,
				CASE WHEN (P_VLRSTFCPINTANT_USADO <= 0) OR ((P_VLRSTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.VLRSTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO END,
                MAX (IMP.PERCSTFCPINTANT),
                MAX (IMP.PERCSUBST)
        INTO P_VLRICMS,
             P_BASESUBST,
             P_VLRSUBST,
             P_BASESTFCPINTANT,
             P_VLRSTFCPINTANT,
             P_PERCSTFCPINTANT,
             P_PERCSUBST
         FROM ( SELECT VLRICMS, 
                       BASESUBST,
                       VLRSUBST,
                       BASESTFCPINTANT,
                       VLRSTFCPINTANT,
                       PERCSTFCPINTANT,
                       PERCSUBST,
                       NUNOTA,
                       SEQUENCIA
                FROM TGFIPRE IPRE
                WHERE IPRE.NUNOTA = P_NUNOTA 
                    AND IPRE.SEQUENCIA = P_SEQUENCIA
                    AND IPRE.DIGITADO = 'S'
              ) IMP,
              TGFITS ITS
        WHERE ITS.NUNOTA = IMP.NUNOTA 
            AND ITS.SEQUENCIA = IMP.SEQUENCIA;
    ELSE   
	    --VALORES ANTERIORES DIGITADOS NO ITEM, SE HOUVER, DEVO USA-LO
		SELECT COUNT (1)
		INTO P_COUNT
		FROM TGFITE ITE
		WHERE ITE.NUNOTA = P_NUNOTA 
			AND ITE.SEQUENCIA = P_SEQUENCIA
			AND ( NVL(VLRICMSANT, 0) + NVL(BASESUBSTITANT, 0) + NVL(VLRSUBSTANT, 0) + NVL(BASESTFCPINTANT, 0) + NVL(VLRSTFCPINTANT, 0) > 0);

		IF P_COUNT > 0 THEN 
			--APURANDO IMPOSTOS CONSUMIDOS
			SELECT     CASE WHEN (P_VLRICMS_USADO <= 0) OR ((P_VLRICMS_USADO > 0) AND ((SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRICMS, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE  SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO END,
					CASE WHEN (P_BASESUBST_USADO <= 0) OR ((P_BASESUBST_USADO > 0) AND ((SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.BASESUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO END,
					CASE WHEN (P_VLRSUBST_USADO <= 0) OR ((P_VLRSUBST_USADO > 0) AND ((SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRSUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO END,
					CASE WHEN (P_BASESTFCPINTANT_USADO <= 0) OR ((P_BASESTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.BASESTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO END,
					CASE WHEN (P_VLRSTFCPINTANT_USADO <= 0) OR ((P_VLRSTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.VLRSTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO END,
					MAX (IMP.PERCSTFCPINTANT),
					MAX (IMP.PERCSUBST)
			INTO P_VLRICMS,
				 P_BASESUBST,
				 P_VLRSUBST,
				 P_BASESTFCPINTANT,
				 P_VLRSTFCPINTANT,
				 P_PERCSTFCPINTANT,
				 P_PERCSUBST
			 FROM (    SELECT VLRICMSANT AS VLRICMS,
						   BASESUBSTITANT AS BASESUBST,
						   VLRSUBSTANT AS VLRSUBST,
						   NVL (BASESTFCPINTANT, 0) AS BASESTFCPINTANT,
						   NVL (VLRSTFCPINTANT, 0) AS VLRSTFCPINTANT,
						   NVL (PERCSTFCPINTANT, 0) AS PERCSTFCPINTANT,
						   NVL (ALIQSTFCPSTANT, 0) AS PERCSUBST,
						   P_NUNOTA AS NUNOTA,
						   P_SEQUENCIA AS SEQUENCIA
					FROM TGFITE ITE
					WHERE ITE.NUNOTA = P_NUNOTA 
						AND ITE.SEQUENCIA = P_SEQUENCIA
				  ) IMP,
				  TGFITS ITS
			WHERE ITS.NUNOTA = IMP.NUNOTA 
				AND ITS.SEQUENCIA = IMP.SEQUENCIA;
		ElSE
			--APURANDO IMPOSTOS CONSUMIDOS
			SELECT     CASE WHEN (P_VLRICMS_USADO <= 0) OR ((P_VLRICMS_USADO > 0) AND ((SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRICMS, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE  SUM (NVL (IMP.VLRICMS, 0)) - P_VLRICMS_USADO END,
					CASE WHEN (P_BASESUBST_USADO <= 0) OR ((P_BASESUBST_USADO > 0) AND ((SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.BASESUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESUBST, 0)) - P_BASESUBST_USADO END,
					CASE WHEN (P_VLRSUBST_USADO <= 0) OR ((P_VLRSUBST_USADO > 0) AND ((SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO) <= 0)) THEN TRUNC (SUM (NVL (IMP.VLRSUBST, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSUBST, 0)) - P_VLRSUBST_USADO END,
					CASE WHEN (P_BASESTFCPINTANT_USADO <= 0) OR ((P_BASESTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.BASESTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.BASESTFCPINTANT, 0)) - P_BASESTFCPINTANT_USADO END,
					CASE WHEN (P_VLRSTFCPINTANT_USADO <= 0) OR ((P_VLRSTFCPINTANT_USADO > 0) AND ((SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO) <= 0)) THEN TRUNC ( SUM (NVL (IMP.VLRSTFCPINTANT, 0) / ITS.QTDENT * P_QTDSAI), 2) ELSE SUM (NVL (IMP.VLRSTFCPINTANT, 0)) - P_VLRSTFCPINTANT_USADO END,
					MAX (IMP.PERCSTFCPINTANT),
					MAX (IMP.PERCSUBST)
			INTO P_VLRICMS,
				 P_BASESUBST,
				 P_VLRSUBST,
				 P_BASESTFCPINTANT,
				 P_VLRSTFCPINTANT,
				 P_PERCSTFCPINTANT,
				 P_PERCSUBST
			 FROM (    SELECT SUM (CASE WHEN DIN.CODIMP = 1 THEN DIN.VALOR ELSE 0 END) AS VLRICMS,
						   SUM (CASE WHEN DIN.CODIMP = 2 THEN CASE WHEN P_UTILBASEREDRAST = 'S' THEN DIN.BASERED
																   ELSE DIN.BASE
															  END
									 ELSE 0
								END) + MAX(NVL(ITE.BASESTEXTRANOTA, 0)) AS BASESUBST,
						   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.VALOR ELSE 0 END) + MAX(NVL(ITE.VLRSTEXTRANOTA, 0)) AS VLRSUBST,
						   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.BASEFCPINT ELSE 0 END) AS BASESTFCPINTANT,
						   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.VLRFCPINT ELSE 0 END) AS VLRSTFCPINTANT,
						   MAX (CASE WHEN DIN.CODIMP = 2 THEN DIN.PERCFCPINT ELSE 0 END) AS PERCSTFCPINTANT,
						   MAX (CASE WHEN DIN.CODIMP = 2 THEN DIN.ALIQUOTA ELSE 0 END) + MAX(NVL(ITE.ALIQSTEXTRANOTA, 0)) AS PERCSUBST,
						   P_NUNOTA AS NUNOTA,
						   P_SEQUENCIA AS SEQUENCIA
					FROM TGFDIN DIN
				, TGFITE ITE
					WHERE DIN.NUNOTA = P_NUNOTA 
						AND DIN.SEQUENCIA = P_SEQUENCIA
						AND ITE.NUNOTA = P_NUNOTA
						AND ITE.SEQUENCIA = P_SEQUENCIA
						AND P_TIPMOV <> 'D'
					UNION ALL    --NOTAS DE COMPLEMENTO
					SELECT NVL (SUM (CASE WHEN DIN.CODIMP = 1 AND P_TIPMOV <> 'D' THEN DIN.VALOR ELSE 0 END), 0) + NVL (ITE.VLRICMSANT, 0) AS VLRICMS,
						   NVL (SUM (CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN CASE WHEN P_UTILBASEREDRAST = 'S' THEN DIN.BASERED ELSE DIN.BASE END ELSE 0 END), 0) + NVL (ITE.BASESUBSTITANT, 0) AS BASESUBST,
						   NVL (SUM (CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN DIN.VALOR ELSE 0 END), 0) + NVL (ITE.VLRSUBSTANT, 0) AS VLRSUBST,
						   NVL (SUM (CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN DIN.BASEFCPINT ELSE 0 END), 0) + NVL (ITE.BASESTFCPINTANT, 0) AS BASESTFCPINTANT,
						   NVL (SUM(CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN DIN.VLRFCPINT ELSE 0 END), 0) + NVL (ITE.VLRSTFCPINTANT, 0) AS VLRSTFCPINTANT,
						   NVL (MAX(CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN DIN.PERCFCPINT ELSE 0 END), 0) AS PERCSTFCPINTANT, -- ITE.PERCSTFCPINTANT, POR ENQUANTO NAO VAMOS CONSIDERAR O PERCENTUAL DA ITE DIFERENTE, ATE TERMOS CASO DE USO
						   NVL (MAX(CASE WHEN DIN.CODIMP = 2 AND P_TIPMOV <> 'D' THEN DIN.ALIQUOTA ELSE 0 END), 0) AS PERCSUBST,
						   P_NUNOTA AS NUNOTA,
						   P_SEQUENCIA AS SEQUENCIA
					FROM TGFVAR VAR,
						 TGFCAB CAB,
						 TGFTOP TP,
						 TGFDIN DIN,
						 TGFITE ITE
					WHERE VAR.NUNOTAORIG = P_NUNOTA
						AND VAR.SEQUENCIAORIG = P_SEQUENCIA
						AND CAB.NUNOTA = VAR.NUNOTA
						AND TP.CODTIPOPER = CAB.CODTIPOPER
						AND TP.DHALTER = CAB.DHTIPOPER
						AND TP.COMPLEMENTO = 'S'
						AND DIN.NUNOTA = VAR.NUNOTA
						AND DIN.SEQUENCIA = VAR.SEQUENCIA
						AND ITE.NUNOTA = DIN.NUNOTA
						AND ITE.SEQUENCIA = DIN.SEQUENCIA
					GROUP BY VAR.QTDATENDIDA,
							 ITE.QTDNEG,
							 ITE.VLRICMSANT,
							 ITE.BASESUBSTITANT,
							 ITE.VLRSUBSTANT,
							 ITE.BASESTFCPINTANT,
							 ITE.VLRSTFCPINTANT -- A TGFDIN PODE TER VARIAS LINAS
				   UNION ALL    --NOTAS DE TRANSFERENCIA
				   SELECT NVL (VAS.VLRICMS, 0) AS VLRICMS,
						  NVL (VAS.BASESUBST, 0) AS BASESUBST,
						  NVL (VAS.VLRSUBST, 0) AS VLRSUBST,
						  NVL (VAS.BASESTFCPINT, 0) AS BASESTFCPINTANT,
						  NVL (VAS.VLRSTFCPINT, 0) AS VLRSTFCPINTANT,
						  NVL (VAS.PERCSTFCPINT, 0) AS PERCSTFCPINTANT,
						  NVL (VAS.PERCSUBST, 0) AS PERCSUBST,
						  P_NUNOTA AS NUNOTA,
						  P_SEQUENCIA AS SEQUENCIA
					 FROM TGFVAS VAS, TGFCAB CAB
					WHERE VAS.NUNOTA = P_NUNOTA
						AND VAS.SEQUENCIA = ABS (P_SEQUENCIA)
						AND CAB.NUNOTA = VAS.NUNOTA
						AND CAB.TIPMOV = 'T'
					UNION ALL    --NOTAS AJUSTADAS PELO PROCESSO DA GERACAO DA CAT 42: QUANDO AS ENTRADAS NAO POSSUEM IMPOSTO CALCULADO
					SELECT CASE WHEN ITE.QTDNEG = NAE.QTDNEG THEN NAE.VLRICMS 
								ELSE NAE.VLRICMSUNIT * ITE.QTDNEG 
						   END AS VLRICMS,
						   CASE WHEN ITE.QTDNEG = NAE.QTDNEG THEN NAE.BASESUBSTIT 
								ELSE NAE.BASESUBSTITUNIT * ITE.QTDNEG 
						   END AS BASESUBST,
						   /*O VLRSUBST DA TGFCAT42R1050NAE COMPREENDE OS VALORES DE ICMS + ST, LOGO DEVO SEPAR-LOS AQUI */
						   CASE WHEN ITE.QTDNEG = NAE.QTDNEG THEN NAE.VLRSUBST 
								ELSE NAE.VLRSUBSTUNIT * ITE.QTDNEG 
						   END -
						   CASE WHEN ITE.QTDNEG = NAE.QTDNEG THEN NAE.VLRICMS 
								ELSE NAE.VLRICMSUNIT * ITE.QTDNEG 
						   END AS VLRSUBST,
						   0 AS BASESTFCPINTANT, /*NO CASO DE USO DA CAT42 "SP" NAO PRECISOU CONSIDERAR O ST DO FCP "UNIVERSAL" */
						   0 AS VLRSTFCPINTANT,
						   0 AS PERCSTFCPINTANT,
						   0 AS PERCSUBST, --VAI SER IMPLEMENTADO EM OUTRA OS NA CAT42
						   P_NUNOTA AS NUNOTA,
						   P_SEQUENCIA AS SEQUENCIA
					FROM TGFCAT42R1050NAE NAE
						INNER JOIN TGFITE ITE ON ITE.NUNOTA = NAE.NUNOTA AND ITE.SEQUENCIA = NAE.SEQUENCIA
					WHERE NAE.NUNOTA = P_NUNOTA
						AND NAE.SEQUENCIA = P_SEQUENCIA
						AND NAE.TIPONOTA = 'A'
					UNION ALL
					SELECT 0 AS VLRICMS,
						  ABS(NVL(IDST.BASESUBSTITCALC,0) - NVL(IDST.BASESUBSTITITEM,0)) AS BASESUBST,
						   IDST.DIFVLRSUBST AS VLRSUBST,
						   0 AS BASESTFCPINTANT,
						   0 AS VLRSTFCPINTANT,
						   0 AS PERCSTFCPINTANT,
						   0 AS PERCSUBST,
						   IDST.NUNOTA,
						   IDST.SEQUENCIA
					FROM TGFIDST IDST
					WHERE IDST.NUNOTA = P_NUNOTA 
						AND IDST.SEQUENCIA = P_SEQUENCIA 
						AND EXISTS(    SELECT 1 
									FROM TGFADST 
									WHERE STATUS = 'L' 
										AND NUNOTA = P_NUNOTA)
				  ) IMP,
				  TGFITS ITS
			WHERE ITS.NUNOTA = IMP.NUNOTA 
				AND ITS.SEQUENCIA = IMP.SEQUENCIA;

			--FALLBACK: AQUI É O CASO ONDE NA PRIMEIRA IMPLANTACAO DO RASTREAMENTO DE ESTOQUE, LOGO NAO HAVERA REGISTRO NA TGFITS, BUSCAR VALORES DIRETAMENTE DA TGFDIN/TGFITE
			--AQUI É O CASO ONDE NA PRIMEIRA IMPLANTACAO DO RASTREAMENTO DE ESTOQUE, LOGO NAO HAVERA REGISTRO NA TGFITS
			IF P_VLRICMS IS NULL AND P_BASESUBST IS NULL AND P_VLRSUBST IS NULL THEN
				SELECT SUM (CASE WHEN DIN.CODIMP = 1 THEN DIN.VALOR ELSE 0 END) AS VLRICMS,
					   SUM (CASE WHEN DIN.CODIMP = 2 THEN CASE WHEN P_UTILBASEREDRAST = 'S' THEN DIN.BASERED
																ELSE DIN.BASE
														   END
							 ELSE 0
						END) + MAX(NVL(ITE.BASESTEXTRANOTA, 0)) AS BASESUBST,
					   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.VALOR ELSE 0 END) + MAX(NVL(ITE.VLRSTEXTRANOTA, 0)) AS VLRSUBST,
					   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.BASEFCPINT ELSE 0 END) AS BASESTFCPINTANT,
					   SUM (CASE WHEN DIN.CODIMP = 2 THEN DIN.VLRFCPINT ELSE 0 END) AS VLRSTFCPINTANT,
					   MAX (CASE WHEN DIN.CODIMP = 2 THEN DIN.PERCFCPINT ELSE 0 END) AS PERCSTFCPINTANT,
					   MAX (CASE WHEN DIN.CODIMP = 2 THEN DIN.ALIQUOTA ELSE 0 END) + MAX(NVL(ITE.ALIQSTEXTRANOTA, 0)) AS PERCSUBST
				INTO P_VLRICMS,
					 P_BASESUBST,
					 P_VLRSUBST,
					 P_BASESTFCPINTANT,
					 P_VLRSTFCPINTANT,
					 P_PERCSTFCPINTANT,
					 P_PERCSUBST
				FROM TGFDIN DIN, TGFITE ITE
				WHERE DIN.NUNOTA = P_NUNOTA
					AND DIN.SEQUENCIA = P_SEQUENCIA
					AND ITE.NUNOTA = P_NUNOTA
					AND ITE.SEQUENCIA = P_SEQUENCIA
					AND P_TIPMOV <> 'D';

				-- Nota: como nao ha QTDENT da TGFITS, os valores ja calculados da TGFDIN sao usados diretamente
				-- descontando apenas os valores ja usados quando aplicavel
				P_VLRICMS := CASE WHEN (P_VLRICMS_USADO > 0) AND (NVL(P_VLRICMS, 0) - P_VLRICMS_USADO > 0) THEN NVL(P_VLRICMS, 0) - P_VLRICMS_USADO ELSE NVL(P_VLRICMS, 0) END;
				P_BASESUBST := CASE WHEN (P_BASESUBST_USADO > 0) AND (NVL(P_BASESUBST, 0) - P_BASESUBST_USADO > 0) THEN NVL(P_BASESUBST, 0) - P_BASESUBST_USADO ELSE NVL(P_BASESUBST, 0) END;
				P_VLRSUBST := CASE WHEN (P_VLRSUBST_USADO > 0) AND (NVL(P_VLRSUBST, 0) - P_VLRSUBST_USADO > 0) THEN NVL(P_VLRSUBST, 0) - P_VLRSUBST_USADO ELSE NVL(P_VLRSUBST, 0) END;
				P_BASESTFCPINTANT := CASE WHEN (P_BASESTFCPINTANT_USADO > 0) AND (NVL(P_BASESTFCPINTANT, 0) - P_BASESTFCPINTANT_USADO > 0) THEN NVL(P_BASESTFCPINTANT, 0) - P_BASESTFCPINTANT_USADO ELSE NVL(P_BASESTFCPINTANT, 0) END;
