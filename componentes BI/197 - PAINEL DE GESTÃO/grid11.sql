SELECT 
1 AS ORDEM,
D.CODPARC, 
D.RAZAOSOCIAL, 
NULLIF(D.VLR,0) AS VLR,
NULLIF(D.VLRFIN,0) AS VLRFIN,
NULLIF(D.VLRDEVOL,0) AS VLRDEVOL,
D.VLRTOTAL,
(D.VLRTOTAL / SUM(D.VLRTOTAL) OVER () )*100 AS REP,
CODCTACTB2
FROM(

	SELECT 
	CODPARC, 
	UPPER(RAZAOSOCIAL) AS RAZAOSOCIAL, 
	SUM(VLR) AS VLR,
    SUM(VLRFIN) AS VLRFIN,
	SUM(VLRDEVOL) AS VLRDEVOL,
	SUM(VALOR) AS VLRTOTAL,
	CODCTACTB2
	FROM(
	
		--TITULOS ORIGEM PORTAL - TOP TIPO "C"/"E"
		SELECT 
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		T.TIPMOV,
		CASE WHEN T.TIPMOV <> 'E' THEN NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) ELSE 0 END AS VLR,
        0 AS VLRFIN,
		CASE WHEN T.TIPMOV = 'E' THEN NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) ELSE 0 END AS VLRDEVOL,
		NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) AS VALOR,
		PAR.CODCTACTB2
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
        LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
		WHERE
		FIN.CODEMP IN :CODEMP  AND  
		FIN.DTENTSAI <= :DAT1 AND 
		(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
		((T.TIPMOV IN ('C') AND FIN.RECDESP = -1) OR 
         (T.TIPMOV IN ('O') AND FIN.RECDESP = -1 AND T.ATUALCTB = 'S') OR 
		 (T.TIPMOV IN ('E') AND FIN.RECDESP = 1)) AND
		:OUTROS IN ('A','P')
		GROUP BY FIN.CODPARC, PAR.RAZAOSOCIAL, T.TIPMOV, PAR.CODCTACTB2
		
		UNION ALL
		
		--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
		SELECT 
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL,
		T.TIPMOV,
		0 AS VLR,
        NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) AS VLRFIN,
		0 AS VLRDEVOL,
		NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) AS VALOR,
		PAR.CODCTACTB2
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
        LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
		WHERE 
		FIN.CODEMP IN :CODEMP  AND  
		FIN.DTENTSAI <= :DAT1 AND 
		(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
		T.TIPMOV IN ('I') AND 
		FIN.CODTIPOPER <> 0 AND  
		FIN.RECDESP = -1 AND
		NAT.AD_TIPOCTBZ = 'N' AND
        T.TIPMOV||'-'||NAT.CODNAT NOT IN ('I-301006') AND
		:OUTROS IN ('A','F')
		GROUP BY FIN.CODPARC, PAR.RAZAOSOCIAL, T.TIPMOV, PAR.CODCTACTB2
		)
		
	GROUP BY CODPARC, RAZAOSOCIAL, CODCTACTB2
	)D

UNION ALL

SELECT 0 AS ORDEM, 0 AS CODPARC, ' .TODOS' AS RAZAOSOCIAL, NULL AS VLR, NULL AS VLRFIN, NULL AS VLRDEVOL, NULL AS VLRTOTAL, NULL AS REP, NULL AS CODCTACTB FROM DUAL
ORDER BY ORDEM, VLRTOTAL, RAZAOSOCIAL
