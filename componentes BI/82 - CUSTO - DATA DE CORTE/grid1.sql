SELECT PRO.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	OBTEMCUSTO_SPARK (PRO.CODPROD,'S',1,'N',0,'N',' ',:P_DATA,4) AS CUSMEDICMS,
	OBTEMCUSTO_SPARK (PRO.CODPROD,'S',1,'N',0,'N',' ',:P_DATA,3) AS CUSMEDSICM,
	OBTEMCUSTO_SPARK (PRO.CODPROD,'S',1,'N',0,'N',' ',:P_DATA,1) AS CUSMED
FROM TGFPRO PRO
WHERE (PRO.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL AND PRO.USOPROD = 'M')
ORDER BY PRO.CODPROD
