SELECT CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTENTSAI,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	CAB.VLRNOTA,
	(CASE WHEN CAB.TIPMOV = 'V' THEN 'Venda' ELSE 'Compra' END) AS TIPMOV
FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
WHERE CAB.DTENTSAI <= :P_DTENTSAI.FIN
	AND CAB.DTENTSAI >= :P_DTENTSAI.INI
	AND CAB.TIPMOV IN (/*'V',*/'C')
	AND CAB.CODEMP = 501
UNION ALL
SELECT C.NUNOTA,
	C.NUMNOTA,
	C.DTENTSAI,
	C.CODPARC,
	P.RAZAOSOCIAL,
	C.VLROUTROS AS VLRNOTA,
	(CASE WHEN C.TIPMOV = 'V' THEN 'Venda' ELSE 'Compra' END) AS TIPMOV
FROM TGFCAB C 
	INNER JOIN TGFPAR P ON C.CODPARC = P.CODPARC
WHERE C.TIPMOV IN ('C'/*,'V'*/) 
	AND C.VLROUTROS > 0 
	AND C.CODEMP = 1 
	AND C.DTENTSAI >= :P_DTENTSAI.INI 
	AND C.DTENTSAI <= :P_DTENTSAI.FIN
