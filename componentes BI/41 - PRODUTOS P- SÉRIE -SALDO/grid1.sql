SELECT T.*
FROM
(SELECT Cabecalho.CODEMP||' - '||Empresa.RAZAOABREV AS EMPRESA
    , Produto.CODPROD
    , Produto.REFERENCIA
    , Produto.DESCRPROD
    , Locais.CODLOCAL
    , Locais.DESCRLOCAL
    , Serie.SERIE
    , SUM(Serie.ATUALESTOQUE) AS ATUALESTOQUE
    , Produto.CODGRUPOPROD
    , Grupo.DESCRGRUPOPROD
    
    , NVL(G2.CODGRUPOPROD,Produto.CODGRUPOPROD) AS COD_GRUP_2
    
    , nvl(G2.DESCRGRUPOPROD ,Grupo.DESCRGRUPOPROD) AS DESC_GRUP_2
    , '__________________'  AS OBS       

FROM TGFSER Serie
    INNER JOIN TGFITE Item ON Serie.NUNOTA = Item.NUNOTA AND Serie.SEQUENCIA = Item.SEQUENCIA
    INNER JOIN TGFCAB Cabecalho ON Serie.NUNOTA = Cabecalho.NUNOTA AND Cabecalho.NUNOTA = Item.NUNOTA
    INNER JOIN TGFPRO Produto ON Produto.CODPROD = Item.CODPROD
    INNER JOIN TSIEMP Empresa ON Empresa.CODEMP = Cabecalho.CODEMP
    INNER JOIN TGFLOC Locais ON Locais.CODLOCAL = Item.CODLOCALORIG
    INNER JOIN TGFGRU Grupo ON Grupo.CODGRUPOPROD = Produto.CODGRUPOPROD
    LEFT JOIN TGFGRU G1 ON G1.CODGRUPOPROD = Grupo.CODGRUPAI
    LEFT JOIN TGFGRU G2 ON G2.CODGRUPOPROD = G1.CODGRUPAI

WHERE 1=1
   AND Cabecalho.CODEMP IN :CODEMP

GROUP BY Serie.SERIE, Produto.CODPROD, Produto.REFERENCIA, Produto.DESCRPROD, Cabecalho.CODEMP, Empresa.RAZAOABREV, Locais.CODLOCAL
                , Locais.DESCRLOCAL, Produto.codgrupoprod, Grupo.DESCRGRUPOPROD,G2.CODGRUPOPROD, G2.DESCRGRUPOPROD

HAVING SUM(Serie.ATUALESTOQUE) != 0

ORDER BY Produto.CODPROD) T

WHERE 1=1
   AND T.COD_GRUP_2 IN :CODGRUPOPROD
