create or replace TRIGGER SPK_TGFASS_INC 
BEFORE INSERT /* OR UPDATE*/ ON AD_TGFASS 
FOR EACH ROW
/*==============================================================================
  Nome do Script : SPK_TGFASS_INC
  Tipo           : Trigger
  Descrição      : Popula automaticamente atributos de série (produto, descrição, referência, data fabricação, lote) consultando view VGFSERIES na inserção.
  Tabela         : AD_TGFASS
  Evento         : BEFORE INSERT
  Escopo         : FOR EACH ROW / STATEMENT

  Autor          : Silvio Vieira
  Cargo          : Analista de Sistemas Sênior
  Empresa        : Spark Eletrônica
  Data de Criação: [A DEFINIR]
  Última Revisão : Abril/2026 — Padronização de cabeçalho e comentários
==============================================================================*/
DECLARE
	P_CODPROD INTEGER;
	P_DESCRPROD VARCHAR(200);
	P_RFINTERNA VARCHAR (60);
	P_DESCRPARVENDA VARCHAR (200);
	P_DTVENDA DATE;
	P_DTFABRICACAO DATE;
	P_TIPO VARCHAR(10);
	P_LOTE VARCHAR(25);
	
	P_NUMOS INTEGER;
    P_SNENTRADA VARCHAR(30);
BEGIN
	P_NUMOS := :NEW.NUMOS;
    P_SNENTRADA := :NEW.SNENTRADA;
	/*GRAVAÇÃO DO CÓDIGO DO PRODUTO PRODUZIDO (OU NO CASO ANDES DO PRODUTO TRANSFERIDO)*/
	SELECT MAX(CODPROD) INTO P_CODPROD 
    FROM (SELECT DISTINCT CODPROD, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND (VGFSERIES.MOVIMENTO = 'SAÍDA' OR VGFSERIES.TOP = 800)
            UNION ALL
            SELECT DISTINCT CODPROD, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.TIPO = 'ANDES') V
    WHERE V.DTVENDA = (SELECT MAX(V.DTVENDA) FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA);
	/*GRAVAÇÃO DA DESCRIÇÃO DO PRODUTO BASEADO NA VIEW*/
	SELECT MAX(DESCRPROD) INTO P_DESCRPROD
	FROM (SELECT DISTINCT DESCRPROD, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.TOP = 800
			UNION ALL
			SELECT DISTINCT DESCRPROD, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.TIPO = 'ANDES') V
	WHERE V.DTVENDA = (SELECT MAX(V.DTVENDA) FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA);
	/*GRAVAÇÃO DA REFERENCIA INTERNA BASEADO NA VIEW*/
	SELECT MAX(RFINTERNA) INTO P_RFINTERNA
	FROM (SELECT DISTINCT RFINTERNA, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.TOP = 800
			UNION ALL
			SELECT DISTINCT RFINTERNA, DTVENDA FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.TIPO = 'ANDES') V
	WHERE V.DTVENDA = (SELECT MAX(V.DTVENDA) FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA);
	/*GRAVAÇÃO DO PARCEIRO DE VENDA BASEADO NA VIEW*/
    SELECT COALESCE (
        (SELECT VGFSERIES.DESCRPARVENDA 
        FROM VGFSERIES 
        WHERE VGFSERIES.SERIE = P_SNENTRADA 
            AND (VGFSERIES.MOVIMENTO = 'SAÍDA' OR VGFSERIES.TIPO = 'ANDES') 
            AND VGFSERIES.DESCRPARVENDA <> 'SPARK ELETRONICA LTDA'
            AND VGFSERIES.DTVENDA = (SELECT MAX(DTVENDA) FROM VGFSERIES S WHERE S.SERIE = P_SNENTRADA AND (S.MOVIMENTO = 'SAÍDA' OR S.TIPO = 'ANDES'))),'VAZIO') INTO P_DESCRPARVENDA
    FROM DUAL;
	/*GRAVAÇÃO DA DATA DE VENDA BASEADO NA VIEW*/
	SELECT MAX(DTVENDA) INTO P_DTVENDA
	FROM VGFSERIES 
	WHERE VGFSERIES.SERIE = P_SNENTRADA 
		AND (VGFSERIES.MOVIMENTO = 'SAÍDA' OR VGFSERIES.TIPO = 'ANDES');
	/*GRAVAÇÃO DA DATA DE FABRICAÇÃO BASEADO NA VIEW*/
	/*SELECT DISTINCT DTVENDA INTO P_DTFABRICACAO
	FROM VGFSERIES 
	WHERE VGFSERIES.SERIE = P_SNENTRADA 
		AND VGFSERIES.MOVIMENTO = 'ENTRADA';
	CÓDIGO ANTIGO PRECISEI ALTERAR EM 21/02/2024 POIS ALGUNS SN NÃO TINHAM RASTREIO DE FABRICAÇÃO*/
	SELECT DTVENDA INTO P_DTFABRICACAO
	FROM(
        SELECT DISTINCT DTVENDA
        FROM VGFSERIES 
        WHERE VGFSERIES.SERIE = P_SNENTRADA
            AND VGFSERIES.MOVIMENTO = 'ENTRADA'
        UNION ALL
        SELECT TO_DATE('01/01/1900')
        FROM DUAL
        WHERE P_SNENTRADA NOT IN (SELECT DISTINCT SERIE FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.MOVIMENTO = 'ENTRADA')
    );	
	/*GRAVAÇÃO DO TIPO BASEADO NA VIEW QUE DEFINE SE É UM SN ANDES OU SANKHYA*/
	SELECT TIPO INTO P_TIPO
	FROM (
		SELECT DISTINCT TIPO
		FROM VGFSERIES 
		WHERE VGFSERIES.SERIE = P_SNENTRADA 
			AND (VGFSERIES.TOP = 800 OR VGFSERIES.TIPO = 'ANDES')
		UNION ALL
		SELECT 'ANDES'
		FROM DUAL
		WHERE P_SNENTRADA NOT IN (SELECT DISTINCT SERIE FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND (VGFSERIES.TOP = 800 OR VGFSERIES.TIPO = 'ANDES')) 
	);
	/*GRAVAÇÃO DO LOTE BASEADO NA VIEW QUE CONCATENA OS LOTES SANKHYA E ANDES EM NOMES MAIS ÚTEIS*/
	SELECT LOTE INTO P_LOTE
	FROM(
		SELECT DISTINCT LOTE
		FROM VGFSERIES 
		WHERE VGFSERIES.SERIE = P_SNENTRADA 
			AND VGFSERIES.MOVIMENTO = 'ENTRADA'
		UNION ALL
		SELECT 'ANDES'
		FROM DUAL
		WHERE P_SNENTRADA NOT IN (SELECT DISTINCT SERIE FROM VGFSERIES WHERE VGFSERIES.SERIE = P_SNENTRADA AND VGFSERIES.MOVIMENTO = 'ENTRADA')
	);
		
	:NEW.T_CODPROD := P_CODPROD;
	:NEW.T_DESCRPROD := P_DESCRPROD;
    :NEW.T_RFINTERNA := P_RFINTERNA;
	:NEW.T_DESCRPARVENDA := P_DESCRPARVENDA;
	:NEW.T_DTVENDA := P_DTVENDA;
	:NEW.T_DTFABRICACAO := P_DTFABRICACAO;
	:NEW.T_TIPO := P_TIPO;
	:NEW.T_LOTE := P_LOTE;
END SPK_TGFASS_INC;