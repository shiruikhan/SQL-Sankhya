create or replace TRIGGER TRG_TGFCAB_TRANSF_SPARK
BEFORE DELETE ON TGFCAB
FOR EACH ROW
DECLARE
P_COUNT          INT;
P_COUNT2         INT;
PRAGMA AUTONOMOUS_TRANSACTION;

BEGIN

    SELECT COUNT(*) INTO P_COUNT
      FROM TGFCAB
     WHERE AD_NUNOTAENT = :OLD.NUNOTA;
     
    SELECT COUNT(*) INTO P_COUNT2
      FROM TGFCAB
     WHERE AD_NUNOTASAI = :OLD.NUNOTA;
     
     IF P_COUNT > 0 AND :OLD.TIPMOV IN ('C', 'V') THEN 
     
     UPDATE TGFCAB SET AD_NUNOTAENT = NULL
     WHERE AD_NUNOTAENT = :OLD.NUNOTA;
     
     COMMIT;
     
     END IF;
     
     IF P_COUNT2 > 0 AND :OLD.TIPMOV IN ('C', 'V')  THEN 
     
     UPDATE TGFCAB SET AD_NUNOTASAI = NULL
     WHERE AD_NUNOTASAI = :OLD.NUNOTA;
     
     COMMIT;
     
     END IF;

END; 