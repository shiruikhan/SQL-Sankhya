SELECT 
TIPO, 
SUM(CASE WHEN TIPO = 'Espécie' OR TIPO = 'Corrente' OR TIPO = 'Aplicação' THEN SALDOREAL2 ELSE NULL END) AS SALDOREAL, 
SUM(CASE WHEN TIPO = 'Espécie' OR TIPO = 'Corrente' OR TIPO = 'Aplicação' THEN SALDOBCO2 ELSE NULL END) AS SALDOBCO,
SUM(CASE WHEN TIPO = 'Empréstimo' THEN SALDOREAL2 ELSE NULL END) AS SALDOEMP,
SUM(CASE WHEN TIPO <> 'Adiantamento' THEN NULL ELSE SALDOREAL2 END) AS SALDOADTOS, 
SUM(CASE WHEN TIPO <>'Outras' THEN NULL ELSE SALDOBCO2 END) AS SALDOOUTRAS
FROM (
	SELECT 
	CTA.CODEMP, 
	(SELECT RAZAOABREV FROM TSIEMP E WHERE E.CODEMP = CTA.CODEMP) AS RAZAOABREV,
	CASE WHEN CLASSE = 'A' THEN 'Aplicação' 
	     WHEN CLASSE = 'D' THEN 'Adiantamento'
	     WHEN CLASSE = 'C' THEN 'Corrente'
	     WHEN CLASSE = 'X' THEN 'Espécie' 
	     WHEN CLASSE = 'G' THEN 'Garantida'
	     WHEN CLASSE = 'E' THEN 'Empréstimo'
	     WHEN CLASSE = 'O' THEN 'Outras' 
	     ELSE 'Corrente' END AS TIPO,  
	CTA.CODCTABCO, 
	CTA.DESCRICAO, 
	CTA.CODCTABCOINT, 
	SBC.REFERENCIA, 
	(NVL(SBC.SALDOREAL,0) + NVL((SELECT SUM(T7.VLRLANC * T7.RECDESP)
	FROM TGFMBC T7 
	WHERE T7.CODCTABCOINT = SBC.CODCTABCOINT AND	  
	T7.DTLANC  >= to_date( '01/'||to_char(:DAT1, 'mm/yyyy')   , 'dd/mm/yyyy') AND 
	T7.DTLANC  < to_char(:DAT1+1,'dd/mm/yyyy')),0)) AS SALDOREAL2,
	(NVL(SBC.SALDOBCO,0) + NVL((SELECT SUM(T7.VLRLANC * T7.RECDESP)
	FROM TGFMBC T7 
	WHERE T7.CODCTABCOINT = SBC.CODCTABCOINT AND	  
	T7.DHCONCILIACAO  >= to_date( '01/'||to_char(:DAT1, 'mm/yyyy')   , 'dd/mm/yyyy') AND 
	T7.DHCONCILIACAO  < to_char(:DAT1+1,'dd/mm/yyyy') AND
	T7.CONCILIADO = 'S'),0)) AS SALDOBCO2,
	CTA.CODCTACTB
	FROM   TGFSBC SBC, TSICTA CTA
	WHERE  
	CTA.CODEMP IN :CODEMP AND CTA.ATIVA='S' AND CTA.CODCTABCOINT NOT IN (30) AND 
	SBC.REFERENCIA = (SELECT MAX(REFERENCIA) FROM   TGFSBC T2  WHERE T2.CODCTABCOINT = SBC.CODCTABCOINT AND T2.REFERENCIA < to_char(:DAT1+1,'dd/mm/yyyy')) AND 
	SBC.CODCTABCOINT = CTA.CODCTABCOINT      
	ORDER BY 2, 4) 
	GROUP BY TIPO
	UNION ALL
	SELECT ' .Todos' AS TIPO, NULL AS SALDOREAL, NULL AS SALDOBCO, NULL AS SALDOEMP, NULL AS SALDOADTOS, NULL AS SALDOOUTRAS FROM DUAL
	ORDER BY  TIPO
