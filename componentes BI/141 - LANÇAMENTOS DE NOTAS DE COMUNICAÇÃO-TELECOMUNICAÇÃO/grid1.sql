SELECT CAB.NUMNOTA,
	CAB.DTFATUR,
	CAB.DTENTSAI,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	PAR.CGC_CPF,
	PAR.IDENTINSCESTAD,
	CAB.VLRNOTA,
	(SELECT DISTINCT ITE.CODCFO FROM TGFITE ITE WHERE ITE.NUNOTA = CAB.NUNOTA) AS CODCFO,
	UFS.UF
FROM TGFCAB CAB
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
	INNER JOIN TSICID CID ON PAR.CODCID = CID.CODCID
	INNER JOIN TSIUFS UFS ON CID.UF = UFS.CODUF
WHERE CAB.CODTIPOPER IN (208,223)
	AND CAB.DTENTSAI >= :P_PERIODO.INI
	AND CAB.DTENTSAI <= :P_PERIODO.FIN
ORDER BY CAB.DTENTSAI,
	CAB.NUMNOTA
