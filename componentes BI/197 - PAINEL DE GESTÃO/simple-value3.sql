SELECT 
	SUM(TOTALVENCIDO) AS TOTALVENCIDO
	FROM(
		--ORIGEM PORTAL - TIPMOV= "V"
		SELECT 
		FIN.CODPARC, 
		PAR.RAZAOSOCIAL, 
		PAR.CODVEND,
		T.TIPMOV,
		(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT AS TOTALVENCIDO,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') = TO_CHAR(SYSDATE,'YYYY/MM') THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_MES,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 0 AND 30 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE30,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 31 AND 60 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE60,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 61 AND 90 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE90,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC)BETWEEN 91 AND 120 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE120,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 121 AND 150 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE150,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 151 AND 180 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_ATE180,
		CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) > 180 THEN (FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT ELSE NULL END AS VENC_MAIS180
		FROM 
		TGFFIN FIN 
		LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
		LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
		LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
		LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
		WHERE
		FIN.CODEMP IN :CODEMP AND  
		TRUNC(FIN.DTNEG) <= TRUNC(SYSDATE) AND  
		FIN.DHBAIXA is null AND
		DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
		FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
		T.TIPMOV IN ('V') AND 
		FIN.RECDESP = 1 AND
		TRUNC(FIN.DTVENC) < TRUNC(SYSDATE)
		)
