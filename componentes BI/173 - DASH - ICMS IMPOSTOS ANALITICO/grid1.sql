SELECT 
	CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTNEG,
	CAB.DTENTSAI,
	CASE 

		WHEN CAB.STATUSNFE IS NULL AND CAB.TIPMOV = 'P' THEN '-----' 
		WHEN CAB.STATUSNFE = 'A' THEN 'Aprovada'
		WHEN CAB.STATUSNFE = 'D' THEN 'Denegada'
		WHEN CAB.STATUSNFE = 'E' THEN 'Aguardando Autorização'
		WHEN CAB.STATUSNFE = 'I' THEN 'Enviada'
		WHEN CAB.STATUSNFE = 'M' THEN 'Não é NF-e'
		WHEN CAB.STATUSNFE = 'P' THEN 'Pendente de Retorno'
		WHEN CAB.STATUSNFE = 'R' THEN 'Aguardando Correção'
		WHEN CAB.STATUSNFE = 'S' THEN 'Enviada EPEC'
		WHEN CAB.STATUSNFE = 'T' THEN 'NF-e Terceiro'
		WHEN CAB.STATUSNFE = 'V' THEN 'Com erro de Validação' 
		ELSE 'Não Enviada' END AS STATUSNFE,
	CAB.CODTIPOPER,
	CAB.CODNAT || ' - ' || (SELECT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = CAB.CODNAT) AS CODNAT,
	TPO.DESCROPER,
	PAR.CODPARC, 
	PAR.NOMEPARC,
	PAR.IDENTINSCESTAD,
	CASE WHEN PAR.SIMPLES = 'S' THEN 'Optante Simples' ELSE 'Não optante' END AS SIMPLES,
    OPTION_LABEL('TGFPAR','CLASSIFICMS',PAR.CLASSIFICMS)  AS CLASSIFICMS,	
	ITE.SEQUENCIA,
	ITE.CODPROD,
	PRO.DESCRPROD,
	PRO.NCM,
	PRO.CODCTACTBEFD,
	(SELECT PLA.DESCRCTA FROM TCBPLA PLA WHERE PLA.CODCTACTB = PRO.CODCTACTBEFD) AS CONTA_CTB,
	ITE.QTDNEG,
	ITE.VLRUNIT, 
	ITE.VLRTOT,
	ITE.VLRDESC,
	LIV.CODCFO,
	ITE.ORIGPROD,
	CASE WHEN NVL(LIV.DIGITADO,'N') = 'S' THEN LIV.CODTRIB ELSE ITE.CODTRIB END AS CODTRIB,
	CASE WHEN NVL(LIV.DIGITADO,'N') = 'S' THEN LIV.ALIQICMS ELSE ITE.ALIQICMS END AS ALIQICMS ,	
	ITE.CSTIPI,
	ITE.ALIQIPI,
	LIV.VLRCTB,
	LIV.OUTRASICMS,
	LIV.ISENTASICMS,
	LIV.OUTRASIPI,
	NVL(LIV.VLRCTB,0) - NVL(LIV.BASEIPI,0) - NVL(LIV.OUTRASIPI,0) - NVL(LIV.VLRIPI,0) AS VAL_IPI,
	LIV.ISENTASIPI,
   CASE WHEN CAB.TIPMOV = 'C' THEN (NVL(ITE.VLRTOT,0) - NVL(ITE.VLRREPRED,0))
                              ELSE (NVL(ITE.VLRTOT,0) - NVL(ITE.VLRREPRED,0) - NVL(ITE.VLRDESC,0)) END   AS VLREFD,

	(SELECT SUM(LIV1.VLRCTB - LIV.ICMSRETENCAO - LIV.VLRIPI)

		FROM TGFLIV LIV1

		WHERE LIV1.NUNOTA = ITE.NUNOTA

			AND LIV1.SEQUENCIA = ITE.SEQUENCIA) AS VLRITELIQ,
			
	CASE WHEN NVL(LIV.DIGITADO,'N') = 'N'
	THEN NVL((SELECT SUM(DIN.BASERED)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1

				AND DIN.CODINC IN (1,3,5)),LIV.BASEICMS)
	  ELSE LIV.BASEICMS END AS BASEICMS,
	CASE WHEN NVL(LIV.DIGITADO,'N') = 'N'
	THEN 
	NVL((SELECT SUM(DIN.VALOR) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1

				AND DIN.CODINC IN (1,3,5)),LIV.VLRICMS) 
				
	ELSE LIV.VLRICMS END AS VLRICMS,
				
	(SELECT SUM(AJD.VLRICMS) FROM TGFAJD AJD WHERE AJD.NUNOTA = LIV.NUNOTA AND AJD.SEQUENCIA = LIV.SEQUENCIA AND AJD.CODOBSPADRAO <> 24 ) AS ICMS_AJUSTE,	
	

	NVL((SELECT SUM(DIN.BASEDIFAL) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1

				AND DIN.CODINC IN (1,3,5)),0) AS BASEDIFAL,
				
	NVL((SELECT SUM(DIN.VLRDIFALDEST) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1

				AND DIN.CODINC IN (1,3,5)),0) AS VLRDIFAL,
				
		NVL((SELECT SUM(DIN.VLRFCP) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1

				AND DIN.CODINC IN (1,3,5)),0) AS VLRFCP,
				
	NVL((SELECT SUM(DIN.BASERED) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 3

				AND DIN.CODINC IN (1,3,5)),ITE.BASEIPI) AS BASEIPI,

	NVL((SELECT SUM(DIN.VALOR) 

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 3

				AND DIN.CODINC IN (1,3,5)),ITE.VLRIPI) AS VLRIPI,

	NVL((SELECT SUM(DIN.BASERED)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS BASE_PIS,

	NVL((SELECT MAX(DIN.CST)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS CST_PIS,

	NVL((SELECT SUM(DIN.VALOR)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS VLR_PIS,

	NVL((SELECT SUM(IDI.VLRPISIMP)
			FROM TGFIDI IDI
			WHERE IDI.NUNOTA = ITE.NUNOTA
				AND IDI.SEQUENCIA = ITE.SEQUENCIA)
		,0) AS VLR_PISIMP,				

	NVL((SELECT SUM(DIN.BASERED)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS BASE_COFINS,

	NVL((SELECT MAX(DIN.CST)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS CST_COFINS,

	NVL((SELECT SUM(DIN.VALOR)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS VLR_COFINS,

	NVL((SELECT SUM(IDI.VLRCOFINSIMP)
			FROM TGFIDI IDI
			WHERE IDI.NUNOTA = ITE.NUNOTA
				AND IDI.SEQUENCIA = ITE.SEQUENCIA)
		,0) AS VLR_COFINSIMP,
				
	NVL((SELECT SUM(DIN.BASE)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 2),0) AS BASE_ST,

	NVL((SELECT MAX(DIN.ALIQUOTA)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 2),0) AS ALIQ_ST,

	NVL((SELECT SUM(DIN.VALOR)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 2),0) AS VLR_ST,

	NVL((SELECT SUM(DIN.VLRFCPINT)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 2),0) AS VLR_FEM_ICMS_ST,  

	NVL((SELECT SUM(DIN.VLRFCPINT)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 1),0) AS VLR_FEM_ICMS_OP,
				
	NVL((SELECT SUM(DIN.BASE)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND (DIN.CODIMP = 6 AND DIN.CODINC = 3)),0) AS FRETE_ITEM,						

	NVL((SELECT SUM(DIN.BASE)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND (DIN.CODIMP = 6 AND DIN.CODINC = 3)),0) 
	 - (NVL(LIV.VLRCTB,0) - NVL(LIV.BASEIPI,0) - NVL(LIV.OUTRASIPI,0) - NVL(LIV.VLRIPI,0)) AS DIF_VAL_IPI,
				
	CID.NOMECID,

	UF.UF,

	CAB.CHAVENFE,

	(SELECT MAX(C.NUMNOTA) 

		FROM TGFCAB C,

			TGFVAR VAR 

		WHERE C.NUNOTA = VAR.NUNOTA 

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND C.TIPMOV = 'D') AS NUMNOTA_DEVOLUCAO,

	(SELECT MAX(I.VLRTOT) 

		FROM TGFCAB C,

			TGFITE I,

			TGFVAR VAR 

		WHERE C.NUNOTA = I.NUNOTA 

			AND C.NUNOTA = VAR.NUNOTA 

			AND I.SEQUENCIA = VAR.SEQUENCIA 

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 

			AND C.TIPMOV = 'D') AS VLRTOT_DEVOLUCAO,

	(SELECT MAX(I.BASEICMS) 

		FROM TGFCAB C,

			TGFITE I,

			TGFVAR VAR 

		WHERE C.NUNOTA = I.NUNOTA

			AND C.NUNOTA = VAR.NUNOTA 

			AND I.SEQUENCIA = VAR.SEQUENCIA 

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 

			AND C.TIPMOV = 'D') AS VLRBCICMS_DEVOLUCAO,

	(SELECT MAX(I.VLRICMS) 

		FROM TGFCAB C,

			TGFITE I, 

			TGFVAR VAR 

		WHERE C.NUNOTA = I.NUNOTA 

			AND C.NUNOTA = VAR.NUNOTA 

			AND I.SEQUENCIA = VAR.SEQUENCIA 

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 

			AND C.TIPMOV = 'D') AS VLRICMS_DEVOLUCAO,

	(SELECT MAX(I.BASEIPI) 

		FROM TGFCAB C,

			TGFITE I, 

			TGFVAR VAR 

		WHERE C.NUNOTA = I.NUNOTA 

			AND C.NUNOTA = VAR.NUNOTA

			AND I.SEQUENCIA = VAR.SEQUENCIA

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA

			AND C.TIPMOV = 'D') AS VLRBCIPI_DEVOLUCAO,

	(SELECT MAX(I.VLRIPI) 

		FROM TGFCAB C,

			TGFITE I,

			TGFVAR VAR 

		WHERE C.NUNOTA = I.NUNOTA 

			AND C.NUNOTA = VAR.NUNOTA 

			AND I.SEQUENCIA = VAR.SEQUENCIA 

			AND VAR.NUNOTAORIG = CAB.NUNOTA 

			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 

			AND C.TIPMOV = 'D') AS VLRIPI_DEVOLUCAO

FROM TGFCAB CAB,

	TGFITE ITE,

	TGFPRO PRO,

	TGFPAR PAR,

	TGFTOP TPO,

	TSICID CID, 

	TSIUFS UF, 

	TGFLIV LIV

WHERE LIV.NUNOTA = CAB.NUNOTA 

	AND LIV.NUNOTA = ITE.NUNOTA

	AND LIV.SEQUENCIA = ITE.SEQUENCIA 

	AND CAB.NUNOTA = ITE.NUNOTA 

	AND ITE.CODPROD = PRO.CODPROD

	AND CAB.CODPARC = PAR.CODPARC

	AND CAB.CODTIPOPER = TPO.CODTIPOPER

	AND CAB.DHTIPOPER = TPO.DHALTER

	AND PAR.CODCID = CID.CODCID

	AND CID.UF = UF.CODUF

	AND TPO.ATUALLIVFIS <> 'N'
	
	AND LIV.DHMOV >= :P_PERIODO.INI
	AND LIV.DHMOV <= :P_PERIODO.FIN
	
	AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)

	AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)

	AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
	
	AND (CAB.CODTIPOPER = :P_CODTIPOPER OR :P_CODTIPOPER IS NULL)

	AND LIV.CODCFO >= :P_CODCFOPINI

	AND LIV.CODCFO <= :P_CODCFOPFIN

	AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	
	AND (CAB.CODPARC = :P_PARCEIRO OR :P_PARCEIRO IS NULL)
UNION ALL
SELECT
     LIS.NUNOTA
    ,LIS.NUMNOTA
    ,CAB.DTNEG
    ,CAB.DTENTSAI
    ,'NF-e Terceiro' AS STATUSNFE
    ,CAB.CODTIPOPER
	,CAB.CODNAT || ' - ' || (SELECT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = CAB.CODNAT) AS CODNAT
    ,TPO.DESCROPER
    ,CAB.CODPARC 
    ,PAR.NOMEPARC
    ,PAR.IDENTINSCESTAD
    ,CASE WHEN PAR.SIMPLES = 'S' THEN 'Optante Simples' ELSE 'Não optante' END AS SIMPLES
    ,OPTION_LABEL('TGFPAR','CLASSIFICMS',PAR.CLASSIFICMS)  AS CLASSIFICMS
	,LIS.SEQUENCIA
    ,PRO.CODPROD 
    ,PRO.DESCRPROD
	,PRO.NCM	
    ,PRO.CODCTACTBEFD
    ,(SELECT PLA.DESCRCTA FROM TCBPLA PLA WHERE PLA.CODCTACTB = PRO.CODCTACTBEFD) AS CONTA_CTB
    ,ITE.QTDNEG
    ,ITE.VLRUNIT
    ,ITE.VLRTOT
	,ITE.VLRDESC
    ,ITE.CODCFO
    ,ITE.ORIGPROD
    ,ITE.CODTRIB 
    ,ITE.ALIQICMS
    ,ITE.CSTIPI
    ,ITE.ALIQIPI
    ,LIS.VLRCTB
    , 0 AS OUTRASICMS
    , 0 AS ISENTASICMS
    , 0 AS OUTRASIPI
    , 0 AS VAL_IPI
    , 0 AS ISENTASIPI
   , CASE WHEN CAB.TIPMOV = 'C' THEN (NVL(ITE.VLRTOT,0) - NVL(ITE.VLRREPRED,0))
                              ELSE (NVL(ITE.VLRTOT,0) - NVL(ITE.VLRREPRED,0) - NVL(ITE.VLRDESC,0)) END   AS VLREFD
   , ITE.VLRTOT AS VLRITELIQ
   , 0 AS BASEICMS
   , 0 AS VLRICMS
   , 0 AS ICMS_AJUSTE
   , 0 AS BASEDIFAL
   , 0 AS VLRDIFAL
   , 0 AS VLRFCP
   , 0 AS BASEIPI
   , 0 AS VLRIPI
   , NVL((SELECT SUM(DIN.BASERED)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS BASE_PIS

   , NVL((SELECT MAX(DIN.CST)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS CST_PIS

	, NVL((SELECT SUM(DIN.VALOR)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 6),0) AS VLR_PIS
	,0 AS VLR_PISIMP

	, NVL((SELECT SUM(DIN.BASERED)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS BASE_COFINS

	, NVL((SELECT MAX(DIN.CST)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS CST_COFINS

	, NVL((SELECT SUM(DIN.VALOR)

			FROM TGFDIN DIN

			WHERE DIN.NUNOTA = ITE.NUNOTA

				AND DIN.SEQUENCIA = ITE.SEQUENCIA

				AND DIN.CODIMP = 7),0) AS VLR_COFINS
	,0 AS VLR_COFINSIMP
    ,0 AS BASE_ST
    ,0 AS ALIQ_ST
    ,0 AS VLR_ST
    ,0 AS VLR_FEM_ICMS_ST
    ,0 AS VLR_FEM_ICMS_OP
    ,0 AS FRETE_ITEM
    ,0 AS DIF_VAL_IPI
    ,CID.NOMECID
    ,UF.UF
    ,CAB.CHAVENFE
    ,0 AS NUMNOTA_DEVOLUCAO
    ,0 AS VLRTOT_DEVOLUCAO
    ,0 AS VLRBCICMS_DEVOLUCAO
    ,0 AS VLRICMS_DEVOLUCAO
    ,0 AS VLRBCIPI_DEVOLUCAO
    ,0 AS VLRIPI_DEVOLUCAO
FROM TGFLIS LIS

INNER JOIN TGFITE ITE
    ON ITE.NUNOTA = LIS.NUNOTA 
     AND ITE.SEQUENCIA = LIS.SEQUENCIA 

INNER JOIN TGFCAB CAB 
    ON CAB.NUNOTA = LIS.NUNOTA

INNER JOIN TGFTOP TPO 
    ON TPO.CODTIPOPER = CAB.CODTIPOPER
      AND TPO.DHALTER = CAB.DHTIPOPER

INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = CAB.CODPARC

INNER JOIN TSICID CID 
    ON CID.CODCID = PAR.CODCID 


INNER JOIN TGFPRO PRO 
    ON PRO.CODPROD = ITE.CODPROD 

INNER JOIN TSIUFS UF 
    ON UF.CODUF = CID.UF

WHERE EXISTS(
	      (SELECT
	        DISTINCT
	        LIS1.NUNOTA
	      FROM
	        TGFLIS LIS1
	      WHERE
	            LIS.DTMOV  >= :P_PERIODO.INI
	        AND LIS1.DTMOV <= :P_PERIODO.FIN
	        AND LIS1.CODEMP IN (1,2)
	        AND LIS1.ORIGEM <> 'F'
	        AND ((LIS1.ORIGEM = 'E' AND LIS1.ENTSAI = 'E' AND
	               EXISTS (SELECT 1 FROM TGFDIN D1 WHERE D1.NUNOTA = LIS1.NUNOTA AND D1.CODIMP IN (6,7)
	                       AND (((D1.VALOR <> 0 OR NVL(D1.VLRCRED,0) <> 0) AND
	                             D1.CST IN (49,50,51,52,53,54,55,56,60,61,62,63,64,65,66))
	                            ))) OR
	              (LIS1.ORIGEM = 'E' AND LIS1.ENTSAI = 'S' AND
	               EXISTS (SELECT 1 FROM TGFDIN WHERE NUNOTA = LIS1.NUNOTA AND CODIMP IN (6,7)))
	            )
	        AND NOT EXISTS (SELECT LIV.NUNOTA FROM TGFLIV LIV WHERE LIV.NUNOTA = LIS1.NUNOTA AND LIV.ORIGEM = LIS1.ORIGEM)
	        AND LIS1.NUNOTA = LIS.NUNOTA
			AND LIS1.CODCFPS  >= :P_CODCFOPINI
			AND LIS1.CODCFPS  <= :P_CODCFOPFIN
			
	      )
	  )
	  AND LIS.CODEMP IN (1,2)
	  AND LIS.ORIGEM = 'E'
