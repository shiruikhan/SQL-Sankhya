SELECT TRUNC(CAB.DTNEG) DTNEG,
	COUNT(DISTINCT CAB.NUNOTA) AS CONTADORATENDIMENTO,
	COUNT(ITE.CODPROD) AS CONTADORITEM,
	SUM(ITE.QTDNEG) AS CONTADORQUANTIDADES,
    CUS.DESCRCENCUS,
	CAB.CODCENCUS
FROM TGFITE ITE 
	LEFT JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA 
	LEFT JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD 
	LEFT JOIN TSICUS CUS ON CAB.CODCENCUS = CUS.CODCENCUS
WHERE (CAB.TIPMOV <> 'J') 
	AND (ITE.STATUSNOTA = 'L') 
	AND (CAB.AD_NUMPS IS NULL)
	AND CAB.CODTIPOPER NOT IN (409)
    AND CAB.CODUSUINC = 81    
    AND (TRUNC(CAB.DTNEG) >= :P_PERIODO.INI AND TRUNC(CAB.DTNEG) <= :P_PERIODO.FIN) 
	AND ITE.ATUALESTOQUE = -1
GROUP BY TRUNC(CAB.DTNEG),
    CUS.DESCRCENCUS,
	CAB.CODCENCUS
ORDER BY TRUNC(CAB.DTNEG), CUS.DESCRCENCUS
