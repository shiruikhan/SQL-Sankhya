SELECT CAB.CODVEND || ' - ' || VEN.APELIDO AS VENDEDOR,
	sum(CAB.VLRNOTA + NVL(CAB.VLROUTROS,0) + NVL(AD_VLROUTROSFRETE,0)) AS VALORTOTAL
FROM TGFCAB CAB
	INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
WHERE CAB.DTNEG >= :P_PERIODO.INI
	AND CAB.DTNEG <= :P_PERIODO.FIN
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
	AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124)
	AND (:P_CODVEND IS NULL OR CAB.CODVEND = :P_CODVEND)
GROUP BY CAB.CODVEND || ' - ' || VEN.APELIDO
