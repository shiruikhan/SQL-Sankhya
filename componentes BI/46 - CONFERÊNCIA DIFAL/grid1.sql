SELECT 
		LIV.CODEMP,
		CAB.CODTIPOPER,
		CAB.CODPARC,
		PAR.NOMEPARC,
		LIV.NUMNOTA, 
		ITE.NUNOTA, 
		LIV.SERIENOTA, 
		LIV.DTDOC,
		LIV.DHMOV,
		ITE.CODPROD, 
		PRO.DESCRPROD,
		PRO.NCM,
		LIV.VLRCTB, 
		
		(SELECT DIF.BASEAJD
		  FROM VGF_CALDIFAL_SPARK DIF
         WHERE DIF.NUNOTA = LIV.NUNOTA 
           AND DIF.SEQUENCIA = LIV.SEQUENCIA 
	    ) AS BASEAJD,
		
		(SELECT DIF.ICMS
		  FROM VGF_CALDIFAL_SPARK DIF
         WHERE DIF.NUNOTA = LIV.NUNOTA 
           AND DIF.SEQUENCIA = LIV.SEQUENCIA 
	    ) AS ICMS,

		ITE.ALIQICMS,
		
		(SELECT DIF.DIFAL
		  FROM VGF_CALDIFAL_SPARK DIF
         WHERE DIF.NUNOTA = LIV.NUNOTA 
           AND DIF.SEQUENCIA = LIV.SEQUENCIA 
	    ) AS DIFAL,	
	
		LIV.DIFICMS, 
		LIV.CODCFO, 
		LIV.UFORIGEM, 
		LIV.UFDESTINO, 
		AJD.VLRICMS AS VLRICMS195,
		(CASE WHEN NVL(ROUND(LIV.DIFICMS,2),0)-NVL(ROUND(AJD.VLRICMS,2),0)<>0 THEN 0 ELSE 1 END) AS CONFERENCIA
		
FROM TGFLIV LIV,
     TGFPAR PAR,
	 TGFITE ITE, 
	 TGFPRO PRO, 
	 TGFAJD AJD,
	 TGFCAB CAB


WHERE   LIV.NUNOTA = ITE.NUNOTA
	AND LIV.SEQUENCIA = ITE.SEQUENCIA
	AND LIV.NUNOTA = AJD.NUNOTA
    AND CAB.CODPARC = PAR.CODPARC
	AND LIV.SEQUENCIA = AJD.SEQUENCIA
	AND ITE.CODPROD = PRO.CODPROD
	AND ITE.NUNOTA = CAB.NUNOTA
	AND TRUNC(DHMOV) BETWEEN :DTINICIO AND :DTFIM
	AND (LIV.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL )
	AND LIV.DIFICMS <> 0 
	
ORDER BY 1, 2, LIV.SEQUENCIA
