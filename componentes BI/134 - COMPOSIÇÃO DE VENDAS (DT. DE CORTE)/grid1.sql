SELECT V.CODPROD AS PRODUTO,
	SUM(V.QTDNEG) AS QTDNEG,
	V.PARCEIRO
FROM (SELECT PRO.AD_AGRUPADOR AS CODPROD,
			SUM(ITE.QTDNEG) AS QTDNEG,
			CAB.CODPARC || ' - ' || PAR.NOMEPARC AS PARCEIRO
		FROM TGFITE ITE
			INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA AND CAB.TIPMOV = 'P' AND CAB.PENDENTE = 'S'
			INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD AND SUBSTR(PRO.CODPROD,1,1) = '3'
			INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
		WHERE CAB.DTPREVENT <= :P_DTCORTE
		GROUP BY PRO.AD_AGRUPADOR,
			CAB.CODPARC || ' - ' || PAR.NOMEPARC
		ORDER BY PRO.AD_AGRUPADOR) V
GROUP BY V.CODPROD,
	V.PARCEIRO
ORDER BY V.CODPROD
