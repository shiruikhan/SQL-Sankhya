/*********BOLETO EM ABERTO****/
SELECT 
     FIN.NUFIN
	,FIN.NUNOTA
    ,FIN.NUMNOTA
	,FIN.CODPARC
	,PAR.NOMEPARC
	,FIN.DTNEG 
	,FIN.DTVENC
    ,SUM(F.VLRLIQUIDO) AS TOTAL

FROM TGFFIN FIN 

 INNER JOIN TSICTA CTA 
    ON CTA.CODCTABCOINT = FIN.CODCTABCOINT

 INNER JOIN VGFFIN F
    ON F.NUFIN = FIN.NUFIN
 
 INNER JOIN TGFPAR PAR 
	ON PAR.CODPARC = FIN.CODPARC

WHERE FIN.DHBAIXA IS NULL 
 AND  FIN.RECDESP = 1
 AND  FIN.PROVISAO = 'N'
 AND  FIN.CODTIPTIT = 4
 AND  FIN.CODCTABCOINT = :A_CONTA
 AND  :A_TIPO = 'A VENCER'
 AND  FIN.DTVENC >= TRUNC(SYSDATE)
 AND  FIN.NOSSONUM IS NOT NULL
 AND  FIN.DTNEG <= TRUNC(SYSDATE) - 1


GROUP BY 
     FIN.NUFIN
	,FIN.NUNOTA
    ,FIN.NUMNOTA
	,FIN.CODPARC
	,PAR.NOMEPARC
	,FIN.DTNEG 
	,FIN.DTVENC
/*********BOLETO VENCIDO****/
