SELECT 	
		 FIN.NUNOTA 
		,FIN.NUFIN
	    ,FIN.CODPARC 
		,PAR.NOMEPARC 
		,FIN.DTENTSAI
		,FIN.DHBAIXA
		,FIN.VLRDESDOB
		,FIN.VLRJURO
		,FIN.VLRDESC
		,FIN.VLRMULTA
		,FIN.VLRBAIXA	
        FROM TGFFIN FIN 
		INNER JOIN TGFPAR PAR 
			ON PAR.CODPARC = FIN.CODPARC 
      WHERE FIN.CODPARC = :A_CODPARC
        AND TRUNC(FIN.DHBAIXA)  >= :P_DTCORTE.INI
		AND TRUNC(FIN.DHBAIXA) <= :P_DTCORTE.FIN
        AND FIN.RECDESP = -1
		AND FIN.PROVISAO = 'N'
        AND FIN.CODEMP  IN :P_CODEMP
    AND FIN.CODTIPOPER NOT IN (1306,1200,1201)
