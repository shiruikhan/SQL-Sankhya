WITH VALOROPCTGFTOP (NUCAMPO,NOMECAMPO,VALOR,OPCAO) AS (	
	SELECT 
		CAM.NUCAMPO,
		CAM.NOMECAMPO,
		OPC.VALOR,
		OPC.OPCAO 
	FROM TDDCAM CAM
	INNER JOIN TDDOPC OPC ON(OPC.NUCAMPO = CAM.NUCAMPO)
	WHERE CAM.NOMETAB = 'TGFTOP'
	AND CAM.NUCAMPO IN (SELECT OPC.NUCAMPO FROM TDDOPC OPC WHERE OPC.NUCAMPO = CAM.NUCAMPO
))	
SELECT
	 TPO.CODTIPOPER,
	 TPO.DESCROPER,
	 TPO.DHALTER,
	 TPO.GRUPO,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'CLASSIFICMS' AND V.VALOR = TPO.CLASSIFICMS) CLASSIFICMS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'TEMICMS' AND V.VALOR = TPO.TEMICMS) TEMICMS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'SOMASUBST' AND V.VALOR = TPO.SOMASUBST) SOMASUBST,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'CALCDIFICMS' AND V.VALOR = TPO.CALCDIFICMS) CALCDIFICMS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'CALCFCPINT' AND V.VALOR = TPO.CALCFCPINT) CALCFCPINT,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'ATUALFIN' AND V.VALOR = TPO.ATUALFIN) ATUALFIN,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'ATUALEST' AND V.VALOR = TPO.ATUALEST) ATUALEST,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'ATUALLIVFIS' AND V.VALOR = TPO.ATUALLIVFIS) ATUALLIVFIS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'ATUALLIVFIS' AND V.VALOR = TPO.ATUALLIVISS) ATUALLIVISS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'TIPIPI' AND V.VALOR = TPO.TIPIPI) TIPIPI,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'TEMIPI' AND V.VALOR = TPO.TEMIPI) TEMIPI,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'SOMARIPI' AND V.VALOR = TPO.SOMARIPI) SOMARIPI,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'IPIEMBUT' AND V.VALOR = TPO.IPIEMBUT) IPIEMBUT,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'TIPICMS' AND V.VALOR = TPO.TIPICMS) TIPICMS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'IPIINCICMS' AND V.VALOR = TPO.IPIINCICMS) IPIINCICMS,
	 TPO.CODCFPS,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'GERAR1400SPED' AND V.VALOR = TPO.GERAR1400SPED) GERAR1400SPED,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'VALTOTNOTAGERLIV' AND V.VALOR = TPO.VALTOTNOTAGERLIV) VALTOTNOTAGERLIV,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'CAT1799SPCCO' AND V.VALOR = TPO.CAT1799SPCCO) CAT1799SPCCO,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'SEMCREDIPIST' AND V.VALOR = TPO.SEMCREDIPIST) SEMCREDIPIST,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'DESCONSLCDPR' AND V.VALOR = TPO.DESCONSLCDPR) DESCONSLCDPR,
 	 TPO.CODCTACTBEFD,  
	 TPO.NATOPERSPED,
	 (SELECT V.OPCAO FROM VALOROPCTGFTOP V WHERE V.NOMECAMPO = 'TIPMOVBEMSPED' AND V.VALOR = TPO.TIPMOVBEMSPED) TIPMOVBEMSPED
FROM TGFTOP TPO
WHERE TPO.CODTIPOPER = (SELECT FIN.CODTIPOPER FROM TGFFIN FIN WHERE FIN.NUFIN = :A_NUFIN)
  AND TPO.DHALTER = (SELECT FIN.DHTIPOPER FROM TGFFIN FIN WHERE FIN.NUFIN = :A_NUFIN)
