WITH EstBase AS (
    SELECT EST.CODPROD, SUM(EST.ESTOQUE) AS ESTOQUE
    FROM TGFEST EST
    WHERE EST.CODLOCAL = 109/* AND EST.CODEMP = 1*/
    GROUP BY EST.CODPROD
),
PlanProcProd AS (
    SELECT PROC.IDIPROC, IPA.CODPRODPA AS CODPROD, SUM(IPA.QTDPRODUZIR) AS QTD_PROD
    FROM TPRIPROC PROC
    INNER JOIN TPRIPA IPA ON IPA.IDIPROC = PROC.IDIPROC
    WHERE PROC.STATUSPROC IN ('A', 'P2')
		AND COALESCE(PROC.DTPREVENT, TRUNC(PROC.DHINC) + 7) <= CAST(:P_DATAPRD AS DATE)
    GROUP BY PROC.IDIPROC, IPA.CODPRODPA
),
EntregasProc AS (
    SELECT C.IDIPROC, I.CODPROD, SUM(I.QTDNEG) AS QTD_ENTREGUE
    FROM TGFCAB C
    INNER JOIN TGFITE I ON I.NUNOTA = C.NUNOTA
    WHERE C.TIPMOV = 'F'
		AND I.ATUALESTOQUE = 1
		AND C.CODTIPOPER <> 900
    GROUP BY C.IDIPROC, I.CODPROD
),
PlanejadoPorProd AS (
    SELECT P.CODPROD, SUM(P.QTD_PROD - COALESCE(E.QTD_ENTREGUE, 0)) AS PLANEJADO_ESTOQUE
    FROM PlanProcProd P
		LEFT JOIN EntregasProc E ON E.IDIPROC = P.IDIPROC AND E.CODPROD = P.CODPROD
    GROUP BY P.CODPROD
),
PedidosEstoquePorProd AS (
    SELECT M.CODPROD, SUM(M.QTDPREV) AS PEDIDO_ABERTO_ESTOQUE
    FROM TGMMET M
    WHERE M.DTREF = ADD_MONTHS(CAST(:P_DATAPRD AS DATE), -1)
    GROUP BY M.CODPROD
),
PedidosVendaPorProd AS (
    SELECT ITE.CODPROD, SUM(ITE.QTDNEG - ITE.QTDENTREGUE) AS PEDIDO_ABERTO_VENDA
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
    WHERE ITE.PENDENTE = 'S'
		AND CAB.PENDENTE = 'S'
		AND CAB.TIPMOV = 'P'
		AND CAB.CODTIPOPER <> 900
		AND CAB.DTPREVENT <= CAST(:P_DATA AS DATE)
    GROUP BY ITE.CODPROD
),
VendasAnoPorProd AS (
    SELECT 
        PRO.CODPROD,
        -- Calcula a quantidade considerando Venda como POSITIVA e Devolução como NEGATIVA
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 12 
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M12_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 11 
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M11_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 10 
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M10_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 9  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M09_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 8  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M08_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 7  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M07_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 6  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M06_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 5  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M05_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 4  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M04_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 3  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M03_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 2  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M02_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 1  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS M01_RETRO,
        SUM(CASE WHEN MONTHS_BETWEEN(TRUNC(CAST(:P_DATA AS DATE), 'MM'), TRUNC(CAB.DTNEG, 'MM')) = 0  
                 THEN (CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) ELSE 0 END) AS MES_ATUAL,
        SUM(CASE WHEN CAB.TIPMOV = 'V' THEN ITE.QTDNEG ELSE -ITE.QTDNEG END) AS TOTAL_12M
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
    INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
    WHERE (
            (CAB.TIPMOV = 'V' AND CAB.CODTIPOPER IN (1100,2200,1111,1190,1124,2202))
            OR 
            (CAB.TIPMOV = 'D' AND CAB.CODTIPOPER IN (1200,1201,1206,1216,1217,1272))
          )
		AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
		AND CAB.DTNEG >= ADD_MONTHS(TRUNC(CAST(:P_DATA AS DATE), 'MM'), -12)
		AND CAB.DTNEG < ADD_MONTHS(TRUNC(CAST(:P_DATA AS DATE), 'MM'), 1)
		AND SUBSTR(TO_CHAR(PRO.CODPROD),1,1) = '3'
    GROUP BY PRO.CODPROD
),
EstoqueProduto AS (
    SELECT 
        PRO.AD_AGRUPADOR,
        PRO.AD_FAMILIA,
        PRO.CODGRUPOPROD,
        GRU.DESCRGRUPOPROD,
        COALESCE(PRO.ESTMIN, 0) AS ESTMIN,
        COALESCE(PRO.ESTMAX, 0) AS ESTMAX,
        COALESCE(EST.ESTOQUE, 0) AS ESTOQUE,
        COALESCE(PRO.AD_LINHA, 'Sem info') AS LINHA,
        COALESCE(PL.PLANEJADO_ESTOQUE, 0) AS PLANEJADO_ESTOQUE,
        COALESCE(PE.PEDIDO_ABERTO_ESTOQUE, 0) AS PEDIDO_ABERTO_ESTOQUE,
        COALESCE(PV.PEDIDO_ABERTO_VENDA, 0) AS PEDIDO_ABERTO_VENDA,
        COALESCE(VEN.M12_RETRO, 0) AS M12_RETRO,
        COALESCE(VEN.M11_RETRO, 0) AS M11_RETRO,
        COALESCE(VEN.M10_RETRO, 0) AS M10_RETRO,
        COALESCE(VEN.M09_RETRO, 0) AS M09_RETRO,
        COALESCE(VEN.M08_RETRO, 0) AS M08_RETRO,
        COALESCE(VEN.M07_RETRO, 0) AS M07_RETRO,
        COALESCE(VEN.M06_RETRO, 0) AS M06_RETRO,
        COALESCE(VEN.M05_RETRO, 0) AS M05_RETRO,
        COALESCE(VEN.M04_RETRO, 0) AS M04_RETRO,
        COALESCE(VEN.M03_RETRO, 0) AS M03_RETRO,
        COALESCE(VEN.M02_RETRO, 0) AS M02_RETRO,
        COALESCE(VEN.M01_RETRO, 0) AS M01_RETRO,
        COALESCE(VEN.MES_ATUAL, 0) AS MES_ATUAL,
        COALESCE(VEN.TOTAL_12M, 0) AS TOTAL_12M,
        (
            OBTEM_TOTAIS_MRP(
                (SELECT MAX(M.NUMPS) FROM TPRMPS M WHERE TRUNC(M.DTINICMPS, 'MM') = TRUNC(CAST(:P_DATAPRD AS DATE), 'MM')), 
                PRO.CODPROD, 
                0, 
                'M'
            ) 
            - OBTEM_TOTAIS_MRP(
                (SELECT MAX(M.NUMPS) FROM TPRMPS M WHERE TRUNC(M.DTINICMPS, 'MM') = TRUNC(CAST(:P_DATAPRD AS DATE), 'MM')), 
                PRO.CODPROD, 
                0, 
                'P'
            ) 
            + COALESCE(
                (SELECT SUM(SALDO) FROM VGFSALDOMRP WHERE CODPROD = PRO.CODPROD AND DTREF < TRUNC(CAST(:P_DATAPRD AS DATE), 'MM')), 
                0
            )
        ) AS SALDO_MRP
    FROM TGFPRO PRO
    INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
		LEFT JOIN EstBase EST ON EST.CODPROD = PRO.CODPROD
		LEFT JOIN PlanejadoPorProd PL ON PL.CODPROD = PRO.CODPROD
		LEFT JOIN PedidosEstoquePorProd PE ON PE.CODPROD = PRO.CODPROD
		LEFT JOIN PedidosVendaPorProd PV ON PV.CODPROD = PRO.CODPROD
		LEFT JOIN VendasAnoPorProd VEN ON VEN.CODPROD = PRO.CODPROD
    WHERE PRO.USOPROD = 'V'
		AND PRO.ATIVO = 'S'
		AND (COALESCE(PRO.AD_OBSOLETO, 'N') = 'N'
		   OR EXISTS (
			   SELECT 1
			   FROM TGFEST EST2
			   WHERE EST2.CODPROD = PRO.CODPROD
				 AND EST2.ESTOQUE > 0
				 AND EST2.CODLOCAL = 109
		   ))
)
-- SELECT FINAL AGRUPADO POR AD_AGRUPADOR
SELECT 
    AD_AGRUPADOR,
    MAX(AD_FAMILIA) AS AD_FAMILIA,
    MAX(CODGRUPOPROD) AS CODGRUPOPROD,
    MAX(DESCRGRUPOPROD) AS DESCRGRUPOPROD,
    SUM(ESTMIN) AS ESTMIN,
    SUM(ESTMAX) AS ESTMAX,
    SUM(ESTOQUE) AS ESTOQUE,
    (CASE WHEN LINHA = '1' THEN 'Linha 1' WHEN LINHA = '2' THEN 'Linha 2' ELSE 'Sem info' END) AS LINHA,
    SUM(PLANEJADO_ESTOQUE) AS PLANEJADO_ESTOQUE,
    SUM(PEDIDO_ABERTO_ESTOQUE) AS PEDIDO_ABERTO_ESTOQUE,
    SUM(PEDIDO_ABERTO_VENDA) AS PEDIDO_ABERTO_VENDA,
    SUM(SALDO_MRP) AS SALDO_MRP,
    SUM(M12_RETRO) AS QTD_M12_RETRO,
    SUM(M11_RETRO) AS QTD_M11_RETRO,
    SUM(M10_RETRO) AS QTD_M10_RETRO,
    SUM(M09_RETRO) AS QTD_M09_RETRO,
    SUM(M08_RETRO) AS QTD_M08_RETRO,
    SUM(M07_RETRO) AS QTD_M07_RETRO,
    SUM(M06_RETRO) AS QTD_M06_RETRO,
    SUM(M05_RETRO) AS QTD_M05_RETRO,
    SUM(M04_RETRO) AS QTD_M04_RETRO,
    SUM(M03_RETRO) AS QTD_M03_RETRO,
    SUM(M02_RETRO) AS QTD_M02_RETRO,
    SUM(M01_RETRO) AS QTD_M01_RETRO,
    SUM(MES_ATUAL) AS QTD_MES_ATUAL,
    SUM(TOTAL_12M) AS TOTAL_VENDAS_12M,
	-- COLUNA DE PICO DE VENDAS
    GREATEST(
        SUM(M12_RETRO), SUM(M11_RETRO), SUM(M10_RETRO), SUM(M09_RETRO), 
        SUM(M08_RETRO), SUM(M07_RETRO), SUM(M06_RETRO), SUM(M05_RETRO), 
        SUM(M04_RETRO), SUM(M03_RETRO), SUM(M02_RETRO), SUM(M01_RETRO), 
        SUM(MES_ATUAL)
    ) AS PICO_VENDAS,
    (SUM(PLANEJADO_ESTOQUE) + SUM(SALDO_MRP) + SUM(ESTOQUE)) 
    / 
    NULLIF(ROUND((SUM(M01_RETRO) + SUM(M02_RETRO) + SUM(M03_RETRO)) / 3, 0), 0) AS SALDOVENDA3M
FROM EstoqueProduto
WHERE AD_AGRUPADOR IS NOT NULL
GROUP BY 
    AD_AGRUPADOR, LINHA
ORDER BY 
    AD_AGRUPADOR