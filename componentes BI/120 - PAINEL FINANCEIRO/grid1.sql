SELECT 
	FIN.NUFIN,
	FIN.NUNOTA,
	FIN.NUMNOTA,
	FIN.DTNEG,
	FIN.DESDOBRAMENTO,
	FIN.CODTIPTIT,
	TIT.DESCRTIPTIT,
	FIN.DTVENC,
	FIN.DHBAIXA,
	FIN.CODPARC,
	PAR.RAZAOSOCIAL,
	FIN.VLRDESDOB,
	FIN.VLRJURO,
	FIN.VLRDESC,
	V.DESPCART,
	(SELECT C.CODCTABCO FROM TSICTA C WHERE C.CODCTABCOINT = FIN.CODCTABCOINT) AS CODCTABCOINT,
	V.CARTAODESC,
	V.VLRLIQUIDO,
	FIN.CODNAT,
	V.VLRMULTA,
	(SELECT M.DHCONCILIACAO FROM TGFMBC M WHERE M.NUBCO = FIN.NUBCO) AS DHCONCIL,
	FIN.VLRVARCAMBIAL,
	(SELECT DISTINCT N.DESCRNAT FROM TGFNAT N WHERE N.CODNAT = FIN.CODNAT) AS NATUREZA,
    (SELECT MAX(T.DESCROPER) FROM TGFTOP T WHERE T.CODTIPOPER = FIN.CODTIPOPER) AS DESCROPER,
    FIN.VLRMOEDABAIXA,
	FIN.VLRBAIXA

FROM TGFFIN FIN

	INNER JOIN TGFPAR PAR 
		ON FIN.CODPARC = PAR.CODPARC

	INNER JOIN VGFFIN V 
		ON FIN.NUFIN = V.NUFIN

	INNER JOIN TGFTIT TIT 
		ON FIN.CODTIPTIT = TIT.CODTIPTIT
	
	INNER JOIN TGFMBC MBC 
		ON MBC.NUBCO = FIN.NUBCO

WHERE FIN.RECDESP = :P_RECDESP
	AND FIN.DHBAIXA IS NOT NULL
	AND FIN.PROVISAO = 'N'
	AND MBC.DHCONCILIACAO >= :P_DTVENC.INI
	AND MBC.DHCONCILIACAO <= :P_DTVENC.FIN
	AND (:P_CODEMP IS NULL OR FIN.CODEMP = :P_CODEMP)
	AND (FIN.CODNAT IS NULL OR FIN.CODNAT IN :P_CODNAT)

ORDER BY FIN.DTVENC
