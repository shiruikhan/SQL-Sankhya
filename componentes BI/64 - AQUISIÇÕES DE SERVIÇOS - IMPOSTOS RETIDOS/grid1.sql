SELECT  CAB.NUNOTA,
        CAB.NUMNOTA,
        CAB.DTENTSAI,
	    CAB.CODPARC || ' - ' || PAR.NOMEPARC AS PARCEIRO,
        SUM(ITE.VLRTOT - ITE.VLRDESC) AS VLRCTB,
		SUM(CASE WHEN CAB.ISSRETIDO = 'S' THEN CAB.VLRISS ELSE 0 END) +  
		(SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 4) AS ISSRETIDO,
		 SUM(CASE WHEN CAB.IRFRETIDO = 'S' THEN CAB.VLRIRF ELSE 0 END) +  
		(SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 8) AS IRFRETIDO,
		 ((SELECT NVL(SUM(DIN.VALOR), 0)
		  FROM	TGFDIN DIN
		  WHERE	DIN.NUNOTA = CAB.NUNOTA
		  AND	DIN.CODIMP = 5
		  AND	DIN.TIPO = -1) +
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 5)) AS INSSRETIDO,
		 ((SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 6) +
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 7) +
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 9)) AS PCCRETIDO,
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 6) AS PISRETIDO,
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 7) AS COFINSRETIDO,
		 (SELECT NVL(SUM(IMP.VALOR), 0)
		 FROM	TGFIMN IMP
		 WHERE	IMP.NUNOTA = CAB.NUNOTA
		 AND    IMP.TIPOIMPOSTO = 9) AS CSLLRETIDO,
		 CAB.VLRNOTA
		 


FROM    TGFCAB CAB, TGFPAR PAR, TGFITE ITE, TGFTOP OPE


WHERE   CAB.CODPARC = PAR.CODPARC
AND     CAB.NUNOTA = ITE.NUNOTA
AND		CAB.CODTIPOPER = OPE.CODTIPOPER
AND		CAB.DHTIPOPER = OPE.DHALTER
AND		OPE.ATUALLIVISS = 'E'
AND     CAB.STATUSNOTA = 'L'
AND     CAB.CODEMP <> 501
AND     CAB.CODEMP IN :CODEMP
AND     CAB.DTENTSAI BETWEEN :PERIODO.INI AND :PERIODO.FIN
AND     (CAB.CODPARC IN :CABCODPARC OR :CABCODPARC IS NULL)

GROUP BY    CAB.NUNOTA,
            CAB.NUMNOTA,
            CAB.DTENTSAI,
			CAB.CODPARC,
			PAR.NOMEPARC,
			CAB.VLRNOTA

ORDER  BY 	3, 2
