SELECT P.NUMERO AS QTDTOTAL, Q.QTD AS QTDATUAL, ROUND(CASE WHEN Q.QTD IS NULL OR Q.QTD = 0 THEN 0 ELSE Q.QTD * 100 / CASE WHEN P.NUMERO IS NULL OR P.NUMERO = 0 THEN Q.QTD ELSE P.NUMERO END END,0) AS PERCCOMPL
  FROM AD_PARAM P,
       (SELECT COUNT(1) AS QTD
         FROM TGFCAB
       WHERE TIPMOV = 'C' 
		AND STATUSNOTA= 'L') Q
 WHERE P.CHAVE = 'QTDTGFNDC'
