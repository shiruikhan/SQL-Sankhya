create or replace NONEDITIONABLE TRIGGER TRG_INCDEVCH_SPARK 
BEFORE INSERT OR DELETE
ON TGFMDC
FOR EACH ROW
 
DECLARE
 
	/*==================== VARIÁVEIS ====================*/
	V_DHTIPOPER TGFTOP.DHALTER %TYPE;
	V_CODTIPOPER     NUMBER := 1222;
    V_CODTIPVENDA    NUMBER := 24;
	V_NUNOTA TGFCAB.NUNOTA %TYPE;
	V_NUFIN TGFFIN.NUFIN %TYPE;
    V_DHTIPVENDA TGFCAB.DHTIPVENDA%TYPE;

BEGIN

IF INSERTING 
THEN 
	/*==================== BUSCA DADOS AUXILIARES ====================*/
	SELECT MAX(DHALTER)
	INTO V_DHTIPOPER
	FROM TGFTOP
	WHERE CODTIPOPER = V_CODTIPOPER;

    SELECT MAX(DHALTER) INTO V_DHTIPVENDA FROM TGFTPV WHERE CODTIPVENDA = V_CODTIPVENDA;

	/*==================== LOOP PRINCIPAL ====================*/
	FOR

	R_DADOS IN (
			SELECT CAB.NUNOTA
				,CAB.SERIENOTA AS SERIE
				,CAB.CODEMP
				,CAB.CODCENCUS
				,CAB.NUMNOTA
				,CAB.DTNEG
				,CAB.CODEMPNEGOC
				,CAB.CODPARC
				,CAB.RATEADO
				,CAB.CODVEICULO
				,CAB.CODTIPVENDA
				,CAB.DHTIPVENDA
				,CAB.CODVEND
				,CAB.COMISSAO
				,CAB.CODMOEDA
				,CAB.CODOBSPADRAO
				,CAB.VLRSEG
				,CAB.VLRICMSSEG
				,CAB.VLRDESTAQUE
				,CAB.VLRJURO
				,CAB.VLRVENDOR
				,CAB.VLROUTROS
				,CAB.VLREMB
				,CAB.VLRICMSEMB
				,CAB.VLRDESCSERV
				,CAB.IPIEMB
				,CAB.TIPIPIEMB
				,CAB.VLRDESCTOT
				,CAB.VLRDESCTOTITEM
				,CAB.VLRFRETE
				,CAB.ICMSFRETE
				,CAB.BASEICMSFRETE
				,CAB.TIPFRETE
				,CAB.VLRNOTA
				,CAB.CODPARCTRANSP
				,CAB.QTDVOL
				,CAB.PENDENTE
				,CAB.BASEICMS
				,CAB.VLRICMS
				,CAB.BASEIPI
				,CAB.VLRIPI
				,CAB.ISSRETIDO
				,CAB.BASEISS
				,CAB.VLRISS
				,CAB.APROVADO
				,CAB.STATUSNOTA
				,CAB.IRFRETIDO
				,CAB.VLRIRF
				,CAB.DTALTER
				,CAB.CODPARCDEST
				,CAB.VLRSUBST
				,CAB.BASESUBSTIT
				,CAB.CODPROJ
				,CAB.NUMCONTRATO
				,CAB.BASEINSS
				,CAB.VLRINSS
				,CAB.VLRREPREDTOT
				,CAB.PERCDESC
				,CAB.CODPARCREMETENTE
				,CAB.CODPARCCONSIGNATARIO
				,CAB.CODPARCREDESPACHO
				,CAB.CODNAT
				,CAB.TROCO
				,CAB.CODUSUCOMPRADOR
				,CAB.CIF_FOB
				,CAB.OBSERVACAO
				,CAB.CODUSU
				,CAB.CODUSUINC
				,F.VLRDESDOB
                ,F.DHMOV
				,:NEW.NUDEV AS AD_NUMDEVCH
			FROM TGFFIN FIN
			INNER JOIN TGFTRC TRC 
				ON TRC.NUBCODEST = FIN.NUBCO
			INNER JOIN TGFFIN F 
				ON F.NUFIN = TRC.NUFIN
			INNER JOIN TGFCAB CAB 
				ON CAB.NUNOTA = F.NUNOTA
			WHERE FIN.NUFIN = :NEW.NUFINORIG
			) LOOP
		/*==================== GERA CHAVES ====================*/
		V_NUNOTA := SNK_GET_NUNOTA;
		V_NUFIN  := SNK_GET_NUFIN;
		
		/*==================== INSERE CAB ====================*/
	INSERT INTO TGFCAB (
		NUNOTA
		,CODEMP
		,SERIENOTA
		,CODCENCUS
		,NUMNOTA
		,DTNEG
		,CODEMPNEGOC
		,CODPARC
		,RATEADO
		,CODVEICULO
		,CODTIPOPER
		,DHTIPOPER
		,TIPMOV
		,CODTIPVENDA
		,DHTIPVENDA
		,CODVEND
		,COMISSAO
		,CODMOEDA
		,CODOBSPADRAO
		,VLRSEG
		,VLRICMSSEG
		,VLRDESTAQUE
		,VLRJURO
		,VLRVENDOR
		,VLROUTROS
		,VLREMB
		,VLRICMSEMB
		,VLRDESCSERV
		,IPIEMB
		,TIPIPIEMB
		,VLRDESCTOT
		,VLRDESCTOTITEM
		,VLRFRETE
		,ICMSFRETE
		,BASEICMSFRETE
		,TIPFRETE
		,VLRNOTA
		,CODPARCTRANSP
		,QTDVOL
		,PENDENTE
		,BASEICMS
		,VLRICMS
		,BASEIPI
		,VLRIPI
		,ISSRETIDO
		,BASEISS
		,VLRISS
		,APROVADO
		,STATUSNOTA
		,IRFRETIDO
		,VLRIRF
		,DTALTER
		,CODPARCDEST
		,VLRSUBST
		,BASESUBSTIT
		,CODPROJ
		,NUMCONTRATO
		,BASEINSS
		,VLRINSS
		,VLRREPREDTOT
		,PERCDESC
		,CODPARCREMETENTE
		,CODPARCCONSIGNATARIO
		,CODPARCREDESPACHO
		,CODNAT
		,TROCO
		,CODUSUCOMPRADOR
		,CIF_FOB
		,OBSERVACAO
		,CODUSU
		,CODUSUINC
		,AD_NUMDEVCH
		)
	VALUES (
		V_NUNOTA
		,R_DADOS.CODEMP
		,R_DADOS.SERIE
		,R_DADOS.CODCENCUS
		,R_DADOS.NUMNOTA
		,TRUNC(SYSDATE)
		,R_DADOS.CODEMPNEGOC
		,R_DADOS.CODPARC
		,R_DADOS.RATEADO
		,R_DADOS.CODVEICULO
		,V_CODTIPOPER
		,V_DHTIPOPER
		,'D'
		,V_CODTIPVENDA
		,V_DHTIPVENDA
		,R_DADOS.CODVEND
		,R_DADOS.COMISSAO
		,R_DADOS.CODMOEDA
		,R_DADOS.CODOBSPADRAO
		,R_DADOS.VLRSEG
		,R_DADOS.VLRICMSSEG
		,R_DADOS.VLRDESTAQUE
		,R_DADOS.VLRJURO
		,R_DADOS.VLRVENDOR
		,R_DADOS.VLROUTROS
		,R_DADOS.VLREMB
		,R_DADOS.VLRICMSEMB
		,R_DADOS.VLRDESCSERV
		,R_DADOS.IPIEMB
		,R_DADOS.TIPIPIEMB
		,R_DADOS.VLRDESCTOT
		,R_DADOS.VLRDESCTOTITEM
		,R_DADOS.VLRFRETE
		,R_DADOS.ICMSFRETE
		,R_DADOS.BASEICMSFRETE
		,R_DADOS.TIPFRETE
		,R_DADOS.VLRNOTA
		,R_DADOS.CODPARCTRANSP
		,R_DADOS.QTDVOL
		,R_DADOS.PENDENTE
		,R_DADOS.BASEICMS
		,R_DADOS.VLRICMS
		,R_DADOS.BASEIPI
		,R_DADOS.VLRIPI
		,R_DADOS.ISSRETIDO
		,R_DADOS.BASEISS
		,R_DADOS.VLRISS
		,R_DADOS.APROVADO
		,'A'
		,R_DADOS.IRFRETIDO
		,R_DADOS.VLRIRF
		,TRUNC(SYSDATE)
		,R_DADOS.CODPARCDEST
		,R_DADOS.VLRSUBST
		,R_DADOS.BASESUBSTIT
		,R_DADOS.CODPROJ
		,R_DADOS.NUMCONTRATO
		,R_DADOS.BASEINSS
		,R_DADOS.VLRINSS
		,R_DADOS.VLRREPREDTOT
		,R_DADOS.PERCDESC
		,R_DADOS.CODPARCREMETENTE
		,R_DADOS.CODPARCCONSIGNATARIO
		,R_DADOS.CODPARCREDESPACHO
		,R_DADOS.CODNAT
		,R_DADOS.TROCO
		,R_DADOS.CODUSUCOMPRADOR
		,R_DADOS.CIF_FOB
		,'ESTORNO DE DEVOLUÇÃO DE CHEQUE'
		,R_DADOS.CODUSU
		,R_DADOS.CODUSUINC
		,R_DADOS.AD_NUMDEVCH
		);

	/*==================== ITEM ====================*/
	INSERT INTO TGFITE (
		NUNOTA
		,SEQUENCIA
		,CODEMP
		,CODPROD
		,CODLOCALORIG
		,CODCFO
		,QTDNEG
		,QTDENTREGUE
		,QTDCONFERIDA
		,VLRUNIT
		,VLRCUS
		,PENDENTE
		,CODVOL
		,ATUALESTOQUE
		,RESERVA
		,STATUSNOTA
		)
	VALUES (
		V_NUNOTA
		,1
		,501
		,999
		,109
		,0
		,1
		,0
		,0
		,R_DADOS.VLRDESDOB
		,0
		,'N'
		,'UN'
		,0
		,'N'
		,'A'
		);

	/*==================== FINANCEIRO ====================*/
	INSERT INTO TGFFIN (
		 NUFIN
        ,NUNOTA
		,CODEMP
		,NUMNOTA
		,DTNEG
		,DTVENC
		,CODPARC
		,CODTIPOPER
		,DHTIPOPER
		,CODNAT
		,CODCENCUS
		,VLRDESDOB
		,RECDESP
		,ORIGEM
		,DTALTER
        ,DHMOV
		)
	VALUES (
		 V_NUFIN
        ,V_NUNOTA
		,R_DADOS.CODEMP
		,V_NUNOTA
		,TRUNC(SYSDATE)
		,TRUNC(SYSDATE)
		,R_DADOS.CODPARC
		,V_CODTIPOPER
		,V_DHTIPOPER
		,R_DADOS.CODNAT
		,R_DADOS.CODCENCUS
		,R_DADOS.VLRDESDOB
		,- 1
		,'E'
		,TRUNC(SYSDATE)
        ,SYSDATE
		);

	/*==================== CONFIRMA O DOCUMENTO FISCAL ====================*/
	--STP_CONFIRMANOTA2(V_NUNOTA, 'N', - 1);
END
LOOP;
END IF;

/*==================== PARTE DO DELETE - QUANDO POR ALGUM MOTIVO PRECISEI FAZER ====================*/

IF DELETING 
THEN 
	DELETE FROM TGFITE WHERE NUNOTA IN (SELECT NUNOTA FROM TGFCAB WHERE AD_NUMDEVCH  = :OLD.NUDEV);
	DELETE FROM TGFFIN  WHERE NUNOTA IN (SELECT NUNOTA FROM TGFCAB WHERE AD_NUMDEVCH  = :OLD.NUDEV);
	DELETE FROM TGFCAB WHERE AD_NUMDEVCH = :OLD.NUDEV;
END IF;

/*EXCEPTION
	WHEN OTHERS THEN
		RAISE_APPLICATION_ERROR(-20001, 'Erro na Trigger TRG_INCDEVCH_SPARK: ' || SQLERRM);*/
END;