SELECT SER.DTALTER AS DATA,
PROC.NUMPS AS NUMEROPLANO,
IPA.IDIPROC AS NROP,
SUBSTR(SER.SERIE,3,8) AS LOTE
FROM TGFSER SER
INNER JOIN TPRIPA IPA ON SUBSTR(SER.SERIE,3,8) = IPA.NROLOTE 
INNER JOIN TPRIATV ATV ON (IPA.IDIPROC = ATV.IDIPROC AND (ATV.CODUSU = 24 OR ATV.CODUSU = 0 OR ATV.CODUSU = 5 OR ATV.CODUSU = 9))
INNER JOIN TPRIPROC PROC ON IPA.IDIPROC = PROC.IDIPROC
WHERE SER.SERIE = :P_SN AND ATUALESTOQUE = 1
