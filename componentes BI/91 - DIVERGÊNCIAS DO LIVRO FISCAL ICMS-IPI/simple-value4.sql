SELECT 
	COUNT(*) QTDEITENS
FROM
(SELECT
	ITE.CODPROD,
	ITE.SEQUENCIA,
	(SELECT 
		E.DTEXCLUSAO
     FROM TGFLIV_EXC E
     WHERE E.NUNOTA = CAB.NUNOTA
       AND E.SEQUENCIA = ITE.SEQUENCIA
       AND E.DTEXCLUSAO =
                       (SELECT MAX(EE.DTEXCLUSAO)
                          FROM TGFLIV_EXC EE
                         WHERE EE.NUNOTA = E.NUNOTA
                           AND EE.SEQUENCIA = E.SEQUENCIA
                           AND EE.ORIGEM = E.ORIGEM)) AS DTEXCLIV
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON(ITE.NUNOTA = CAB.NUNOTA)
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
INNER JOIN TGFTOP TPO ON(TPO.CODTIPOPER = CAB.CODTIPOPER AND TPO.DHALTER = CAB.DHTIPOPER)
WHERE TPO.ATUALLIVFIS = 'N'            
  AND COALESCE(CAB.STATUSNFE, 'X') <> 'D'
  AND ((COALESCE(TPO.NFE, 'M') NOT IN ('M', 'T') AND CAB.STATUSNFE = 'A')
	   OR
       (COALESCE(TPO.CTE, 'M') NOT IN ('M', 'T') AND CAB.STATUSCTE = 'A')
	   OR 
	   (COALESCE(TPO.NFE, 'M') IN ('M', 'T') AND CAB.STATUSNOTA = 'L')
	   OR 
	   (COALESCE(TPO.CTE, 'M') IN ('M', 'T') AND CAB.STATUSNOTA = 'L'))
  AND (CAB.DTENTSAI BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN)
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
  AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
  AND NOT EXISTS (SELECT 1 FROM TGFLIV LIV WHERE LIV.NUNOTA = ITE.NUNOTA AND LIV.ORIGEM IN ('E', 'A'))
  AND CAB.TIPMOV IN ('C','E','V','D','T')
  AND ITE.SEQUENCIA > 0
)R
WHERE ((CASE WHEN R.DTEXCLIV IS NULL THEN 'N' ELSE 'S' END) = :P_MOSTRAEXCLIV OR :P_MOSTRAEXCLIV = 'T')
