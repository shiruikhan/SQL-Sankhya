SELECT 
    -- 1º Coluna: O Valor Atual (Onde o ponteiro vai ficar) = Vendas - Devoluções
    (SUM(NVL(V.VENDAS, 0)) - SUM(NVL(D.DEVOLUCOES, 0))) AS VENDAS_LIQUIDAS,
    
    -- 2º Coluna: A Meta (O final/alvo do velocímetro)
    SUM(M.VLRMET) AS META_TOTAL,
    
    -- Colunas extras de apoio (caso queira exibir no tooltip do gráfico)
    SUM(NVL(V.VENDAS, 0)) AS VENDAS_BRUTAS,
    SUM(NVL(D.DEVOLUCOES, 0)) AS TOTAL_DEVOLUCOES,
    
    -- Percentual de atingimento global
    CASE 
        WHEN SUM(M.VLRMET) = 0 THEN 0 
        ELSE ROUND(((SUM(NVL(V.VENDAS, 0)) - SUM(NVL(D.DEVOLUCOES, 0))) / SUM(M.VLRMET)) * 100, 2) 
    END AS PERC_ATINGIMENTO

FROM AD_TGSSGM M
LEFT JOIN (
    SELECT 
        COMP.CODSGRU,
        SUM(I.QTDNEG) AS VENDAS
    FROM TGFCAB C
    INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
    INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
    INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
    INNER JOIN AD_TGSISGM COMP ON (
        (COMP.TIPO = 'G' AND G.CODGRUPOPROD = COMP.CODGRUPOPROD) OR
        (COMP.TIPO = 'P' AND G.CODGRUPAI = COMP.CODGRUPOPROD)
    )
    WHERE C.CODTIPOPER IN (1100,2200,1111,1190,1124,2202)
        AND C.TIPMOV = 'V'
        AND P.USOPROD = 'V'
        AND TO_CHAR(C.DTNEG, 'YYYY') = TO_CHAR(:P_ANO)
        AND TO_CHAR(C.DTNEG, 'MM') = :P_MES
        AND COMP.ANO = :P_ANO
        AND COMP.MES = :P_MES
    GROUP BY COMP.CODSGRU
) V ON M.CODSGRU = V.CODSGRU
LEFT JOIN (
    SELECT 
        COMP.CODSGRU,
        SUM(I.QTDNEG) AS DEVOLUCOES
    FROM TGFCAB C
    INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA
    INNER JOIN TGFPRO P ON I.CODPROD = P.CODPROD
    INNER JOIN TGFGRU G ON P.CODGRUPOPROD = G.CODGRUPOPROD
    INNER JOIN AD_TGSISGM COMP ON (
        (COMP.TIPO = 'G' AND G.CODGRUPOPROD = COMP.CODGRUPOPROD) OR
        (COMP.TIPO = 'P' AND G.CODGRUPAI = COMP.CODGRUPOPROD)
    )
    WHERE C.CODTIPOPER IN (1200,1201,1206,1216,1217,1272)
        AND C.TIPMOV = 'D'
        AND P.USOPROD = 'V'
        AND (C.CODEMP = 501 OR C.STATUSNFE <> 'D')
        AND TO_CHAR(C.DTNEG, 'YYYY') = TO_CHAR(:P_ANO)
        AND TO_CHAR(C.DTNEG, 'MM') = :P_MES
        AND COMP.ANO = :P_ANO
        AND COMP.MES = :P_MES
    GROUP BY COMP.CODSGRU
) D ON M.CODSGRU = D.CODSGRU
WHERE M.ANO = :P_ANO
  AND M.MES = :P_MES
