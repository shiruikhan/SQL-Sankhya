SELECT SUM(CASE 
			WHEN TAB.STATUS = 'CHEQUE RECEBIDO E DESCONTADO'
				THEN TAB.VLRDESDOB
			ELSE 0
			END) AS CHEQUE_R_E_DESCONTADO
	,SUM(CASE 
			WHEN TAB.STATUS = 'CHEQUE RECEBIDO E NÃO DESCONTADO'
				THEN TAB.VLRDESDOB
			ELSE 0
			END) AS CHEQUE_R_NAO_DESCONTADO
	,SUM(CASE 
			WHEN TAB.STATUS = 'CHEQUE NÃO RECEBIDO'
				THEN TAB.VLRDESDOB
			ELSE 0
			END) AS CHEQUE_N_RECEBIDO
FROM (
	SELECT CAB.NUNOTA
		,FIN.NUFIN
		,NVL(CAB.CODPARC, FIN.CODPARC) AS CODPARC
		,PAR.NOMEPARC
		,NVL(CAB.CODVEND, FIN.CODVEND) AS CODVEND
		,VEN.APELIDO
		,NVL(CAB.DTNEG, FIN.DTNEG) AS DTNEG
		,NVL(CAB.NUMNOTA, FIN.NUMNOTA) AS NUMNOTA
		,FIN.DESDOBRAMENTO
		,FIN.VLRBAIXA AS VLRDESDOB
		,(
			SELECT CHQ.NUMCHEQUE
			FROM TGFCHQ CHQ
			WHERE CHQ.NUFIN = FIN.NUFIN
			) AS NR_CHEQUE
		,'CHEQUE RECEBIDO E DESCONTADO' AS STATUS
	FROM TGFFIN FIN
	LEFT JOIN TGFCAB CAB ON FIN.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFVEN VEN ON VEN.CODVEND = CAB.CODVEND
		OR VEN.CODVEND = FIN.CODVEND
	WHERE FIN.CODEMP = 501
		AND FIN.RECDESP = 1
		AND FIN.PROVISAO = 'N'
		AND EXISTS (
			SELECT 1
			FROM TGFMBC MBC
			WHERE MBC.NUBCO = FIN.NUBCO
				AND MBC.CONCILIADO = 'S'
				AND MBC.CODCTABCOINT = 502
			)
	
	UNION ALL
	
	SELECT CAB.NUNOTA
		,FIN.NUFIN
		,NVL(CAB.CODPARC, FIN.CODPARC) AS CODPARC
		,PAR.NOMEPARC
		,NVL(CAB.CODVEND, FIN.CODVEND) AS CODVEND
		,VEN.APELIDO
		,NVL(CAB.DTNEG, FIN.DTNEG) AS DTNEG
		,NVL(CAB.NUMNOTA, FIN.NUMNOTA) AS NUMNOTA
		,FIN.DESDOBRAMENTO
		,FIN.VLRBAIXA AS VLRDESDOB
		,(
			SELECT CHQ.NUMCHEQUE
			FROM TGFCHQ CHQ
			WHERE CHQ.NUFIN = FIN.NUFIN
			) AS NR_CHEQUE
		,'CHEQUE RECEBIDO E NÃO DESCONTADO' AS STATUS
	FROM TGFFIN FIN
	LEFT JOIN TGFCAB CAB ON FIN.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFVEN VEN ON VEN.CODVEND = CAB.CODVEND
		OR VEN.CODVEND = FIN.CODVEND
	WHERE FIN.CODEMP = 501
		AND FIN.RECDESP = 1
		AND FIN.PROVISAO = 'N'
		AND EXISTS (
			SELECT 1
			FROM TGFMBC MBC
			WHERE MBC.NUBCO = FIN.NUBCO
				AND MBC.CONCILIADO = 'N'
				AND MBC.CODCTABCOINT = 502
			)
	
	UNION ALL
	
	SELECT CAB.NUNOTA
		,FIN.NUFIN
		,CAB.CODPARC
		,PAR.NOMEPARC
		,CAB.CODVEND
		,VEN.APELIDO
		,CAB.DTNEG
		,CAB.NUMNOTA
		,FIN.DESDOBRAMENTO
		,FIN.VLRDESDOB
		,(
			SELECT CHQ.NUMCHEQUE
			FROM TGFCHQ CHQ
			WHERE CHQ.NUFIN = FIN.NUFIN
			) AS NR_CHEQUE
		,'CHEQUE NÃO RECEBIDO' AS STATUS
	FROM TGFCAB CAB
	INNER JOIN TGFFIN FIN ON FIN.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
	INNER JOIN TGFVEN VEN ON VEN.CODVEND = CAB.CODVEND
	WHERE CAB.CODEMP = 501
		AND CAB.CODTIPVENDA = 139
		AND FIN.RECDESP = 1
		AND FIN.CODTIPTIT = 5
		AND (FIN.NUBCO IS NULL AND FIN.NUCOMPENS IS NULL)
		AND FIN.PROVISAO = 'N'
	) TAB
