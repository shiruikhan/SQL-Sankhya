SELECT V.CODPROD , PRO.DESCRPROD, PRO.M3, PRO.PESOBRUTO,
CASE WHEN FRACIONADO = 'S' THEN 'Fracionado' ELSE 'Fechado' END AS FRACIONADO,
FRACIONADO AS FRAC,
SUM(V.VOLUME) AS VOLUME, 
SUM(V.PESO) AS PESO, 
--SUM(QTDNEG) AS QTDITENS, 
COUNT(*) AS QTDCAIXA ,
PRO.M3 * COUNT(*) AS M3TOT
  FROM AD_VOLPED V, TGFPRO PRO
 WHERE V.CODPROD = PRO.CODPROD
   AND V.NUNOTA = :P_NUNOTA
 GROUP BY V.CODPROD , PRO.DESCRPROD, 
CASE WHEN FRACIONADO = 'S' THEN 'Fracionado' ELSE 'Fechado' END, 
FRACIONADO, PRO.M3, PRO.PESOBRUTO
