SELECT 
     TAB.NUNOTA
	   ,TAB.NUMNOTA
	   ,TAB.DTNEG
    ,TAB.CODPARC
    ,TAB.NOMEPARC
    ,TAB.CODPARCTRANSP
    ,TAB.TRASNP
    ,TAB.VLROUTROSFRETE
    ,TAB.VLR_FRETE_NOTA
    ,TAB.FRETE_COBRADO
    ,TAB.VLR_FRETE_NOTA + TAB.VLROUTROSFRETE - TAB.FRETE_COBRADO AS DIF
	,(ABS(TAB.VLR_FRETE_NOTA + TAB.VLROUTROSFRETE - TAB.FRETE_COBRADO) / (TAB.VLR_FRETE_NOTA +TAB.VLROUTROSFRETE))*100 AS ANALISEP
FROM(
SELECT 
    CAB.NUNOTA,
	   CAB.NUMNOTA,
    CAB.DTNEG,
    CAB.CODPARC,
    PAR.NOMEPARC,
    CAB.CODPARCTRANSP,
    (SELECT P.NOMEPARC FROM TGFPAR P WHERE CAB.CODPARCTRANSP = P.CODPARC) AS TRASNP,
    NVL(CAB.AD_VLROUTROSFRETE, 0) AS VLROUTROSFRETE,
    (
        SELECT NVL(SUM(DIN.BASE),0)
        FROM TGFDIN DIN 
        WHERE DIN.NUNOTA = CAB.NUNOTA 
          AND DIN.CODINC = 3 
          AND DIN.CODIMP = 1
    ) AS VLR_FRETE_NOTA,
    NVL(SUM(C.VLRNOTA), 0) AS FRETE_COBRADO
FROM TGFCAB CAB
INNER JOIN TGFPAR PAR 
    ON PAR.CODPARC = CAB.CODPARC
INNER JOIN TGFNCT NCT 
    ON NCT.CHAVENFE = CAB.CHAVENFE
INNER JOIN TGFCAB C 
    ON C.NUNOTA = NCT.NUNOTA
   AND C.TIPMOV = 'C'
WHERE CAB.TIPMOV = 'V'
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
  AND ((CAB.TIPFRETE = 'S' AND CAB.VLRFRETE > 0)
        OR CAB.AD_VLROUTROSFRETE > 0)
  AND CAB.DTNEG >= :P_PERIODO.INI  
	 AND CAB.DTNEG <= :P_PERIODO.FIN
  AND CAB.CODTIPOPER IN (1100,1124)
GROUP BY 
    CAB.NUNOTA,
	   CAB.NUMNOTA,
	   CAB.DTNEG,
    CAB.CODPARC,
    PAR.NOMEPARC,
    CAB.CODPARCTRANSP,
    CAB.AD_VLROUTROSFRETE,
    CAB.CHAVENFE
)TAB
