SELECT 
	 LIV.CODEMP
	,CAB.CODTIPOPER
	,CAB.CODPARC
	,PAR.NOMEPARC
	,LIV.NUMNOTA
	,ITE.NUNOTA
	,LIV.SERIENOTA
	,LIV.DTDOC
	,LIV.DHMOV
	,ITE.CODPROD
	,PRO.DESCRPROD
	,PRO.NCM
	,LIV.VLRCTB
	,IMN.BASE AS BASEAJD
	,IMN.ALIQUOTA AS ICMS
	,IMN.VALOR AS DIFAL
	,LIV.DIFICMS
	,LIV.CODCFO
	,LIV.UFORIGEM
	,LIV.UFDESTINO
	,AJD.VLRICMS AS VLRICMS195
	,(
		CASE 
			WHEN NVL(ROUND(IMN.VALOR, 2), 0) - NVL(ROUND(AJD.VLRICMS, 2), 0) <> 0
				THEN 0
			ELSE 1
			END
		) AS CONFERENCIA
FROM TGFLIV LIV
	,TGFPAR PAR
	,TGFITE ITE
	,TGFPRO PRO
	,TGFAJD AJD
	,TGFCAB CAB
    ,TGFIMN IMN
WHERE LIV.NUNOTA = ITE.NUNOTA
	AND LIV.SEQUENCIA = ITE.SEQUENCIA
	AND LIV.NUNOTA = AJD.NUNOTA
	AND CAB.CODPARC = PAR.CODPARC
	AND LIV.SEQUENCIA = AJD.SEQUENCIA
	AND ITE.CODPROD = PRO.CODPROD
    AND IMN.NUNOTA = CAB.NUNOTA
    AND IMN.SEQUENCIA = ITE.SEQUENCIA
	AND ITE.NUNOTA = CAB.NUNOTA
	AND TRUNC(DHMOV) BETWEEN :DTINICIO
		AND :DTFIM
    AND EXISTS (SELECT 1
                     FROM TGFIMN IMN
                 WHERE IMN.NUNOTA = CAB.NUNOTA 
                    AND IMN.CODIMP IN (17,18) 
                )
    
	AND (
		LIV.NUMNOTA = :P_NUMNOTA
		OR :P_NUMNOTA IS NULL
		)
    

ORDER BY 
     1
	,2
	,LIV.SEQUENCIA
