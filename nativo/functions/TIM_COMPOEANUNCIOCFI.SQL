CREATE OR REPLACE FUNCTION TIM_COMPOEANUNCIOCFI (P_CLFCODIGO IN NUMBER, P_IMVCODIGO IN NUMBER, P_ANUCODIGO IN NUMBER) RETURN VARCHAR2 IS
 P_ANUDESCRICAO  VARCHAR2(2000);
 P_CFIDESCRICAO  VARCHAR2(4000);
 P_CLFOBSERVACAO VARCHAR2(60);
 P_PARAQUE       VARCHAR2(1);    
 P_VALOR         VARCHAR2(20);
 P_IMVASSINATURA VARCHAR2(50);
BEGIN

    SELECT ANUDESCRICAO INTO  P_ANUDESCRICAO 
    FROM TIMANU 
    WHERE ANUIMOVEL =  P_IMVCODIGO
    AND ANUCODIGO = P_ANUCODIGO;
        
    SELECT CLFOBSERVACAO,CLFPARAQUE  INTO  P_CLFOBSERVACAO, P_PARAQUE 
    FROM TIMCLF 
    WHERE CLFCODIGO =  P_CLFCODIGO;
      
    IF (P_PARAQUE = '1') THEN
        SELECT 'R$ '||TRIM(TO_CHAR(ADMDFPRECODEVENDA,'999g999g990d00')) INTO P_VALOR FROM TIMADM WHERE  ADMIMOVEL  = P_IMVCODIGO AND ADMNUCONTRATO = (SELECT MAX(ADMNUCONTRATO) FROM TIMADM WHERE ADMIMOVEL = P_IMVCODIGO);
    ELSE
        SELECT 'R$ '||TRIM(TO_CHAR(ADMDFPRECOALUGUEL,'999g999g990d00')) INTO P_VALOR FROM TIMADM WHERE  ADMIMOVEL  = P_IMVCODIGO AND ADMNUCONTRATO = (SELECT MAX(ADMNUCONTRATO) FROM TIMADM WHERE ADMIMOVEL = P_IMVCODIGO);
    END IF; 
    
    SELECT IMVASSINATURA INTO P_IMVASSINATURA FROM  TIMIMV WHERE IMVCODIGO = P_IMVCODIGO;
    
    
    P_CFIDESCRICAO := P_ANUDESCRICAO||'. '||P_CLFOBSERVACAO||' .'||P_VALOR||' .'||P_IMVASSINATURA;
 
    RETURN QUEBRALINHACHAR( P_CFIDESCRICAO,30);
END;
