CREATE OR REPLACE VIEW VW_CTE_AUTORIZADOS AS
SELECT
    X.NUARQUIVO AS NRARQUIVO,
    X.NUMNOTA,
    X.NUNOTA,
    X.CHAVEACESSO,
    X.DHIMPORT,
    X.DHPROCESS,
    X.XML,
    X.TIPO,
    X.CODUSUIMP,
    X.CODUSUPROC,
    X.CODTIPOPER,
    X.SITUACAOCTE,
    X.ULTEVEDFE,
    X.DOCSREF,
    T.CHAVEACESSO_REF,
    (SELECT CODTIPOPER FROM TGFCAB WHERE CHAVENFE = T.CHAVEACESSO_REF AND ROWNUM = 1) AS CODTIPOPER_NFE,
    T.NR_SEQUENCIA,
    X.CNPJREMET,
    X.CNPJDEST,
    X.CFOPXML
FROM TGFIXN X,
     XMLTABLE(
         '/docsRef/chaveAcesso'
         PASSING XMLTYPE(X.DOCSREF)
         COLUMNS
             CHAVEACESSO_REF  VARCHAR2(50)  PATH '.',
             NR_SEQUENCIA     FOR ORDINALITY
     ) T
WHERE X.TIPO = 'C'
  AND X.SITUACAOCTE = 'A'
  AND X.DOCSREF IS NOT NULL;
