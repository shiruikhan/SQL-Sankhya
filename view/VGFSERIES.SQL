/*==============================================================================
  Nome do Script : VGFSERIES
  Tipo           : View
  Descrição      : Consulta unificada de números de série (Andes + Sankhya) com nota, produto, parceiro, lote, movimento e local.
  Empresa        : Spark Eletrônica
  Observações    : - Descoberta no inventário de 08/10/2026: NÃO é nativa — consolida seriais de AD_ANDSER (Andes) e TGFSER (TOPs 800/1314/213, locais 109/201) e usa campos AD_* (AD_REFINTERNA, AD_NUMPS).
                   - No banco: criada em 17/01/2024, última alteração em 28/09/2026. Referenciada ~78 vezes em componentes BI do repositório.
                   - Capturado do banco em 08/10/2026 via DBMS_METADATA.GET_DDL; fonte preservado sem alteração (removida só a qualificação "SPARKPRD".).
==============================================================================*/
  CREATE OR REPLACE FORCE EDITIONABLE VIEW "VGFSERIES" ("NFSAIDA", "CODPROD", "DESCRPROD", "RFINTERNA", "SERIE", "DESCRPARVENDA", "LOTE", "DTVENDA", "TIPO", "MOVIMENTO", "LOCAL", "TOP") AS 
  SELECT NUMNFSAIDA AS NFSAIDA,
    CODPRODUTO AS CODPROD,
    DESCPRODUTONOTA AS DESCRPROD,
    REFERENCIAINTERNA AS RFINTERNA,
    NUMSERIAL AS SERIE,
    NVL(RAZAOSOCIAL,' - ') AS DESCRPARVENDA,
    PLANO || ' - ' || ANO || ' - ' || NUMFICPRO AS LOTE,
    DATAEMISSAO AS DTVENDA,
    'ANDES' AS TIPO,
    'ENTRADA' AS MOVIMENTO,
    109 AS LOCAL,
    NULL AS TOP
FROM AD_ANDSER
UNION ALL
/*SERIAL NUMBERS PADRÃO SANKHYA*/
SELECT SER.NUNOTA AS NUNOTASAIDA,
    SER.CODPROD AS CODPROD,
    PRO.DESCRPROD AS DESCRPROD,
    PRO.AD_REFINTERNA AS RFINTERNA,
    SER.SERIE AS SERIE,
    PAR.RAZAOSOCIAL  AS DESCRPARVENDA,
    'MPS - ' || CAB.AD_NUMPS AS LOTE,
    CAB.DTNEG AS DTVENDA,
    'SANKHYA' AS TIPO,
    (CASE WHEN SER.ATUALESTOQUE = -1 THEN 'SAÍDA' WHEN SER.ATUALESTOQUE = 1 THEN 'ENTRADA'END) AS MOVIMENTO,
    ITE.CODLOCALORIG AS LOCAL,
    CAB.CODTIPOPER AS TOP
FROM TGFSER SER
    INNER JOIN TGFPRO PRO ON SER.CODPROD = PRO.CODPROD
    INNER JOIN TGFCAB CAB ON SER.NUNOTA = CAB.NUNOTA
    LEFT JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
    LEFT JOIN TGFITE ITE ON (SER.NUNOTA = ITE.NUNOTA AND SER.SEQUENCIA = ITE.SEQUENCIA)
WHERE (SER.ATUALESTOQUE = -1 OR SER.ATUALESTOQUE = 1)
    AND (CAB.CODTIPOPER = 800 OR (ITE.CODLOCALORIG = 109 AND CAB.TIPMOV = 'V'))
UNION ALL
SELECT SER.NUNOTA AS NUNOTASAIDA,
    SER.CODPROD AS CODPROD,
    PRO.DESCRPROD AS DESCRPROD,
    PRO.AD_REFINTERNA AS RFINTERNA,
    SER.SERIE AS SERIE,
    PAR.RAZAOSOCIAL  AS DESCRPARVENDA,
    'MPS - ' || CAB.AD_NUMPS AS LOTE,
    CAB.DTNEG AS DTVENDA,
    'SANKHYA' AS TIPO,
    (CASE WHEN SER.ATUALESTOQUE = -1 THEN 'SAÍDA' WHEN SER.ATUALESTOQUE = 1 THEN 'ENTRADA'END) AS MOVIMENTO,
    ITE.CODLOCALORIG AS LOCAL,
    CAB.CODTIPOPER AS TOP
FROM TGFSER SER
    INNER JOIN TGFPRO PRO ON SER.CODPROD = PRO.CODPROD
    INNER JOIN TGFCAB CAB ON SER.NUNOTA = CAB.NUNOTA
    LEFT JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
    LEFT JOIN TGFITE ITE ON (SER.NUNOTA = ITE.NUNOTA AND SER.SEQUENCIA = ITE.SEQUENCIA)
WHERE (SER.ATUALESTOQUE = -1 OR SER.ATUALESTOQUE = 1)
    AND CAB.CODTIPOPER = 1314
    AND ITE.CODLOCALORIG = 201
UNION ALL
SELECT SER.NUNOTA AS NUNOTASAIDA,
    SER.CODPROD AS CODPROD,
    PRO.DESCRPROD AS DESCRPROD,
    PRO.AD_REFINTERNA AS RFINTERNA,
    SER.SERIE AS SERIE,
    PAR.RAZAOSOCIAL  AS DESCRPARVENDA,
    'IMPORTADO ANDES' AS LOTE,
    CAB.DTNEG AS DTVENDA,
    'ANDES' AS TIPO,
    'ENTRADA' AS MOVIMENTO,
    ITE.CODLOCALORIG AS LOCAL,
    CAB.CODTIPOPER AS TOP
FROM TGFSER SER
    INNER JOIN TGFPRO PRO ON SER.CODPROD = PRO.CODPROD
    INNER JOIN TGFCAB CAB ON SER.NUNOTA = CAB.NUNOTA
    LEFT JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
    LEFT JOIN TGFITE ITE ON (SER.NUNOTA = ITE.NUNOTA AND SER.SEQUENCIA = ITE.SEQUENCIA)
WHERE SER.ATUALESTOQUE = 1
    AND (CAB.CODTIPOPER = 213 OR (ITE.CODLOCALORIG = 109 AND CAB.TIPMOV = 'V'));
