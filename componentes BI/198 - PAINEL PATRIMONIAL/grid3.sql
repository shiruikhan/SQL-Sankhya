SELECT 
*
FROM (
        SELECT 
                  BEM.CODEMP AS "CODEMP"
                , PRO.CODGRUPOPROD AS "CODGRUPO"
                , GRU.DESCRGRUPOPROD AS "DESCR_GRUPO"
                , BEM.CODPROD AS "CODPROD"
                , PRO.DESCRPROD AS "DESCR_PRODUTO"
                , BEM.CODBEM AS "CODBEM"
                , BEM.DESCRABREV
                , BEM.DESCRBEM
                , TO_CHAR(BEM.DTCOMPRA, 'DD/MM/YYYY') AS "DATA_AQUISICAO"
                , TO_CHAR(BEM.DTCOMPRA, 'YYYY/MM') AS "REF_AQUISICAO"
                , BEM.VLRAQUISICAO AS "VALOR_AQUISICAO"
                , CASE WHEN TO_CHAR(BEM.DTCOMPRA, 'MM/YYYY') = TO_CHAR(:DAT1, 'MM/YYYY') THEN BEM.VLRAQUISICAO ELSE 0 END AS "AQUIS_MES"
                , NVL(CASE WHEN BEM.TEMDEPRECIACAO = 'S' THEN BEM.VLRDEP END,0) AS "BASE_DEPRECIACAO"
                , TO_CHAR(BEM.DTINICIODEP, 'DD/MM/YYYY') AS "DATA_INICIO_DEP"
                , BEM.NUNOTA AS "NUNOTA_COMPRA"
                , BEM.NUMNOTA AS "NOTA_COMPRA"
                , NVL(LOC.CODDEPTO,0) AS "CODDEPTO"
                , (SELECT DESCRDEP FROM TFPDEP WHERE CODDEP = NVL(LOC.CODDEPTO,0)) AS "DESCR_DEPTO"
                , NVL(NVL(CASE WHEN /*BEM.DTBAIXA IS NOT NULL OR */ BEM.TEMDEPRECIACAO = 'N' THEN 0 ELSE CASE WHEN BEM.VLRDEP = BEM.VLRSALDO THEN BEM.VLRDEP ELSE SAL.TOTALDEP END END, BEM.VLRSALDO), 0) AS "DEPRECIACAO_ACUMULADA" 
                , NVL(CASE WHEN /* BEM.DTBAIXA IS NOT NULL OR */ BEM.TEMDEPRECIACAO = 'N' THEN 0 ELSE CASE WHEN BEM.VLRDEP = BEM.VLRSALDO  THEN 0 ELSE BEM.VLRDEP - NVL(SAL.TOTALDEP,BEM.VLRSALDO) END END, 0) AS "SALDO_A_DEPRECIAR"
                , BEM.DTBAIXA AS DATA_BAIXA
                , NVL(CASE WHEN BEM.TEMDEPRECIACAO = 'S' THEN DEPMES.TOTDEPMES ELSE 0 END,0) AS "DEPRECIACAO_MES"
                , (SELECT MAX (TAX.TAXA) FROM TCITAX TAX WHERE TAX.CODPROD = PRO.CODPROD AND (TAX.CODBEM = BEM.CODBEM OR TAX.CODBEM = '<TODOS>')) AS TAXA 
				, CTA.CODCTACTB AS CTACTBAQUIS
				, CTA2.CODCTACTB AS CTACTBDEPR
				, NVL(DECODE(BEM.TEMCREDPISCOFINSDEPR,'S','SIM-s/Deprec.',NULL),DECODE(BEM.TEMCREDPISCOFINSAQUI,'S','SIM-s/Aquis.',NULL)) AS CREDPC 
				, CASE WHEN (BEM.TEMCREDPISCOFINSDEPR = 'N' AND BEM.TEMCREDPISCOFINSAQUI = 'N') THEN NULL ELSE BEM.CSTPIS ||' / '||BEM.CSTCOFINS END AS CSTPC	 
				, CASE WHEN (BEM.TEMCREDPISCOFINSDEPR = 'N' AND BEM.TEMCREDPISCOFINSAQUI = 'N') THEN NULL ELSE BEM.ALIQPIS||' / '||BEM.ALIQCOFINS END AS ALIQPC
                FROM 
                TCIBEM BEM
			    JOIN TSIEMP EMP ON BEM.CODEMP = EMP.CODEMP 
                JOIN TGFPRO PRO ON BEM.CODPROD = PRO.CODPROD
                JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
                LEFT JOIN (SELECT SAL.CODPROD,SAL.CODBEM, MAX (REFERENCIA) AS ULTREF FROM TCISAL SAL WHERE SAL.REFERENCIA <= SNK_TRUNC_DATE(:DAT1, 'MM') GROUP BY SAL.CODPROD, SAL.CODBEM) MAXSAL ON (MAXSAL.CODPROD = BEM.CODPROD AND MAXSAL.CODBEM = BEM.CODBEM)
                LEFT JOIN TCISAL SAL ON (MAXSAL.CODPROD = SAL.CODPROD AND MAXSAL.CODBEM = SAL.CODBEM AND SAL.REFERENCIA = MAXSAL.ULTREF)
                LEFT JOIN (SELECT LOC.CODBEM, LOC.CODPROD, MAX(LOC.DTENTRADA) AS ULTREF FROM TCILOC LOC WHERE LOC.DTENTRADA <= :DAT1 GROUP BY LOC.CODBEM, LOC.CODPROD) MAXDEP ON (MAXDEP.CODPROD = BEM.CODPROD AND MAXDEP.CODBEM = BEM.CODBEM)
                LEFT JOIN TCILOC LOC ON (MAXDEP.CODPROD = LOC.CODPROD AND MAXDEP.CODBEM = LOC.CODBEM AND LOC.DTENTRADA = MAXDEP.ULTREF)
                LEFT JOIN ( SELECT CODPROD, CODBEM, SUM (NVL(VLRDEP, 0)) AS TOTDEPMES FROM TCIMOV MOV WHERE MOV.TIPMOV = 'A' AND SNK_TRUNC_DATE(MOV.REFERENCIA, 'MM') = SNK_TRUNC_DATE(:DAT1, 'MM') GROUP BY CODPROD, CODBEM) DEPMES ON (DEPMES.CODPROD = BEM.CODPROD AND DEPMES.CODBEM = BEM.CODBEM) 
			    LEFT JOIN TCICTA CTA ON BEM.CODPROD = CTA.CODPROD AND CTA.CODBEM = '<TODOS>' AND CTA.TIPO= '2'
			    LEFT JOIN TCICTA CTA2 ON BEM.CODPROD = CTA2.CODPROD AND CTA2.CODBEM = '<TODOS>' AND CTA2.TIPO= 'E'
                WHERE 
                (SNK_TRUNC_DATE(BEM.DTBAIXA,'MM') > SNK_TRUNC_DATE(:DAT1, 'MM') OR 
                 SNK_TRUNC_DATE(BEM.DTBAIXA, 'MM') IS NULL) AND 
                 SNK_TRUNC_DATE(BEM.DTCOMPRA, 'MM') <= :DAT1 AND 
                 BEM.CODBEM <> '<TODOS>' AND 
                 EMP.CODEMP IN :EMPRESA AND
                 (PRO.CODGRUPOPROD = :GRUPO OR :GRUPO = 0)        
 )
WHERE
(CODPROD = :PRODUTO OR :PRODUTO = 0) AND 
(REF_AQUISICAO LIKE :MESANO OR SUBSTR(REF_AQUISICAO, 1,4) LIKE :MESANO OR :MESANO IS NULL)
ORDER BY 4 DESC, 9 DESC
