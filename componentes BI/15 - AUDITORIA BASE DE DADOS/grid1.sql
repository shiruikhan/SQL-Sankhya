SELECT TSIEMP.CODEMP, 
       TSIEMP.CGC,
       TSIEMP.RAZAOSOCIAL,
       TSIEMP.NOMEFANTASIA,
       ( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.CODEMP = TSIEMP.CODEMP AND TGFFIN.RECDESP <> 0 ) QtdeFinanceiros,
       ((( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.CODEMP = TSIEMP.CODEMP AND TGFFIN.RECDESP <> 0 ) * 100 ) /  
       ( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.RECDESP <> 0 )) PercentualFinanceiros,
       ( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.CODEMP = TSIEMP.CODEMP AND TGFCAB.TIPMOV <> 'Z') QtdeOperacoes,
       ((( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.CODEMP = TSIEMP.CODEMP AND TGFCAB.TIPMOV <> 'Z' ) * 100 ) /  
       ( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.TIPMOV <> 'Z' )) PercentualOperacoes
  FROM TSIEMP
ORDER BY TSIEMP.CODEMP
