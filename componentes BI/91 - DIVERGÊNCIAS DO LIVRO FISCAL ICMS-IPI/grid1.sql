SELECT 
	CASE X.TIPDOC WHEN 'I' THEN 'Financeiro' WHEN 'N' THEN 'Nota' WHEN 'CT' THEN 'Conhecimento Transporte' END TIPDOC,	
	(SELECT OPC.OPCAO LABEL FROM TDDOPC OPC WHERE OPC.NUCAMPO = (SELECT A.NUCAMPO FROM TDDCAM A WHERE A.NOMETAB = 'TGFTOP' AND A.NOMECAMPO = 'TIPMOV') AND UPPER(OPC.VALOR) = UPPER(X.TIPMOV)) TIPMOV,  
    (SELECT OPC.OPCAO LABEL FROM TDDOPC OPC WHERE OPC.NUCAMPO = (SELECT A.NUCAMPO FROM TDDCAM A WHERE A.NOMETAB = 'TGFTOP' AND A.NOMECAMPO = 'ATUALLIVFIS') AND OPC.VALOR = X.ATUALLIVFIS) ATUALLIVFIS,
	X.CODEMP,
	(SELECT EMP.RAZAOSOCIAL FROM TSIEMP EMP WHERE EMP.CODEMP = X.CODEMP) NOMEEMP,
	X.NUNOTA,
	X.NUMNOTA,
	X.VLRNOTA,
	X.DTNEG,
	X.DHMOV,
	X.DTENTSAI,
	CASE WHEN X.TIPDOC <> 'F' THEN (SELECT OPC.OPCAO LABEL FROM TDDOPC OPC WHERE OPC.NUCAMPO = (SELECT A.NUCAMPO FROM TDDCAM A WHERE A.NOMETAB = 'TGFCAB' AND (UPPER(A.NOMECAMPO) = 'STATUSNOTA')) AND OPC.VALOR = X.STATUS) ELSE X.STATUS END STATUS,
	CASE WHEN X.TIPDOC <> 'F' THEN COALESCE((SELECT OPC.OPCAO LABEL FROM TDDOPC OPC WHERE OPC.NUCAMPO = (SELECT A.NUCAMPO FROM TDDCAM A WHERE A.NOMETAB = 'TGFCAB' AND (UPPER(A.NOMECAMPO) = 'STATUSNFE')) AND OPC.VALOR = X.STATUSNFE),'Não definido') ELSE 'Não é Documento Fiscal' END STATUSNFE,
	(SELECT OPC.OPCAO LABEL FROM TDDOPC OPC WHERE OPC.NUCAMPO = (SELECT A.NUCAMPO FROM TDDCAM A WHERE A.NOMETAB = 'TGFTOP' AND (UPPER(A.NOMECAMPO) = 'CODMODDOC')) AND OPC.VALOR = X.CODMODDOCNOTA) MODELODOC,      
    CASE WHEN X.TIPDOC <> 'F' THEN X.NUNOTA ELSE NULL END A_NUNOTA,
    X.CODTIPOPER,
    X.DHTIPOPER
FROM
(SELECT 
	 'N' TIPDOC,
	 CAB.TIPMOV,
	 CAB.CODEMP,
	 CAB.NUNOTA,
	 CAB.NUMNOTA,
	 CAB.VLRNOTA,
	 CASE WHEN CAB.TIPMOV = 'C' THEN COALESCE(CAB.DTENTSAI, CAB.DTFATUR, CAB.DTMOV, CAB.DTNEG) ELSE CAB.DTNEG END DTNEG,	  
	 CAB.DTMOV DHMOV,
	 CAB.DTENTSAI,
	 CAB.STATUSNOTA STATUS,
	 CAB.STATUSNFE STATUSNFE,
	 (SELECT TGFTOP.ATUALLIVFIS FROM TGFTOP WHERE TGFTOP.CODTIPOPER = CAB.CODTIPOPER AND TGFTOP.DHALTER = CAB.DHTIPOPER) ATUALLIVFIS, 
     (SELECT TGFTOP.CODMODDOC FROM TGFTOP WHERE TGFTOP.CODTIPOPER = CAB.CODTIPOPER AND TGFTOP.DHALTER = CAB.DHTIPOPER) CODMODDOCNOTA,
      CAB.CODTIPOPER,
      CAB.DHTIPOPER 
FROM TGFCAB CAB
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
WHERE CAB.DTENTSAI BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND EXISTS (SELECT 1 FROM TGFLIV LIV WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) AND LIV.NUNOTA = CAB.NUNOTA AND LIV.ESPDOC = 'NF')
UNION ALL
SELECT 
	 'CT' TIPDOC,
	 CAB.TIPMOV,
	 CAB.CODEMP,
	 CAB.NUNOTA,
	 CAB.NUMNOTA,
	 CAB.VLRNOTA,
	 CASE WHEN CAB.TIPMOV = 'C' THEN COALESCE(CAB.DTENTSAI,CAB.DTFATUR,CAB.DTMOV, CAB.DTNEG) ELSE CAB.DTNEG END DTNEG,	  
	 CAB.DTMOV DHMOV,
	 CAB.DTENTSAI,
	 CAB.STATUSNOTA STATUS,
	 CAB.STATUSNFE STATUSNFE,
	 (SELECT TGFTOP.ATUALLIVFIS FROM TGFTOP WHERE TGFTOP.CODTIPOPER = CAB.CODTIPOPER AND TGFTOP.DHALTER = CAB.DHTIPOPER) ATUALLIVFIS, 
     (SELECT TGFTOP.CODMODDOC FROM TGFTOP WHERE TGFTOP.CODTIPOPER = CAB.CODTIPOPER AND TGFTOP.DHALTER = CAB.DHTIPOPER) CODMODDOCNOTA,
      CAB.CODTIPOPER,
      CAB.DHTIPOPER 
FROM TGFCAB CAB
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = CAB.CODEMP)
WHERE CAB.DTENTSAI BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND EXISTS (SELECT 1 FROM TGFLIV LIV WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) AND LIV.NUNOTA = CAB.NUNOTA AND LIV.ESPDOC = 'CT')
UNION ALL
SELECT 
	 'I' TIPDOC,
	 'I-Financeiro' TIPMOV,
	 FIN.CODEMP,
	 FIN.NUFIN,
	 FIN.NUMNOTA,
	 FIN.VLRDESDOB,
	 FIN.DTNEG,
	 FIN.DHMOV,
	 FIN.DTENTSAI,
	 CASE WHEN FIN.DHBAIXA IS NOT NULL THEN 'Baixado' ELSE 'Pendente' end STATUS,
	 'M' STATUSNFE,
	 (SELECT TGFTOP.ATUALLIVFIS FROM TGFTOP WHERE TGFTOP.CODTIPOPER = FIN.CODTIPOPER AND TGFTOP.DHALTER = FIN.DHTIPOPER) ATUALLIVFIS,
     (SELECT TGFTOP.CODMODDOC FROM TGFTOP WHERE TGFTOP.CODTIPOPER = FIN.CODTIPOPER AND TGFTOP.DHALTER = FIN.DHTIPOPER) CODMODDOCNOTA,
      FIN.CODTIPOPER,
      FIN.DHTIPOPER
FROM TGFFIN FIN
INNER JOIN TSIEMP EMP ON(EMP.CODEMP = FIN.CODEMP)
WHERE FIN.DTNEG BETWEEN :P_DTNEG.INI AND :P_DTNEG.FIN
  AND (EMP.CODEMPMATRIZ = :P_CODEMPMATRIZ OR :P_CODEMPMATRIZ = 9999)
  AND EXISTS (SELECT 1 FROM TGFLIV LIV WHERE (LIV.SEQUENCIA = 9999 OR LIV.SEQUENCIA = 9998) AND LIV.ORIGEM = 'F' AND LIV.NUNOTA = FIN.NUFIN)
)X
WHERE (X.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
  AND (X.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
ORDER BY 
	X.TIPDOC, 
	X.DHMOV DESC
