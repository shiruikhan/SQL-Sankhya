SELECT 
1 AS ORDEM,
D.CODPARC,
D.RAZAOSOCIAL,
D.APELIDO,
D.VALOR,
(D.VALOR / SUM(VALOR) OVER () )*100 AS REP
FROM(
SELECT 
CODPARC,
UPPER(RAZAOSOCIAL) AS RAZAOSOCIAL,
APELIDO,
SUM(VALOR) AS VALOR 
FROM(
--ORIGEM PORTAL - TIPMOV= "V"
SELECT 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
VEN.APELIDO,
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR
FROM TGFFIN FIN , TGFPAR PAR , TGFNAT NAT , TGFTOP T, TGFVEN VEN 
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
NVL(PAR.CODVEND,0) = NVL(VEN.CODVEND,0) AND
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODEMP IN :CODEMP AND  
FIN.DTNEG <= :DAT1 AND  
FIN.DHBAIXA is null AND
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('V') AND 
FIN.RECDESP = 1 AND
((FIN.CODTIPOPER <> 3206 AND :VDAGER = 'S') OR :VDAGER = 'N') AND
to_date(SYSDATE,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') > 0 AND
:OUTROS IN ('A','P')

UNION ALL

--ORIGEM FINANCEIRO - TIPMOV= "I"
SELECT 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
VEN.APELIDO,
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR
FROM TGFFIN FIN , TGFPAR PAR , TGFNAT NAT , TGFTOP T, TGFVEN VEN  
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
NVL(PAR.CODVEND,0) = NVL(VEN.CODVEND,0) AND
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
FIN.DHBAIXA is null AND
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('I') AND 
NAT.AD_TIPOCTBZ = 'N' AND
((FIN.CODTIPOPER <> 3206 AND :VDAGER = 'S') OR :VDAGER = 'N') AND
FIN.RECDESP = 1 AND
to_date(SYSDATE,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') > 0 AND
:OUTROS IN ('A','F')
)
GROUP BY CODPARC, RAZAOSOCIAL, APELIDO
)D
UNION ALL
SELECT 0 AS ORDEM, 0 AS CODPARC, '. TODOS' AS RAZAOSOCIAL, NULL AS APELIDO, 0 AS VALOR, NULL AS REP FROM DUAL
ORDER BY ORDEM, VALOR DESC
