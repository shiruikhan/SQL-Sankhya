SELECT V.CODPROD,
	V.DESCRPROD,
	V.CODVOL,
	V.CODGRUPOPROD,
	V.DESCRGRUPOPROD,
	V.REFERENCIA,
	V.COMPLDESC,
	V.ESTOQUE,
	V.PLANEJADO_ESTOQUE,
	V.PEDIDO_ABERTO_ESTOQUE,
	V.PEDIDO_ABERTO_VENDA,
	V.AD_AGRUPADOR,
	V.ESTOQUE + V.PLANEJADO_ESTOQUE + V.PEDIDO_ABERTO_ESTOQUE - V.PEDIDO_ABERTO_VENDA AS SALDO,
	V.ESTOQUE /*+ V.PLANEJADO_ESTOQUE*/ + V.PEDIDO_ABERTO_ESTOQUE - V.PEDIDO_ABERTO_VENDA AS SALDOSEMPLANEJADO
	/*(SELECT SUM(AD.QTDPREV) - SUM((SELECT OBTEM_TOTAIS_MRP((SELECT MAX(M.NUMPS) FROM TPRMPS M WHERE TRUNC(M.DTINICMPS, 'MM') = TRUNC(AD.DTREF,'MM')),AD.CODPROD,0,'P') FROM DUAL)) - SUM(AD.QTDREDMET) + SUM((SELECT SALDO  FROM (SELECT nvl(SUM(VGF.SALDO),0) AS SALDO FROM VGFSALDOMRP VGF WHERE VGF.CODPROD = AD.CODPROD AND VGF.DTREF < AD.DTREF) D)) FROM AD_TGFMET AD WHERE AD.CODPROD = V.CODPROD AND AD.DTREF <= :P_DATA) AS SALDOMETA*/
FROM(SELECT PRO.CODPROD,
			PRO.DESCRPROD,
			PRO.CODVOL,
			PRO.CODGRUPOPROD,
			GRU.DESCRGRUPOPROD,
			PRO.REFERENCIA, 
			PRO.COMPLDESC,
			PRO.AD_AGRUPADOR,
			SUM(NVL(EST.ESTOQUE,0)) AS ESTOQUE,
			NVL((SELECT SUM(IPA.QTDPRODUZIR) - SUM(NVL((SELECT SUM(I.QTDNEG) FROM TGFCAB C INNER JOIN TGFITE I ON (C.NUNOTA=I.NUNOTA) WHERE C.TIPMOV='F' AND C.IDIPROC= PROC.IDIPROC AND I.ATUALESTOQUE=1 AND I.CODPROD = IPA.CODPRODPA),0)) FROM TPRIPROC PROC INNER JOIN  TPRIPA IPA ON (PROC.IDIPROC = IPA.IDIPROC) WHERE PROC.STATUSPROC IN ('A','P2') AND IPA.CODPRODPA = PRO.CODPROD AND NVL(PROC.DTPREVENT,TRUNC(PROC.DHINC)+ 7) <= :P_DATA),0) AS PLANEJADO_ESTOQUE,
			NVL((SELECT SUM(QTDPREV) FROM TGMMET WHERE DTREF = ADD_MONTHS(:P_DATA,-1) AND CODPROD = PRO.CODPROD),0) AS PEDIDO_ABERTO_ESTOQUE,
			NVL((SELECT SUM(QTDNEG-QTDENTREGUE) FROM TGFCAB CAB, TGFITE ITE WHERE CAB.NUNOTA = ITE.NUNOTA AND ITE.CODPROD = PRO.CODPROD AND CAB.PENDENTE = 'S' AND CAB.TIPMOV = 'P' AND ITE.PENDENTE = 'S' AND CAB.CODTIPOPER <> 900 AND CAB.DTPREVENT <= :P_DATA),0) AS PEDIDO_ABERTO_VENDA
		FROM TGFPRO PRO 
			LEFT JOIN  TGFEST EST ON (PRO.CODPROD = EST.CODPROD AND EST.CODLOCAL = 109 AND EST.CODEMP = 1)
			INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
		WHERE ( PRO.DESCRPROD LIKE '%' || UPPER(:P_DESCRPROD) || '%' OR :P_DESCRPROD IS NULL) AND (SUBSTR(PRO.CODGRUPOPROD,0,4) like SUBSTR(:P_CODGRUPO,0,4) OR :P_CODGRUPO IS NULL) AND PRO.USOPROD='V' AND PRO.ATIVO='S' AND ( NVL(PRO.AD_OBSOLETO,'N') = 'N' OR EXISTS (SELECT 1 FROM TGFEST EST WHERE EST.CODPROD = PRO.CODPROD AND EST.ESTOQUE > 0 AND EST.CODLOCAL =109))
		GROUP BY PRO.CODPROD, PRO.DESCRPROD, PRO.CODVOL, PRO.REFERENCIA, PRO.COMPLDESC, PRO.CODGRUPOPROD,GRU.DESCRGRUPOPROD,PRO.AD_AGRUPADOR) V 
ORDER BY PEDIDO_ABERTO_VENDA DESC,PLANEJADO_ESTOQUE DESC, DESCRPROD
