SELECT B.CODPARC CODPARCEIROS,
       B.NOMEPARC NOMEPARCEIRO,
       SUM( B.QTDEOPERACOES) OPERACOES,
       ( SUM( B.QTDEOPERACOES) * 100 ) / ( SELECT COUNT(*) 
                                            FROM TGFCAB INNER JOIN TGFPAR ON TGFCAB.CODPARC = TGFPAR.CODPARC
                                           WHERE TGFPAR.FORNECEDOR = 'S'
                                             AND TGFCAB.TIPMOV <> 'Z' ) PERCENTUAL
  FROM ( SELECT A.CODPARC,
                A.NOMEPARC,
                A.QTDEOPERACOES,
                A.TOTAL
           FROM ( SELECT TGFPAR.CODPARC, TGFPAR.NOMEPARC,
                       ( SELECT COUNT(TGFPAR.CODPARC) FROM TGFPAR WHERE TGFPAR.FORNECEDOR = 'S' ) TOTAL,
                       ( SELECT COUNT(*) FROM TGFFIN WHERE TGFFIN.CODPARC = TGFPAR.CODPARC AND TGFFIN.RECDESP <> 0 ) QtdeFinanceiros,
                       ( SELECT COUNT(*) FROM TGFCAB WHERE TGFCAB.CODPARC = TGFPAR.CODPARC AND TGFCAB.TIPMOV <> 'Z') QtdeOperacoes
  FROM TGFPAR 
 WHERE TGFPAR.FORNECEDOR = 'S') A
WHERE A.QTDEOPERACOES <> 0 ) B
GROUP BY B.CODPARC, B.NOMEPARC
ORDER BY SUM(B.QTDEOPERACOES) DESC
