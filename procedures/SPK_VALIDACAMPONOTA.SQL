create or replace PROCEDURE SPK_VALIDACAMPONOTA (P_NUNOTA INT, P_SUCESSO OUT VARCHAR, P_MENSAGEM OUT VARCHAR2, P_CODUSULIB OUT NUMERIC) AS
BEGIN
    DECLARE
        P_CODTRIB NUMBER;
		P_CSTIPI NUMBER;
        P_QTDLINHAS NUMBER;
    BEGIN
        SELECT COUNT(SEQUENCIA) INTO P_QTDLINHAS
        FROM TGFITE
        WHERE NUNOTA = P_NUNOTA;

        FOR I IN 1..P_QTDLINHAS
        LOOP
            BEGIN
				SELECT NVL(CODTRIB,9999) INTO P_CODTRIB
				FROM TGFITE
				WHERE NUNOTA = P_NUNOTA
					AND SEQUENCIA = (SELECT SEQUENCIA FROM (SELECT A.*, ROWNUM RNUM FROM (SELECT SEQUENCIA FROM TGFITE WHERE NUNOTA = P_NUNOTA) A WHERE ROWNUM <= I) WHERE RNUM >= I);
				EXCEPTION WHEN NO_DATA_FOUND THEN
				P_CODTRIB := 9999;
			END;
			BEGIN
				SELECT NVL(CSTIPI,9999) INTO P_CSTIPI
				FROM TGFITE 
				WHERE NUNOTA = P_NUNOTA
					AND SEQUENCIA = (SELECT SEQUENCIA FROM (SELECT A.*, ROWNUM RNUM FROM (SELECT SEQUENCIA FROM TGFITE WHERE NUNOTA = P_NUNOTA) A WHERE ROWNUM <= I) WHERE RNUM >= I);
				EXCEPTION WHEN NO_DATA_FOUND THEN
				P_CSTIPI := 9999;
			END;
            P_SUCESSO := 'S';
			IF P_CODTRIB = 9999 OR P_CSTIPI = 9999 THEN
				P_MENSAGEM := 'Os campos CST do ICMS ou CST do IPI estão zerados e precisam ser preenchidos!';
				P_SUCESSO := 'N';
                RETURN;
			END IF;
       END LOOP;

    END;

END;