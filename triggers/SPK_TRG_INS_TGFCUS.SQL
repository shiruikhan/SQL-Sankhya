create or replace TRIGGER SPK_TRG_INS_TGFCUS
BEFORE INSERT OR UPDATE ON TGFCUS
FOR EACH ROW
DECLARE
    P_INICIAL NUMBER;
    P_VLRCUSTO NUMBER;
	P_MAXCODREG NUMBER;
	P_MAXSEQUENCIA NUMBER;
	P_CODPROD NUMBER;
	P_EXISTE NUMBER;

BEGIN
    
    P_VLRCUSTO := :NEW.CUSMED;
	P_CODPROD := :NEW.CODPROD;
	P_EXISTE := 0;
	P_INICIAL := 0;

	SELECT MAX(CODREG) INTO P_MAXCODREG 
	FROM AD_TGSCIT;
	
	SELECT COUNT(CODPROD) INTO P_EXISTE 
	FROM AD_TGSCIT 
	WHERE CODREG = P_MAXCODREG 
		AND CODPROD = P_CODPROD;
	
	IF P_EXISTE > 0 THEN
		P_MAXCODREG := P_MAXCODREG+1;
		P_MAXSEQUENCIA := 1;
	END IF;
	
	SELECT SUBSTR(P_CODPROD,1) INTO P_INICIAL
	FROM DUAL;
	
	IF P_INICIAL = 3 THEN
		INSERT INTO AD_TGSCIT (CODREG, SEQUENCIA, CODPROD, CUSTO) VALUES (P_MAXCODREG, P_MAXSEQUENCIA, P_CODPROD, P_VLRCUSTO);
	END IF;
END;