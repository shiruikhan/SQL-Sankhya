SELECT DISTINCT CAB.NUNOTA,
	CAB.DTPREVENT,
	CAB.NUMNOTA,
	CAB.VLRNOTA,
	CAB.DTNEG,
	CAB.CODPARC,
	PAR.NOMEPARC,
	CAB.CODVEND,
	VEN.APELIDO,
	CAB.CODEMP,
	EMP.NOMEFANTASIA,
	CAB.CODTIPOPER,
	(SELECT DISTINCT DESCROPER FROM TGFTOP WHERE CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER,
	CAB.CODNAT,
	(SELECT DESCRNAT FROM TGFNAT WHERE CODNAT = CAB.CODNAT) AS DESCRNAT
FROM TGFCAB CAB
	INNER JOIN TGFITE ITE ON CAB.NUNOTA = ITE.NUNOTA
	INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
	INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
	INNER JOIN TSIEMP EMP ON CAB.CODEMP = EMP.CODEMP
WHERE (TRUNC(CAB.DTPREVENT) >= :P_PERIODO.INI AND TRUNC(CAB.DTPREVENT) <= :P_PERIODO.FIN)
	AND (:P_CODPARC = CAB.CODPARC OR :P_CODPARC IS NULL)
	AND (:P_CODPROD = ITE.CODPROD OR :P_CODPROD IS NULL)
	AND CAB.TIPMOV = 'O'
	AND CAB.STATUSNOTA = 'L'
	AND CAB.PENDENTE = 'S'
ORDER BY CAB.DTPREVENT
