/*==============================================================================
  Nome do Script : TIM_MONTAINQUILINO
  Tipo           : Function Nativa Sankhya (referencia -- nao customizada)
  Descricao      : Qualifica em texto contratual os inquilinos de uma locacao.
  Assinatura     : TIM_MONTAINQUILINO (CODLOCACAO IN NUMBER) RETURN VARCHAR2
  Observacoes    : - Objeto nativo do ERP -- atualizacoes do Sankhya podem
                    sobrescrever esta function. Revisar apos cada upgrade
                    (mesmo cuidado descrito em trigger_nativa/README.md).
                  - Capturado do banco em 08/10/2026, via:
                    SELECT DBMS_METADATA.GET_DDL('FUNCTION', 'TIM_MONTAINQUILINO', 'SPARKPRD') FROM dual;
==============================================================================*/
CREATE OR REPLACE FUNCTION TIM_MONTAINQUILINO (CODLOCACAO IN NUMBER) RETURN VARCHAR2 IS
 --AUTOR: BOSCO
 RSP VARCHAR2(4000);
 PARTE VARCHAR2(1000);
 
 CURSOR RSLCD IS 
      SELECT PAR.CODPARC, RAZAOSOCIAL, DECODE(PAR.TIMESTADOCIVIL, 'NI', '', 'SO', 'Solteiro(a)', 'CA', 'Casado(a)', 'DI', 'Divorciado(a)', 'SJ', 'Sep. Judicalmente', 'VI', 'Viuvo(a)', 'Outros(as)') ESTCIVIL , 
           PAI.TIMNACIONALIDAD NACIONALIDADE, PRF.PRFPROFISSAO PROFISSAO, TIMESTADOCIVIL, PAR.CGC_CPF, 
           PAR.IDENTINSCESTAD, PAR.TIMORGAO, EDD.TIPO, EDD.DESCRICAOCORREIO ENDERECO, PAR.NUMEND, PAR.COMPLEMENTO, 
           BAI.DESCRICAOCORREIO BAIRRO, CID.DESCRICAOCORREIO CIDADE, UFS.DESCRICAO ESTADO, PAR.DTNASC, PAR.TIPPESSOA,
           CTC.NOMECONTATO CONJUGE, PAC.TIMNACIONALIDAD NACCONJUGE, PRC.PRFPROFISSAO PROFCONJUGE, CTC.CPF CPFCONJUGE,  CTC.TIMRG RGCONJUGE, 
           CTR.NOMECONTATO RESPONSAVEL, PIR.TIMNACIONALIDAD NACRESP, PRR.PRFPROFISSAO PROFRESP, CTR.CPF CPFRESP,  CTC.TIMRG RGRESP 
      FROM TIMLCL LCL INNER JOIN TGFPAR PAR ON LCL.LCLLOCATARIO = PAR.CODPARC LEFT JOIN TSIPAI PAI ON PAR.TIMNACIONALIDAD = PAI.CODPAIS 
           LEFT JOIN TIMPRF PRF ON PAR.TIMPROFISSAO = PRF.PRFCODIGO LEFT JOIN TSIEND EDD ON PAR.CODEND = EDD.CODEND LEFT JOIN TSIBAI BAI ON PAR.CODBAI = BAI.CODBAI
           LEFT JOIN TSICID CID ON PAR.CODCID = CID.CODCID LEFT JOIN TSIUFS UFS ON CID.UF = UFS.CODUF 
           LEFT JOIN TGFCTT CTC ON PAR.CODPARC = CTC.CODPARC AND CTC.CARGO = 'CONJUGE'  
                LEFT JOIN TSIPAI PAC ON CTC.TIMNACIONALIDAD = PAC.CODPAIS LEFT JOIN TIMPRF PRC ON CTC.TIMPROFISSAO = PRC.PRFCODIGO  
           LEFT JOIN TGFCTT CTR ON PAR.CODPARC = CTR.CODPARC AND CTC.CARGO = 'RESPONSÁVEL'  
                LEFT JOIN TSIPAI PIR ON CTC.TIMNACIONALIDAD = PIR.CODPAIS LEFT JOIN TIMPRF PRR ON CTC.TIMPROFISSAO = PRR.PRFCODIGO  
     WHERE LCL.LCLLOCACAO = CODLOCACAO  
     ORDER BY RAZAOSOCIAL;
 
 BEGIN
 
   RSP := '';
   FOR PES IN RSLCD LOOP
     IF LENGTH(RSP) > 10 THEN
       RSP := TRIM(RSP) || '; ';
     END IF;
     PARTE := Tim_Formatapessoa(PES.RAZAOSOCIAL, PES.NACIONALIDADE, PES.ESTCIVIL, PES.PROFISSAO, PES.TIPPESSOA, PES.CGC_CPF, PES.IDENTINSCESTAD, PES.TIMORGAO, 
                            Tim_Formataendereco( PES.TIPO, PES.ENDERECO, PES.NUMEND, PES.COMPLEMENTO, PES.BAIRRO, PES.CIDADE, PES.ESTADO), PES.TIMESTADOCIVIL,
                            Tim_Formatapessoa(PES.CONJUGE, PES.NACCONJUGE, NULL, PES.PROFCONJUGE, 'F', PES.CPFCONJUGE, PES.RGCONJUGE, NULL, NULL, 'NI', NULL, NULL),
                            Tim_Formatapessoa(PES.RESPONSAVEL, PES.NACRESP, NULL, PES.PROFRESP, 'F', PES.CPFRESP, PES.RGRESP, NULL, NULL, 'NI', NULL, NULL));
     RSP := RSP || PARTE;                    
   END LOOP;
       
 RETURN RSP;

END;
