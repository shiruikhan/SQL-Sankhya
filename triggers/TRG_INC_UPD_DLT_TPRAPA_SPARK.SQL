create or replace TRIGGER TRG_INC_UPD_DLT_TPRAPA_SPARK
BEFORE INSERT OR UPDATE OR DELETE
ON TPRAPA
FOR EACH ROW
/*==============================================================================
  Nome do Script : TRG_INC_UPD_DLT_TPRAPA_SPARK
  Tipo           : Trigger
  Descrição      : Gerencia séries apontadas por atividade e registra na tabela de apontamento de produção
  Tabela         : TPRAPA
  Evento         : BEFORE INSERT OR UPDATE OR DELETE
  Escopo         : FOR EACH ROW / STATEMENT

  Autor          : Silvio Vieira
  Cargo          : Analista de Sistemas Sênior
  Empresa        : Spark Eletrônica
  Data de Criação: [A DEFINIR]
  Última Revisão : Abril/2026 — Padronização de cabeçalho e comentários
==============================================================================*/
DECLARE 
ERRMSG VARCHAR2(100);
P_QTDPRODUZIR  TPRIPA.QTDPRODUZIR%TYPE;
P_NROLOTE      TPRIPA.NROLOTE%TYPE;
P_IDIPROC      TPRIPA.IDIPROC%TYPE;
P_IDIATV       TPRIATV.IDIATV%TYPE;
P_IDEFX        TPRIATV.IDEFX%TYPE;
P_IDPROC       TPRIPROC.IDPROC%TYPE;

BEGIN

BEGIN
SELECT IPA.QTDPRODUZIR,IPA.NROLOTE, IPA.IDIPROC, TV.IDIATV, TV.IDEFX, PROC.IDPROC  INTO P_QTDPRODUZIR, P_NROLOTE, P_IDIPROC, P_IDIATV, P_IDEFX, P_IDPROC
FROM TPRIPA IPA INNER JOIN TPRIATV TV ON (IPA.IDIPROC = TV.IDIPROC)
INNER JOIN TPRIPROC PROC ON (PROC.IDIPROC = TV.IDIPROC)
INNER JOIN TPRAPO APO ON (APO.IDIATV = TV.IDIATV)
WHERE APO.NUAPO = :NEW.NUAPO; 
EXCEPTION WHEN NO_DATA_FOUND THEN
RETURN;
END TRG_INC_UPD_DLT_TPRAPA_SPARK;

-- SERÁ TRANSITÓRIA ESSA ATUALIZAÇÃO CONFORME APONTAMENTO, OS VALORES OFICIAIS SERÃO GUARDADOS NA TABELA AD_TPRSERAPO CONFORME CONFIRMAÇÃO APONTAMENTO
DELETE TPRSERPA WHERE IDIPROC = P_IDIPROC AND CODPRODPA = :NEW.CODPRODPA;



-- INCLUIR NA TABELA DE SERIA APONTADA A SÉRIE UTILIZADA NA ATIVIDADE, ISSO FOI NECESSÁRIO POIS O SISTEMA NÃO É PREPARADO PARA LIBERAR SÉRIE POR ATIVIDADE
IF :NEW.QTDFAT > 0 THEN

INSERT INTO  AD_TPRSERAPO (NUAPO,SEQAPA,SEQ,SERIEPA,DTINCLUSAO,CODUSUINC)
SELECT :NEW.NUAPO, :NEW.SEQAPA,(SELECT NVL(MAX(SEQ),0)FROM AD_TPRSERAPO WHERE NUAPO=:NEW.NUAPO AND SEQAPA =:NEW.SEQAPA)+ROWNUM,SERIEPA,SYSDATE,STP_GET_CODUSULOGADO()
FROM TPRSERPA WHERE IDIPROC = P_IDIPROC
AND LIBERADO='N'
UNION
SELECT * FROM (
SELECT :NEW.NUAPO, :NEW.SEQAPA,(SELECT NVL(MAX(SEQ),0)FROM AD_TPRSERAPO WHERE NUAPO=:NEW.NUAPO AND SEQAPA =:NEW.SEQAPA)+ROWNUM,SERIEPA,SYSDATE,STP_GET_CODUSULOGADO()
FROM AD_TPRSERPA PA WHERE 
IDIPROC = P_IDIPROC 
AND NOT EXISTS (SELECT 1 FROM AD_TPRSERAPO APO WHERE APO.SERIEPA = PA.SERIEPA
AND APO.NUAPO IN (SELECT NUAPO FROM TPRAPO WHERE IDIATV IN (SELECT IDIATV FROM TPRIATV WHERE IDIPROC = P_IDIPROC AND IDEFX = P_IDEFX))
)ORDER BY SERIEPA) WHERE ROWNUM <=:NEW.QTDAPONTADA
ORDER BY SERIEPA; 
END IF;


IF P_IDEFX NOT IN (570) THEN

-- INCLUI A SÉRIE CONFORME QUANTIDADE APONTADA DE FORMA SEQUENCIAL,
INSERT INTO TPRSERPA (IDIPROC, CODPRODPA, SERIEPA, PERDA, LIBERADO, NUAPO)
SELECT * FROM (
SELECT P_IDIPROC, :NEW.CODPRODPA AS CODPRODPA, PA.SERIEPA AS SERIEPA,'N' AS PERDA,'N' AS LIBERADO, NULL AS NUAPO FROM AD_TPRSERPA PA 
WHERE 
PA.IDIPROC = P_IDIPROC
AND NOT EXISTS (SELECT 1 FROM AD_TPRSERAPO APO WHERE APO.SERIEPA = PA.SERIEPA
AND APO.NUAPO IN (SELECT NUAPO FROM TPRAPO WHERE IDIATV IN (SELECT IDIATV FROM TPRIATV WHERE IDIPROC = P_IDIPROC AND IDEFX = P_IDEFX))) 
ORDER BY PA.SERIEPA) WHERE ROWNUM <=:NEW.QTDAPONTADA 
UNION
SELECT P_IDIPROC, :NEW.CODPRODPA, APO.SERIEPA,'N','S', NULL FROM AD_TPRSERAPO APO 
WHERE APO.NUAPO IN (SELECT NUAPO FROM TPRAPO WHERE IDIATV IN (SELECT IDIATV FROM TPRIATV WHERE IDIPROC = P_IDIPROC AND IDEFX = P_IDEFX))
;
END IF;


IF P_IDEFX = 570 THEN


INSERT INTO TPRSERPA (IDIPROC, CODPRODPA, SERIEPA, PERDA, LIBERADO, NUAPO)
SELECT P_IDIPROC, :NEW.CODPRODPA AS CODPRODPA, PA.SERIEPA AS SERIEPA,'N' AS PERDA,'N' AS LIBERADO, NULL AS NUAPO FROM AD_TPRSERPA PA 
WHERE 
PA.IDIPROC = P_IDIPROC AND (P_IDPROC =21 AND P_IDEFX = 570)
AND NOT EXISTS (SELECT 1 FROM TPRSERPA P WHERE P.IDIPROC = PA.IDIPROC AND P.CODPRODPA = PA.CODPRODPA AND P.SERIEPA = PA.SERIEPA); --CASO ESPECIFICO ATÉ ACABER ORDENS DO DESSE ID PROC, NA ATIVIDADE EXPEDICAO/CONFERENCIA PRECISA TRAZER TUDO

END IF;

END; 