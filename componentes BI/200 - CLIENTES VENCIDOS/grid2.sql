SELECT 
FIN.CODEMP, 
FIN.DTNEG,
FIN.DTENTSAI, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
FIN.DTVENC, 
(TRUNC(SYSDATE) - FIN.DTVENC) as DIAS_ATRASO,
FIN.CODTIPTIT||'-'||TIT.DESCRTIPTIT AS TIPTITULO,
FIN.CODNAT||'-'||NAT.DESCRNAT AS NATUREZA,
FIN.CODTIPOPER,
FIN.HISTORICO,
VEN.APELIDO,
CASE WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') = TO_CHAR(SYSDATE,'YYYY/MM') THEN 'Vencido no mês'
	WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 0 AND 30 THEN 'Vencido até 30 dias'
     WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 31 AND 60 THEN 'Vencido até 60 dias'
     WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 61 AND 90 THEN 'Vencido até 90 dias'
     WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 91 AND 120 THEN 'Vencido até 120 dias'
     WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 121 AND 150 THEN 'Vencido até 150 dias'
	WHEN TO_CHAR(FIN.DTVENC,'YYYY/MM') < TO_CHAR(SYSDATE,'YYYY/MM')  AND (TRUNC(SYSDATE) - FIN.DTVENC) BETWEEN 151 AND 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO
FROM 
TGFFIN FIN, TGFPAR PAR, TGFNAT NAT, TGFTOP T , TGFTIT TIT, TGFVEN VEN
WHERE 
FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODTIPTIT = TIT.CODTIPTIT AND
PAR.CODVEND = VEN.CODVEND AND
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0) AND
FIN.CODEMP IN :CODEMP AND  
TRUNC(FIN.DTNEG) <= TRUNC(SYSDATE) AND  
FIN.DHBAIXA is null AND
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('V') AND 
FIN.RECDESP = 1 AND
TRUNC(FIN.DTVENC) < TRUNC(SYSDATE)
