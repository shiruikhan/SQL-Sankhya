SELECT ITE.CODPROD,
	PRO.DESCRPROD,
	CAB.DTENTSAI,
	CAB.AD_NUMPS AS PLANO,
	PRC.NROLOTE,
	ITE.CODLOCALORIG,
	LOC.DESCRLOCAL,
	SER.SERIE,
	(CASE WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S 
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA 
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 7 THEN 'Apontada e Conferida Expedição'
		WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S 
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA 
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 6 AND ITE.CODLOCALORIG = 109 THEN 'Conferida na expedição porem não apontada na montagem final'
        WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S 
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA 
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 6 THEN 'Apontada ate o setor Montagem final'
		WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 5 THEN 'Apontada ate o setor de teste'
		WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA 
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 4 THEN 'Apontada ate o setor de tampa e gabinete' 
		WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 3 THEN 'Apontada ate o setor de dissipador'        
        WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 2 THEN 'Apontada ate o setor de solda'        
        WHEN (SELECT COUNT(S.SERIE)
				FROM TGFSER S
					INNER JOIN TGFITE I ON I.SEQUENCIA=S.SEQUENCIA AND I.NUNOTA=S.NUNOTA
					INNER JOIN TGFCAB C ON C.NUNOTA=S.NUNOTA
				WHERE S.SERIE=SER.SERIE
					AND C.TIPMOV = 'F') = 1 THEN 'Apontada ate o setor de inserção'
		ELSE 'Serie com apontamento duplo ou Setaup menor' END) AS STATUS
FROM TGFCAB CAB
	INNER JOIN TGFITE ITE ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFSER SER ON SER.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
	INNER JOIN TPRIPROC PRC ON PRC.IDIPROC = CAB.IDIPROC
	INNER JOIN TGFLOC LOC ON ITE.CODLOCALORIG = LOC.CODLOCAL
WHERE TRUNC(CAB.DTENTSAI) >= :P_DTENTSAI.INI
	AND TRUNC(CAB.DTENTSAI) <= :P_DTENTSAI.FIN
	AND CAB.CODTIPOPER IN (800,802)
	AND PRO.USOPROD = 'V'
	AND (:P_CODLOCALORIG IS NULL OR ITE.CODLOCALORIG = :P_CODLOCALORIG)
	AND (:P_ADNUMPS IS NULL OR CAB.AD_NUMPS = :P_ADNUMPS)
	AND (:P_NROLOTE IS NULL OR PRC.NROLOTE = :P_NROLOTE)
	AND (:P_SERIE IS NULL OR SER.SERIE = :P_SERIE)
