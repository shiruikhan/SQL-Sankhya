SELECT

EST.CODEMP,
EST.CODLOCAL,
LOC.DESCRLOCAL,
PRO.CODPROD,
PRO.DESCRPROD AS PRODUTO,
EST.CONTROLE,
PRO.CODVOL AS UNIDADE,
EST.ESTOQUE,
EST.ESTMIN,
EST.ESTMAX,
PRO.ATIVO,
GRU.DESCRGRUPOPROD,
CASE WHEN ESTOQUE < 0 THEN 'RED' END AS FGCOLOR

  FROM 

    TGFPRO PRO
      INNER JOIN TGFEST EST ON (EST.CODPROD = PRO.CODPROD)
      INNER JOIN TGFLOC LOC ON (EST.CODLOCAL = LOC.CODLOCAL)
      INNER JOIN TGFGRU GRU ON (PRO.CODGRUPOPROD = GRU.CODGRUPOPROD)

  WHERE (EST.CODEMP = :EMPRESA OR :EMPRESA IS NULL)
          
    AND (LOC.CODLOCAL = :LOCAL OR :LOCAL IS NULL)
    AND (PRO.CODPROD = :PRODUTO OR :PRODUTO IS NULL)
    AND PRO.USOPROD <> 'S'
    AND EST.CODPARC = 0
    
  


ORDER BY EST.CODEMP,EST.CODLOCAL, GRU.CODGRUPOPROD, PRO.CODPROD, PRO.ATIVO
