SELECT CAB.CODEMP,
	EMP.NOMEFANTASIA AS EMPFATURAMENTO,
    SER.NUNOTA,
    CAB.NUMNOTA AS NPEDIDO,
    CAB.DTNEG,
	CAB.CODPARC,
    PAR.NOMEPARC,
    CAB.DTPREVENT,
    SER.CODPROD,
    SER.SEQUENCIA,
    SER.SERIE    
FROM TGFSER SER 
    INNER JOIN TGFCAB CAB ON CAB.NUNOTA = SER.NUNOTA
    INNER JOIN TGFPAR PAR ON PAR.CODPARC = CAB.CODPARC
    INNER JOIN TSIEMP EMP ON CAB.CODEMP = EMP.CODEMP    
WHERE TRUNC(CAB.DTPREVENT) >= :P_PERIODO.INI AND TRUNC(CAB.DTPREVENT) <= :P_PERIODO.FIN
	AND CAB.PENDENTE = 'S'
	AND CAB.CODEMP = 2
