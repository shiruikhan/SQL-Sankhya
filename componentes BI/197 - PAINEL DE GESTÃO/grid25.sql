SELECT * FROM
(

	/*CLIENTES EM ABERTO E DEVOLUÇÕES DE CLIENTES EM ABERTO - INICIO*/
	--TITULOS ORIGEM FINANCEIRO - TOP TIPO "V"
	SELECT 
	CASE WHEN T.TIPMOV = 'V' THEN '1 - Clientes em Aberto'
		 WHEN T.TIPMOV = 'D' THEN '3 - Devoluções de Clientes em Aberto'
	     ELSE '2 - Financeiro Receita em Aberto' END AS RELATORIO,
	CASE WHEN T.TIPMOV = 'V' THEN 'Portal'
		 WHEN T.TIPMOV = 'D' THEN 'Devolução'
	     ELSE 'Financeiro' END AS ORIGEM,
	FIN.CODEMP, 
	FIN.DTNEG,
	FIN.DTENTSAI, 
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
		WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
	     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	CASE WHEN T.TIPMOV = 'V' THEN PAR.CODCTACTB
		 WHEN T.TIPMOV = 'D' THEN 197
	     ELSE PAR.CODCTACTB END AS CODCTACTB1,
	NULL AS CODCTACTB2
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
	WHERE
	FIN.CODEMP IN :CODEMP AND  
	(CASE WHEN T.TIPMOV = 'V' THEN FIN.DTNEG ELSE FIN.DTENTSAI END) <= :DAT1 AND  
	(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
	 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
	FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
	((T.TIPMOV IN ('V') AND FIN.RECDESP = 1) OR
	(T.TIPMOV IN ('D') AND FIN.RECDESP = -1))
	
	UNION ALL
	
	--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
	SELECT
	CASE WHEN T.TIPMOV = 'V' THEN '1 - Clientes em Aberto'
		 WHEN T.TIPMOV = 'D' THEN '3 - Devoluções de Clientes em Aberto'
	     ELSE '2 - Financeiro Receita em Aberto' END AS RELATORIO,
	CASE WHEN T.TIPMOV <> 'I' THEN 'Portal'
	     ELSE 'Financeiro' END AS ORIGEM,
	FIN.CODEMP, 
	FIN.DTNEG, 
	FIN.DTENTSAI,
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
		WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
	     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	PAR.CODCTACTB AS CODCTACTB,
	NULL AS CODCTACTB
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
	WHERE
	FIN.CODEMP IN :CODEMP AND  
	FIN.DTNEG <= :DAT1 AND  
	(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND
	 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
	FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
	T.TIPMOV IN ('I') AND 
	FIN.RECDESP = 1 AND
	NAT.AD_TIPOCTBZ = 'N'
	/*CLIENTES EM ABERTO E DEVOLUÇÕES DE CLIENTES EM ABERTO - FIM*/

UNION ALL

	/*FORNECEDORES EM ABERTO E DEVOLUÇÕES DE FORNECEDORES EM ABERTO - INICIO*/
	--TITULOS ORIGEM PORTAL - TOP TIPO "C"/"E"
	SELECT
	CASE WHEN T.TIPMOV = 'C' THEN '4 - Fornecedores em Aberto'
		 WHEN T.TIPMOV = 'E' THEN '6 - Devolução à Fornecedores em Aberto'
		 ELSE '5 - Financeiro Despesa em Aberto' END AS RELATORIO,
	CASE WHEN T.TIPMOV = 'C' THEN 'Compra'
		 WHEN T.TIPMOV = 'E' THEN 'Devolução'
		 ELSE 'Financeiro' END AS ORIGEM,
	FIN.CODEMP,
	FIN.DTNEG, 
	FIN.DTENTSAI, 
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	NVL(((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) as VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
		WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
	     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	CASE WHEN T.TIPMOV = 'C' THEN PAR.CODCTACTB2
		 WHEN T.TIPMOV = 'E' THEN 198
		 ELSE PAR.CODCTACTB2 END AS CODCTACTB1,
	NULL AS CODCTACTB2
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
    LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
	WHERE
	FIN.CODEMP IN :CODEMP  AND  
	FIN.DTENTSAI <= :DAT1 AND 
	(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
	DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
	FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
	((T.TIPMOV IN ('C') AND FIN.RECDESP = -1) OR 
	 (T.TIPMOV IN ('E') AND FIN.RECDESP = 1))
	
	UNION ALL
	
	--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
	SELECT
	CASE WHEN T.TIPMOV = 'C' THEN '4 - Fornecedores em Aberto'
		 WHEN T.TIPMOV = 'E' THEN '6 - Devolução à Fornecedores em Aberto'
		 ELSE '5 - Financeiro Despesa em Aberto' END AS RELATORIO,
	CASE WHEN T.TIPMOV <> 'I' THEN 'Portal'
	     ELSE 'Financeiro' END AS ORIGEM,
	FIN.CODEMP,
	FIN.DTNEG, 
	FIN.DTENTSAI, 
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	NVL(((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) As VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
		WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
	     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	PAR.CODCTACTB2 AS CODCTACTB1,
	NULL AS CODCTACTB2
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
    LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
	WHERE
	FIN.CODEMP IN :CODEMP  AND  
	FIN.DTENTSAI <= :DAT1 AND 
	(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
	DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
	FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
	T.TIPMOV IN ('I') AND
	FIN.CODTIPOPER <> 0 AND  
	FIN.RECDESP = -1 AND
	NAT.AD_TIPOCTBZ = 'N' AND
    T.TIPMOV||'-'||NAT.CODNAT NOT IN ('I-301006')
	/*FORNECEDORES EM ABERTO E DEVOLUÇÕES DE FORNECEDORES EM ABERTO - FIM*/

UNION ALL

	/*PARCELAMENTOS TRIBUTÁRIOS - INÍCIO*/
	SELECT 
	'8 - Parcelamentos Tributários em Aberto' AS RELATORIO,
	'Financeiro' AS ORIGEM,
	FIN.CODEMP,
	FIN.DTNEG, 
	FIN.DTENTSAI, 
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	(FIN.VLRDESDOB)*FIN.RECDESP As VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||upper(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago' 
	     WHEN MONTHS_BETWEEN(TRUNC(DTVENC),TO_CHAR(:DAT1,'DD/MM/YYYY')) < 0 THEN 'Vencido' 
	     WHEN MONTHS_BETWEEN(TRUNC(DTVENC),TO_CHAR(:DAT1,'DD/MM/YYYY')) <= 12 THEN 'A vencer até 12 meses' 
	     ELSE 'Vencimento maior que 12 meses' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	NAT.CODCTACTB AS CODCTACTB1,
	NAT.CODCTACTB2 AS CODCATCTB2
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
	WHERE
	FIN.CODEMP IN :CODEMP AND  
	FIN.DTENTSAI <= :DAT1 AND  
	(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
	FIN.RECDESP = -1 AND 
	FIN.PROVISAO = 'N' AND 
	NAT.CODNATPAI= 999999
	/*PARCELAMENTOS TRIBUTÁRIOS - FIM*/	

UNION ALL

	/*ADIANTAMENTOS - INÍCIO*/	
	SELECT 
	'9 - Adiantamentos em Aberto' AS RELATORIO,
	'Financeiro' AS ORIGEM,
	FIN.CODEMP,
	FIN.DTNEG, 
	FIN.DTENTSAI, 
	FIN.NUMNOTA, 
	FIN.NUFIN, 
	FIN.CODPARC, 
	PAR.RAZAOSOCIAL, 
	(FIN.VLRDESDOB)*FIN.RECDESP As VALOR, 
	FIN.DTVENC, 
	FIN.DHBAIXA,
	FIN.CODTIPTIT||' - '||UPPER(TIT.DESCRTIPTIT) AS TIPTIT,
	FIN.CODNAT, 
	NAT.DESCRNAT,
	FIN.CODTIPOPER,
	FIN.NURENEG,
	CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
		 WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
	     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
	FIN.HISTORICO,
	NAT.CODCTACTB AS CODCTACTB1,
	NULL AS CODCATCTB2
	FROM 
	TGFFIN FIN 
	LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
	LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
	LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
	LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB
	LEFT JOIN TGFTIT TIT ON TIT.CODTIPTIT = FIN.CODTIPTIT
	WHERE 
	FIN.CODEMP IN :CODEMP  AND  
	FIN.DTENTSAI <= :DAT1 AND 
	(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
	DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
	FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
	T.TIPMOV IN ('I')  AND
	NAT.AD_TIPOCTBZ = 'A'
	/*ADIANTAMENTOS - FIM*/		
	
)
ORDER BY 
RELATORIO,
CODPARC,
DTENTSAI,
CODNAT,
DTVENC,
NUMNOTA,
NUFIN
