create or replace PROCEDURE "SPK_VALIDANATUREZA" (P_NUNOTA INT, P_SUCESSO OUT VARCHAR, P_MENSAGEM OUT VARCHAR2, P_CODUSULIB OUT NUMERIC) AS FIELD_NUNOTA NUMBER;
BEGIN
    DECLARE
        P_CODNATC   NUMBER;
        P_CODNATF   NUMBER;
    BEGIN

        BEGIN
            SELECT NVL(CODNAT,0) INTO P_CODNATC
            FROM TGFCAB
            WHERE NUNOTA = P_NUNOTA;

            SELECT NVL(CODNAT,0) INTO P_CODNATF
            FROM TGFCAB
            WHERE NUNOTA = P_NUNOTA;
        END;

        UPDATE TGFFIN SET CODNAT = P_CODNATC WHERE NUNOTA = P_NUNOTA;

        P_SUCESSO := 'S';       

    END;

END;