SELECT * FROM(
SELECT 
FIN.CODEMP,
FIN.DTENTSAI, 
FIN.DTNEG, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) As VALOR,
FIN.DTVENC,  
FIN.DHBAIXA,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
FIN.NURENEG,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Débito Pago/Compensado'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 0 THEN 'Débito a compensar'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 30 THEN 'Débito gerado até 30 dias'
	     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 60 THEN 'Débito gerado até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 90 THEN 'Débito gerado até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTENTSAI,'DD/MM/YYYY') <= 180 THEN 'Débito gerado até 180 dias'
     ELSE 'Débito gerado a mais de 180 dias' END AS CLASSIFICACAO,
HISTORICO,
197 AS CTACTB
FROM TGFFIN FIN , TGFPAR PAR , TGFNAT NAT , TGFTOP T  
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1  AND  
(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null)  AND  
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não'  AND  
FIN.VLRDESDOB * FIN.RECDESP <> 0  
AND  T.TIPMOV IN ('D')  AND
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0)
ORDER BY FIN.CODPARC, FIN.DTVENC
)
WHERE (CLASSIFICACAO = :CLASSIFICACAO OR :CLASSIFICACAO IS NULL)
