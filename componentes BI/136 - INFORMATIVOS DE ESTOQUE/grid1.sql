SELECT PRO.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,	
	(SELECT NVL(SUM(E101.ESTOQUE),0) FROM TGFEST E101 WHERE E101.CODPROD = PRO.CODPROD AND E101.CODLOCAL = 101) AS E101,
	(SELECT NVL(SUM(E107.ESTOQUE),0) FROM TGFEST E107 WHERE E107.CODPROD = PRO.CODPROD AND E107.CODLOCAL = 107) AS E107,
	(SELECT NVL(SUM(E114.ESTOQUE),0) FROM TGFEST E114 WHERE E114.CODPROD = PRO.CODPROD AND E114.CODLOCAL = 114) AS E114,
	(SELECT NVL(SUM(E201.ESTOQUE),0) FROM TGFEST E201 WHERE E201.CODPROD = PRO.CODPROD AND E201.CODLOCAL = 201) AS E201,
	(CASE WHEN PRO.ATIVO = 'S' THEN 'ATIVO' ELSE 'INATIVO' END) AS ATIVO,
	CASE WHEN EXISTS (SELECT LMP.CODPRODMP 
						FROM TPRLMP LMP 
							INNER JOIN TGFPRO PRO2 ON(PRO2.CODPROD = LMP.CODPRODMP) 
							INNER JOIN TPREFX EFX ON(EFX.IDEFX = LMP.IDEFX) 
							INNER JOIN TGFLOC LOC ON(LOC.CODLOCAL = LMP.CODLOCALORIG) 
						WHERE LMP.CODPRODMP = PRO.CODPROD 
							AND (NVL(LMP.CONTROLEPA, ' ') = ' ' OR LMP.CONTROLEPA = ' ') 
							AND (LMP.TIPOUSOMP IN ('N'))) 
		THEN 'SIM' ELSE 'NÃO' END AS FICHA,
	CASE WHEN EXISTS (SELECT LMP.CODPRODMP 
						FROM TPRLMP LMP 
							INNER JOIN TGFPRO PRO2 ON(PRO2.CODPROD = LMP.CODPRODMP) 
							INNER JOIN TPREFX EFX ON(EFX.IDEFX = LMP.IDEFX) 
							INNER JOIN TGFLOC LOC ON(LOC.CODLOCAL = LMP.CODLOCALORIG) 
						WHERE LMP.CODPRODMP = PRO.CODPROD 
							AND (NVL(LMP.CONTROLEPA, ' ') = ' ' OR LMP.CONTROLEPA = ' ') 
							AND (LMP.TIPOUSOMP IN ('N'))) 
		THEN '#cfe2f3' ELSE '#fff2cc' END AS BKCOLOR,	
	(SELECT MAX(C.DTENTSAI) FROM TGFCAB C INNER JOIN TGFITE I ON C.NUNOTA = I.NUNOTA WHERE I.CODPROD = PRO.CODPROD AND C.TIPMOV = 'C') AS ULTCOMPRA
FROM TGFPRO PRO 
WHERE (PRO.CODGRUPOPROD = :P_CODGRUPOPROD OR :P_CODGRUPOPROD IS NULL)
	AND (PRO.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	--AND PRO.ATIVO = 'S'
	AND PRO.USOPROD = 'M'
ORDER BY PRO.CODPROD
