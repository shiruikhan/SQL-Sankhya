SELECT
    CASE 
        WHEN PRO.CODPROD IS NOT NULL 
             AND SUBSTR(TO_CHAR(PRO.CODPROD), 1, 1) = '3' THEN 
            TO_NUMBER(
                SUBSTR(TO_CHAR(PRO.CODPROD), 1, 1) || 
                '1' || 
                SUBSTR(TO_CHAR(PRO.CODPROD), 3)
            )
        ELSE PRO.CODPROD
    END AS CODPROD_TRATADO,

    TO_CHAR(CAB.DTNEG, 'Mon/YYYY') AS PERIODO,
    TO_CHAR(CAB.DTNEG, 'YYYYMM') AS ORDEM,

    SUM(
        (
            (ITE.VLRTOT)
            - (CASE WHEN :DESC = 'S' THEN ITE.VLRDESC ELSE 0 END)
            - (CASE WHEN :REP  = 'S' THEN ITE.VLRREPRED ELSE 0 END)
            + (CASE WHEN :ST   = 'S' THEN ITE.VLRSUBST ELSE 0 END)
            + (CASE WHEN :IPI  = 'S' THEN ITE.VLRIPI ELSE 0 END)
        )
        * CASE WHEN CAB.TIPMOV = 'D' THEN -1 ELSE 1 END
        * VCAB.INDITENS
    ) AS VALOR

FROM TGFCAB CAB
JOIN TGFPAR PAR   ON CAB.CODPARC     = PAR.CODPARC
JOIN TGFITE ITE   ON CAB.NUNOTA      = ITE.NUNOTA
JOIN TGFPRO PRO   ON ITE.CODPROD     = PRO.CODPROD
JOIN TGFTOP TPO   ON CAB.CODTIPOPER  = TPO.CODTIPOPER
                  AND CAB.DHTIPOPER  = TPO.DHALTER
JOIN VGFCAB VCAB  ON VCAB.NUNOTA     = CAB.NUNOTA

WHERE 
    (CAB.STATUSNOTA = 'L' OR :STATUSNOTA = 'N')
    AND ITE.USOPROD <> 'D'
    AND TPO.GOLSINAL = -1
    AND (CAB.CODEMP = 501 OR CAB.STATUSNFE <> 'D')
    AND TPO.GRUPO IN :TOP
    AND CAB.DTNEG BETWEEN :PERIODO.INI AND :PERIODO.FIN
    AND (:PRODUTO IS NULL OR PRO.CODPROD = :PRODUTO)

GROUP BY 
    CASE 
        WHEN PRO.CODPROD IS NOT NULL 
             AND SUBSTR(TO_CHAR(PRO.CODPROD), 1, 1) = '3' THEN 
            TO_NUMBER(
                SUBSTR(TO_CHAR(PRO.CODPROD), 1, 1) || 
                '1' || 
                SUBSTR(TO_CHAR(PRO.CODPROD), 3)
            )
        ELSE PRO.CODPROD
    END,
    TO_CHAR(CAB.DTNEG, 'Mon/YYYY'),
    TO_CHAR(CAB.DTNEG, 'YYYYMM')

ORDER BY ORDEM
