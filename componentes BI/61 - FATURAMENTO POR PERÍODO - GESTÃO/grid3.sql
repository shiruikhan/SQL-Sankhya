SELECT ITE.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTENTSAI,
	CAB.CODEMP,
	CAB.CODPARC,
	PAR.RAZAOSOCIAL,
	ITE.CODPROD,
	PRO.DESCRPROD,
	PRO.CODVOL,
	ITE.QTDNEG,
	(ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED) AS TOTALLIQ,
	(NVL(ITE.AD_VLROUTROS,0)) AS TOTALOUTROS,
	(ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED) + (NVL(ITE.AD_VLROUTROS,0)) AS TOTAL,
	(ITE.QTDNEG/(SELECT SUM(ITE2.QTDNEG)
						FROM TGFITE ITE2
						INNER JOIN TGFCAB CAB2 ON ITE2.NUNOTA = CAB2.NUNOTA
						INNER JOIN TGFPRO PRO2 ON ITE2.CODPROD = PRO2.CODPROD
						INNER JOIN TGFGRU GRU2 ON PRO2.CODGRUPOPROD = GRU2.CODGRUPOPROD
						INNER JOIN TGFVEN VEN2 ON CAB2.CODVEND = VEN2.CODVEND
						WHERE TRUNC(CAB2.DTNEG) >= :P_PER.INI AND TRUNC(CAB2.DTNEG) <= :P_PER.FIN AND CAB2.TIPMOV = 'V' AND PRO2.USOPROD = 'V' AND ((:P_CODEMP IS NULL) OR (CAB2.CODEMP = :P_CODEMP)) AND ((:P_CODVEND IS NULL) OR (VEN2.CODVEND = :P_CODVEND)) AND CAB2.CODTIPOPER IN (1100,1124,2200))) * 100 AS PARTE,
	(((ITE.VLRTOT - ITE.VLRDESC - ITE.VLRREPRED) + NVL(ITE.AD_VLROUTROS,0))/(SELECT SUM(ITE3.VLRTOT - ITE3.VLRDESC - ITE3.VLRREPRED) + SUM(NVL(ITE3.AD_VLROUTROS,0))
																					FROM TGFITE ITE3
																					INNER JOIN TGFCAB CAB3 ON ITE3.NUNOTA = CAB3.NUNOTA
																					INNER JOIN TGFPRO PRO3 ON ITE3.CODPROD = PRO3.CODPROD
																					INNER JOIN TGFGRU GRU3 ON PRO3.CODGRUPOPROD = GRU3.CODGRUPOPROD
																					INNER JOIN TGFVEN VEN3 ON CAB3.CODVEND = VEN3.CODVEND
																					WHERE TRUNC(CAB3.DTNEG) >= :P_PER.INI AND TRUNC(CAB3.DTNEG) <= :P_PER.FIN AND CAB3.TIPMOV = 'V' AND PRO3.USOPROD = 'V' AND ((:P_CODEMP IS NULL) OR (CAB3.CODEMP = :P_CODEMP)) AND ((:P_CODVEND IS NULL) OR (VEN3.CODVEND = :P_CODVEND)) AND CAB3.CODTIPOPER IN (1100,1124,2200))) * 100 AS PARTEFATURADO
FROM TGFITE ITE
INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
INNER JOIN TGFVEN VEN ON CAB.CODVEND = VEN.CODVEND
INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
WHERE TRUNC(CAB.DTNEG) >= :P_PER.INI AND TRUNC(CAB.DTNEG) <= :P_PER.FIN AND CAB.TIPMOV = 'V' AND PRO.USOPROD = 'V' AND ((:P_CODEMP IS NULL) OR (CAB.CODEMP = :P_CODEMP)) AND ((:P_CODVEND IS NULL) OR (VEN.CODVEND = :P_CODVEND)) AND CAB.CODTIPOPER IN (1100,1124,2200) AND (ITE.CODPROD IN (SELECT PRO4.CODPROD FROM TGFPRO PRO4 WHERE PRO4.AD_AGRUPADOR = :A_AD_AGRUPADOR)) AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
ORDER BY ITE.NUNOTA
