SELECT NUMNOTA,DTENTSAI, COUNT(NUFIN) AS QTDE, SUM(VRCP) AS VRCP, SUM(VRLP) AS VRLP, SUM(VRTOT) AS VRTOT, :NATUREZA AS NATUREZA2 FROM (
SELECT 
FIN.NUMNOTA,
FIN.CODNAT,
NAT.DESCRNAT,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN (FIN.VLRDESDOB + FIN.VLRJURO)*FIN.RECDESP ELSE 0 END As VRCP,
CASE WHEN MONTHS_BETWEEN(DTVENC,:DAT1) <= 12 THEN 0 ELSE (FIN.VLRDESDOB + FIN.VLRJURO)*FIN.RECDESP END As VRLP,
FIN.DTENTSAI, 
FIN.NUMNOTA As "Nro_Nota", 
FIN.DTVENC As "DtVencto", 
(FIN.VLRDESDOB*FIN.RECDESP) As "Vlr_Amortizacao", 
(FIN.VLRJURO*FIN.RECDESP) As "Vlr_Juros", 
((FIN.VLRDESDOB + FIN.VLRJURO)*FIN.RECDESP) As "VRTOT", 
FIN.CODTIPOPER As "Top", 
FIN.HISTORICO As "Historico", 
FIN.NUFIN As Nufin 
FROM TGFFIN FIN, TGFPAR PAR, TGFNAT NAT
WHERE PAR.CODPARC = FIN.CODPARC AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.CODNAT = NAT.CODNAT AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTENTSAI <= :DAT1 AND  
(FIN.DHBAIXA > :DAT1 OR FIN.DHBAIXA is null) AND 
FIN.RECDESP = -1 AND 
FIN.PROVISAO = 'N' AND 
NAT.CODNATPAI= 040500 AND
(NAT.CODNAT = :NATUREZA OR :NATUREZA = 0)

)
GROUP BY NUMNOTA, DTENTSAI

UNION ALL

SELECT 0 AS NUMNOTA, TO_DATE('01/01/1900','DD/MM/YYYY') AS DTENTSAI, 0 AS QTDE, 0 AS VRCP, 0 AS VRLP, 0 AS VRTOT, :NATUREZA AS NATUREZA2 FROM DUAL

ORDER BY DTENTSAI, NUMNOTA
