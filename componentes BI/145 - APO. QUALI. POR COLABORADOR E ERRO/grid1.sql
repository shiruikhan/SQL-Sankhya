SELECT OPE.NOMEFUNC AS OPERADORTESTE,
	OPE2.NOMEFUNC AS OPERADORFAB,
	REV2.NOMEFUNC AS REVISORFAB,
	REV.NOMEFUNC AS REVISOR,
	NVL(SUM(APO.MINSERIDO),0) AS MINSERIDO,
	NVL(SUM(APO.FALTANDO),0) AS FALTANDO,
	NVL(SUM(APO.INVERTIDO),0) AS INVERTIDO,
	NVL(SUM(APO.TROCADO),0) AS TROCADO,
	NVL(SUM(APO.QUEIMADO),0) AS QUEIMADO,
	NVL(SUM(APO.CURTO),0) AS CURTO,
	NVL(SUM(APO.SOLDAFRIA),0) AS SOLDAFRIA,
	NVL(SUM(APO.DEFEITOMP),0) AS DEFEITOMP
FROM AD_APOQLD APO
	LEFT JOIN TFPFUN OPE ON APO.FUNCOPERADOR = OPE.CODFUNC
	LEFT JOIN TFPFUN REV ON APO.FUNCREVISOR = REV.CODFUNC
	LEFT JOIN TFPFUN OPE2 ON APO.FUNCOPERADOR2 = OPE2.CODFUNC
	LEFT JOIN TFPFUN REV2 ON APO.FUNCREVISOR2 = REV2.CODFUNC
WHERE (:P_PERIODO IS NULL OR (:P_PERIODO >= APO.DTAPO AND :P_PERIODO <= APO.DTAPO))
	AND APO.SETOR IN :P_SETOR
GROUP BY OPE.NOMEFUNC,
	REV.NOMEFUNC,
	OPE2.NOMEFUNC,
	REV2.NOMEFUNC
ORDER BY OPE.NOMEFUNC
