SELECT ITE.NUNOTA,
	ITE.CODPROD,
	PRO.DESCRPROD,
	ITE.CODVOL,
	(CASE WHEN VOA.CODPROD IS NULL THEN ITE.QTDNEG WHEN VOA.DIVIDEMULTIPLICA = 'D' THEN ITE.QTDNEG * VOA.QUANTIDADE	ELSE ITE.QTDNEG / VOA.QUANTIDADE END) AS QTDNEG
FROM TGFITE ITE
	INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	LEFT JOIN TGFVOA VOA ON (VOA.CODPROD = ITE.CODPROD AND VOA.CODVOL = ITE.CODVOL AND ((ITE.CONTROLE IS NULL AND VOA.CONTROLE = ' ') OR (ITE.CONTROLE IS NOT NULL AND ITE.CONTROLE = VOA.CONTROLE)))
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
WHERE CAB.CODTIPOPER IN (1202)
	AND ITE.NUNOTA IN (SELECT DISTINCT C.NUNOTA FROM TGFCAB C WHERE C.CODTIPOPER = 1202 AND C.CHAVENFEREF = (SELECT CHAVENFE FROM TGFCAB WHERE NUNOTA = :A_NUNOTA))
ORDER BY ITE.CODPROD
