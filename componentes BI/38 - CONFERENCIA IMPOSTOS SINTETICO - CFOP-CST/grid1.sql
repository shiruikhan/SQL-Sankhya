SELECT NUNOTA, NUMNOTA, DTNEG, DTENTSAI, STATUSNFE, CODTIPOPER, CODPARC, NOMEPARC, CODTIPPARC, 
UF_DEST AS UF_DEST, 
UF_ORIG AS UF_ORIG,
CHAVENFE, 
IDENTINSCESTAD,
--DESCRGRUPOPROD,
SUM(VLRCTB) AS VLRTOT, 
MAX(CODCFO) AS CODCFO,  
MAX(CODTRIB) AS CODTRIB, 
SUM(BASEICMS) AS BASEICMS, 
MAX(ALIQICMS) AS ALIQICMS, 
SUM(VLRICMS) AS VLRICMS, 
MAX(CSTIPI) AS CSTIPI, 
SUM(BASEIPI) AS BASEIPI, 
MAX(ALIQIPI) AS ALIQIPI , 
SUM(VLRIPI) AS VLRIPI,
SUM(BASE_PIS) AS BASE_PIS,
SUM(VLR_PIS) AS VLR_PIS,
SUM(BASE_COFINS) AS BASE_COFINS,
SUM(VLR_COFINS) AS VLR_COFINS,
SUM(BASE_ST) AS BASE_ST,
SUM(VLR_ST) AS VLR_ST,
SUM(VLR_FEM_ICMS_ST) AS VLR_FEM_ICMS_ST,
SUM(VLR_FEM_ICMS_OP) AS VLR_FEM_ICMS_OP

FROM
(
   SELECT CAB.NUNOTA, CAB.NUMNOTA, CAB.DTNEG, CAB.DTENTSAI,
	CASE 
		WHEN CAB.STATUSNFE IS NULL AND CAB.TIPMOV = 'P' THEN '-----' 
		WHEN CAB.STATUSNFE = 'A' THEN 'Aprovada'
		WHEN CAB.STATUSNFE = 'D' THEN 'Denegada'
		WHEN CAB.STATUSNFE = 'E' THEN 'Aguardando Autorização'
		WHEN CAB.STATUSNFE = 'I' THEN 'Enviada'
		WHEN CAB.STATUSNFE = 'M' THEN 'Não é NF-e'
		WHEN CAB.STATUSNFE = 'P' THEN 'Pendente de Retorno'
		WHEN CAB.STATUSNFE = 'R' THEN 'Aguardando Correção'
		WHEN CAB.STATUSNFE = 'S' THEN 'Enviada EPEC'
		WHEN CAB.STATUSNFE = 'T' THEN 'NF-e Terceiro'
		WHEN CAB.STATUSNFE = 'V' THEN 'Com erro de Validação' 
		ELSE 'Não Enviada' END AS STATUSNFE, 
CAB.CODTIPOPER, PAR.CODPARC, PAR.NOMEPARC, PAR.CODTIPPARC, ITE.SEQUENCIA, ITE.CODPROD, PRO.DESCRPROD, 
ITE.QTDNEG, ITE.VLRUNIT, LIV.VLRCTB, ITE.CODCFO,  ITE.CODTRIB, ITE.BASEICMS, ITE.ALIQICMS, ITE.VLRICMS, 
ITE.CSTIPI, ITE.BASEIPI, ITE.ALIQIPI , ITE.VLRIPI,  LIV.UFDESTINO AS "UF_DEST", LIV.UFORIGEM AS "UF_ORIG",
(SELECT SUM(DIN.BASERED)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 6) AS BASE_PIS,
(SELECT SUM(DIN.VALOR)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 6) AS VLR_PIS,

(SELECT SUM(DIN.BASERED)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 7) AS BASE_COFINS,
(SELECT SUM(DIN.VALOR)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 7) AS VLR_COFINS,

(SELECT SUM(DIN.BASE)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 2) AS BASE_ST,
(SELECT SUM(DIN.VALOR)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 2) AS VLR_ST,   

(SELECT SUM(DIN.VLRFCPINT)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 2) AS VLR_FEM_ICMS_ST,   
   
(SELECT SUM(DIN.VLRFCPINT)
   FROM TGFDIN DIN
  WHERE DIN.NUNOTA = ITE.NUNOTA
   AND DIN.SEQUENCIA = ITE.SEQUENCIA
   AND DIN.CODIMP = 1) AS VLR_FEM_ICMS_OP,

   GRU.DESCRGRUPOPROD, 
   PAR.IDENTINSCESTAD,
   CAB.CHAVENFE, 
   (SELECT MAX(C.NUMNOTA) FROM TGFCAB C, TGFVAR VAR WHERE C.NUNOTA = VAR.NUNOTA AND VAR.NUNOTAORIG = CAB.NUNOTA AND C.TIPMOV = 'D') AS NUMNOTA_DEVOLUCAO,
   (SELECT MAX(I.VLRTOT) FROM TGFCAB C, TGFITE I, TGFVAR VAR WHERE C.NUNOTA = I.NUNOTA AND C.NUNOTA = VAR.NUNOTA AND I.SEQUENCIA = VAR.SEQUENCIA AND VAR.NUNOTAORIG = CAB.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA AND C.TIPMOV = 'D') AS VLRTOT_DEVOLUCAO,
   (SELECT MAX(I.VLRIPI) FROM TGFCAB C, TGFITE I, TGFVAR VAR WHERE C.NUNOTA = I.NUNOTA AND C.NUNOTA = VAR.NUNOTA AND I.SEQUENCIA = VAR.SEQUENCIA AND VAR.NUNOTAORIG = CAB.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA AND C.TIPMOV = 'D') AS VLRIPI_DEVOLUCAO,
   (SELECT MAX(I.VLRICMS) FROM TGFCAB C, TGFITE I, TGFVAR VAR WHERE C.NUNOTA = I.NUNOTA AND C.NUNOTA = VAR.NUNOTA AND I.SEQUENCIA = VAR.SEQUENCIA AND VAR.NUNOTAORIG = CAB.NUNOTA AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA AND C.TIPMOV = 'D') AS VLRICMS_DEVOLUCAO
   
   FROM TGFCAB CAB, TGFITE ITE, TGFPRO PRO, TGFPAR PAR, TGFTOP TPO, TGFGRU GRU, TSICID CID, TSIUFS UF, TGFLIV LIV
   WHERE LIV.NUNOTA = CAB.NUNOTA 
   AND LIV.NUNOTA = ITE.NUNOTA 
   AND LIV.SEQUENCIA = ITE.SEQUENCIA 
   AND CAB.NUNOTA = ITE.NUNOTA 
   AND ITE.CODPROD = PRO.CODPROD
   AND CAB.CODPARC = PAR.CODPARC
   AND PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
   AND CAB.CODCIDDESTINO = CID.CODCID
   AND CID.UF = UF.CODUF
   AND CAB.CODTIPOPER = TPO.CODTIPOPER
   AND CAB.DHTIPOPER = TPO.DHALTER
   AND TPO.ATUALLIVFIS <> 'N'
   AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
   AND (CAB.DTNEG >= :P_PERIODO.INI or :P_PERIODO.INI is null)
   AND (CAB.DTNEG <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)
   AND (CAB.DTENTSAI >= :P_DTENTSAI.INI or :P_DTENTSAI.INI is null)
   AND (CAB.DTENTSAI <= :P_DTENTSAI.FIN or :P_DTENTSAI.FIN is null)
   AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
   AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)   
   AND ITE.CODCFO >= :P_CODCFOPINI
   AND ITE.CODCFO <= :P_CODCFOPFIN
   --AND CAB.TIPMOV = 'V'
) V 
GROUP BY NUNOTA, NUMNOTA, DTNEG, DTENTSAI, STATUSNFE, CODTIPOPER, CODPARC, NOMEPARC, CODTIPPARC, UF_DEST, 
UF_ORIG, CHAVENFE, IDENTINSCESTAD, CODCFO, CODTRIB
ORDER BY DTNEG, DTENTSAI, NUMNOTA, UF_ORIG, UF_DEST
