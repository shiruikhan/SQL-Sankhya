SELECT abs(SUM(VALOR)) AS VALOR, CLASSIFICACAO, :PARCEIRO AS PARCEIRO2 FROM(
--TITULOS ORIGEM PORTAL - TOP TIPO "C"/"E"
SELECT
CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) AS VALOR
FROM 
TGFFIN FIN 
LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
WHERE
FIN.CODEMP IN :CODEMP  AND  
FIN.DTENTSAI <= :DAT1 AND 
(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
((T.TIPMOV IN ('C') AND FIN.RECDESP = -1) OR 
(T.TIPMOV IN ('O') AND FIN.RECDESP = -1 AND T.ATUALCTB = 'S') OR 
 (T.TIPMOV IN ('E') AND FIN.RECDESP = 1)) AND
FIN.CODTIPOPER <> 0 AND  
FIN.RECDESP = -1 AND
(FIN.CODPARC = :PARCEIRO OR :PARCEIRO = 0) AND
:OUTROS IN ('A','P')
GROUP BY FIN.DTVENC, FIN.DHBAIXA
UNION ALL
--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
SELECT
CASE WHEN DHBAIXA IS NOT NULL THEN 'Pago/Compensado'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
NVL(SUM((FIN.VLRDESDOB-NVL(IMF.VALOR,0))*FIN.RECDESP),0) AS VALOR
FROM 
TGFFIN FIN 
LEFT JOIN TGFPAR PAR ON PAR.CODPARC = FIN.CODPARC
LEFT JOIN TGFNAT NAT ON NAT.CODNAT = FIN.CODNAT
LEFT JOIN TGFTOP T ON T.CODTIPOPER = FIN.CODTIPOPER AND T.DHALTER = FIN.DHTIPOPER
LEFT JOIN TCBPLA PLA ON PLA.CODCTACTB = PAR.CODCTACTB2
LEFT JOIN (SELECT NUFIN, SUM(VALOR) AS VALOR FROM TGFIMF GROUP BY NUFIN) IMF ON IMF.NUFIN = FIN.NUFIN
WHERE
FIN.CODEMP IN :CODEMP  AND  
FIN.DTENTSAI <= :DAT1 AND 
(FIN.DHBAIXA > :DAT1  OR  FIN.DHBAIXA is null) AND 
DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0  AND  
T.TIPMOV IN ('I') AND 
NAT.AD_TIPOCTBZ = 'N' AND
FIN.CODTIPOPER <> 0 AND  
FIN.RECDESP = -1 AND
(FIN.CODPARC = :PARCEIRO OR :PARCEIRO = 0) AND
T.TIPMOV||'-'||NAT.CODNAT NOT IN ('I-301006') AND
:OUTROS IN ('A','P')
GROUP BY FIN.DTVENC, FIN.DHBAIXA)
Group by classificacao
