SELECT T.CODPROD,
	T.DESCRPROD,
	T.CODVOL,
	SUM(T.QTDRECEBIDA) AS QTDREC,
	SUM(T.QTDENVIADA) AS QTDENV
FROM (SELECT ITE.CODPROD,
		PRO.DESCRPROD,
		PRO.CODVOL,
		(CASE WHEN CAB.CODTIPOPER IN (1202,1212,1213) THEN ITE.QTDNEG ELSE 0 END) AS QTDRECEBIDA,
		(CASE WHEN CAB.CODTIPOPER IN (1108,2208,1123/*,2223*/) THEN -ITE.QTDNEG ELSE 0 END) AS QTDENVIADA
	FROM TGFITE ITE
		INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
		INNER JOIN TGFPAR PAR ON CAB.CODPARC = PAR.CODPARC
		INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
	WHERE CAB.DTENTSAI >= :P_PERIODO.INI
		AND CAB.DTENTSAI <= :P_PERIODO.FIN
		AND (:P_CODPARC IS NULL OR CAB.CODPARC = :P_CODPARC)
		AND (:P_CODPROD IS NULL OR ITE.CODPROD = :P_CODPROD)
		--AND ITE.ATUALESTOQUE <> 0
		AND CAB.STATUSNOTA = 'L'
		AND CAB.CODTIPOPER IN (1202,1108,2208,1123,1212,1213/*,2223*/)) T
GROUP BY T.CODPROD,
	T.DESCRPROD,
	T.CODVOL
ORDER BY T.CODPROD