SELECT *
FROM (SELECT ITE.CODPROD,
		PRO.DESCRPROD,
		PRO.CODVOL,
		SUM(ITE.QTDNEG) AS QTDNEG,
		EXTRACT(MONTH FROM CAB.DTENTSAI) AS MES,
		GRU.CODGRUPOPROD || '-' || GRU.DESCRGRUPOPROD AS DESCRGRUPOPROD,
		PAR.CODPARC || '-' || PAR.RAZAOSOCIAL AS PARCEIRO,
		PRO.ESTMIN
	FROM TGFITE ITE
		INNER JOIN TGFPRO PRO ON ITE.CODPROD = PRO.CODPROD
		INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
		INNER JOIN TGFGRU GRU ON PRO.CODGRUPOPROD = GRU.CODGRUPOPROD
		LEFT JOIN TGFPAR PAR ON PRO.CODPARCFORN = PAR.CODPARC
	WHERE CAB.STATUSNOTA = 'L'
		AND CAB.TIPMOV = 'Q' --APENAS REQUISIÇÕES, PARA TRATAR AS TRANSFERENCIAS PRECISA INCLUIR O 'T'
		AND ITE.ATUALESTOQUE = -1 --VALIDAÇÃO DE APENAS SAÍDAS DE ESTOQUE - IGNORAR AS ENTRADAS -
		AND EXTRACT(YEAR FROM CAB.DTENTSAI) = :P_ANO --O ANO É NECESSÁRIO PARA FILTRAR OS MESES
		AND (:P_CODGRUPOPROD IS NULL OR (PRO.CODGRUPOPROD = :P_CODGRUPOPROD)) 
		AND (:P_CODPROD IS NULL OR (ITE.CODPROD = :P_CODPROD)) 
		AND ITE.CODLOCALORIG = 101 --APENAS REQUISIÇÕES SAINDO DO ALMOXARIFADO
		AND (:P_CODPARC IS NULL OR PRO.CODPARCFORN = :P_CODPARC)
	GROUP BY ITE.CODPROD,
		PRO.DESCRPROD,
		PRO.CODVOL,
		ITE.ATUALESTOQUE,
		EXTRACT(MONTH FROM CAB.DTENTSAI),
		GRU.CODGRUPOPROD || '-' || GRU.DESCRGRUPOPROD,
		PAR.CODPARC || '-' || PAR.RAZAOSOCIAL,
		PRO.ESTMIN
	ORDER BY ITE.CODPROD) V
PIVOT (SUM(NVL(QTDNEG,0)) FOR MES IN (
        '01' AS Janeiro,
        '02' AS Fevereiro,
        '03' AS Marco,
        '04' AS Abril,
        '05' AS Maio,
        '06' AS Junho,
        '07' AS Julho,
		'08' AS Agosto,
		'09' AS Setembro,
		'10' AS Outubro,
		'11' AS Novembro,
		'12' AS Dezembro))
ORDER BY CODPROD
