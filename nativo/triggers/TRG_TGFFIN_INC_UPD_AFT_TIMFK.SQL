/*==============================================================================
  Nome do Script : TRG_TGFFIN_INC_UPD_AFT_TIMFK
  Tipo           : Trigger de origem Sankhya (lote de atualização do ERP de 01/07/2022 — referência)
  Descrição      : Trigger AFTER STATEMENT INSERT OR UPDATE sobre TGFFIN.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 01/07/2022, última alteração em 21/09/2026.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026 (recaptura em pedaços — DDL completo, conferido pelo tamanho), via GET_DDL('TRIGGER', 'TRG_TGFFIN_INC_UPD_AFT_TIMFK', 'SPARKPRD').
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_TGFFIN_INC_UPD_AFT_TIMFK" 
AFTER INSERT OR UPDATE
ON TGFFIN
DECLARE
    P_COUNT INT;
    P_ERRMSG VARCHAR(255);
    ERROR EXCEPTION;
    
    TYPE OLD_TGFFIN_TYPE IS TABLE OF TGFFIN_INC_UPD_TIMFK%ROWTYPE INDEX BY PLS_INTEGER;
    OLD_TGFFIN_LIST OLD_TGFFIN_TYPE;

    OLD_FIN TGFFIN_INC_UPD_TIMFK%ROWTYPE;
    NEW_FIN TGFFIN%ROWTYPE;
BEGIN

   IF STP_GET_ATUALIZANDO THEN
    RETURN;
   END IF;

   IF NOT STP_GET_TIMUTILIZAIMOB
   THEN
      RETURN;
   END IF;

    DELETE
    FROM TGFFIN_INC_UPD_TIMFK DLT
    WHERE NOT EXISTS (
        SELECT 1
        FROM TGFFIN
        WHERE NUFIN = DLT.NUFIN
    );

    SELECT * BULK COLLECT INTO OLD_TGFFIN_LIST
    FROM TGFFIN_INC_UPD_TIMFK
    WHERE PROCESSANDO = 'N';

    FOR I IN 1..OLD_TGFFIN_LIST.COUNT
    LOOP
        UPDATE TGFFIN_INC_UPD_TIMFK
        SET PROCESSANDO = 'S'
        WHERE NUFIN = OLD_TGFFIN_LIST(I).NUFIN;
    END LOOP;
    
    FOR I IN 1..OLD_TGFFIN_LIST.COUNT
    LOOP
        OLD_FIN := OLD_TGFFIN_LIST(I);
        
        SELECT * INTO NEW_FIN
        FROM TGFFIN
        WHERE NUFIN = OLD_FIN.NUFIN;
        
        
        IF ((NEW_FIN.TIMCONTAREP IS NOT NULL AND NEW_FIN.CODPARC IS NOT NULL)
            AND (OLD_FIN.TIMCONTAREP IS NULL OR OLD_FIN.CODPARC IS NULL OR OLD_FIN.TIMCONTAREP != NEW_FIN.TIMCONTAREP OR OLD_FIN.CODPARC != NEW_FIN.CODPARC)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMCBL
            WHERE CBLCODIGO = NEW_FIN.TIMCONTAREP
            AND CBLLOCADOR = NEW_FIN.CODPARC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMCONTAREP')||'"",""'||FIELD_LABEL('TGFFIN','CODPARC')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMCONTRATOLOC IS NOT NULL AND NEW_FIN.TIMNEGOCIACAO IS NOT NULL)
            AND (OLD_FIN.TIMCONTRATOLOC IS NULL OR OLD_FIN.TIMNEGOCIACAO IS NULL OR OLD_FIN.TIMCONTRATOLOC != NEW_FIN.TIMCONTRATOLOC OR OLD_FIN.TIMNEGOCIACAO != NEW_FIN.TIMNEGOCIACAO)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMLCR
            WHERE LCRCONTRATO = NEW_FIN.TIMCONTRATOLOC
            AND LCRCONTADOR = NEW_FIN.TIMNEGOCIACAO;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLOC')||'"",""'||FIELD_LABEL('TGFFIN','TIMNEGOCIACAO')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMFECHAMENTO IS NOT NULL AND NEW_FIN.TIMCONTRATOLOC IS NOT NULL)
            AND (OLD_FIN.TIMFECHAMENTO IS NULL OR OLD_FIN.TIMCONTRATOLOC IS NULL OR OLD_FIN.TIMFECHAMENTO != NEW_FIN.TIMFECHAMENTO OR OLD_FIN.TIMCONTRATOLOC != NEW_FIN.TIMCONTRATOLOC)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMFEI
            WHERE FEIFECHAMENTO = NEW_FIN.TIMFECHAMENTO
            AND FEICONTRATOLOC = NEW_FIN.TIMCONTRATOLOC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMFECHAMENTO')||'"",""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLOC')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMFECHAMENTOALU IS NOT NULL AND NEW_FIN.TIMCONTRATOLOC IS NOT NULL)
            AND (OLD_FIN.TIMFECHAMENTOALU IS NULL OR OLD_FIN.TIMCONTRATOLOC IS NULL OR OLD_FIN.TIMFECHAMENTOALU != NEW_FIN.TIMFECHAMENTOALU OR OLD_FIN.TIMCONTRATOLOC != NEW_FIN.TIMCONTRATOLOC)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMFAI
            WHERE FAIFECHAMENTO = NEW_FIN.TIMFECHAMENTOALU
            AND FAICONTRATOLOC = NEW_FIN.TIMCONTRATOLOC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMFECHAMENTOALU')||'"",""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLOC')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMRENEGCANCLOTE IS NOT NULL AND NEW_FIN.TIMCONTRATOLTV IS NOT NULL)
            AND (OLD_FIN.TIMRENEGCANCLOTE IS NULL OR OLD_FIN.TIMCONTRATOLTV IS NULL OR OLD_FIN.TIMRENEGCANCLOTE != NEW_FIN.TIMRENEGCANCLOTE OR OLD_FIN.TIMCONTRATOLTV != NEW_FIN.TIMCONTRATOLTV)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMLVR
            WHERE LVRCODIGO = NEW_FIN.TIMRENEGCANCLOTE
            AND LVRCONTRATO = NEW_FIN.TIMCONTRATOLTV;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMRENEGCANCLOTE')||'"",""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLTV')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMRENEGLOTE IS NOT NULL AND NEW_FIN.TIMCONTRATOLTV IS NOT NULL)
            AND (OLD_FIN.TIMRENEGLOTE IS NULL OR OLD_FIN.TIMCONTRATOLTV IS NULL OR OLD_FIN.TIMRENEGLOTE != NEW_FIN.TIMRENEGLOTE OR OLD_FIN.TIMCONTRATOLTV != NEW_FIN.TIMCONTRATOLTV)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMLVR
            WHERE LVRCODIGO = NEW_FIN.TIMRENEGLOTE
            AND LVRCONTRATO = NEW_FIN.TIMCONTRATOLTV;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMRENEGLOTE')||'"",""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLTV')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF ((NEW_FIN.TIMRESCISAOLTV IS NOT NULL AND NEW_FIN.TIMCONTRATOLTV IS NOT NULL)
            AND (OLD_FIN.TIMRESCISAOLTV IS NULL OR OLD_FIN.TIMCONTRATOLTV IS NULL OR OLD_FIN.TIMRESCISAOLTV != NEW_FIN.TIMRESCISAOLTV OR OLD_FIN.TIMCONTRATOLTV != NEW_FIN.TIMCONTRATOLTV)) THEN
    
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMDLV
            WHERE DLVCODIGO = NEW_FIN.TIMRESCISAOLTV
            AND DLVCONTRATO = NEW_FIN.TIMCONTRATOLTV;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'Os campos ""'||FIELD_LABEL('TGFFIN','TIMRESCISAOLTV')||'"",""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLTV')||'"" não possuem valores válidos.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMCONTALANC IS NULL AND NEW_FIN.TIMCONTALANC IS NOT NULL) OR (OLD_FIN.TIMCONTALANC != NEW_FIN.TIMCONTALANC) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TSICTA
            WHERE CODCTABCOINT = NEW_FIN.TIMCONTALANC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMCONTALANC')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMCONTRATOADM IS NULL AND NEW_FIN.TIMCONTRATOADM IS NOT NULL) OR (OLD_FIN.TIMCONTRATOADM != NEW_FIN.TIMCONTRATOADM) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMADM
            WHERE ADMNUCONTRATO = NEW_FIN.TIMCONTRATOADM;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMCONTRATOADM')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMCONTRATOLOC IS NULL AND NEW_FIN.TIMCONTRATOLOC IS NOT NULL) OR (OLD_FIN.TIMCONTRATOLOC != NEW_FIN.TIMCONTRATOLOC) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMLOC
            WHERE LOCCODIGO = NEW_FIN.TIMCONTRATOLOC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLOC')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMCONTRATOLTV IS NULL AND NEW_FIN.TIMCONTRATOLTV IS NOT NULL) OR (OLD_FIN.TIMCONTRATOLTV != NEW_FIN.TIMCONTRATOLTV) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMLTV
            WHERE LTVCODIGO = NEW_FIN.TIMCONTRATOLTV;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMCONTRATOLTV')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMFINGARANTORIG IS NULL AND NEW_FIN.TIMFINGARANTORIG IS NOT NULL) OR (OLD_FIN.TIMFINGARANTORIG != NEW_FIN.TIMFINGARANTORIG) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TGFFIN
            WHERE NUFIN = NEW_FIN.TIMFINGARANTORIG;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMFINGARANTORIG')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMIMOVEL IS NULL AND NEW_FIN.TIMIMOVEL IS NOT NULL) OR (OLD_FIN.TIMIMOVEL != NEW_FIN.TIMIMOVEL) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMIMV
            WHERE IMVCODIGO = NEW_FIN.TIMIMOVEL;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMIMOVEL')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMNUFINORIG IS NULL AND NEW_FIN.TIMNUFINORIG IS NOT NULL) OR (OLD_FIN.TIMNUFINORIG != NEW_FIN.TIMNUFINORIG) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TGFFIN
            WHERE NUFIN = NEW_FIN.TIMNUFINORIG;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMNUFINORIG')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMREPINTELIGENTE IS NULL AND NEW_FIN.TIMREPINTELIGENTE IS NOT NULL) OR (OLD_FIN.TIMREPINTELIGENTE != NEW_FIN.TIMREPINTELIGENTE) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TSIUSU
            WHERE CODUSU = NEW_FIN.TIMREPINTELIGENTE;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMREPINTELIGENTE')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMRESCISAOLOC IS NULL AND NEW_FIN.TIMRESCISAOLOC IS NOT NULL) OR (OLD_FIN.TIMRESCISAOLOC != NEW_FIN.TIMRESCISAOLOC) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMREC
            WHERE RECCODIGO = NEW_FIN.TIMRESCISAOLOC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMRESCISAOLOC')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMSAC IS NULL AND NEW_FIN.TIMSAC IS NOT NULL) OR (OLD_FIN.TIMSAC != NEW_FIN.TIMSAC) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMSAC
            WHERE SACCODIGO = NEW_FIN.TIMSAC;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMSAC')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        IF (OLD_FIN.TIMTIPOINTERMED IS NULL AND NEW_FIN.TIMTIPOINTERMED IS NOT NULL) OR (OLD_FIN.TIMTIPOINTERMED != NEW_FIN.TIMTIPOINTERMED) THEN
            SELECT COUNT(*) INTO P_COUNT
            FROM TIMTIN
            WHERE TINCODIGO = NEW_FIN.TIMTIPOINTERMED;
    
            IF P_COUNT = 0 THEN
                P_ERRMSG := 'O campo ""'||FIELD_LABEL('TGFFIN','TIMTIPOINTERMED')||'"" não possui valor válido.';
                RAISE ERROR;
            END IF;
        END IF;
        
    END LOOP;
    

    FOR I IN 1..OLD_TGFFIN_LIST.COUNT
    LOOP
        DELETE
        FROM TGFFIN_INC_UPD_TIMFK
        WHERE NUFIN = OLD_TGFFIN_LIST(I).NUFIN;
    END LOOP;
    
EXCEPTION
WHEN ERROR THEN
    RAISE_APPLICATION_ERROR(-20201, P_ERRMSG);
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_TGFFIN_INC_UPD_AFT_TIMFK" ENABLE;
