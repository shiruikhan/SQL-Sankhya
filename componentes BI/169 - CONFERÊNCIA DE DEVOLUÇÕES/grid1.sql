SELECT 
     TAB.NOTADEV
    ,TAB.DTENT
    ,TAB.PARCEIRO
    ,TAB.CODCFODEV
    ,TAB.NUNOTA
    ,TAB.NUMNOTA
    ,TAB.DTENTSAI
    ,TAB.CODCFO
    ,TAB.CODPROD
    ,TAB.DESCRPROD
    ,TAB.CODVOL
    ,TAB.QTDATENDIDA
    ,TAB.VLRCTB
    ,TAB.BASEATUAL
    ,TAB.ICMS
    ,TAB.PROPOR
    ,TAB.BASEATUAL * (TAB.PROPOR / 100) AS BASENOVA
    ,(TAB.BASEATUAL * (TAB.PROPOR / 100)) * (TAB.ALIQICMS / 100) AS ICMSNOVO
    ,TAB.ALIQICMS
    ,TAB.ICMS - ((TAB.BASEATUAL * (TAB.PROPOR / 100)) * (TAB.ALIQICMS / 100)) AS DIFERENCA
    
FROM (
    SELECT 
         CAB1.NUMNOTA AS NOTADEV
        ,CAB1.DTENTSAI AS DTENT
        ,CAB1.CODPARC || ' - ' || 
         (SELECT P.RAZAOSOCIAL FROM TGFPAR P WHERE P.CODPARC = CAB1.CODPARC) AS PARCEIRO
        ,(SELECT MAX(I.CODCFO) FROM TGFITE I WHERE I.NUNOTA = CAB1.NUNOTA) AS CODCFODEV
        ,CAB.NUNOTA
        ,LIV.SEQUENCIA
        ,CAB.NUMNOTA
        ,CAB.DTENTSAI
        ,ITE.CODCFO
        ,ITE.CODPROD
        ,PRO.DESCRPROD
        ,ITE.CODVOL
        ,CASE WHEN LIV.ALIQICMS = 0 THEN ITE.AD_ALIQICMSSP ELSE LIV.ALIQICMS END AS ALIQICMS
        ,ITE.QTDNEG AS QTDATENDIDA
        ,LIV.VLRCTB
        ,CASE WHEN LIV.VLRICMS = 0 THEN ITE.AD_VLRICMSSP ELSE LIV.VLRICMS END    AS ICMS
        ,CASE WHEN LIV.BASEICMS = 0 THEN ITE.AD_BASEICMSSP ELSE LIV.BASEICMS END  AS BASEATUAL
        ,CASE 
            WHEN TRUNC(CAB1.DTENTSAI, 'MM') <> :P_PERIODO.INI 
            THEN (
                SELECT MAX(I.ICMS) 
                FROM AD_TGFPIM I 
                WHERE I.ANO = EXTRACT(YEAR FROM (CAB1.DTENTSAI)) 
                  AND I.MES = EXTRACT(MONTH FROM (CAB1.DTENTSAI))
            )
            ELSE 0 
         END AS PROPOR
    FROM TGFCAB CAB
    INNER JOIN TGFITE ITE 
        ON CAB.NUNOTA = ITE.NUNOTA
    LEFT JOIN TGFVAR VAR 
        ON VAR.NUNOTA = CAB.NUNOTA
        AND VAR.SEQUENCIA = ITE.SEQUENCIA
    INNER JOIN TGFPRO PRO 
        ON ITE.CODPROD = PRO.CODPROD
    INNER JOIN TGFLIV LIV 
        ON LIV.NUNOTA = CAB.NUNOTA
        AND LIV.SEQUENCIA = ITE.SEQUENCIA
    RIGHT JOIN TGFCAB CAB1
        ON CAB1.NUNOTA = VAR.NUNOTAORIG
    WHERE CAB.CODTIPOPER = 305
      AND CAB.DTNEG >= :P_PERIODO.INI
      AND CAB.DTNEG <= :P_PERIODO.FIN
      AND CAB.STATUSNOTA = 'L'
      AND CAB.CODEMP = 1
) TAB
ORDER BY TAB.NUNOTA, TAB.SEQUENCIA ASC
