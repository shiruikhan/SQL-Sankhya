SELECT * FROM(
--TITULOS ORIGEM FINANCEIRO - TOP TIPO "V"
SELECT 
CASE WHEN T.TIPMOV <> 'I' THEN 'Portal'
     ELSE 'Financeiro' END AS ORIGEM,
FIN.CODEMP, 
FIN.DTNEG,
FIN.DTENTSAI, 
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
FIN.NURENEG,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
FIN.HISTORICO,
PAR.CODCTACTB
FROM TGFFIN FIN, TGFPAR PAR, TGFNAT NAT, TGFTOP T  
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0) AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTNEG <= :DAT1 AND  
FIN.DHBAIXA is null AND
 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('V') AND 
to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') > 0 AND
FIN.RECDESP = 1

UNION ALL

--TITULOS ORIGEM FINANCEIRO - TOP TIPO "I"
SELECT 
CASE WHEN T.TIPMOV <> 'I' THEN 'Portal'
     ELSE 'Financeiro' END AS ORIGEM,
FIN.CODEMP, 
FIN.DTNEG, 
FIN.DTENTSAI,
FIN.NUMNOTA, 
FIN.NUFIN, 
FIN.CODPARC, 
PAR.RAZAOSOCIAL, 
(FIN.VLRDESDOB * FIN.RECDESP) - FIN.VLRJUROEMBUT - FIN.VLRMULTAEMBUT + FIN.VLRDESCEMBUT As VALOR, 
FIN.DTVENC, 
FIN.DHBAIXA,
FIN.CODNAT, 
NAT.DESCRNAT,
FIN.CODTIPOPER,
FIN.NURENEG,
CASE WHEN DHBAIXA IS NOT NULL THEN 'Recebido'
	WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 0 THEN 'A Vencer'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 30 THEN 'Vencido até 30 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 60 THEN 'Vencido até 60 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 90 THEN 'Vencido até 90 dias'
     WHEN to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') <= 180 THEN 'Vencido até 180 dias'
     ELSE 'Vencido mais de 180 dias' END AS CLASSIFICACAO,
FIN.HISTORICO,
159 AS CODCTACTB
FROM TGFFIN FIN, TGFPAR PAR, TGFNAT NAT, TGFTOP T  
WHERE FIN.CODTIPOPER = T.CODTIPOPER AND 
FIN.CODPARC = PAR.CODPARC AND 
FIN.DHTIPOPER = T.DHALTER AND 
FIN.CODNAT = NAT.CODNAT AND 
(FIN.CODPARC = :PARCEIRO or :PARCEIRO = 0) AND
FIN.CODEMP IN :CODEMP AND  
FIN.DTNEG <= :DAT1 AND  
FIN.DHBAIXA is null AND
 DECODE(FIN.PROVISAO, 'S', 'Sim', 'Não') = 'Não' AND 
FIN.VLRDESDOB * FIN.RECDESP <> 0 AND  
T.TIPMOV IN ('I') AND 
to_date(:DAT1,'DD/MM/YYYY') - TO_DATE(FIN.DTVENC,'DD/MM/YYYY') > 0 AND
/* NAT.AD_TIPOCTBZ IS NULL AND */
FIN.RECDESP = 1
)
ORDER BY CODPARC, DTVENC, DTNEG
