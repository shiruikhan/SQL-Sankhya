SELECT ITE.CODPROD,
	PRO.DESCRPROD,
	SUM(ITE.QTDNEG) AS QTDNEG
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
WHERE PRO.USOPROD = 'V'
	AND TRUNC(CAB.DTENTSAI) >= :P_DTENTSAI.INI
	AND TRUNC(CAB.DTENTSAI) <= :P_DTENTSAI.FIN
	AND CAB.CODTIPOPER IN (800,213)
GROUP BY ITE.CODPROD, PRO.DESCRPROD
