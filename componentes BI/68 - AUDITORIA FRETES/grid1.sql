SELECT 
      CAB.NUNOTA,
      CAB.CODEMP,
      CAB.NUMNOTA,
      ITE.CODCFO AS CODCFO,
      CAB.CODPARC,
      PAR.NOMEPARC,
      CAB.CODTIPOPER,
      CAB.DTENTSAI,
      CAB.VLRNOTA,
	  CAB.CODNAT,
	  NAT.DESCRNAT,
	  CAB.CODCENCUS,
	  CUS.DESCRCENCUS,
	  NAT.CODCTACTB,
	 NVL((
			SELECT PLA.DESCRCTA
			FROM TCBPLA PLA
			WHERE PLA.CODCTACTB = NVL(NAT.CODCTACTB, 0)
		  ),'SEM CONTA') AS DESC_CONTA,
	  (SELECT PLA.CTACTB FROM TCBPLA PLA WHERE PLA.CODCTACTB = NVL(NAT.CODCTACTB, 0)) AS EFD_CONTA,		 
      MAX(ITE.CODTRIB) AS CST_ICMS,		  
      SUM(CASE WHEN DIN.CODIMP = 1 THEN DIN.BASERED ELSE 0 END) AS BASEICMS,
      SUM(CASE WHEN DIN.CODIMP = 1 THEN DIN.VALOR ELSE 0 END) AS ICMS,
      MAX(CASE WHEN DIN.CODIMP = 6 THEN DIN.CST ELSE 0 END) AS CST_PIS,
      SUM(CASE WHEN DIN.CODIMP = 6 THEN DIN.BASERED ELSE 0 END) AS BASEPIS,
      SUM(CASE WHEN DIN.CODIMP = 6 THEN DIN.VALOR ELSE 0 END) AS PIS,
      MAX(CASE WHEN DIN.CODIMP = 7 THEN DIN.CST ELSE 0 END) AS CST_COFINS,
      SUM(CASE WHEN DIN.CODIMP = 7 THEN DIN.BASERED ELSE 0 END) AS BASECOFINS,
      SUM(CASE WHEN DIN.CODIMP = 7 THEN DIN.VALOR ELSE 0 END) AS COFINS,
     TO_NUMBER(0)     AS NUNOTAVINCULADO,
     TO_CHAR(0)     AS NUMERO,
     CAB.CHAVENFE   AS CHAVENFE,
     0     AS TOPVINCULADA,
     TO_CHAR('SEM TOP')     AS TPO,
	  'NÃO' AS  VALIDADOR,
	  0     AS VLRFRETEVINCULADO
FROM TGFCAB CAB
	
	INNER JOIN TGFTOP TPO 
		ON TPO.CODTIPOPER = CAB.CODTIPOPER
		  AND TPO.DHALTER = CAB.DHTIPOPER
		  	
	
	INNER JOIN TGFITE ITE 
		ON ITE.NUNOTA = CAB.NUNOTA
	
	INNER JOIN TGFDIN DIN 
		ON DIN.NUNOTA = ITE.NUNOTA 
	AND DIN.SEQUENCIA = ITE.SEQUENCIA
   
	INNER JOIN TGFNAT NAT 
		ON NAT.CODNAT = CAB.CODNAT
	
	INNER JOIN TGFPAR PAR 
		ON CAB.CODPARC = PAR.CODPARC
	
	INNER JOIN TSICUS CUS 
		ON CUS.CODCENCUS = CAB.CODCENCUS 
	
WHERE CAB.CODTIPOPER IN (225,226,234,242) 

 AND TRUNC(CAB.DTENTSAI) BETWEEN :P_PRAZO.INI AND :P_PRAZO.FIN
 AND (:P_CODPARC1 IS NULL OR CAB.CODPARC = :P_CODPARC1)
 AND (:P_NUMNOTA IS NULL OR CAB.NUMNOTA = :P_NUMNOTA)
 AND (:P_NUMNOTAVINCULADA IS NULL OR CAB.NUMNOTA = :P_NUMNOTAVINCULADA)
 AND NOT EXISTS (SELECT 1
					FROM TGFNCT NCT 
				WHERE NCT.NUNOTA = CAB.NUNOTA 
				 )
 GROUP BY 
      CAB.NUNOTA,
      CAB.CODEMP,
      CAB.NUMNOTA,
      ITE.CODCFO,
      CAB.CODPARC,
      PAR.NOMEPARC,
      CAB.CODTIPOPER,
      CAB.DTENTSAI,
      CAB.VLRNOTA,
	  CAB.CODNAT,
	  NAT.DESCRNAT,
	  CAB.CODCENCUS,
	  CUS.DESCRCENCUS,
	  NAT.CODCTACTB,
      CAB.CHAVENFE
