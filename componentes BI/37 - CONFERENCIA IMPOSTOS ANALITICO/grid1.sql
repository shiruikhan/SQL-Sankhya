SELECT CAB.NUNOTA,
	CAB.NUMNOTA,
	CAB.DTNEG,
	CAB.DTENTSAI,
	CASE 
		WHEN CAB.STATUSNFE IS NULL AND CAB.TIPMOV = 'P' THEN '-----' 
		WHEN CAB.STATUSNFE = 'A' THEN 'Aprovada'
		WHEN CAB.STATUSNFE = 'D' THEN 'Denegada'
		WHEN CAB.STATUSNFE = 'E' THEN 'Aguardando Autorização'
		WHEN CAB.STATUSNFE = 'I' THEN 'Enviada'
		WHEN CAB.STATUSNFE = 'M' THEN 'Não é NF-e'
		WHEN CAB.STATUSNFE = 'P' THEN 'Pendente de Retorno'
		WHEN CAB.STATUSNFE = 'R' THEN 'Aguardando Correção'
		WHEN CAB.STATUSNFE = 'S' THEN 'Enviada EPEC'
		WHEN CAB.STATUSNFE = 'T' THEN 'NF-e Terceiro'
		WHEN CAB.STATUSNFE = 'V' THEN 'Com erro de Validação' 
		ELSE 'Não Enviada' END AS STATUSNFE,
	CAB.CODTIPOPER,
	TPO.DESCROPER,
	PAR.CODPARC, 
	PAR.NOMEPARC,
	PAR.IDENTINSCESTAD,
	CASE WHEN PAR.CLASSIFICMS = 'R' THEN 'Revendedor' 
		WHEN PAR.CLASSIFICMS = 'C' THEN 'Consumidor Final'
		WHEN PAR.CLASSIFICMS = 'X' THEN 'Consumidor Contribuinte'
		ELSE '-----' END AS CLASSIFICMS,	
	ITE.SEQUENCIA,
	ITE.CODPROD,
	(CASE
		WHEN PRO.USOPROD = '1' THEN 'Subproduto'
		WHEN PRO.USOPROD = '2' THEN 'Prod.Intermediário'
		WHEN PRO.USOPROD = '4' THEN 'Demonstração'
		WHEN PRO.USOPROD = 'B' THEN 'Brinde'
		WHEN PRO.USOPROD = 'C' THEN 'Consumo'
		WHEN PRO.USOPROD = 'D' THEN 'Revenda (por fórmula)'
		WHEN PRO.USOPROD = 'E' THEN 'Embalagem'
		WHEN PRO.USOPROD = 'F' THEN 'Brinde (NF)'
		WHEN PRO.USOPROD = 'I' THEN 'Imobilizado'
		WHEN PRO.USOPROD = 'M' THEN 'Matéria prima'
		WHEN PRO.USOPROD = 'O' THEN 'Outros insumos'
		WHEN PRO.USOPROD = 'P' THEN 'Em Processo'
		WHEN PRO.USOPROD = 'R' THEN 'Revenda'
		WHEN PRO.USOPROD = 'T' THEN 'Terceiros'
		WHEN PRO.USOPROD = 'V' THEN 'Venda (fabricação própria)'
		ELSE 'Cadastro incorreto'
	END) AS USOPROD,
	PRO.DESCRPROD,
	ITE.QTDNEG,
	ITE.VLRUNIT, 
	LIV.CODCFO,
	ITE.CODTRIB,
	ITE.ALIQICMS,	
	ITE.CSTIPI,
	ITE.ALIQIPI,
	LIV.VLRCTB,
	LIV.OUTRASICMS,
	LIV.ISENTASICMS,
	LIV.OUTRASIPI,
	LIV.ISENTASIPI,
	(SELECT SUM(LIV1.VLRCTB - LIV.ICMSRETENCAO - LIV.VLRIPI)
		FROM TGFLIV LIV1
		WHERE LIV1.NUNOTA = ITE.NUNOTA
			AND LIV1.SEQUENCIA = ITE.SEQUENCIA) AS VLRITELIQ,
	NVL((SELECT SUM(DIN.BASERED)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 1
				AND DIN.CODINC IN (1,3,5)),0) AS BASEICMS,
	NVL((SELECT SUM(DIN.VALOR) 
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 1
				AND DIN.CODINC IN (1,3,5)),0) AS VLRICMS,
	NVL((SELECT SUM(DIN.BASERED) 
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 3
				AND DIN.CODINC IN (1,3,5)),0) AS BASEIPI,
	NVL((SELECT SUM(DIN.VALOR) 
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 3
				AND DIN.CODINC IN (1,3,5)),0) AS VLRIPI,
	NVL((SELECT SUM(DIN.BASERED)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 6),0) AS BASE_PIS,
	NVL((SELECT MAX(DIN.CST)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 6),0) AS CST_PIS,
	NVL((SELECT SUM(DIN.VALOR)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 6),0) AS VLR_PIS,
	NVL((SELECT SUM(DIN.BASERED)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 7),0) AS BASE_COFINS,
	NVL((SELECT MAX(DIN.CST)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 7),0) AS CST_COFINS,
	NVL((SELECT SUM(DIN.VALOR)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 7),0) AS VLR_COFINS,
	NVL((SELECT SUM(DIN.BASE)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 2),0) AS BASE_ST,
	NVL((SELECT MAX(DIN.ALIQUOTA)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 2),0) AS ALIQ_ST,
	NVL((SELECT SUM(DIN.VALOR)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 2),0) AS VLR_ST,
	NVL((SELECT SUM(DIN.VLRFCPINT)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 2),0) AS VLR_FEM_ICMS_ST,  
	NVL((SELECT SUM(DIN.VLRFCPINT)
			FROM TGFDIN DIN
			WHERE DIN.NUNOTA = ITE.NUNOTA
				AND DIN.SEQUENCIA = ITE.SEQUENCIA
				AND DIN.CODIMP = 1),0) AS VLR_FEM_ICMS_OP,
	CID.NOMECID,
	UF.UF,
	CAB.CHAVENFE,
	(SELECT MAX(C.NUMNOTA) 
		FROM TGFCAB C,
			TGFVAR VAR 
		WHERE C.NUNOTA = VAR.NUNOTA 
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND C.TIPMOV = 'D') AS NUMNOTA_DEVOLUCAO,
	(SELECT MAX(I.VLRTOT) 
		FROM TGFCAB C,
			TGFITE I,
			TGFVAR VAR 
		WHERE C.NUNOTA = I.NUNOTA 
			AND C.NUNOTA = VAR.NUNOTA 
			AND I.SEQUENCIA = VAR.SEQUENCIA 
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 
			AND C.TIPMOV = 'D') AS VLRTOT_DEVOLUCAO,
	(SELECT MAX(I.BASEICMS) 
		FROM TGFCAB C,
			TGFITE I,
			TGFVAR VAR 
		WHERE C.NUNOTA = I.NUNOTA
			AND C.NUNOTA = VAR.NUNOTA 
			AND I.SEQUENCIA = VAR.SEQUENCIA 
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 
			AND C.TIPMOV = 'D') AS VLRBCICMS_DEVOLUCAO,
	(SELECT MAX(I.VLRICMS) 
		FROM TGFCAB C,
			TGFITE I, 
			TGFVAR VAR 
		WHERE C.NUNOTA = I.NUNOTA 
			AND C.NUNOTA = VAR.NUNOTA 
			AND I.SEQUENCIA = VAR.SEQUENCIA 
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 
			AND C.TIPMOV = 'D') AS VLRICMS_DEVOLUCAO,
	(SELECT MAX(I.BASEIPI) 
		FROM TGFCAB C,
			TGFITE I, 
			TGFVAR VAR 
		WHERE C.NUNOTA = I.NUNOTA 
			AND C.NUNOTA = VAR.NUNOTA
			AND I.SEQUENCIA = VAR.SEQUENCIA
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA
			AND C.TIPMOV = 'D') AS VLRBCIPI_DEVOLUCAO,
	(SELECT MAX(I.VLRIPI) 
		FROM TGFCAB C,
			TGFITE I,
			TGFVAR VAR 
		WHERE C.NUNOTA = I.NUNOTA 
			AND C.NUNOTA = VAR.NUNOTA 
			AND I.SEQUENCIA = VAR.SEQUENCIA 
			AND VAR.NUNOTAORIG = CAB.NUNOTA 
			AND VAR.SEQUENCIAORIG = ITE.SEQUENCIA 
			AND C.TIPMOV = 'D') AS VLRIPI_DEVOLUCAO
FROM TGFCAB CAB,
	TGFITE ITE,
	TGFPRO PRO,
	TGFPAR PAR,
	TGFTOP TPO,
	TSICID CID, 
	TSIUFS UF, 
	TGFLIV LIV
WHERE LIV.NUNOTA = CAB.NUNOTA 
	AND LIV.NUNOTA = ITE.NUNOTA
	AND LIV.SEQUENCIA = ITE.SEQUENCIA 
	AND CAB.NUNOTA = ITE.NUNOTA 
	AND ITE.CODPROD = PRO.CODPROD
	AND CAB.CODPARC = PAR.CODPARC
	AND CAB.CODTIPOPER = TPO.CODTIPOPER
	AND CAB.DHTIPOPER = TPO.DHALTER
	AND PAR.CODCID = CID.CODCID
	AND CID.UF = UF.CODUF
	AND TPO.ATUALLIVFIS <> 'N'
	AND (CAB.CODEMP = :P_CODEMP OR :P_CODEMP IS NULL)
	AND (CAB.DTNEG >= :P_PERIODO.INI or :P_PERIODO.INI is null)
	AND (CAB.DTNEG <= :P_PERIODO.FIN or :P_PERIODO.FIN is null)
	AND (CAB.DTENTSAI >= :P_DTENTSAI.INI or :P_DTENTSAI.INI is null)
	AND (CAB.DTENTSAI <= :P_DTENTSAI.FIN or :P_DTENTSAI.FIN is null)
	AND (CAB.NUNOTA = :P_NUNOTA OR :P_NUNOTA IS NULL)
	AND (CAB.NUMNOTA = :P_NUMNOTA OR :P_NUMNOTA IS NULL)
	AND LIV.CODCFO >= :P_CODCFOPINI
	AND LIV.CODCFO <= :P_CODCFOPFIN
	AND (ITE.CODPROD = :P_CODPROD OR :P_CODPROD IS NULL)
	AND (:P_CODTIPOPER IS NULL OR CAB.CODTIPOPER = :P_CODTIPOPER)
	AND (:P_UF IS NULL OR UF.CODUF = :P_UF)
