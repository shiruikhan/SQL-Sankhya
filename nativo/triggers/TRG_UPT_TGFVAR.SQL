/*==============================================================================
  Nome do Script : TRG_UPT_TGFVAR
  Tipo           : Trigger — origem a confirmar (criada isoladamente em 12/12/2023)
  Descrição      : Trigger BEFORE EACH ROW UPDATE sobre TGFVAR.
  Empresa        : Spark Eletrônica
  Observações    : - Estado no banco: ENABLED; criada em 12/12/2023, última alteração em 03/07/2024.
                   - Objeto do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - Capturado do banco em 08/10/2026 (recaptura em pedaços — DDL completo, conferido pelo tamanho), via GET_DDL('TRIGGER', 'TRG_UPT_TGFVAR', 'SPARKPRD').
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE TRIGGER "SPARKPRD"."TRG_UPT_TGFVAR" 
BEFORE UPDATE ON TGFVAR
FOR EACH ROW
    WHEN ((NEW.NUNOTAORIG <> NEW.NUNOTA) OR ((OLD.QTDATENDIDA <> 0) AND (NEW.QTDATENDIDA = 0))) DECLARE
    P_COUNT               INT;
    P_QTDNEG              FLOAT;
    P_QTDENT        FLOAT;
    P_NUMTRANSF     TGMTRA.NUMTRANSF%TYPE;
    P_NEWNUMTRANSF  TGMTRA.NUMTRANSF%TYPE;
    P_CODMETA       TGMTRA.CODMETA%TYPE;
    P_DTREF         TGMTRA.DTREF%TYPE;
    P_CODEMP        TGMTRA.CODEMP%TYPE;
    P_CODPROD       TGMTRA.CODPROD%TYPE;
    P_CODGRUPOPROD  TGMTRA.CODGRUPOPROD%TYPE;
    P_CODLOCAL      TGMTRA.CODLOCAL%TYPE;
    P_CONTROLE      TGMTRA.CONTROLE%TYPE;
  P_MARCA         TGMTRA.MARCA%TYPE;
  P_CODPROJ       TGMTRA.CODPROJ%TYPE;
  P_CODCENCUS     TGMTRA.CODCENCUS%TYPE;
  P_CODNAT        TGMTRA.CODNAT%TYPE;
  P_CODCTACTB     TGMTRA.CODCTACTB%TYPE;
  P_CODREG        TGMTRA.CODREG%TYPE;
  P_CODGER        TGMTRA.CODGER%TYPE;
  P_CODVEND       TGMTRA.CODVEND%TYPE;
  P_CODPARC       TGMTRA.CODPARC%TYPE;
  P_CODUF         TGMTRA.CODUF%TYPE;
  P_CODCID        TGMTRA.CODCID%TYPE;
  P_CODPAIS       TGMTRA.CODPAIS%TYPE;
  P_CODTIPPARC    TGMTRA.CODTIPPARC%TYPE;
  P_VALOR         TGMTRA.VALOR%TYPE;
  P_CODUSU        TGMTRA.CODUSU%TYPE;
  P_NUFIN         TGMTRA.NUFIN%TYPE;
  P_STATUS        TGMTRA.STATUS%TYPE;
  P_CODUSULIB     TGMTRA.CODUSULIB%TYPE;
  P_GRAU          TGMTRA.GRAU%TYPE;
  P_TIPO          TGMTRA.TIPO%TYPE;
  P_SINAL         TGMTRA.SINAL%TYPE;
  P_DTNEG         TGFCAB.DTNEG%TYPE;
  P_SEQUENCIA     TGMTRA.SEQUENCIA%TYPE;
  ERRMSG            VARCHAR2(255);
  ERROR             EXCEPTION;
  P_VALIDAR BOOLEAN;    
  CURSOR CUR_TGMTRA1 IS
    SELECT
    TRA.NUMTRANSF,
    TRA.CODMETA,
    CASE WHEN (SELECT PERIODO FROM TGMCFG WHERE CODMETA = TRA.CODMETA) = 9 THEN TRUNC(CAB.DTNEG, 'YEAR') ELSE TRUNC(CAB.DTNEG, 'MONTH') END,
    TRA.CODEMP,
    TRA.CODPROD, TRA.CODGRUPOPROD, TRA.CODLOCAL, TRA.CONTROLE, TRA.MARCA,
    TRA.CODPROJ, TRA.CODCENCUS, TRA.CODNAT, TRA.CODCTACTB,
    TRA.CODREG, TRA.CODGER, TRA.CODVEND,
    TRA.CODPARC, TRA.CODUF, TRA.CODCID, TRA.CODPAIS, TRA.CODTIPPARC,
      CASE WHEN ROUND(TRA.VALOR_ORIG / ITE.QTDNEG * :NEW.QTDATENDIDA,2) > (INE.VLRTOT - INE.VLRDESC + INE.VLRSUBST + INE.VLRIPI) THEN (INE.VLRTOT - INE.VLRDESC + INE.VLRSUBST + INE.VLRIPI) ELSE ROUND(TRA.VALOR_ORIG / ITE.QTDNEG * :NEW.QTDATENDIDA,2) END,
    TRA.TIPO,
    TRA.SINAL,
    TRA.CODUSU,
    TRA.NUFIN,
    TRA.STATUS,
    TRA.CODUSULIB,
    TRA.GRAU
    FROM TGMTRA TRA
    , TGFITE ITE
    , TGMTME TME
    , TGFCAB CAB
    , TGFITE INE
    WHERE TRA.NUNOTA = :NEW.NUNOTAORIG
    AND TRA.SEQUENCIAITE = :NEW.SEQUENCIAORIG
    AND TRA.TIPO = 'C'
    AND TRA.CODMETA = TME.CODMETA
    AND CAB.NUNOTA = :NEW.NUNOTA
    AND CAB.CODTIPOPER = TME.CODTIPOPER
    AND ITE.NUNOTA = :NEW.NUNOTAORIG
    AND ITE.SEQUENCIA = :NEW.SEQUENCIAORIG
    AND ITE.QTDNEG <> 0
    AND INE.NUNOTA = :NEW.NUNOTA
    AND INE.SEQUENCIA = :NEW.SEQUENCIA;

BEGIN

  IF STP_GET_ATUALIZANDO THEN
    RETURN;
  END IF;
  /* 
  Sincronizacao de dados
  */
    P_VALIDAR := Fpodevalidar('TGFVAR'); 

  IF ((:NEW.NUNOTA <> :OLD.NUNOTA) OR (:OLD.SEQUENCIA <> :NEW.SEQUENCIA)) THEN
    ERRMSG := 'A coluna NUNOTA e SEQUENCIA nï¿½o podem ser alteradas.';
    RAISE ERROR;
  END IF;

  IF ((:OLD.STATUSNOTA <> :NEW.STATUSNOTA) AND (:NEW.STATUSNOTA <> 'L')) THEN
    ERRMSG := 'A unica atualizacao permitida para o Status da Nota e a passagem deste para L.';
    RAISE ERROR;
  END IF;

  /* Garantir que sempre sera o mesmo produto da nota e sua nota de origem */
  IF ((:NEW.NUNOTAORIG <> :OLD.NUNOTAORIG) OR (:NEW.SEQUENCIAORIG <> :OLD.SEQUENCIAORIG)) THEN
    IF (:OLD.QTDATENDIDA <> 0) THEN
      SELECT COUNT(1)
        INTO P_COUNT
      FROM TGFITE
      WHERE (NUNOTA = :OLD.NUNOTAORIG)
      AND (SEQUENCIA = :OLD.SEQUENCIAORIG);
      
      IF P_COUNT > 0 THEN
        UPDATE TGFITE
        SET QTDENTREGUE = ROUND(QTDENTREGUE - (CASE  WHEN :OLD.FIXACAO = 'S' THEN 0 ELSE :OLD.QTDATENDIDA END),9),
        QTDFIXADA = NVL(QTDFIXADA, 0) - (CASE  WHEN :OLD.FIXACAO = 'S' THEN :OLD.QTDATENDIDA ELSE 0 END)
        WHERE (NUNOTA = :OLD.NUNOTAORIG)
        AND (SEQUENCIA = :OLD.SEQUENCIAORIG);
      END IF;
      
    END IF;

    IF (:NEW.QTDATENDIDA <> 0) THEN
      SELECT COUNT(1)
        INTO P_COUNT
      FROM TGFITE
      WHERE (NUNOTA = :NEW.NUNOTAORIG)
      AND (SEQUENCIA = :NEW.SEQUENCIAORIG);
      
      IF P_COUNT > 0 THEN
        UPDATE TGFITE
        SET QTDENTREGUE = ROUND(QTDENTREGUE + (CASE  WHEN :NEW.FIXACAO = 'S' THEN 0 ELSE :NEW.QTDATENDIDA END),9),
          QTDFIXADA = NVL(QTDFIXADA, 0)   + (CASE  WHEN :NEW.FIXACAO = 'S' THEN :NEW.QTDATENDIDA ELSE 0 END)
        WHERE (NUNOTA = :NEW.NUNOTAORIG)
        AND (SEQUENCIA = :NEW.SEQUENCIAORIG);
      END IF;
      
    END IF;
  ELSIF ((:NEW.QTDATENDIDA <> :OLD.QTDATENDIDA) OR (:NEW.FIXACAO <> :OLD.FIXACAO)) THEN
    SELECT COUNT(1)
      INTO P_COUNT
    FROM TGFITE
    WHERE (NUNOTA = :NEW.NUNOTAORIG)
    AND (SEQUENCIA = :NEW.SEQUENCIAORIG);
    
    IF P_COUNT > 0 THEN
      UPDATE TGFITE
      SET  QTDENTREGUE = QTDENTREGUE + (CASE  WHEN :NEW.FIXACAO = 'S' THEN 0 ELSE :NEW.QTDATENDIDA END) - (CASE  WHEN :OLD.FIXACAO = 'S' THEN 0 ELSE :OLD.QTDATENDIDA END),
      QTDFIXADA = NVL(QTDFIXADA, 0)   + (CASE  WHEN :NEW.FIXACAO = 'S' THEN :NEW.QTDATENDIDA ELSE 0 END) - (CASE  WHEN :OLD.FIXACAO = 'S' THEN :OLD.QTDATENDIDA ELSE 0 END)
      WHERE (NUNOTA = :NEW.NUNOTAORIG)
      AND (SEQUENCIA = :NEW.SEQUENCIAORIG);
    END IF;
    
  END IF;

  SELECT COUNT(1)
  INTO P_COUNT
  FROM TGMTRA TRA
  , TGMTME TME
  , TGFCAB CAB
  WHERE TRA.NUNOTA = :NEW.NUNOTAORIG
  AND TRA.SEQUENCIAITE = :NEW.SEQUENCIAORIG
  AND TRA.TIPO = 'C'
  AND TRA.CODMETA = TME.CODMETA
  AND CAB.NUNOTA = :NEW.NUNOTA
  AND CAB.CODTIPOPER = TME.CODTIPOPER;

  IF (P_COUNT <> 0) THEN
    SELECT COUNT(*)
    INTO P_COUNT
    FROM TGMTRA
    WHERE NUNOTA = :NEW.NUNOTA
    AND SEQUENCIAITE = :NEW.SEQUENCIA
    AND TIPO = 'C';

    IF (P_COUNT <> 0) THEN
      DELETE FROM TGMTRA
      WHERE NUNOTA = :NEW.NUNOTA
      AND SEQUENCIAITE = :NEW.SEQUENCIA
      AND TIPO = 'C'
      AND CODMETA IN (SELECT TME.CODMETA
           FROM TGFCAB CAB, TGMTME TME
           WHERE CAB.NUNOTA = :NEW.NUNOTA
           AND CAB.CODTIPOPER = TME.CODTIPOPER);

      OPEN CUR_TGMTRA1;
      LOOP
        FETCH CUR_TGMTRA1 INTO
        P_NUMTRANSF,
        P_CODMETA,
        P_DTREF,
        P_CODEMP,
        P_CODPROD, 
        P_CODGRUPOPROD, 
        P_CODLOCAL, 
        P_CONTROLE, 
        P_MARCA,
        P_CODPROJ, 
        P_CODCENCUS, 
        P_CODNAT, 
        P_CODCTACTB,
        P_CODREG, 
        P_CODGER, 
        P_CODVEND,
        P_CODPARC, 
        P_CODUF, 
        P_CODCID, 
        P_CODPAIS, 
        P_CODTIPPARC,
        P_VALOR,
        P_TIPO,
        P_SINAL,
        P_CODUSU,
        P_NUFIN,
        P_STATUS,
        P_CODUSULIB,
        P_GRAU;
        EXIT WHEN CUR_TGMTRA1%NOTFOUND;

        P_SEQUENCIA := SNK_GET_PROX_SEQ_TGMTRA(P_NUMTRANSF, :NEW.SEQUENCIA, 3000);
	    P_NEWNUMTRANSF := SNK_VERIFICA_PK_TGMTRA(P_NUMTRANSF, P_SEQUENCIA, :NEW.SEQUENCIA);
	    
	    IF(P_NEWNUMTRANSF <> P_NUMTRANSF) THEN
	   		STP_TROCA_NUMTRANSF(P_NUMTRANSF, P_NEWNUMTRANSF, :NEW.NUNOTAORIG);	
	   		P_NUMTRANSF := P_NEWNUMTRANSF;
	    	P_SEQUENCIA := SNK_GET_PROX_SEQ_TGMTRA(P_NUMTRANSF, :NEW.SEQUENCIA,	 3000);
	    END IF;

        INSERT INTO TGMTRA (
          NUMTRANSF,
          SEQUENCIA,
          NUNOTA, 
          SEQUENCIAITE,
          CODMETA,
          DTREF,
          CODEMP,
          CODPROD, 
          CODGRUPOPROD, 
          CODLOCAL, 
          CONTROLE, 
          MARCA,
          CODPROJ, 
          CODCENCUS, 
          CODNAT, 
          CODCTACTB,
          CODREG, 
          CODGER, 
          CODVEND,
          CODPARC, 
          CODUF, 
          CODCID, 
          CODPAIS, 
          CODTIPPARC,
          TIPO,
          SINAL,
          VALOR,
          VALOR_ORIG,
          CODUSU,
          DTALTER,
          NUFIN,
          STATUS,
          CODUSULIB,
          GRAU)
        VALUES (
          P_NUMTRANSF,
          P_SEQUENCIA,
          :NEW.NUNOTA,
          :NEW.SEQUENCIA,
          P_CODMETA,
          P_DTREF,
          P_CODEMP,
          P_CODPROD, 
          P_CODGRUPOPROD, 
          P_CODLOCAL, 
          P_CONTROLE, 
          P_MARCA,
          P_CODPROJ, 
          P_CODCENCUS, 
          P_CODNAT, 
          P_CODCTACTB,
          P_CODREG, 
          P_CODGER, 
          P_CODVEND,
          P_CODPARC, 
          P_CODUF, 
          P_CODCID, 
          P_CODPAIS, 
          P_CODTIPPARC,
          P_TIPO,
          P_SINAL,
          P_VALOR,
          P_VALOR,
          P_CODUSU,
          TRUNC(SYSDATE, 'MI'),
          P_NUFIN,
          P_STATUS,
          P_CODUSULIB,
          P_GRAU);
      END LOOP;
      CLOSE CUR_TGMTRA1;

      SELECT QTDNEG, QTDENTREGUE  INTO P_QTDNEG, P_QTDENT
      FROM TGFITE ITE
      WHERE ITE.NUNOTA = :NEW.NUNOTAORIG
      AND ITE.SEQUENCIA = :NEW.SEQUENCIAORIG;

      IF ((P_QTDNEG - P_QTDENT) = 0) THEN
        UPDATE TGMTRA SET VALOR = 0
        WHERE NUNOTA = :NEW.NUNOTAORIG
        AND SEQUENCIAITE = :NEW.SEQUENCIAORIG
        AND TIPO = 'C';
        ELSE
        UPDATE TGMTRA SET VALOR = ROUND(VALOR_ORIG / P_QTDNEG * (P_QTDNEG - P_QTDENT),2)
        WHERE NUNOTA = :NEW.NUNOTAORIG
        AND SEQUENCIAITE = :NEW.SEQUENCIAORIG
        AND TIPO = 'C';
      END IF;
    END IF;
  END IF;
  RETURN;
EXCEPTION
  WHEN ERROR THEN
    /* 
    Sincronizacao de dados nao faz validacoes
    */
    IF (P_VALIDAR) THEN 
      RAISE_APPLICATION_ERROR(-20101, ERRMSG);
    END IF; 
END;
/
ALTER TRIGGER "SPARKPRD"."TRG_UPT_TGFVAR" ENABLE;
