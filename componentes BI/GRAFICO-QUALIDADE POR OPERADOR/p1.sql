SELECT APO.NUAPO,
	APO.OBSERVACAO,
	APO.DTAPO,
	APO.MINSERIDO,
	APO.FALTANDO,
	APO.INVERTIDO,
	APO.TROCADO,
	APO.QUEIMADO,
	APO.CURTO,
	APO.SOLDAFRIA,
	APO.DEFEITOMP,
	APO.CHICOTE,
	APO.DISPLAY,
	APO.AJUTENSAO,
	APO.ACORRENTE,
	APO.LED,
	APO.CONSUMO,
	APO.CORRENTE,
	APO.PROGRAMACAO,
	APO.OUTROSDEFEITOS,
	APO.ADESIVOTROC,
	APO.ADESIVOTORT,
	APO.GABARRANHADO,
	APO.GABAMASSADO,
	APO.TAMPATROCA,
	APO.TAMPAAMASS
FROM AD_APOQLD APO
WHERE (APO.FUNCOPERADOR = :A_IDFUNC OR APO.FUNCOPERADOR2 = :A_IDFUNC OR APO.FUNCREVISOR2 = :A_IDFUNC)
	AND APO.DTAPO >= :P_PERIODO.INI
	AND APO.DTAPO <= :P_PERIODO.FIN