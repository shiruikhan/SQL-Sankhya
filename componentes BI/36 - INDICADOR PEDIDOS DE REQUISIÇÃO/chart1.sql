SELECT COUNT(CAB.NUNOTA) AS CONTADOR,
	CAB.CODTIPOPER,
	(SELECT DISTINCT DESCROPER FROM TGFTOP WHERE CODTIPOPER = CAB.CODTIPOPER) AS DESCROPER
FROM TGFCAB CAB
	INNER JOIN TSICUS CUS ON CAB.CODCENCUS = CUS.CODCENCUS
WHERE (TRUNC(CAB.DTNEG) >= :P_PERIODO.INI AND TRUNC(CAB.DTNEG) <= :P_PERIODO.FIN) 
	AND (CAB.TIPMOV = 'J') 
	AND (CAB.STATUSNOTA = 'L') 
	AND (CAB.AD_NUMPS IS NULL)
	AND (CUS.DESCRCENCUS = :A_DESCRCENCUS)
 AND CAB.CODTIPOPER NOT IN (409)
GROUP BY CODTIPOPER
