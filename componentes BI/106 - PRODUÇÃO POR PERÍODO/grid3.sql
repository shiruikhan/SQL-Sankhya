SELECT ITE.CODPROD,
	PRO.DESCRPROD,
	SUM(ITE.QTDNEG) AS QTDNEG,
	SUM(ITE.VLRUNIT*QTDNEG) / SUM(ITE.QTDNEG) AS VLRUNIT,
	SUM(ITE.AD_VLRCHEIOCOM*QTDNEG) / SUM(ITE.QTDNEG) AS VLRCHEIO
FROM TGFITE ITE
	INNER JOIN TGFCAB CAB ON ITE.NUNOTA = CAB.NUNOTA
	INNER JOIN TGFPRO PRO ON PRO.CODPROD = ITE.CODPROD
WHERE TRUNC(CAB.DTENTSAI) >= :P_DTENTSAI.INI
	AND TRUNC(CAB.DTENTSAI) <= :P_DTENTSAI.FIN
	AND CAB.CODTIPOPER IN (1211)
	--AND SUBSTR(ITE.CODPROD,0,1) = 2
GROUP BY ITE.CODPROD, PRO.DESCRPROD
ORDER BY ITE.CODPROD
