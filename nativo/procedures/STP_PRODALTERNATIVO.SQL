/*==============================================================================
  Nome do Script : STP_PRODALTERNATIVO
  Tipo           : Procedure Nativa Sankhya (referência — não customizada)
  Descrição      : Mantém e propaga a cadeia de produtos alternativos/substitutos de TGFPRO (CODPRODSUBST), usando a tabela temporária TEMP_PRODALT.
  Empresa        : Spark Eletrônica
  Observações    : - Objeto nativo do ERP — atualizações do Sankhya podem sobrescrever; revisar após cada upgrade (nativo/README.md).
                   - No banco: criada em 07/12/2021, última alteração em 01/07/2022.
                   - Capturado do banco em 08/10/2026 (em pedaços — DDL completo, conferido pelo tamanho), via GET_DDL('PROCEDURE', 'STP_PRODALTERNATIVO', 'SPARKPRD').
                   - Descrição resumida a partir da leitura do código.
==============================================================================*/
  CREATE OR REPLACE EDITIONABLE PROCEDURE "SPARKPRD"."STP_PRODALTERNATIVO" (P_CODPROD INT, P_CODPRODALT INT, P_OLDCODPRODALT INT, P_DTSUBST DATE) AS
P_COUNT INT;
BEGIN

  IF P_CODPRODALT IS NOT NULL THEN 
    INSERT INTO TEMP_PRODALT (CODPROD, CODPRODALT)
    SELECT T.CODPROD, T.CODPRODSUBST FROM 
    ( SELECT CODPROD
        , 0 AS CODPRODSUBST
    FROM TGFPRO
    WHERE CODPRODSUBST = P_CODPROD 
    UNION
    SELECT 0 AS CODPROD 
        ,CODPRODSUBST
    FROM TGFPRO
    WHERE CODPROD = P_CODPRODALT
    AND CODPRODSUBST IS NOT NULL
    UNION
    SELECT 0 AS CODPROD 
        , P_CODPRODALT
    FROM DUAL  ) T;
    
    P_COUNT := 1;
    
    WHILE P_COUNT = 1
    LOOP
      SELECT COUNT(1) INTO P_COUNT
      FROM TGFPRO
      WHERE CODPROD <> P_CODPROD AND
        ((CODPRODSUBST IN (SELECT T1.CODPROD FROM TEMP_PRODALT T1 WHERE T1.CODPRODALT = 0)
        AND CODPROD NOT IN (SELECT T2.CODPROD FROM TEMP_PRODALT T2 WHERE T2.CODPRODALT = 0))
        OR
        (CODPROD IN (SELECT T3.CODPRODALT FROM TEMP_PRODALT T3 WHERE T3.CODPROD = 0)
        AND CODPRODSUBST NOT IN (SELECT T4.CODPRODALT FROM TEMP_PRODALT T4 WHERE T4.CODPROD = 0))) 
        ;
      
      INSERT INTO TEMP_PRODALT(CODPROD, CODPRODALT)
      SELECT CASE WHEN (CODPRODSUBST IN (SELECT T1.CODPROD FROM TEMP_PRODALT T1 WHERE T1.CODPRODALT = 0)
        AND CODPROD NOT IN (SELECT T2.CODPROD FROM TEMP_PRODALT T2 WHERE T2.CODPRODALT = 0)) THEN CODPROD ELSE 0 END AS CODPROD
        , CASE WHEN (CODPROD IN (SELECT T3.CODPRODALT FROM TEMP_PRODALT T3 WHERE T3.CODPROD = 0)
        AND CODPRODSUBST NOT IN (SELECT T4.CODPRODALT FROM TEMP_PRODALT T4 WHERE T4.CODPROD = 0)) THEN CODPRODSUBST ELSE 0 END AS CODPRODSUBST
      FROM TGFPRO
      WHERE CODPROD <> P_CODPROD AND
        ((CODPRODSUBST IN (SELECT T1.CODPROD FROM TEMP_PRODALT T1 WHERE T1.CODPRODALT = 0)
        AND CODPROD NOT IN (SELECT T2.CODPROD FROM TEMP_PRODALT T2 WHERE T2.CODPRODALT = 0))
        OR
        (CODPROD IN (SELECT T3.CODPRODALT FROM TEMP_PRODALT T3 WHERE T3.CODPROD = 0)
        AND CODPRODSUBST NOT IN (SELECT T4.CODPRODALT FROM TEMP_PRODALT T4 WHERE T4.CODPROD = 0))) 
        ;
      
    END LOOP;
    
    --DELETAR LINHAS QUE PERDERAM A REFERENCIA DE SUBSTITUIC?O
    DELETE FROM TGFPAL WHERE CODPRODALT = P_OLDCODPRODALT;  
  
    --INSERE O PRODUTO ALTERNATIVO SE N?O HOUVER
    MERGE INTO TGFPAL PAL
         USING ( SELECT CASE WHEN CODPROD = 0 THEN P_CODPROD ELSE CODPROD END AS CODPROD
                        ,CASE WHEN CODPRODALT = 0 THEN P_CODPRODALT ELSE CODPRODALT END AS CODPRODALT
                 FROM TEMP_PRODALT
                 WHERE CASE WHEN CODPROD = 0 THEN P_CODPROD ELSE CODPROD END 
                       <> 
                       CASE WHEN CODPRODALT = 0 THEN P_CODPRODALT ELSE CODPRODALT END        
                        ) T
                                    
         ON    ( PAL.CODPROD = T.CODPROD 
             AND PAL.CODPRODALT = T.CODPRODALT)                           
         WHEN MATCHED THEN
           UPDATE SET SUBSTITUTO = 'S', DTVIGENCIA = P_DTSUBST
         WHEN NOT MATCHED THEN
           INSERT  (CODPROD , CODPRODALT, SUBSTITUTO, DTVIGENCIA)
                   VALUES ( T.CODPROD, T.CODPRODALT, 'S', P_DTSUBST );
  END IF;
END;
